// 界面巡检截图：各页面在桌面与窄屏下各截一张，供人工看样式。用法：node shots.mjs <url> <目录>
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { mkdirSync } from 'node:fs'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright')
const [url = 'http://127.0.0.1:8899/', dir = fileURLToPath(new URL('./artifacts/screenshots', import.meta.url))] = process.argv.slice(2)
mkdirSync(dir, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge' })
const PDF = Buffer.from('%PDF-1.4\n%%EOF\n')
for (const [tag, width, height] of [['desk', 1440, 900], ['laptop', 1280, 720], ['phone', 390, 844]]) {
  const page = await (await browser.newContext({ viewport: { width, height } })).newPage()
  const snap = (n) => page.screenshot({ path: `${dir}/${tag}-${n}.png`, fullPage: true })
  await page.goto(url)
  await snap('01-login')
  await page.getByLabel('账号').fill(tag === 'desk' ? 'lin' : 'zhou')
  await page.getByLabel('密码').fill('LimsDemo2026')
  await page.getByRole('button', { name: '登录' }).click()
  await page.getByRole('heading', { name: '我的待办' }).waitFor()
  await page.getByText(/共 \d+ 条/).waitFor()
  await page.waitForTimeout(300)
  await snap('02a-tasks')
  await page.goto(url + '#/samples')
  await page.getByText(/共 \d+ 条/).waitFor()
  await page.waitForTimeout(300)
  await snap('02-pool')
  await page.goto(url + '#/samples/2')
  await page.getByRole('heading', { name: '样品工作表' }).waitFor()
  await page.waitForTimeout(300)
  await snap('03-sample')
  if (tag === 'desk') {
    await page.goto(url + '#/samples/4')
    await page.waitForTimeout(600)
    await snap('04-frozen')
    await page.goto(url + '#/samples/1')
    await page.getByRole('button', { name: '领取样品' }).click()
    await page.getByRole('status').waitFor()
    await page.getByRole('button', { name: '转交' }).click()
    await page.waitForTimeout(300)
    await snap('05-transfer-dialog')
    await page.getByRole('button', { name: '关闭' }).click()
    await page.getByRole('button', { name: '创建报告' }).click()
    await page.getByRole('heading', { name: '检测报告工作表' }).waitFor()
    await page.waitForTimeout(300)
    await snap('06-report-empty')
    const ed = page.locator('details', { hasText: '编制操作' })
    if ((await ed.count()) && (await ed.getAttribute('open')) === null) await ed.locator('summary').click()
    await page.getByLabel('PDF 文件').setInputFiles({ name: '原始记录-溪流水样.pdf', mimeType: 'application/pdf', buffer: PDF })
    await page.getByRole('button', { name: '保存 PDF' }).click()
    await page.getByRole('status').waitFor()
    await snap('07-report-uploaded')
    await page.goto(url + '#/reports')
    await page.getByText(/共 \d+ 条/).waitFor()
    await snap('08-reports')
  }
  await page.context().close()
}
await browser.close()
console.log('done')
