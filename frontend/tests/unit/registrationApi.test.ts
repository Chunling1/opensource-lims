  const editProfile = structuredClone(saved.profile)
  editProfile.attachments.education = []
  // Merely editing/removing on the client never changes the persisted record.
  expect((await (await call(`/quality/personnel/${saved.id}`)).json()).profile.attachments.education).toHaveLength(1)
  const updated = await call(`/quality/personnel/${saved.id}/save`, { ...saved, profile: editProfile })
