  const call = await client(), id = randomUUID(), path = `/attachment-drafts/${id}`
  const scope = { scope: 'personnel', recordId: '' }
  const uploaded = await call(`${path}/upload`, { ...scope, file: { id: randomUUID(), name: 'proof.txt', type: 'text/plain', size: 3, dataUrl: 'data:text/plain;base64,YWJj' } })
  expect(uploaded.status).toBe(200)
  const ref = await uploaded.json()
  expect(ref.dataUrl).toBe('')
  expect((await (await call(`${path}/file`, { ...scope, fileId: ref.id })).text())).toBe('abc')
  const profile = emptyPersonnelProfile(); profile.attachments.education.push(ref)
  const input = { name: '临时附件人员', code: 'STAGED-1', gender: '男', qualification: '工程师', position: '检测员', department: '实验室', profile, attachmentDraftId: id }
  expect((await call('/quality/personnel', { ...input, code: '' })).status).toBe(422)
  expect((await call(`${path}/file`, { ...scope, fileId: ref.id })).status).toBe(200)
  const result = await call('/quality/personnel', input)
  expect(result.status).toBe(200)
  const saved = await result.json()
