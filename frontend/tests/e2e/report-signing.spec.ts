import { toolbarButton, openToolbarExport } from './helpers/toolbar'
import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) test(`signing shares print filters, columns, plans and export at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/reports/signing')
  const form = page.getByRole('form', { name: '报告签章条件', exact: true })
  const table = page.getByRole('table', { name: '报告签章列表', exact: true })
  await expect(table.getByRole('row').filter({ hasText: 'SP2026090094' })).toBeVisible()
  await expect(table.getByRole('row').filter({ hasText: 'SP2026090091' })).toHaveCount(0)
  await expect(form.getByLabel('查询内容').locator('option')).toHaveText(['样品编号', '报告编号', '委托编号', '委托单位', '委托人', '项目名称', '报告标题'])
  await expect(form.getByLabel('查询内容')).toHaveValue('reportCode')
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByLabel('日期字段').locator('option')).toHaveText(['批准日期', '试验开始日期', '试验结束日期', '委托日期'])
  await expect(form.getByLabel('状态', { exact: true }).locator('option')).toHaveText(['全部', '待签章', '签章中', '待确认', '签章失败', '签章完成'])
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await expect(plans.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true })).toBeVisible()
  await plans.getByRole('button', { name: '关闭', exact: true }).click()
  await (await toolbarButton(page, '报告签章', '显示')).click()
  const columns = page.getByRole('dialog', { name: '报告签章显示列', exact: true })
  for (const name of ['签章状态', '签章日期', '检测方案', '项目名称', '结论']) await expect(columns.getByLabel(name, { exact: true })).toBeVisible()
  await expect(columns.getByLabel('打印人', { exact: true })).toHaveCount(0)
  await expect(columns.getByLabel('打印日期', { exact: true })).toHaveCount(0)
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await form.getByLabel('状态', { exact: true }).selectOption('签章失败')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.getByRole('row').filter({ hasText: 'SP2026090093' })).toHaveCount(0)
  await table.getByRole('button', { name: 'SP2026090094 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['预览', '查看签章进度', '重试签章', '下载报告', '查看附件'])
  await expect(page.getByRole('menuitem', { name: '下载报告', exact: true })).toBeDisabled()
  await expect(page.getByRole('menuitem', { name: '重试签章', exact: true })).toBeEnabled()
  await form.getByLabel('包含').click()
  await openToolbarExport(page, '报告签章')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('报告签章.csv')
  const response = await page.request.post('/api/registration/reports/lifecycle/signing-export', { headers: { 'X-Demo-Actor': 'admin' }, data: { signingStatus: '签章失败' } })
  const csv = await response.text()
  expect(csv).toContain('SP2026090094'); expect(csv).not.toContain('SP2026090091'); expect(csv).not.toContain('SP2026090093')
  expect(csv).toContain('"签章状态","签章日期"')
  await page.screenshot({ path: info.outputPath(`report-signing-${width}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('signing query shows loading, clears stale rows on failure and retries', async ({ page }) => {
  await page.goto('/#/reports/signing?signingStatus=签章失败')
  const row = page.getByRole('row').filter({ hasText: 'SP2026090094' })
  await expect(row).toBeVisible()
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/reports/lifecycle/signing-query', async route => {
    await pending
    await route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '签章列表暂时不可用' } } })
  })
  const form = page.getByRole('form', { name: '报告签章条件', exact: true })
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(form.getByRole('button', { name: '查询', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'SP2026090094 更多操作', exact: true })).toBeDisabled()
  release()
  await expect(page.getByRole('region', { name: '报告签章列表区域' }).getByText('签章列表暂时不可用', { exact: true })).toBeVisible()
  await expect(row).toHaveCount(0)
  await page.unroute('**/reports/lifecycle/signing-query')
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(row).toBeVisible()
})
