import { test, expect } from '@playwright/test'

test('opening edited customer names lists all organizations and preserves selections across remote pages', async ({ page }) => {
  await page.goto('/#/commissions/registration/commissions/new')
  const customer = page.getByLabel('委托单位', { exact: true })
  const open = page.getByRole('button', { name: '选择委托单位', exact: true })
  const dialog = page.getByRole('dialog')
  const table = dialog.getByRole('table', { name: '可选单位列表' })
  await customer.fill('示范食品有限公司（083）')
  const query = page.waitForRequest(request => request.url().endsWith('/organizations/query') && request.postDataJSON().keyword === '')
  await open.click(); await query
  await expect(dialog.getByLabel('单位名称', { exact: true })).toHaveValue('')
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(dialog.getByText('已选 1 家', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '尾页', exact: true }).click()
  await expect(table.getByRole('checkbox', { name: '选择 示范食品有限公司（083）', exact: true })).toBeChecked()
  await dialog.getByLabel('单位名称', { exact: true }).fill('示范食品有限公司（083）')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByLabel('单位名称', { exact: true })).toHaveValue('示范食品有限公司（083）')
  await expect(table.getByRole('checkbox', { name: '选择 示范食品有限公司（083）', exact: true })).toBeChecked()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await table.locator('tbody tr').first().locator('td').nth(1).click({ position: { x: 2, y: 2 } })
  await expect(table.getByRole('checkbox', { name: '选择 示范食品有限公司（083）', exact: true })).toBeChecked()
  await table.getByRole('checkbox', { name: '选择 示范食品有限公司（083）', exact: true }).uncheck()
  await expect(table.getByRole('checkbox', { name: '选择 示范食品有限公司（083）', exact: true })).not.toBeChecked()
  await table.getByRole('cell', { name: '示范食品有限公司（083）', exact: true }).click()
  await expect(table.getByRole('checkbox', { name: '选择 示范食品有限公司（083）', exact: true })).not.toBeChecked()
  await dialog.getByRole('button', { name: '返回', exact: true }).click()

  await page.getByRole('button', { name: '清除委托单位', exact: true }).click()
  await customer.fill('示范食品有限公司（011）; 远景建设集团；手填新单位')
  await open.click()
  await expect(table.getByRole('checkbox', { name: '选择 远景建设集团', exact: true })).toBeChecked()
  await dialog.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table.getByRole('checkbox', { name: '选择 示范食品有限公司（011）', exact: true })).toBeChecked()
  await expect(table.getByRole('checkbox', { name: '选择 示范食品有限公司（083）', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(customer).toHaveValue(['示范食品有限公司（011）', '远景建设集团', '手填新单位'].join('；'))

  await page.getByRole('button', { name: '清除委托单位', exact: true }).click()
  await customer.fill('未收录的新单位')
  await open.click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(dialog.getByText('已选 1 家', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '返回', exact: true }).click()
  await expect(customer).toHaveValue(['未收录的新单位'].join('；'))
})
