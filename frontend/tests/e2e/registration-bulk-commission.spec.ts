import { test, expect } from '@playwright/test'
const root = '/commissions/registration'
const headers = { 'X-Demo-Actor': 'admin' }

test('bulk form patches checked fields, imports the parent and preserves drafts on failure', async ({ page }) => {
  await page.goto(`/#${root}?current=demo-wt-1&sSort=code&sDirection=asc`)
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  await expect(table).toContainText('SP2026090015')
  const parent = await (await page.request.get('/api/registration/commissions/demo-wt-1', { headers })).json()
  const second = await (await page.request.get('/api/registration/samples/demo-yp-15', { headers })).json()
  await page.request.put('/api/registration/samples/demo-yp-15', { headers, data: { input: { ...second, commissionInfo: { ...second.commissionInfo, phone: '另一电话' } }, version: second.version } })
  for (const code of ['SP2026090001', 'SP2026090015']) await table.getByRole('checkbox', { name: `选择样品 ${code}`, exact: true }).check()
  await page.getByRole('button', { name: '批量修改（2）', exact: true }).click()
  await expect(page.getByRole('heading', { name: '批量修改委托信息', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '从委托获取', exact: true })).toBeDisabled()
  await expect(page.locator('#commission-contact')).toBeDisabled()
  await expect(page.locator('#commission-phone')).toHaveValue('')
  await expect(page.getByText('所选样品的值不同', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('checkbox', { name: '委托编号', exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: '委托日期', exact: true })).toHaveCount(0)
  await page.getByRole('checkbox', { name: '委托人', exact: true }).check()
  await page.locator('#commission-contact').fill('临时修改')
  await page.getByRole('button', { name: '从委托获取', exact: true }).click()
  await expect(page.locator('#commission-contact')).toHaveValue(parent.contact)
  await expect(page.locator('#commission-phone')).toHaveValue('')
  await page.locator('#commission-contact').fill('批量联系人')
  await page.getByRole('checkbox', { name: '委托单位', exact: true }).check()
  await page.locator('#commission-customer').fill('甲单位；乙单位\n丙单位')
  await page.getByRole('checkbox', { name: '委托人电话', exact: true }).check()
  let fail = true
  await page.route('**/api/registration/samples/bulk-commission', async route => {
    const body = route.request().postDataJSON()
    expect(body.changes).toEqual({ contact: '批量联系人', phone: '', customer: '甲单位；乙单位\n丙单位' })
    expect(body.targets.map((row: { id: string }) => row.id).sort()).toEqual(['demo-yp-1', 'demo-yp-15'])
    if (fail) { fail = false; return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'INTERNAL', message: '保存暂时失败' } }) }) }
    return route.continue()
  })
  await page.getByRole('button', { name: '保存', exact: true }).click()
  let confirm = page.getByRole('dialog', { name: '确认批量修改', exact: true })
  await expect(confirm).toContainText('（清空）')
  await confirm.getByRole('button', { name: '确认保存', exact: true }).click()
  await expect(confirm).toBeHidden()
  await expect(page.getByText('保存暂时失败', { exact: true })).toBeVisible()
  await expect(page.locator('#commission-contact')).toHaveValue('批量联系人')
  await expect(page.getByRole('checkbox', { name: '委托人', exact: true })).toBeChecked()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await confirm.getByRole('button', { name: '确认保存', exact: true }).click()
  await expect(page.getByText('已更新 2 张样品单的委托信息。', { exact: true })).toBeVisible()
  expect(await (await page.request.get('/api/registration/commissions/demo-wt-1', { headers })).json()).toEqual(parent)
  const saved = await (await page.request.get('/api/registration/samples/demo-yp-15', { headers })).json()
  expect(saved.commissionInfo).toMatchObject({ contact: '批量联系人', customer: '甲单位；乙单位\n丙单位', phone: '' })
  expect(saved.name).toBe(second.name)
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  await expect(page).toHaveURL(/current=demo-wt-1/)
})

test('cross-commission and completed selections are blocked and narrow bulk fields support leaving safely', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/#${root}?scope=all&sSort=code&sDirection=asc`)
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  await table.getByRole('checkbox', { name: '选择样品 SP2026090001', exact: true }).check()
  await table.getByRole('checkbox', { name: '选择样品 SP2026090003', exact: true }).check()
  const bulk = page.getByRole('button', { name: '批量修改（2）', exact: true })
  await expect(bulk).toBeDisabled()
  await expect(bulk).toHaveAttribute('title', '只能批量修改同一委托单下的样品')
  await page.goto(`/#${root}/samples/bulk-edit?ids=demo-yp-1,demo-yp-3`)
  await expect(page.getByText('只能批量修改同一委托单下的样品，不能跨委托单。', { exact: true })).toBeVisible()
  await page.goto(`/#${root}/samples/bulk-edit?ids=demo-yp-29`)
  await expect(page.getByText('所选样品包含已完成或已作废记录，请仅选择未完成样品。', { exact: true })).toBeVisible()
  await page.goto(`/#${root}/samples/bulk-edit?ids=demo-yp-1,demo-yp-15`)
  await page.getByRole('checkbox', { name: '全选', exact: true }).check()
  await expect(page.locator('#commission-contact')).toBeEnabled()
  await page.getByRole('checkbox', { name: '全选', exact: true }).uncheck()
  await expect(page.locator('#commission-contact')).toBeDisabled()
  await page.getByRole('checkbox', { name: '委托人', exact: true }).check()
  await page.locator('#commission-contact').fill('未保存内容')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: testInfo.outputPath('bulk-commission-phone.png'), fullPage: true })
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  const leave = page.getByRole('dialog', { name: '离开当前页面？', exact: true })
  await expect(leave).toBeVisible()
  await leave.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(page.locator('#commission-contact')).toHaveValue('未保存内容')
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  await leave.getByRole('button', { name: '放弃修改并离开', exact: true }).click()
  await expect(page.getByRole('table', { name: '委托列表', exact: true })).toBeVisible()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
})
