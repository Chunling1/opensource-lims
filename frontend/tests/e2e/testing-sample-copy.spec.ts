import { toolbarButton } from './helpers/toolbar'
import { test, expect } from '@playwright/test'

for (const width of [1440, 390]) test(`sample copy filters, columns and dialog at ${width}`, async ({ page }, info) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/testing/sample-copy')
  const form = page.getByRole('form', { name: '复制样品数据条件', exact: true })
  const table = page.getByRole('table', { name: '复制样品数据列表', exact: true })
  await expect(table).toBeVisible()
  await expect(form.getByLabel('数据状态')).toHaveValue('')
  await expect(form.getByLabel('查询内容').locator('option')).toHaveText(['样品编号', '报告编号', '委托编号', '委托单位', '项目名称', '报告标题'])
  await expect(form.getByLabel('数据状态').locator('option')).toHaveText(['全部', '委托登记中', '委托登记完成', '委托复核中', '委托复核完成', '样品入库中', '样品入库完成', '任务分配中', '任务分配完成', '样品出库中', '样品出库完成', '样品待领取', '样品已领取', '任务处理中', '任务处理完成', '检测数据录入中', '检测数据录入完成', '检测数据校核中', '检测数据校核完成', '报告校核中', '报告校核完成', '报告审核中', '报告审核完成', '报告批准中', '报告批准完成', '报告打印中', '报告打印完成', '委托更改中', '检测更改中', '报告更改中', '委托作废申请中', '委托已作废', '报告更改审批中', '任务已取消', '终止'])
  await form.getByLabel('数据状态').selectOption('委托登记完成')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr').first()).toContainText('委托登记完成')
  await form.getByLabel('数据状态').selectOption('检测数据录入中')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('SP2026090076')
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByLabel('日期字段').locator('option')).toHaveText(['委托日期', '试验开始日期', '试验结束日期', '校核日期', '审核日期', '批准日期', '签发日期', '归档日期'])
  await form.getByLabel('包含', { exact: true }).fill('不存在的编号')
  await expect(table).toContainText('SP2026090076')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).not.toContainText('SP2026090076')
  await form.getByLabel('包含', { exact: true }).fill('')
  await form.getByLabel('数据状态').selectOption('检测数据录入中')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await (await toolbarButton(page, '复制样品数据', '显示')).click()
  const columns = page.getByRole('dialog', { name: '复制样品数据显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(47)
  await expect(columns.getByRole('checkbox', { name: '检测方案', exact: true })).not.toBeChecked()
  await columns.getByRole('checkbox', { name: '实际价格费用', exact: true }).check()
  await columns.getByRole('checkbox', { name: '附件', exact: true }).check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await expect(table.getByRole('columnheader', { name: '实际价格费用', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await plans.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true }).click()
  await expect(plans.getByText('已选 1 项', { exact: true })).toBeVisible()
  await plans.getByRole('button', { name: '关闭', exact: true }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  const row = table.getByRole('row').filter({ hasText: 'SP2026090076' })
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['复制'])
  await page.getByRole('menuitem', { name: '复制', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '复制样品', exact: true })
  await expect(dialog).toContainText('SP2026090076')
  await expect(dialog.getByRole('radio', { name: '分项/阶段性报告样品', exact: true })).toBeChecked()
  await expect(dialog.getByLabel('指定样品数据状态')).toHaveValue('委托登记中')
  await expect(dialog.getByLabel('指定样品数据状态').locator('option')).toHaveText(['委托登记中', '委托登记完成', '检测数据录入中'])
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('复制样品报告编号后缀').fill(`-COPY-${width}`)
  await dialog.getByLabel('指定样品检测部门').selectOption('实验室')
  for (const [kind, suffix] of [['英文报告样品', '(E)'], ['补充报告', 'BC']]) {
    await dialog.getByRole('radio', { name: kind!, exact: true }).check()
    await expect(dialog.getByLabel('指定样品数据状态')).toBeEnabled()
    await expect(dialog.getByLabel('指定样品检测部门')).toBeDisabled()
    await expect(dialog.getByLabel('复制样品报告编号后缀')).toBeDisabled()
    await dialog.getByRole('button', { name: '确定', exact: true }).click()
    const confirmation = page.getByRole('dialog', { name: '确认复制样品', exact: true })
    await expect(confirmation).toContainText('确定后将无法修改')
    await expect(confirmation).toContainText('委托登记完成')
    await expect(confirmation.locator('dd').last()).toHaveText(new RegExp(suffix!.replace(/[()]/g, '\\$&') + '$'))
    await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  }
  await dialog.getByRole('radio', { name: '分项/阶段性报告样品', exact: true }).check()
  await expect(dialog.getByLabel('复制样品报告编号后缀')).toHaveValue(`-COPY-${width}`)
  await expect(dialog.getByLabel('指定样品检测部门')).toHaveValue('实验室')
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: '确认复制样品', exact: true })
  await expect(confirmation).toContainText(`-COPY-${width}`)
  await page.screenshot({ path: info.outputPath(`sample-copy-confirm-${width}.png`), fullPage: true })
  const copied = page.waitForResponse(response => response.url().endsWith('/samples/demo-yp-76/copy') && response.request().method() === 'POST')
  await confirmation.getByRole('button', { name: '确定', exact: true }).click()
  expect((await copied).ok()).toBe(true)
  await expect(page.getByRole('status').filter({ hasText: '复制成功' })).toBeVisible()
  await expect(dialog).toBeHidden()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await page.reload()
  await expect(table.getByRole('columnheader', { name: '实际价格费用', exact: true })).toBeVisible()
  const exported = await page.request.post('/api/registration/samples/sample-copy/export', { headers: { 'X-Demo-Actor': 'admin' }, data: { ids: ['demo-yp-76'] } })
  expect(exported.ok()).toBe(true)
  const csv = await exported.text()
  expect(csv.split('\r\n')[0]!.split(',')).toHaveLength(47)
  expect(csv.split('\r\n')[0]).toContain('"打印日期","打印人","发放日期","发放人"')
  expect(csv).toContain('SP2026090076'); expect(csv).not.toContain('SP2026090077')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`sample-copy-${width}.png`), fullPage: true })
  // Supply report-progress fixtures to verify the same dialog at later stages.
  let sourceStatus = '报告审核完成'
  await page.route('**/api/registration/samples/sample-copy/query', async route => {
    const response = await route.fetch()
    const result = await response.json()
    result.items = result.items.map((item: Record<string, unknown>) => ({ ...item, dataStatus: sourceStatus }))
    await route.fulfill({ response, json: result })
  })
  for (const [progress, options] of [
    ['报告审核完成', ['委托登记中', '委托登记完成', '检测数据录入中', '检测数据录入完成', '报告审核完成']],
    ['报告批准完成', ['委托登记中', '委托登记完成', '检测数据录入中', '检测数据录入完成', '报告审核完成', '报告批准完成']],
  ] as const) {
    sourceStatus = progress
    await page.reload()
    await expect(row).toContainText(progress)
    await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
    await page.getByRole('menuitem', { name: '复制', exact: true }).click()
    await expect(dialog.getByLabel('指定样品数据状态').locator('option')).toHaveText([...options])
    await dialog.getByLabel('指定样品数据状态').selectOption(progress)
    await dialog.getByRole('radio', { name: '补充报告', exact: true }).check()
    await expect(dialog.getByLabel('指定样品数据状态')).toHaveValue(progress)
    await dialog.getByRole('button', { name: '确定', exact: true }).click()
    await expect(confirmation).toContainText(progress === '报告批准完成' ? '报告打印中' : '报告批准中')
    await confirmation.getByRole('button', { name: '取消', exact: true }).click()
    await dialog.getByRole('button', { name: '返回', exact: true }).click()
  }
})
