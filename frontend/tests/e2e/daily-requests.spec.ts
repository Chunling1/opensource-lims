import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { toolbarButton, openToolbarExport } from './helpers/toolbar'
for (const width of [1440, 390]) test(`daily request draft, files, submission, withdrawal and deletion at ${width}`, async ({ page }, info) => {
  test.setTimeout(120000)
  await page.request.post('/api/registration/session')
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/requests')
  const table = page.getByRole('table', { name: '日常事务申请列表', exact: true })
  await expect(table).toContainText('检测合同用印（示例）')
  const form = page.getByRole('form', { name: '日常事务申请查询', exact: true })
  await expect(form.getByRole('button', { name: '重置', exact: true })).toHaveCount(0)
  await (await toolbarButton(page, '日常事务申请', '新增')).click()
  let dialog = page.getByRole('dialog', { name: '新增申请', exact: true })
  await expect(dialog.getByLabel('申请人', { exact: true })).toHaveValue('演示用户')
  await expect(dialog.getByLabel('申请人', { exact: true })).toBeDisabled()
  await expect(dialog.getByLabel('申请部门', { exact: true })).toHaveValue('实验室')
  await dialog.getByRole('button', { name: '提交', exact: true }).click()
  await expect(dialog.locator('[data-field-feedback]')).toContainText('办理事由')
  await dialog.getByLabel('办理事由', { exact: true }).fill('申请测试资料')
  await dialog.getByRole('button', { name: '提交', exact: true }).click()
  await expect(dialog.locator('[data-field-feedback]')).toContainText('办理事项')
  await dialog.getByRole('checkbox', { name: '加盖检测合同章', exact: true }).check()
  await dialog.getByRole('checkbox', { name: '其他', exact: true }).check()
  await expect(dialog.locator('[data-field-feedback]')).toHaveCount(0)
  await dialog.getByLabel('其他办理事项', { exact: true }).fill('补充证明')
  await dialog.getByLabel('份数', { exact: true }).fill('2')
  const upload = page.waitForResponse(response => response.url().includes('/attachment-drafts/') && response.url().endsWith('/upload'))
  await dialog.locator('input[type=file]').setInputFiles({ name: '事务证明.txt', mimeType: 'text/plain', buffer: Buffer.from('daily request evidence') })
  expect((await upload).ok()).toBe(true)
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeEnabled()
  await expect(dialog.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  await dialog.screenshot({ path: info.outputPath(`daily-request-new-${width}.png`) })
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await form.getByLabel('办理事由', { exact: true }).fill('申请测试资料')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText('申请中')
  const headers = { 'X-Demo-Actor': 'admin' }
  const saved = (await (await page.request.post('/api/registration/quality/requests/query', { headers, data: { reason: '申请测试资料' } })).json()).items[0]
  expect(saved.files[0].dataUrl).toBe('')
  const downloadResponse = await page.request.post(`/api/registration/attachment-drafts/${crypto.randomUUID()}/file`, { headers, data: { scope: 'daily-request', recordId: saved.id, fileId: saved.files[0].id } })
  expect((await downloadResponse.body()).toString()).toBe('daily request evidence')
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '查看申请', exact: true })
  await expect(dialog.getByLabel('办理事由', { exact: true })).toBeDisabled()
  await expect(dialog.getByText('事务证明.txt', { exact: true })).toBeVisible()
  await expect(dialog.locator('input[type=file]')).toHaveCount(0)
  await dialog.getByRole('button', { name: '返回', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '修改', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '修改申请', exact: true })
  await expect(dialog.getByLabel('份数', { exact: true })).toHaveValue('2')
  await dialog.getByRole('button', { name: '提交', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table).toContainText('待审批')
  await table.getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem', { name: '修改', exact: true })).toBeDisabled()
  await expect(page.getByRole('menuitem', { name: '删除', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '撤销', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '撤销申请', exact: true })
  await dialog.getByRole('button', { name: '确认撤销', exact: true }).click()
  await expect(dialog.locator('[data-field-feedback]')).toContainText('撤回原因')
  await dialog.getByRole('textbox', { name: /撤回原因/ }).fill('补充附件后提交')
  await dialog.getByRole('button', { name: '确认撤销', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table).toContainText('申请中')
  await table.locator('tbody tr').getByRole('checkbox').check()
  await openToolbarExport(page, '日常事务申请')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  const result = await download, csv = await readFile((await result.path())!, 'utf8')
  expect(csv).toContain('撤回原因'); expect(csv).toContain('补充附件后提交'); expect(csv).toContain('其他：补充证明')
  await page.screenshot({ path: info.outputPath(`daily-request-list-${width}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '删除申请', exact: true })
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(table).toContainText('暂无符合条件')
})
test('daily request status filters, latest save and ownership', async ({ page }) => {
  await page.request.post('/api/registration/session')
  await page.goto('/#/quality/requests')
  const table = page.getByRole('table', { name: '日常事务申请列表', exact: true }), form = page.getByRole('form', { name: '日常事务申请查询', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(6)
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await form.getByLabel('审批状态', { exact: true }).selectOption('申请中')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '修改', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '修改申请', exact: true })
  await expect(dialog.getByLabel('办理事由', { exact: true })).toHaveValue('检测业务资料用印（示例）')
  const headers = { 'X-Demo-Actor': 'admin' }, path = '/api/registration/quality/requests'
  const record = await (await page.request.post(`${path}/detail`, { headers, data: { id: 'daily-request-1' } })).json()
  expect((await page.request.post(`${path}/save`, { headers, data: { ...record, reason: '其他窗口修改' } })).ok()).toBe(true)
  await dialog.getByRole('button', { name: '提交', exact: true }).click()
  await expect(dialog).toBeHidden()
  await form.getByLabel('审批状态', { exact: true }).selectOption('待审批')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await page.evaluate(() => localStorage.setItem('lims.identity.v1', 'reviewer')); await page.reload()
  await expect(table).toContainText('检测业务资料用印（示例）')
  await expect(await toolbarButton(page, '日常事务申请', '新增')).toBeEnabled()
  await table.getByRole('row').filter({ hasText: '检测业务资料用印（示例）' }).getByRole('button', { name: /更多操作/ }).click()
  for (const name of ['修改', '撤销', '删除']) await expect(page.getByRole('menuitem', { name, exact: true })).toBeDisabled()
  const current = await (await page.request.post(`${path}/detail`, { headers, data: { id: record.id } })).json()
  const denied = await page.request.post(`${path}/save`, { headers: { 'X-Demo-Actor': 'reviewer' }, data: current })
  expect(denied.status()).toBe(403)
})

test('ordinary staff can access requests, attach files and manage only their own applications', async ({ page }) => {
  await page.request.post('/api/registration/session')
  await page.goto('/#/dashboard')
  await page.evaluate(() => localStorage.setItem('lims.identity.v1', 'business'))
  await page.reload()
  await page.goto('/#/quality/requests')
  const table = page.getByRole('table', { name: '日常事务申请列表', exact: true })
  await expect(table).toContainText('检测合同用印（示例）')
  await (await toolbarButton(page, '日常事务申请', '新增')).click()
  const dialog = page.getByRole('dialog', { name: '新增申请', exact: true })
  await expect(dialog.getByLabel('申请人', { exact: true })).toHaveValue('张受理')
  await dialog.getByLabel('办理事由', { exact: true }).fill('普通人员申请')
  await dialog.getByRole('checkbox', { name: '加盖检测合同章', exact: true }).check()
  const upload = page.waitForResponse(r => r.url().endsWith('/upload'))
  await dialog.locator('input[type=file]').setInputFiles({ name: '证明.txt', mimeType: 'text/plain', buffer: Buffer.from('proof') })
  expect((await upload).ok()).toBe(true)
  await dialog.getByRole('button', { name: '提交', exact: true }).click()
  await expect(dialog).toBeHidden()
  const row = table.locator('tbody tr').filter({ hasText: '普通人员申请' })
  await row.getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem', { name: '撤销', exact: true })).toBeEnabled()
  await page.getByRole('menuitem', { name: '撤销', exact: true }).click()
  const withdraw = page.getByRole('dialog', { name: '撤销申请', exact: true })
  await expect(withdraw).toContainText('恢复为申请中')
  await withdraw.getByRole('textbox', { name: /撤回原因/ }).fill('补充内容')
  await withdraw.getByRole('button', { name: '确认撤销', exact: true }).click()
  await expect(withdraw).toBeHidden()
  await expect(row).toContainText('申请中')
  await table.locator('tbody tr').filter({ hasText: '检测业务资料用印（示例）' }).getByRole('button', { name: /更多操作/ }).click()
  for (const name of ['修改', '撤销', '删除']) await expect(page.getByRole('menuitem', { name, exact: true })).toBeDisabled()
})
