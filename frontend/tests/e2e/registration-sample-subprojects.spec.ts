import { test, expect } from '@playwright/test'
import { selectGeneralSamplePlan } from './helpers/sample-plan'
import { checkOnlyWithControl } from './helpers/table-selection'
import { toolbarButton } from './helpers/toolbar'

test('subprojects add, edit, view, cancel, delete and persist without changing fees', async ({ page }, testInfo) => {
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  await page.getByLabel('工程/产品名称', { exact: false }).fill('空气过滤器')
  await page.getByLabel('检测类别', { exact: false }).selectOption('委托')
  await page.getByLabel('标准价格', { exact: true }).fill('9000')
  const section = page.getByRole('region', { name: '子项目信息', exact: true })
  const table = section.getByRole('table', { name: '子项目明细' })
  await expect(section.getByRole('button', { name: '修改', exact: true })).toBeDisabled()
  await section.getByRole('button', { name: '增加', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '新增子项目', exact: true })
  await dialog.getByLabel('子项目名称', { exact: false }).selectOption('空气过滤器检测')
  await expect(dialog.getByRole('textbox', { name: '核算部门', exact: true })).toHaveValue('环境控制检测部')
  await expect(dialog.getByLabel('业务三级分类', { exact: true })).toHaveValue('其他产品及设备检测')
  await dialog.getByLabel('子项金额', { exact: true }).fill('9000')
  await dialog.getByLabel('子项目名称', { exact: false }).selectOption('通风设备检测')
  await expect(dialog.getByLabel('核算部门', { exact: true })).toHaveValue('通风设备检测部')
  await expect(dialog.getByLabel('业务三级分类', { exact: true })).toHaveValue('通风设备检测')
  await expect(dialog.getByLabel('子项金额', { exact: true })).toHaveValue('9000')
  await dialog.getByLabel('子项目名称', { exact: false }).selectOption('空气过滤器检测')
  await dialog.getByLabel('核算部门', { exact: true }).fill('自定义核算部门')
  await dialog.getByLabel('业务三级分类', { exact: true }).fill('自定义业务分类')
  await dialog.getByLabel('收款金额', { exact: true }).fill('0')
  await expect(dialog.getByLabel('收款类型', { exact: true })).toHaveValue('预收款')
  await expect(dialog.getByLabel('收款类型', { exact: true }).locator('option')).toHaveText(['请选择', '预收款', '结算款', '进度款', '保证金', '奖惩', '其他'])
  await dialog.getByLabel('收款类型', { exact: true }).selectOption('结算款')
  await dialog.getByLabel('付款说明', { exact: true }).fill('检测费')
  await dialog.getByLabel('备注', { exact: true }).fill('第一行\n第二行')
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(table).toContainText('9,000.00')
  await expect(table).toContainText('0.00')
  await expect(page.getByLabel('折扣价格', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('实际价格', { exact: true })).toHaveValue('')
  await section.getByRole('button', { name: '查看', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '查看子项目', exact: true })
  await expect(dialog.getByLabel('子项金额', { exact: true })).not.toBeEditable()
  await expect(dialog.getByLabel('子项目名称', { exact: false })).toBeDisabled()
  await expect(dialog.getByLabel('子项目名称', { exact: false })).toHaveValue('空气过滤器检测')
  await expect(dialog.getByLabel('核算部门', { exact: true })).toHaveValue('自定义核算部门')
  await expect(dialog.getByLabel('业务三级分类', { exact: true })).toHaveValue('自定义业务分类')
  await expect(dialog.getByLabel('收款类型', { exact: true })).toBeDisabled()
  await expect(dialog.getByLabel('收款类型', { exact: true })).toHaveValue('结算款')
  await expect(dialog.getByLabel('备注', { exact: true })).toHaveValue('第一行\n第二行')
  await dialog.getByRole('button', { name: '返回', exact: true }).click()
  await section.getByRole('button', { name: '修改', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '修改子项目', exact: true })
  await expect(dialog.getByLabel('核算部门', { exact: true })).toHaveValue('自定义核算部门')
  await expect(dialog.getByLabel('业务三级分类', { exact: true })).toHaveValue('自定义业务分类')
  await dialog.getByLabel('收款金额', { exact: true }).fill('120.50')
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(table).toContainText('120.50')
  await section.getByRole('button', { name: '增加', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '新增子项目', exact: true })
  await dialog.getByLabel('子项目名称', { exact: false }).selectOption('通风设备检测')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(table).not.toContainText('通风设备检测')
  await selectGeneralSamplePlan(page)
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page).toHaveURL(/samples\/[^/]+\/edit/)
  await page.reload()
  await expect(table).toContainText('120.50')
  await expect(table).toContainText('结算款')
  await expect(table).toContainText('自定义核算部门')
  await expect(table).toContainText('自定义业务分类')
  await expect(page.getByLabel('标准价格', { exact: true })).toHaveValue('9000')
  await checkOnlyWithControl(table.locator('tbody tr').first(), table.getByRole('radio', { name: '选择子项目 空气过滤器检测' }))
  for (const [width, theme] of [[1440, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(t => document.documentElement.setAttribute('data-bs-theme', t), theme)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const toolbar = section.getByRole('group', { name: '子项目工具栏', exact: true })
    await expect.poll(() => toolbar.locator('button:visible').evaluateAll(nodes => {
      const boxes = nodes.map(node => node.getBoundingClientRect())
      return Math.max(...boxes.map(box => box.top)) - Math.min(...boxes.map(box => box.top))
    })).toBeLessThan(2)
    await section.screenshot({ path: testInfo.outputPath(`subprojects-${width}.png`) })
  }
  await (await toolbarButton(page, '子项目', '删除')).click()
  dialog = page.getByRole('dialog', { name: '删除子项目', exact: true })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(table).toContainText('空气过滤器检测')
  await (await toolbarButton(page, '子项目', '删除')).click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(table).toContainText('暂无子项目')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('样品已保存。', { exact: true })).toBeVisible()
  await page.reload()
  await expect(table).toContainText('暂无子项目')
})
