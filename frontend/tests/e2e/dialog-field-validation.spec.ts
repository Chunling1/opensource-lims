import { test, expect } from '@playwright/test'

for (const width of [1440, 390]) test(`device picker validation is attached to the field at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/equipment/plans/interim')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '新增设备期间核查计划', exact: true })
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  const field = dialog.locator('#interim-code'), hint = dialog.locator('[data-field-feedback]')
  await expect(hint).toHaveText('请选择设备。')
  await expect(field).toHaveAttribute('aria-invalid', 'true')
  await expect(field).toBeFocused()
  await expect(field).toHaveAttribute('aria-describedby', await hint.getAttribute('id') as string)
  await expect(dialog.locator('.toast.show')).toHaveCount(0)
  const box = await hint.boundingBox(), inputBox = await field.boundingBox()
  expect(box!.y).toBeGreaterThanOrEqual(inputBox!.y + inputBox!.height)
  await expect(dialog.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  await dialog.screenshot({ path: info.outputPath(`field-validation-${width}.png`) })
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(hint).toHaveCount(1)
  await dialog.getByRole('button', { name: '选择设备', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择设备', exact: true })
  await picker.getByRole('radio').first().check()
  await picker.getByRole('button', { name: '确定', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '新增设备期间核查计划', exact: true })
  await expect(dialog.locator('[data-field-feedback]')).toHaveCount(0)
  await expect(dialog.locator('#interim-code')).not.toHaveAttribute('aria-invalid', 'true')
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(dialog).toBeHidden()
})

test('native required fields and API duplicate errors use one inline hint and clear when edited', async ({ page }) => {
  await page.goto('/#/quality/equipment/ledger')
  await expect(page.getByRole('table', { name: '设备台账列表', exact: true }).locator('tbody tr').first()).toBeVisible()
  const existing = (await (await page.request.post('/api/registration/quality/equipment/ledger/query', { headers: { 'X-Demo-Actor': 'admin' }, data: {} })).json()).items[0].code
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新增设备', exact: true }), code = dialog.getByLabel('档案号', { exact: true }), name = dialog.getByLabel('仪器设备名称', { exact: true })
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeEnabled()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(code).toBeFocused()
  await expect(code).toHaveAttribute('aria-invalid', 'true')
  await expect(name).toHaveAttribute('aria-invalid', 'true')
  await expect(dialog.locator('[data-field-feedback]')).toHaveCount(2)
  await code.fill(existing); await name.fill('校验设备')
  await expect(dialog.locator('[data-field-feedback]')).toHaveCount(0)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.locator('[data-field-feedback]')).toHaveText('档案号已存在，请使用其他档案号。')
  await expect(code).toBeFocused()
  await expect(dialog.locator('.toast.show')).toHaveCount(0)
  await code.fill('FIELD-VALIDATION-NEW')
  await expect(dialog.locator('[data-field-feedback]')).toHaveCount(0)
  await expect(code).not.toHaveAttribute('aria-invalid', 'true')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
})

test('personnel server errors are assigned in form order and recover on input', async ({ page }) => {
  await page.goto('/#/quality/personnel/registration')
  await page.getByRole('table', { name: '人员登记列表', exact: true }).locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑人员', exact: true })
  await expect(dialog.getByLabel('人员编号', { exact: true })).toBeEnabled()
  await page.route(/\/quality\/personnel\/[^/?]+\/save$/, route => route.fulfill({ status: 422, json: { error: { code: 'VALIDATION', message: '请检查表单。', fieldErrors: { position: '岗位无效', code: '编号重复' } } } }))
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByLabel('人员编号', { exact: true })).toBeFocused()
  await expect(dialog.locator('[data-field-feedback]')).toHaveText(['编号重复', '岗位无效'])
  await expect(dialog.locator('.toast.show')).toHaveCount(0)
  await dialog.getByLabel('人员编号', { exact: true }).fill('NEW-CODE')
  await expect(dialog.locator('[data-field-feedback]')).toHaveText(['岗位无效'])
})

test('file format errors appear beside the file control', async ({ page }) => {
  await page.goto('/#/quality/personnel/registration')
  await page.getByRole('button', { name: '导入', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '导入人员', exact: true }), file = dialog.getByLabel('导入文件')
  await file.setInputFiles({ name: 'wrong.txt', mimeType: 'text/plain', buffer: Buffer.from('bad') })
  await dialog.getByRole('button', { name: '导入', exact: true }).click()
  await expect(dialog.locator('[data-field-feedback]')).toContainText('CSV')
  await expect(file).toHaveAttribute('aria-invalid', 'true')
  await expect(dialog.locator('.toast.show')).toHaveCount(0)
  await file.setInputFiles({ name: 'new.csv', mimeType: 'text/csv', buffer: Buffer.from('bad') })
  await expect(dialog.locator('[data-field-feedback]')).toHaveCount(0)
})
