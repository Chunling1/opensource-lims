import { test, expect } from '@playwright/test'

test('dispatch validates staff inline, retains failed drafts and waits for backend acceptance before closing', async ({ page }, testInfo) => {
  await page.goto('/#/samples/outbound')
  const table = page.getByRole('table', { name: '样品出库列表', exact: true }), form = page.getByRole('form', { name: '样品出库查询' })
  await expect(table).toContainText('SP2026090019')
  await table.getByRole('button', { name: 'SP2026090019 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '出库', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '样品出库', exact: true })
  await expect(modal.getByLabel('样品管理员工号')).toHaveValue('admin')
  await expect(modal.getByLabel('样品管理员姓名')).toHaveValue('演示用户')
  await expect(modal.getByLabel('出库时间')).toHaveValue(await page.evaluate(() => new Date().toLocaleDateString('sv-SE')))
  await modal.getByLabel('样品管理员姓名').fill('错误姓名')
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.locator('#outbound-name-error')).toContainText('工号与姓名不匹配')
  await expect(modal.getByLabel('样品管理员工号')).toBeFocused()
  await expect(modal).not.toContainText('诊断编号')
  await modal.getByLabel('样品管理员姓名').fill('演示用户')
  await modal.getByLabel('出库时间').fill('2026-09-24')
  await modal.getByLabel('样品管理员姓名').click()
  await page.route('**/samples/demo-yp-19/outbound-action', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '出库服务暂不可用' } } }), { times: 1 })
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('出库服务暂不可用')
  await expect(modal.getByLabel('出库时间')).toHaveValue('2026-09-24')
  await page.screenshot({ path: testInfo.outputPath('dispatch-form.png') })
  let release = () => {}
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/samples/demo-yp-19/outbound-action', async route => { const response = await route.fetch(); await gate; await route.fulfill({ response }) }, { times: 1 })
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('button', { name: '正在提交…', exact: true })).toBeDisabled()
  await expect(modal.getByRole('button', { name: '取消', exact: true })).toBeDisabled()
  await expect(modal.getByLabel('样品管理员工号')).toBeDisabled()
  release()
  await expect(modal).toBeHidden()
  await expect(table).not.toContainText('SP2026090019')
  await form.getByLabel('数据状态').selectOption('样品待领取')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('SP2026090019')
  await table.getByRole('button', { name: 'SP2026090019 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '出库', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '撤销出库', exact: true }).click()
  const undo = page.getByRole('dialog', { name: '撤销出库', exact: true })
  await expect(undo).toContainText('确认对这条样品执行“撤销出库”？')
  await undo.getByRole('button', { name: '确认', exact: true }).click()
  await expect(undo).toBeHidden()
  await expect(table).not.toContainText('SP2026090019')
  await form.getByLabel('数据状态').selectOption('样品出库中')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('SP2026090019')
})

for (const type of ['commission', 'assignment'] as const) test(`return ${type} saves its reason and applies only the backend target state`, async ({ page }, testInfo) => {
  await page.goto(`/#/samples/outbound?status=${encodeURIComponent(type === 'assignment' ? '样品待领取' : '样品出库中')}`)
  const code = type === 'assignment' ? 'SP2026090020' : 'SP2026090019', id = type === 'assignment' ? 'demo-yp-20' : 'demo-yp-19'
  const table = page.getByRole('table', { name: '样品出库列表', exact: true })
  await expect(table).toContainText(code)
  await table.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  await page.getByRole('menuitem', { name: '退回委托', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '退回委托', exact: true })
  await expect(modal.getByRole('radio', { name: '委托信息错误', exact: true })).toBeChecked()
  await modal.getByRole('radio', { name: type === 'assignment' ? '任务分配错误' : '委托信息错误', exact: true }).click()
  await expect(modal.getByRole('radio', { name: type === 'assignment' ? '委托信息错误' : '任务分配错误', exact: true })).not.toBeChecked()
  await modal.getByLabel('退回原因', { exact: false }).fill(' ')
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.locator('#outbound-reason-error')).toBeVisible()
  await modal.getByLabel('退回原因', { exact: false }).fill('请核对委托及任务信息')
  await modal.getByLabel('补充说明').fill('更正后重新提交')
  await modal.getByLabel('退回时间').fill('2026-09-24')
  await modal.getByLabel('退回时间').press('Tab')
  if (type === 'assignment') await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath(`return-${type}.png`) })
  const response = page.waitForResponse(response => response.url().endsWith(`/samples/${id}/outbound-action`))
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  const saved = await (await response).json()
  expect(saved).toMatchObject({ dataStatus: type === 'assignment' ? '完成登记' : '委托登记中', status: type === 'assignment' ? 'completed' : 'pending', reviewStatus: 'unreviewed' })
  expect(saved.outboundInfo.returns.at(-1)).toMatchObject({ type, reason: '请核对委托及任务信息', details: '更正后重新提交', date: '2026-09-24' })
  await expect(modal).toBeHidden()
  await expect(table).not.toContainText(code)
  await page.goto(`/#/samples/outbound?status=${encodeURIComponent('样品已领取')}`)
  await expect(table).toContainText('SP2026090021')
  await table.getByRole('button', { name: 'SP2026090021 更多操作', exact: true }).click()
  for (const name of ['出库', '撤销出库', '退回委托']) await expect(page.getByRole('menuitem', { name, exact: true })).toBeDisabled()
})
