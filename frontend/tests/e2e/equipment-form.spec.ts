      const grid = form.getByRole('table', { name: '期间核查测量数据', exact: true })
      expect(await grid.evaluate(el => el.parentElement!.scrollWidth > el.parentElement!.clientWidth)).toBe(true)
      await grid.getByLabel('核查点 5 误差', { exact: true }).scrollIntoViewIfNeeded()
