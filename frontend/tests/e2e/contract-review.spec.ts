test('compliance layout fits short content and scrolls long results with stable header height', async ({ page }, testInfo) => {
  await page.goto(`/#${list}`)
  await page.getByRole('checkbox', { name: '选择样品 SP2026090002', exact: true }).check()
  await page.getByRole('button', { name: '快速评审', exact: true }).click()
  let longResult = false
  await page.route('**/samples/demo-yp-2/review-check', async route => {
    const response = await route.fetch(), body = await response.json()
    if (longResult) body.messages.push({ tone: 'info', text: '<img src=x onerror=alert(1)>' + '长结果提示内容。'.repeat(180) })
    await route.fulfill({ response, json: body })
  })
  const dialog = page.getByRole('dialog', { name: '合同评审', exact: true })
  const read = dialog.getByRole('checkbox', { name: '我已阅读并确认上述校核结果', exact: true })
  const bounds = () => dialog.evaluate(el => ['[aria-labelledby="review-requirements-title"] > .card-header', '[aria-labelledby="review-remarks-title"] > .card-header', '[aria-labelledby="review-check-title"] > .card-header'].map(selector => {
    const rect = el.querySelector(selector)!.getBoundingClientRect()
    return [selector.includes('card-header') ? 0 : Math.round(rect.y), Math.round(rect.height)]
  }))
  for (const [width, height, theme] of [[1440, 1000, 'light'], [390, 780, 'dark'], [1440, 600, 'light']] as const) {
    await page.setViewportSize({ width, height })
    await page.evaluate(value => document.documentElement.setAttribute('data-bs-theme', value), theme)
    await expect(dialog).toBeVisible()
    const before = await bounds()
    expect(new Set(before.map(([, height]) => height)).size).toBe(1)
    for (const long of [false, true]) {
      longResult = long
      await dialog.getByRole('button', { name: '校验', exact: true }).click()
      await expect(dialog.getByRole('button', { name: '校验中…', exact: true })).toBeDisabled()
      expect(await bounds()).toEqual(before)
      await expect(read).not.toBeChecked()
      await expect(dialog.getByRole('button', { name: '校验', exact: true })).toBeEnabled()
      expect(await bounds()).toEqual(before)
      await expect(dialog.locator('.alert img')).toHaveCount(0)
      if (!long && width === 1440 && height === 1000) {
        const content = await dialog.locator('.modal-content').boundingBox()
        expect(content!.height).toBeLessThan(800)
        const bottomSpace = await dialog.locator('#review-check-results').evaluate(el => {
          const last = el.lastElementChild!.getBoundingClientRect()
          return el.getBoundingClientRect().bottom - last.bottom
        })
        expect(bottomSpace).toBeLessThanOrEqual(20)
        await page.screenshot({ path: testInfo.outputPath('review-short-desktop.png') })
      }
      if (long) {
        const desktop = width >= 992 && height >= 700
        const scrolling = dialog.locator(desktop ? '#review-check-results' : '.modal-body')
        await expect.poll(() => scrolling.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
        await expect.poll(() => dialog.locator('.modal-body').evaluate(el => el.scrollHeight > el.clientHeight)).toBe(!desktop)
        await scrolling.evaluate(el => { el.scrollTop = el.scrollHeight })
        expect(await bounds()).toEqual(before)
        if (desktop) {
          await scrolling.focus()
          await page.keyboard.press('Home')
        }
        await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
        const footer = await dialog.locator('.modal-footer').boundingBox()
        expect(footer!.y + footer!.height).toBeLessThanOrEqual(height)
        await expect(read).toBeInViewport()
        await read.check()
        await page.screenshot({ path: testInfo.outputPath(`review-long-${width}-${height}.png`) })
      }
    }
  }
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
})

