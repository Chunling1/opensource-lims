async function menu(page: Page, code: string) {
  await page.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  return page.getByRole('menu', { name: `${code} 更多操作`, exact: true })
}
async function confirm(page: Page, action: string) {
  const dialog = page.getByRole('dialog', { name: action, exact: true })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).toBeHidden()
}

async function checkAndRead(page: Page) {
  const dialog = page.getByRole('dialog', { name: '合同评审', exact: true })
  await dialog.getByRole('button', { name: '校验', exact: true }).click()
  await dialog.getByRole('checkbox', { name: '我已阅读并确认上述校核结果', exact: true }).check()
}

