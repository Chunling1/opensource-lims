import { toolbarButton } from './helpers/toolbar'
import { test, expect } from '@playwright/test'
for (const width of [1440, 390]) test(`detection changes edit, complete and plan filter at ${width}`, async ({ page }, info) => {
  test.setTimeout(90000)
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/testing/data-changes')
  const table = page.getByRole('table', { name: '检测数据更改列表', exact: true })
  const form = page.getByRole('form', { name: '检测数据更改查询', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await expect(form.getByLabel('处理结果')).toHaveValue('问题处理中')
  await expect(form.getByLabel('问题来源').locator('option')).toHaveText(['全部', '问题处理', '报告更改'])
  await (await toolbarButton(page, '检测数据更改', '显示')).click()
  const columns = page.getByRole('dialog', { name: '检测数据更改显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(15)
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await drawer.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true }).click()
  await drawer.getByRole('button', { name: '关闭', exact: true }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  const row = table.getByRole('row').filter({ hasText: 'SP2026090079' }), listUrl = page.url()
  await row.getByRole('button', { name: 'SP2026090079 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['更改', '完成', '附件管理'])
  await page.getByRole('menuitem', { name: '更改', exact: true }).click()
  await expect(page).toHaveURL(/data-changes\/demo-yp-79\?/)
  await page.getByLabel('备注', { exact: true }).fill('修改后的检测备注')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('试验信息已保存。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '返回检测数据更改', exact: true }).click()
  await expect(page).toHaveURL(listUrl)
  await expect(table).toContainText('SP2026090079')
  await page.screenshot({ path: info.outputPath(`data-changes-${width}.png`), fullPage: true })
  await row.getByRole('button', { name: 'SP2026090079 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '附件管理', exact: true }).click()
  const attachments = page.getByRole('dialog', { name: '附件', exact: true })
  await expect(attachments).toBeVisible()
  await attachments.getByRole('button', { name: '关闭', exact: true }).click()
  await row.getByRole('button', { name: 'SP2026090079 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '完成', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '完成', exact: true })
  await expect(modal).toContainText('完成更改')
  await modal.getByRole('button', { name: '取消', exact: true }).click()
  await expect(table).toContainText('SP2026090079')
  await row.getByRole('button', { name: 'SP2026090079 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '完成', exact: true }).click()
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.locator('.toast.show.toast-border-warning')).toContainText('请检查试验信息')
  await expect(modal).toContainText('第 1 项试验日期')
  await expect(modal.getByRole('button', { name: '打开检测数据更改，检查并补充资料' })).toBeVisible()
  await modal.getByRole('button', { name: '取消', exact: true }).click()
  const root = '/api/registration/samples/demo-yp-79/data-entry', headers = { 'X-Demo-Actor': 'admin' }
  const detail = await (await page.request.get(root, { headers })).json()
  const savedResponse = await page.request.post(`${root}/save`, { headers, data: { version: detail.version, sampleVersion: detail.sample.version, requestId: crypto.randomUUID(), form: { ...detail.form, conclusion: '符合要求', conclusionStatus: '合格', tester1Id: 'analyst', testDates: [{ kind: 'range', from: '2026-09-01', to: '2026-09-02' }] } } })
  expect(savedResponse.ok()).toBe(true)
  const draft = await savedResponse.json()
  expect((await page.request.post(`${root}/combine`, { headers, data: { version: draft.version, sampleVersion: draft.sample.version, requestId: crypto.randomUUID() } })).ok()).toBe(true)
  await expect.poll(async () => (await (await page.request.get(root, { headers })).json()).reportStatus).toBe('ready')
  await page.reload()
  await row.getByRole('button', { name: 'SP2026090079 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '完成', exact: true }).click()
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.locator('.toast.show.toast-border-warning')).toContainText('尚未上传原始记录，是否继续完成更改？')
  await modal.getByRole('button', { name: '继续完成', exact: true }).click()
  await expect(modal).toBeHidden()
  await expect(table).not.toContainText('SP2026090079')
  const saved = await (await page.request.get('/api/registration/samples/demo-yp-79', { headers: { 'X-Demo-Actor': 'admin' } })).json()
  expect(saved).toMatchObject({ dataStatus: '检测数据录入完成', dataChange: { result: '问题已处理' } })
})
