import { toolbarButton } from './helpers/toolbar'
import { test, expect } from '@playwright/test'
import { originalPdf } from '../helpers/originalPdf'

for (const width of [1440, 390]) test(`data inquiry filters, columns and read-only report at ${width}`, async ({ page }, info) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width, height: 1000 })
  await page.addInitScript(() => {
    Object.defineProperty(HTMLIFrameElement.prototype, 'contentWindow', { configurable: true, get() { return { print() { document.documentElement.dataset.printCalls = String(Number(document.documentElement.dataset.printCalls || 0) + 1) } } } })
  })
  const writes: string[] = []
  page.on('request', request => { if (request.method() !== 'GET' && request.url().includes('/data-entry')) writes.push(request.url()) })
  await page.goto('/#/testing/data-query')
  const form = page.getByRole('form', { name: '检测数据查询条件', exact: true })
  const table = page.getByRole('table', { name: '检测数据查询列表', exact: true })
  await expect(table).toBeVisible()
  await expect(form.getByLabel('数据状态')).toHaveValue('')
  await expect(form.getByLabel('查询内容').locator('option')).toHaveText(['样品编号', '报告编号', '委托编号', '委托单位', '委托人', '项目名称', '数据录入人', '报告标题'])
  await form.getByLabel('包含', { exact: true }).fill('SP2026090076')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByLabel('日期字段').locator('option')).toHaveText(['委托日期', '要求试验日期', '试验开始日期', '试验结束日期'])
  await (await toolbarButton(page, '检测数据查询', '显示')).click()
  const columns = page.getByRole('dialog', { name: '检测数据查询显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(22)
  await columns.getByRole('checkbox', { name: '检测结果', exact: true }).check()
  await columns.getByRole('checkbox', { name: '不合格参数项', exact: true }).check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await plans.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true }).click()
  await plans.getByRole('button', { name: '关闭', exact: true }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  const row = table.getByRole('row').filter({ hasText: 'SP2026090076' })
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['报告预览', '查看数据', '原始记录预览', '打印任务单'])
  await page.getByRole('menuitem', { name: '报告预览', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '报告预览', exact: true })
  await expect(modal).toContainText('暂无可预览报告')
  await page.screenshot({ path: info.outputPath(`data-query-empty-preview-${width}.png`), fullPage: true })
  await expect(modal.locator('input[type=file]')).toHaveCount(0)
  await modal.getByRole('button', { name: '关闭', exact: true }).click()
  const listUrl = page.url()
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '查看数据', exact: true }).click()
  await expect(page).toHaveURL(/\/testing\/data-query\/demo-yp-76\?/)
  await expect(page.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '报告填写', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: '原始记录', exact: true }).click()
  await expect(page.getByRole('button', { name: '上传记录', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '返回检测数据查询', exact: true }).click()
  await expect(page).toHaveURL(listUrl)
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '打印任务单', exact: true }).click()
  await expect(page).toHaveURL(/\/testing\/data-query\/demo-yp-76\/print\?/)
  await expect(page.getByRole('button', { name: /生成/ }).first()).toBeEnabled()
  await page.getByRole('link', { name: '返回检测数据查询', exact: true }).click()
  await expect(page).toHaveURL(listUrl)
  const pdf = await originalPdf([595], 'Data inquiry report preview')
  let failPreview = true
  await page.route('**/samples/demo-yp-76/data-entry', async route => {
    const response = await route.fetch(), detail = await response.json()
    await route.fulfill({ response, json: { ...detail, reportStatus: 'ready', job: { id: 'query-preview', status: 'ready' } } })
  })
  await page.route('**/data-entry/report-tasks/query-preview/pdf', async route => {
    if (failPreview) await route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '报告预览暂时不可用。' } } })
    else await route.fulfill({ contentType: 'application/pdf', body: pdf })
  })
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '报告预览', exact: true }).click()
  await expect(modal).toContainText('报告预览暂时不可用。')
  failPreview = false
  await modal.getByRole('button', { name: '刷新预览', exact: true }).click()
  await expect(modal.locator('iframe')).toHaveAttribute('src', /^blob:/)
  await page.screenshot({ path: info.outputPath(`data-query-preview-${width}.png`), fullPage: true })
  await modal.getByRole('button', { name: '关闭', exact: true }).click()
  await page.route('**/samples/demo-yp-76/data-entry/original-records', async route => {
    const response = await route.fetch(), original = await response.json()
    await route.fulfill({ response, json: { ...original, records: [{ id: 'preview-only-record', name: '原始记录.pdf', source: 'file', files: [], status: '', capabilities: { canUpload: false, canLink: false, canDelete: false } }] } })
  })
  await page.route('**/samples/demo-yp-76/data-entry/original-records/preview?*', route => route.fulfill({ contentType: 'application/pdf', body: pdf }))
  for (const action of ['原始记录预览']) {
    await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
    await page.getByRole('menuitem', { name: action, exact: true }).click()
    const original = page.getByRole('dialog', { name: action, exact: true })
    await expect(original.locator('iframe')).toHaveAttribute('src', /^blob:/)
    await expect(original.getByRole('button', { name: '打印', exact: true })).toBeEnabled()
    await expect(original.getByRole('button', { name: '上传记录', exact: true })).toHaveCount(0)
    await expect(original.locator('input[type=file]')).toHaveCount(0)
    await expect(page.locator('html')).not.toHaveAttribute('data-print-calls')
    await original.getByRole('button', { name: '关闭', exact: true }).click()
  }
  await page.reload()
  await expect(table.getByRole('columnheader', { name: '检测结果', exact: true })).toBeVisible()
  const csv = await page.request.post('/api/registration/samples/data-query/export', { headers: { 'X-Demo-Actor': 'admin' }, data: { ids: ['demo-yp-76'] } })
  expect(csv.ok()).toBe(true)
  expect((await csv.text()).split('\r\n')[0]!.split(',')).toHaveLength(22)
  expect(writes).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath(`data-query-${width}.png`), fullPage: true })
})
