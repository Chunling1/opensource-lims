import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('equipment toolbar progressively fits actions while resizing', async ({ page }, info) => {
  await page.goto('/#/quality/equipment/ledger')
  const toolbar = page.getByRole('group', { name: '设备台账工具栏', exact: true })
  await expect(page.getByRole('table', { name: '设备台账列表', exact: true }).locator('tbody tr')).toHaveCount(10)
  const counts = new Set<number>()
  for (const width of [1920, 1440, 1280, 1200, 1100, 1024, 900, 768, 600, 500, 390, 1920]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    const geometry = await toolbar.evaluate(element => {
      const buttons = [...element.querySelectorAll<HTMLButtonElement>('button')].filter(button => button.getClientRects().length && !button.closest('.dropdown-menu'))
      const boxes = buttons.map(button => button.getBoundingClientRect())
      const parent = element.parentElement!.getBoundingClientRect()
      return { count: buttons.length, tops: boxes.map(box => box.top), fits: boxes.every(box => box.left >= parent.left && box.right <= parent.right), overflow: document.documentElement.scrollWidth > innerWidth + 1 }
    })
    counts.add(geometry.count)
    expect(geometry.fits).toBe(true); expect(geometry.overflow).toBe(false)
    expect(Math.max(...geometry.tops) - Math.min(...geometry.tops)).toBeLessThan(2)
    if ([1920, 1100, 390].includes(width)) await page.locator('.card-header').first().screenshot({ path: info.outputPath(`toolbar-${width}.png`) })
  }
  expect(counts.size).toBeGreaterThanOrEqual(3)
  await expect(toolbar.getByRole('button', { name: '设备台账更多操作', exact: true })).toHaveCount(0)
})

for (const width of [1920, 1440, 1024, 390]) test(`equipment ledger layout and queries at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/equipment/ledger')
  const table = page.getByRole('table', { name: '设备台账列表', exact: true })
  const query = page.getByRole('form', { name: '设备台账查询', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  const toolbar = page.getByRole('group', { name: '设备台账工具栏', exact: true })
  await expect(toolbar.getByRole('button', { name: '新增', exact: true })).toBeVisible()
  const secondary = ['批量修改', '分组关联', '下载模板', '导入']
  const moreActions = toolbar.getByRole('button', { name: '设备台账更多操作', exact: true })
  if (await moreActions.isVisible()) {
    await moreActions.click()
    for (const name of secondary) await expect(toolbar.getByRole('button', { name, exact: true })).toBeVisible()
    await moreActions.click()
  } else {
    for (const name of secondary) await expect(toolbar.getByRole('button', { name, exact: true })).toBeVisible()
  }
  await expect(table.getByRole('columnheader')).toHaveCount(9)
  await expect(query.getByLabel('仪器出厂号', { exact: true })).toBeHidden()
  await query.screenshot({ path: info.outputPath(`query-${width}.png`) })
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table).toContainText('DEMO-011')
  await page.getByLabel('设备台账每页条数', { exact: true }).selectOption('50')
  await expect(table.locator('tbody tr')).toHaveCount(24)
  await query.getByRole('button', { name: /更多筛选/ }).click()
  await expect(query.getByLabel('日期类型').locator('option')).toHaveText(['不限', '最近检定/测试日期', '计划检定/测试日期', '实际检定/测试日期', '购入日期'])
  await expect(query.getByLabel('日期类型')).toHaveValue('')
  await expect(query.getByLabel('日期范围')).toBeDisabled()
  await expect(query.getByRole('button', { name: /更多筛选/ })).not.toContainText('（')
  await query.getByLabel('日期类型').selectOption('plannedTestDate')
  await expect(query.getByLabel('日期范围')).toBeEnabled()
  await query.getByRole('button', { name: '查询', exact: true }).click()
  const [from, to] = (await query.getByLabel('日期范围').inputValue()).split(' 至 ')
  const all = await (await page.request.post('/api/registration/quality/equipment/ledger/query', { headers: { 'X-Demo-Actor': 'admin' }, data: { pageSize: 50 } })).json()
  const expectedCodes = all.items.filter((row: { plannedTestDate: string }) => row.plannedTestDate >= from! && row.plannedTestDate <= to!).map((row: { code: string }) => row.code)
  await expect(table.locator('tbody tr')).toHaveCount(expectedCodes.length)
  for (const code of expectedCodes) await expect(table.getByRole('cell', { name: code, exact: true })).toBeVisible()
  await query.getByLabel('日期类型').selectOption('')
  await query.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(24)
  await page.reload()
  await expect(table.locator('tbody tr')).toHaveCount(24)
  await query.getByRole('button', { name: /更多筛选/ }).click()
  await expect(query.getByLabel('日期类型')).toHaveValue('')
  await expect(query.getByLabel('日期范围')).toBeDisabled()
  await expect(query.getByLabel('未关联部门设备', { exact: true })).toBeVisible()
  await query.getByLabel('未关联部门设备', { exact: true }).check()
  await query.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  for (const code of ['DEMO-022', 'DEMO-023', 'DEMO-024']) await expect(table).toContainText(code)
  await query.getByLabel('未关联部门设备', { exact: true }).uncheck()
  await query.getByLabel('档案号', { exact: true }).fill('DEMO-001')
  await query.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await table.getByRole('cell', { name: 'DEMO-001', exact: true }).click()
  await expect(table.getByRole('checkbox', { checked: true })).toHaveCount(0)
  await table.getByRole('button', { name: 'DEMO-001 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['查看', '编辑', '删除'])
  await expect(page.getByRole('menuitem', { name: '查看', exact: true })).toBeEnabled()
  await expect(page.getByRole('menuitem', { name: '编辑', exact: true })).toBeEnabled()
  await expect(page.getByRole('menuitem', { name: '删除', exact: true })).toBeEnabled()
  await query.getByLabel('档案号', { exact: true }).click()
  if (!await toolbar.getByRole('button', { name: '显示', exact: true }).isVisible()) await moreActions.click()
  await page.getByRole('button', { name: '显示', exact: true }).click()
  const columns = page.getByRole('dialog', { name: '设备台账显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(23)
  await columns.getByRole('checkbox', { name: '购入价格', exact: true }).check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await expect(columns).toBeHidden()
  await expect(table.getByRole('columnheader')).toHaveCount(10)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath(`ledger-${width}.png`) })
  await table.getByRole('checkbox', { name: '选择设备台账 DEMO-001', exact: true }).check()
  const exportButton = toolbar.getByRole('button', { name: '导出', exact: true })
  if (await exportButton.isVisible()) await exportButton.click(); else await moreActions.click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出已选记录（1）', exact: true }).click()
  const file = await download, csv = await readFile((await file.path())!, 'utf8')
  expect(csv).toContain('DEMO-001'); expect(csv).not.toContain('DEMO-002'); expect(csv).toContain('验收单')
  await page.reload()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(query.getByLabel('档案号', { exact: true })).toHaveValue('DEMO-001')
  await expect(query.getByRole('button', { name: /更多筛选/ })).toHaveAttribute('aria-expanded', 'false')
})
