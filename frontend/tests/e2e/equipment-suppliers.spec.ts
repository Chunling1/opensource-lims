test('supplier conflict reload and read-only access', async ({ page }) => {
  await page.request.post('/api/registration/session'); await page.goto('/#/quality/equipment/suppliers')
  const table = page.getByRole('table', { name: '供应商列表', exact: true })
  await expect(table).toBeVisible(); await action(table, '编辑')
  const dialog = page.getByRole('dialog', { name: '编辑设备服务商', exact: true })
  await expect(dialog.getByLabel('单位编码')).toHaveValue('GYS-001')
  const base = '/api/registration/quality/equipment/suppliers', headers = { 'X-Demo-Actor': 'admin' }
  const detail = await (await page.request.post(`${base}/detail`, { headers, data: { kind: 'suppliers', id: 'equipment-supplier-1' } })).json()
  expect((await page.request.post(`${base}/save`, { headers, data: { ...detail, kind: 'suppliers', contact: '并发修改' } })).ok()).toBe(true)
  await dialog.getByRole('button', { name: '保存', exact: true }).click(); await expect(dialog).toContainText('记录已更新')
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '重新加载', exact: true }).click(); await expect(dialog.getByLabel('联系人')).toHaveValue('并发修改')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.evaluate(() => localStorage.setItem('lims.identity.v1', 'reviewer')); await page.reload()
  await expect(table).toBeVisible(); await expect(page.getByRole('button', { name: /新增供应商|新增评价/ })).toHaveCount(0)
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem', { name: '查看', exact: true })).toBeVisible()
  for (const name of ['编辑', '删除', '新增评价']) await expect(page.getByRole('menuitem', { name, exact: true })).toBeDisabled()
})
