import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { emptyEquipment } from '../../src/types/quality/equipmentForm'
import { openToolbarExport, toolbarButton } from './helpers/toolbar'

const headers = { 'X-Demo-Actor': 'admin' }, base = '/api/registration/quality/equipment/loans', label = '领用与归还记录'
for (const width of [1440, 390]) test(`loan history filters, columns and exports at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.request.post('/api/registration/session')
  const ids: string[] = []
  for (let i = 0; i < 12; i++) {
    const response = await page.request.post('/api/registration/quality/equipment/ledger/save', { headers, data: { ...emptyEquipment(), code: `HISTORY-${String(i).padStart(2, '0')}`, name: '记录测试设备', departmentId: 'lab', keeper: '设备保管员' } })
    expect(response.ok()).toBe(true); ids.push((await response.json()).id)
  }
  const context = await (await page.request.post(`${base}/context`, { headers, data: { mode: 'borrow', ids } })).json()
  const targets = (items: { id: string; version: number; equipmentVersion: number }[]) => items.map(({ id, version, equipmentVersion }) => ({ id, version, equipmentVersion }))
  expect((await page.request.post(`${base}/borrow`, { headers, data: { records: targets(context.items), borrower: '记录领用人', borrowedStatus: '正常', date: '2026-09-07', notes: '领用历史备注' } })).ok()).toBe(true)
  const records = await (await page.request.post(`${base}/query`, { headers, data: { kind: 'records', code: 'HISTORY-', pageSize: 50 } })).json()
  expect((await page.request.post(`${base}/return`, { headers, data: { records: targets(records.items.filter((row: { code: string }) => row.code.endsWith('00'))), returner: '记录归还人', date: '2026-10-07', returnedStatus: '异常', notes: '归还历史备注' } })).ok()).toBe(true)

  await page.goto('/#/quality/equipment/loan-records?field=code&value=HISTORY-&from=2026-09-07&to=2026-10-07')
  const form = page.getByRole('form', { name: `${label}查询`, exact: true }), table = page.getByRole('table', { name: `${label}列表`, exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(table.getByRole('columnheader')).toHaveCount(10)
  await expect(table.getByRole('button', { name: /更多操作/ })).toHaveCount(0)
  await expect(form.getByLabel('日期范围')).toBeDisabled()
  await expect(form.getByLabel('查询内容')).toBeVisible()
  await expect(form.getByLabel('包含')).toHaveValue('HISTORY-')
  await expect(page.getByRole('button', { name: '新增', exact: true })).toHaveCount(0)
  const download = page.waitForEvent('download')
  await openToolbarExport(page, label); await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const csv = await readFile((await (await download).path())!, 'utf8')
  expect(csv).toContain('HISTORY-11'); expect(csv).toContain('归还历史备注'); expect(csv).toContain('归还人'); expect(csv).toContain('记录归还人'); expect(csv).toContain('归还操作人')
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await form.getByLabel('日期类型').selectOption('returnedAt')
  await expect(form.getByLabel('日期范围')).toBeEnabled()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText('记录归还人'); await expect(table).toContainText('HISTORY-00'); await expect(table).toContainText('异常')
  await table.getByRole('checkbox', { name: '选择领用与归还记录 HISTORY-00', exact: true }).check()
  const selectedDownload = page.waitForEvent('download')
  await openToolbarExport(page, label); await page.getByRole('button', { name: /导出已选记录/ }).click()
  const selectedCsv = await readFile((await (await selectedDownload).path())!, 'utf8')
  expect(selectedCsv).toContain('HISTORY-00'); expect(selectedCsv).not.toContain('HISTORY-01')
  await form.getByLabel('日期类型').selectOption('borrowedAt')
  await form.getByLabel('日期范围').click()
  await page.locator('.flatpickr-calendar.open .flatpickr-monthDropdown-months').selectOption('8')
  const day = page.locator('.flatpickr-calendar.open .flatpickr-day[aria-label="2026-09-07"]:not(.prevMonthDay):not(.nextMonthDay)')
  await day.click(); await day.click()
  await form.getByLabel('查询内容').selectOption('borrowedStatus'); await form.getByLabel('包含').fill('正常')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await form.getByLabel('查询内容').selectOption('returnedStatus'); await form.getByLabel('包含').fill('异常')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await (await toolbarButton(page, label, '显示')).click()
  const columns = page.getByRole('dialog', { name: `${label}显示列`, exact: true })
  await columns.getByLabel('归还备注', { exact: true }).check(); await columns.getByRole('button', { name: '完成', exact: true }).click()
  await expect(columns).toBeHidden(); await expect(table).toContainText('归还历史备注')
  await page.reload(); await expect(table).toContainText('归还历史备注')
  await page.screenshot({ path: info.outputPath(`history-${width}.png`) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(form.getByLabel('包含')).toHaveValue('异常')
  await form.getByLabel('日期类型').selectOption('')
  await form.getByLabel('查询内容').selectOption('')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
})
