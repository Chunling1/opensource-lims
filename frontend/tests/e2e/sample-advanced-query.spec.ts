const root = '/#/commissions/query'
test('sample advanced query is independent, submits every field and retains navigation and export conditions', async ({ page }, testInfo) => {
  const requests: Record<string, unknown>[] = []
  page.on('request', r => { if (r.url().endsWith('/samples/query')) requests.push(r.postDataJSON()) })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${root}?scope=all&sSearchField=manufacturer&sContains=NoMatch&sDataStatus=评审完成&sSampleType=英文报告样品`)
  const form = page.getByRole('form', { name: '样品查询', exact: true })
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  const region = page.getByRole('region', { name: '样品列表区域', exact: true })
  const dialog = page.getByRole('dialog', { name: '样品高级查询', exact: true })
  const open = () => form.getByRole('button', { name: '高级', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  const before = requests.length
  await open()
  await expect(dialog.getByRole('textbox')).toHaveCount(sampleAdvancedFields.length + 1 + sampleWorkflowDateFields.length)
  for (const { label } of sampleAdvancedFields) await expect(dialog.getByLabel(label, { exact: true })).toBeVisible()
  for (const label of ['结构部位', '施工单位']) await expect(dialog.getByLabel(label, { exact: true })).toHaveCount(0)
  await expect(dialog.getByLabel('委托日期', { exact: true })).toBeDisabled()
  await expect(dialog.getByLabel('数据状态')).toHaveValue('')
  await expect(dialog.getByLabel('样品类型')).toHaveValue('')
  await dialog.getByLabel('样品编号', { exact: true }).fill('Unsubmitted')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  expect(requests).toHaveLength(before)
  await open()
  await expect(dialog.getByLabel('样品编号', { exact: true })).toHaveValue('')
  await dialog.getByLabel('样品编号', { exact: true }).fill('sp2026090001')
  await dialog.getByLabel('报告编号', { exact: true }).fill('bg2026090001')
  await dialog.getByLabel('委托编号', { exact: true }).fill('wt202609001')
  await dialog.screenshot({ path: testInfo.outputPath('sample-advanced-desktop.png') })
  await dialog.getByLabel('委托编号', { exact: true }).press('Enter')
  await expect(table).toContainText('SP2026090001')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  expect(requests.at(-1)).toMatchObject({ workspace: 'query', sampleAdvanced: { code: 'sp2026090001', reportCode: 'bg2026090001', commissionCode: 'wt202609001' } })
  for (const key of ['contains', 'searchField', 'dataStatus', 'sampleType', 'commissionFrom', 'commissionTo']) expect(requests.at(-1)).not.toHaveProperty(key)
  await expect(form.getByLabel('包含')).toHaveValue('NoMatch')
  await region.getByRole('button', { name: '导出', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await region.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const csv = await readFile((await (await downloading).path())!, 'utf8')
  expect(csv.split('\r\n')).toHaveLength(2)
  expect(csv).toContain('SP2026090001')
  await table.getByRole('link', { name: 'SP2026090001', exact: true }).click()
  await page.getByRole('link', { name: '返回委托查询', exact: true }).click()
  await page.reload()
  await expect(table).toContainText('SP2026090001')
  await open()
  await expect(dialog.getByLabel('样品编号', { exact: true })).toHaveValue('sp2026090001')
  for (const { key, label } of sampleAdvancedFields) await dialog.getByLabel(label, { exact: true }).fill(`value-${key}`)
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  expect(requests.at(-1)).toMatchObject({ sampleAdvanced: Object.fromEntries(sampleAdvancedFields.map(({ key }) => [key, `value-${key}`])) })
  await page.reload()
  await open()
  for (const { key, label } of sampleAdvancedFields) {
    await expect(dialog.getByLabel(label, { exact: true })).toHaveValue(`value-${key}`)
    await dialog.getByLabel(label, { exact: true }).fill('')
  }
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await region.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page).toHaveURL(/sPage=2/)
  expect(requests.at(-1)).toMatchObject({ sampleAdvanced: {}, page: 2 })
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  expect(requests.at(-1)).not.toHaveProperty('sampleAdvanced')
})

test('sample advanced dates, state, type and commission scope remain backend constraints with retry', async ({ page }) => {
  await page.goto(`${root}?current=demo-wt-1`)
  const form = page.getByRole('form', { name: '样品查询', exact: true })
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  const dialog = page.getByRole('dialog', { name: '样品高级查询', exact: true })
  const open = () => form.getByRole('button', { name: '高级', exact: true }).click()
  await open()
  await dialog.getByLabel('样品编号', { exact: true }).fill('SP2026090002')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  await open()
  await dialog.getByLabel('样品编号', { exact: true }).fill('SP2026090001')
  await dialog.getByLabel('数据状态').selectOption('评审完成')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  await open()
  await dialog.getByLabel('数据状态').selectOption('委托登记中')
  await dialog.getByLabel('样品类型').selectOption('原始样品')
  await dialog.getByLabel('按委托日期查询').check()
  const dates = dialog.getByLabel('委托日期', { exact: true })
  await dates.click()
  await pickRangeDay(page, '2000-01-01')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('请选择结束日期')
  await dates.click(); await pickRangeDay(page, '2000-12-31')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  await open()
  const range = clientYearRange()
  await pickDateRange(page, dates, range.to, range.to)
  let fail = true
  await page.route('**/samples/query', async route => {
    if (fail) { fail = false; await route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '样品高级查询暂时失败' } } }); return }
    await route.continue()
  })
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByText('样品高级查询暂时失败', { exact: true })).toBeVisible()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: /重试/ }).click()
  await expect(table).toContainText('SP2026090001')
  await open()
  await expect(dates).toHaveValue(`${range.to} 至 ${range.to}`)
  await expect(dialog.getByLabel('数据状态')).toHaveValue('委托登记中')
  await expect(dialog.getByLabel('样品类型')).toHaveValue('原始样品')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
})

test('sample advanced modal scrolls on phones and keeps date picker and footer within the viewport', async ({ page }, testInfo) => {
  await page.goto(`${root}?scope=all`)
  await expect(page.getByRole('table', { name: '样品列表', exact: true }).locator('tbody tr')).toHaveCount(10)
  const form = page.getByRole('form', { name: '样品查询', exact: true })
  const dialog = page.getByRole('dialog', { name: '样品高级查询', exact: true })
  for (const [width, theme] of [[390, 'dark'], [320, 'light']] as const) {
    await page.setViewportSize({ width, height: 844 })
    await page.evaluate(theme => document.documentElement.setAttribute('data-bs-theme', theme), theme)
    await form.getByRole('button', { name: '高级', exact: true }).click()
    await dialog.getByLabel('按委托日期查询').check()
    await dialog.getByLabel('委托日期', { exact: true }).click()
    const calendar = page.locator('.flatpickr-calendar.open')
    await expect(calendar).toBeVisible()
    await expect.poll(async () => {
      const box = await calendar.boundingBox()
      return !!box && box.y >= 0 && box.y + box.height <= 844 && box.x >= 0 && box.x + box.width <= width + 1
    }).toBe(true)
    const footer = await dialog.getByRole('button', { name: '查询', exact: true }).boundingBox()
    expect(footer!.y + footer!.height).toBeLessThanOrEqual(844)
    await page.screenshot({ animations: 'disabled', path: testInfo.outputPath(`sample-advanced-${width}-${theme}.png`) })
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
})


test('workflow ranges and conclusion submit independently, restore, cancel and clear without using basic conditions', async ({ page }, testInfo) => {
  const requests: Record<string, any>[] = []
  page.on('request', r => { if (r.url().endsWith('/samples/query')) requests.push(r.postDataJSON()) })
  await page.goto(`${root}?scope=all`)
  const form = page.getByRole('form', { name: '样品查询', exact: true })
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  const dialog = page.getByRole('dialog', { name: '样品高级查询', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  const open = () => form.getByRole('button', { name: '高级', exact: true }).click()
  await open()
  await expect(dialog.getByLabel('结论').locator('option')).toHaveText(['全部', '合格', '不合格'])
  await expect(dialog.getByLabel('结论')).toHaveValue('')
  const range = clientYearRange()
  for (const { label } of sampleWorkflowDateFields) {
    await expect(dialog.getByLabel(label, { exact: true })).toBeDisabled()
    await expect(dialog.getByLabel(label, { exact: true })).toHaveValue(`${range.from} 至 ${range.to}`)
    await dialog.getByLabel(`按${label}查询`, { exact: true }).check()
  }
  await dialog.getByLabel('结论').selectOption('qualified')
  const dates = dialog.getByLabel('检测开始日期', { exact: true })
  await dates.click(); await pickRangeDay(page, '2024-03-01')
  // Dismiss the calendar before submitting an incomplete range.
  await dialog.getByRole('heading', { name: '样品高级查询', exact: true }).click()
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('请选择结束日期')
  await dates.click(); await pickRangeDay(page, '2024-03-02')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  const expectedDates = Object.fromEntries(sampleWorkflowDateFields.map(({ key }) => [key, key === 'testStartDate' ? { from: '2024-03-01', to: '2024-03-02' } : range]))
  expect(requests.at(-1)).toMatchObject({ sampleWorkflow: { dates: expectedDates, conclusion: 'qualified' } })
  expect(requests.at(-1)).not.toHaveProperty('commissionFrom')
  await page.reload()
  await open()
  await expect(dialog.getByLabel('结论')).toHaveValue('qualified')
  for (const { label } of sampleWorkflowDateFields) await expect(dialog.getByLabel(`按${label}查询`, { exact: true })).toBeChecked()
  await expect(dates).toHaveValue('2024-03-01 至 2024-03-02')
  await dialog.getByLabel('结论').selectOption('unqualified')
  await dialog.getByLabel('按检测开始日期查询').uncheck()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await open()
  await expect(dialog.getByLabel('结论')).toHaveValue('qualified')
  await expect(dialog.getByLabel('按检测开始日期查询')).toBeChecked()
  await dialog.getByLabel('按制作日期查询').scrollIntoViewIfNeeded()
  await dialog.screenshot({ path: testInfo.outputPath('workflow-dates-desktop.png') })
  for (const { label } of sampleWorkflowDateFields) await dialog.getByLabel(`按${label}查询`, { exact: true }).uncheck()
  await dialog.getByLabel('结论').selectOption('')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  expect(requests.at(-1)).not.toHaveProperty('sampleWorkflow')
  await open()
  await dialog.getByLabel('结论').selectOption('unqualified')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  expect(requests.at(-1)).toMatchObject({ sampleWorkflow: { conclusion: 'unqualified' } })
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  expect(requests.at(-1)).not.toHaveProperty('sampleWorkflow')
})
