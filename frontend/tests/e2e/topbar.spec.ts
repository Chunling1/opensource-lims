import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

const originalTopbar = readFileSync('docs/HTML/Master/src/partials/topbar.html', 'utf8')
test('template user menus and topbar actions work across theme and layout changes', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/#/dashboard')
  const avatar = page.locator('#page-header-user-dropdown img')
  await expect(avatar).toBeVisible()
  await expect.poll(() => avatar.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true)
  const comparison = await page.evaluate(source => {
    const original = new DOMParser().parseFromString(source, 'text/html')
    const selectors = ['.topbar-user', '#page-header-user-dropdown', '#page-header-user-dropdown img', '#page-header-user-dropdown > span', '#page-header-user-dropdown > span > span', '.user-name-text', '.user-name-sub-text', '.topbar-user .dropdown-menu', '.topbar-user .dropdown-header', '.topbar-user .dropdown-divider']
    const classes = (element: Element | null) => [...element!.classList].sort()
    return selectors.map(selector => ({ selector, original: classes(original.querySelector(selector)), current: classes(document.querySelector(selector)) }))
  }, originalTopbar)
  for (const item of comparison) expect(item.current, item.selector).toEqual(item.original)
  const user = page.getByRole('button', { name: '用户菜单', exact: true })
  const menu = page.locator('.topbar-user .dropdown-menu')
  await user.click()
  await expect(menu).toBeVisible()
  await expect(menu.getByRole('link', { name: '待办样品', exact: true })).toHaveCount(0)
  await expect(menu.getByRole('link', { name: '切换演示身份' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('user-menu-light.png') })
  await menu.getByRole('button', { name: '个人资料' }).click()
  await expect(page.locator('.modal.show')).toContainText('当前使用模拟身份')
  await page.getByRole('button', { name: '关闭弹窗' }).click()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await user.click(); await page.keyboard.press('Escape'); await expect(menu).toBeHidden()
  await user.click(); await menu.getByRole('button', { name: '主题 设置', exact: true }).click()
  await expect(page.locator('#theme-settings-offcanvas')).toHaveClass(/\bshow\b/)
  await page.getByTestId('theme-user').check()
  await page.getByRole('button', { name: '关闭主题设置' }).click()
  await expect(user).toBeHidden()
  await page.getByRole('button', { name: '侧栏用户菜单' }).click()
  await expect(page.locator('.sidebar-user .dropdown-menu')).toBeVisible()
  await expect(page.locator('.sidebar-user .dropdown-menu').getByRole('link', { name: '待办样品', exact: true })).toHaveCount(0)
  await page.locator('.sidebar-user .dropdown-menu').getByRole('button', { name: '使用帮助' }).click()
  await expect(page.locator('.modal.show')).toContainText('样品处理流程')
  await page.getByRole('button', { name: '关闭弹窗' }).click()
  await page.getByRole('button', { name: '打开主题设置' }).click()
  await page.getByTestId('theme-user').uncheck()
  await page.getByRole('button', { name: '关闭主题设置' }).click()
  await page.getByRole('button', { name: '切换明暗模式' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-bs-theme', 'dark')
  await user.click()
  await page.screenshot({ path: testInfo.outputPath('user-menu-dark.png') })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '进入全屏' }).click()
  await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(true)
  await page.getByRole('button', { name: '退出全屏' }).click()
  await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(false)
  await page.getByRole('button', { name: '快捷应用', exact: true }).click()
  await page.locator('[aria-labelledby="page-header-apps-dropdown"]').getByRole('link', { name: '样品入库', exact: true }).click()
  await expect(page).toHaveURL(/#\/samples\/inbound$/)
  await page.getByRole('button', { name: '通知消息', exact: true }).click()
  await expect(page.locator('#notificationDropdown .notification-item')).toHaveCount(3)
  await page.screenshot({ path: testInfo.outputPath('notifications-dark.png') })
  const notificationMenu = page.locator('#notificationDropdown .dropdown-menu')
  await expect(notificationMenu.getByRole('link')).toHaveCount(0)
  for (const message of await notificationMenu.locator('.notification-item').all()) {
    await message.click()
    await expect(page).toHaveURL(/#\/samples\/inbound$/)
    await expect(notificationMenu).toBeVisible()
  }
  await page.keyboard.press('Escape')
  await expect(page.locator('.dropdown-menu.show')).toHaveCount(0)
  for (const layout of ['horizontal', 'twocolumn', 'semibox', 'vertical']) {
    await page.getByRole('button', { name: '打开主题设置' }).click()
    await page.getByTestId(`theme-label-layout-${layout}`).click()
    await page.getByRole('button', { name: '关闭主题设置' }).click()
    await user.click(); await expect(menu).toBeVisible()
    await page.keyboard.press('Escape'); await expect(menu).toBeHidden()
  }
  expect(errors).toEqual([])
})

test('mobile search and content-only notifications fit the viewport without database reads', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/dashboard')
  await page.getByRole('button', { name: '打开手机搜索' }).click()
  await page.getByRole('searchbox', { name: '手机样品搜索' }).fill('地表水')
  await page.getByRole('button', { name: '搜索样品', exact: true }).click()
  await expect(page).toHaveURL(/#\/commissions\/query\?scope=all&sKeyword=/)
  expect(decodeURIComponent(page.url())).toContain('sKeyword=地表水')
  await expect(page.locator('.dropdown-menu.show')).toHaveCount(0)
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await page.getByRole('button', { name: '用户菜单', exact: true }).click()
    const bounds = await page.locator('.topbar-user .dropdown-menu').boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width + 1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`user-menu-mobile-${width}.png`) })
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '通知消息', exact: true }).click()
    const notifications = page.locator('#notificationDropdown .dropdown-menu')
    const notificationBounds = await notifications.boundingBox()
    expect(notificationBounds!.x).toBeGreaterThanOrEqual(0)
    expect(notificationBounds!.x + notificationBounds!.width).toBeLessThanOrEqual(width + 1)
    expect(notificationBounds!.y + notificationBounds!.height).toBeLessThanOrEqual(844)
    await expect(notifications.getByRole('link')).toHaveCount(0)
    for (const paragraph of await notifications.locator('.notification-item p').all()) {
      expect(await paragraph.evaluate(el => el.scrollWidth <= el.clientWidth && el.scrollHeight <= el.clientHeight)).toBe(true)
    }
    await page.screenshot({ path: testInfo.outputPath(`notifications-mobile-${width}.png`) })
    await page.keyboard.press('Escape')
  }
  await page.evaluate(() => { const original = IDBObjectStore.prototype.get; (window as unknown as { restoreRead: () => void }).restoreRead = () => { IDBObjectStore.prototype.get = original }; IDBObjectStore.prototype.get = function () { throw new Error('数据库读取失败') } })
  await page.getByRole('button', { name: '通知消息', exact: true }).click()
  await expect(page.locator('#notificationDropdown [role="alert"]')).toHaveCount(0)
  await expect(page.locator('#notificationDropdown .notification-item')).toHaveCount(3)
  await expect(page.locator('#notificationDropdown')).toContainText('委托资料和样品信息已保存')
  await page.evaluate(() => (window as unknown as { restoreRead: () => void }).restoreRead())
})

test('notification center shows the same messages and does not navigate when clicked', async ({ page }, info) => {
  await page.goto('/#/notifications')
  const messages = page.getByRole('region', { name: '演示通知', exact: true })
  await expect(messages.locator('.notification-item')).toHaveCount(3)
  await expect(page.locator('main').getByRole('link')).toHaveCount(0)
  await page.getByRole('button', { name: '通知消息', exact: true }).click()
  expect(await messages.locator('p').allTextContents()).toEqual(await page.locator('#notificationDropdown .notification-item p').allTextContents())
  await page.keyboard.press('Escape')
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    for (const message of await messages.locator('.notification-item').all()) {
      await message.click()
      await expect(page).toHaveURL(/#\/notifications$/)
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`notification-center-${width}.png`), fullPage: true })
  }
})

