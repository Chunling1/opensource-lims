  await drawer.getByRole('checkbox', { name: '选择 常规检测方案', exact: true }).click()
  await expect(page.locator('#inbound-plans')).toHaveText('检测方案')
  const beforeHide = queries.length
  await drawer.getByRole('button', { name: '仅显示有样品', exact: true }).click()
