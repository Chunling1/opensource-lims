import { test, expect } from '@playwright/test'

test('pickup validates personnel, retains failed input and writes once after confirmation', async ({ page }, info) => {
  await page.goto('/#/testing/sample-pickup')
  const table = page.getByRole('table', { name: '检测样品领取列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await table.locator('tbody input[type=checkbox]').first().check()
  await table.getByRole('button', { name: 'SP2026090020 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '领取样品', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '领取样品', exact: true })
  await expect(modal.getByLabel('领样员工号')).toHaveValue('admin')
  await expect(modal.getByLabel('领样员姓名')).toHaveValue('演示用户')
  const today = await page.evaluate(() => { const date = new Date(); return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}` })
  await expect(modal.getByLabel('领样时间')).toHaveValue(today)
  await modal.getByLabel('领样员工号').fill('business')
  await modal.getByLabel('领样员姓名').fill('不匹配')
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.locator('#pickup-name-error')).toContainText('不匹配')
  await expect(modal.getByLabel('领样员工号')).toBeFocused()
  await expect(modal).not.toContainText('诊断编号')
  await modal.getByLabel('领样员姓名').fill('张受理')
  await modal.getByLabel('领样时间').fill('2026-09-26')
  await modal.getByLabel('领样时间').press('Tab')
  await page.route('**/samples/demo-yp-20/pickup-action', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '领样服务暂不可用' } } }), { times: 1 })
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('领样服务暂不可用')
  await expect(modal.getByLabel('领样时间')).toHaveValue('2026-09-26')
  await expect(modal.getByLabel('领样员姓名')).toHaveValue('张受理')
  await page.screenshot({ path: info.outputPath('pickup-modal-desktop.png') })
  let release = () => {}
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/samples/demo-yp-20/pickup-action', async route => { const response = await route.fetch(); await gate; await route.fulfill({ response }) }, { times: 1 })
  const response = page.waitForResponse(response => response.url().endsWith('/samples/demo-yp-20/pickup-action'))
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('button', { name: '正在提交…', exact: true })).toBeDisabled()
  await expect(modal.getByRole('button', { name: '取消', exact: true })).toBeDisabled()
  await expect(modal.getByLabel('领样员工号')).toBeDisabled()
  await page.keyboard.press('Escape'); await expect(modal).toBeVisible()
  release()
  expect(await (await response).json()).toMatchObject({ dataStatus: '样品已领取', flowInfo: { collection: { account: 'business', name: '张受理', date: '2026-09-26', recordedBy: { id: 'admin' } } } })
  await expect(modal).toBeHidden()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(table.locator('tbody input:checked')).toHaveCount(0)
  const form = page.getByRole('form', { name: '检测样品领取条件', exact: true })
  await form.getByLabel('数据状态').selectOption('样品已领取')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await table.getByRole('button', { name: 'SP2026090020 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '领取样品', exact: true })).toBeDisabled()
})

test('pickup conflicts require refresh and the dialog fits mobile dark mode', async ({ page }, info) => {
  await page.goto('/#/testing/sample-pickup')
  const table = page.getByRole('table', { name: '检测样品领取列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await table.getByRole('button', { name: 'SP2026090020 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '领取样品', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '领取样品', exact: true })
  await expect(modal).toBeFocused()
  const account = await modal.getByLabel('领样员工号').boundingBox(), name = await modal.getByLabel('领样员姓名').boundingBox()
  expect(name!.y).toBeGreaterThan(account!.y + account!.height)
  await page.screenshot({ path: info.outputPath('pickup-modal-mobile-dark.png') })
  await page.keyboard.press('Escape'); await expect(modal).toBeHidden()
  await table.getByRole('button', { name: 'SP2026090020 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '领取样品', exact: true }).click()
  const response = await page.request.post('/api/registration/samples/demo-yp-20/pickup-action', { headers: { 'X-Demo-Actor': 'admin' }, data: { version: 1, receipt: { account: 'analyst', name: '李检测', date: '2026-09-26' } } })
  expect(response.ok()).toBe(true)
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('记录已更新')
  await expect(modal.getByRole('button', { name: '确认', exact: true })).toBeDisabled()
  await expect(modal.getByLabel('领样员工号')).toHaveValue('admin')
  await modal.getByRole('button', { name: '刷新列表', exact: true }).click()
  await expect(modal).toBeHidden()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
