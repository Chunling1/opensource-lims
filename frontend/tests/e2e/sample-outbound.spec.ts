import { test, expect } from '@playwright/test'

test('outbound uses its own queue, filter counts and menus while retaining shared table behavior', async ({ page }, testInfo) => {
  const queries: Record<string, unknown>[] = []
  page.on('request', request => { if (request.url().endsWith('/samples/outbound/query')) queries.push(request.postDataJSON()) })
  await page.goto('/#/samples/outbound')
  const table = page.getByRole('table', { name: '样品出库列表', exact: true })
  const form = page.getByRole('form', { name: '样品出库查询' })
  await expect(table).toContainText('SP2026090019')
  await expect(table.locator('tbody tr')).toHaveCount(4)
  await expect(form.getByLabel('数据状态')).toHaveValue('样品出库中')
  await expect(form.getByLabel('数据状态').locator('option')).toHaveText(['全部', '样品出库中', '样品待领取'])
  await expect(table.getByRole('columnheader', { name: '委托单位', exact: true })).toBeVisible()
  await expect(table.getByRole('columnheader', { name: '委托编号', exact: true })).toHaveCount(0)
  await expect(table.getByRole('columnheader', { name: '合同编号', exact: true })).toHaveCount(0)
  await table.getByRole('button', { name: 'SP2026090019 更多操作', exact: true }).click()
  for (const name of ['出库', '退回委托']) await expect(page.getByRole('menuitem', { name, exact: true })).toBeEnabled()
  await expect(page.getByRole('menuitem', { name: '撤销出库', exact: true })).toBeDisabled()
  await expect(page.getByRole('menuitem', { name: '入库', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.screenshot({ path: testInfo.outputPath('outbound-desktop.png') })
  for (const status of ['样品待领取', '']) {
    await form.getByLabel('数据状态').selectOption(status)
    await form.getByRole('button', { name: '查询', exact: true }).click()
    await expect(table.locator('tbody tr')).toHaveCount(status ? 3 : 10)
    if (status) for (const row of await table.locator('tbody tr').all()) await expect(row).toContainText(status)
  }
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await expect(drawer.getByRole('button', { name: '综合检测部', exact: true })).toBeVisible()
  await expect(drawer.getByRole('button', { name: '空调设备检测部（热湿）', exact: true })).toHaveCount(0)
  const before = queries.length
  await drawer.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true }).click()
  await expect(drawer.getByText('已选 1 项', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: '关闭', exact: true }).click()
  expect(queries).toHaveLength(before)
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  expect(queries.at(-1)).toMatchObject({ plans: { groupIds: [], planIds: ['general-1'] }, page: 1 })
  await table.getByRole('button', { name: 'SP2026090019', exact: true }).click()
  await expect(page.getByRole('heading', { name: '样品详情', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '返回样品出库', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await page.reload()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await expect(form.getByRole('button', { name: '查询', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.main-content')).toHaveCSS('margin-left', '0px')
  await page.screenshot({ path: testInfo.outputPath('outbound-mobile-dark.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
