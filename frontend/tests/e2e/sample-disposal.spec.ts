import { test, expect } from '@playwright/test'
import { pickDateRange } from './helpers/dateRange'

test('disposal query enables the last-year date range only for disposed samples and submits independent filters', async ({ page }, testInfo) => {
  const requests: Record<string, unknown>[] = []
  page.on('request', request => { if (request.url().endsWith('/samples/disposal/query')) requests.push(request.postDataJSON()) })
  await page.goto('/#/samples/disposal')
  const form = page.getByRole('form', { name: '样品处置查询', exact: true }), table = page.getByRole('table', { name: '样品处置列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(form.locator('label.form-label')).toHaveText(['查询内容', '包含', '处置要求', '处置状态', '处置时间'])
  await expect(form.getByLabel('查询内容').locator('option')).toHaveText(['样品编号', '报告编号', '合同编号', '委托编号', '样品/工程名称', '委托单位名称', '委托单位地址', '委托人', '委托人电话', '生产单位', '备注', '邮寄地址'])
  await expect(form.getByLabel('处置要求').locator('option')).toHaveText(['全部', '中心处置', '客户取回'])
  const range = await page.evaluate(() => {
    const date = new Date(), start = new Date(date.getFullYear() - 1, date.getMonth(), 1)
    start.setDate(Math.min(date.getDate(), new Date(date.getFullYear() - 1, date.getMonth() + 1, 0).getDate()))
    return { from: start.toLocaleDateString('sv-SE'), to: date.toLocaleDateString('sv-SE') }
  })
  await expect(form.getByLabel('处置时间')).toHaveValue(`${range.from} 至 ${range.to}`)
  await expect(form.getByLabel('处置时间')).toBeDisabled()
  const disabledBackground = await form.getByLabel('处置时间').evaluate(element => getComputedStyle(element).backgroundColor)
  const disabledColor = await form.getByLabel('处置时间').evaluate(element => getComputedStyle(element).color)
  expect(requests.at(-1)).not.toHaveProperty('from')
  await expect(form.getByRole('button', { name: '检测方案', exact: true })).toHaveCount(0)
  await expect(page.getByRole('group', { name: '样品处置工具栏', exact: true }).getByRole('button', { name: '检测方案', exact: true })).toHaveText('检测方案')
  await form.getByLabel('查询内容').selectOption('customerAddress')
  const inputBox = await form.getByLabel('包含').boundingBox()
  expect(inputBox!.width).toBeGreaterThanOrEqual(200)
  expect(inputBox!.width).toBeLessThanOrEqual((await form.boundingBox())!.width * 0.3)
  const dateBox = await form.getByLabel('处置时间').boundingBox(), searchBox = await form.getByRole('button', { name: '查询', exact: true }).boundingBox()
  expect(Math.abs(dateBox!.y - searchBox!.y)).toBeLessThan(2)
  const formRight = await form.evaluate(element => element.getBoundingClientRect().right - parseFloat(getComputedStyle(element).paddingRight))
  expect(Math.abs(searchBox!.x + searchBox!.width - formRight)).toBeLessThan(2)
  for (const label of ['查询内容', '处置要求', '处置状态']) {
    const spacing = await form.getByLabel(label, { exact: true }).evaluate(element => {
      const select = element as HTMLSelectElement, style = getComputedStyle(select), context = document.createElement('canvas').getContext('2d')!
      context.font = style.font
      return { text: Math.max(...Array.from(select.options, option => context.measureText(option.text).width)), available: select.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight) }
    })
    expect(spacing.text, label).toBeLessThanOrEqual(spacing.available + 1)
  }
  await page.screenshot({ path: testInfo.outputPath('disposal-filters-desktop.png') })
  await form.getByLabel('查询内容').selectOption('code')
  await form.getByLabel('处置状态').selectOption('样品已处置')
  await expect(form.getByLabel('处置时间')).toBeEnabled()
  await expect(form.getByLabel('处置时间')).not.toHaveCSS('background-color', disabledBackground)
  await expect(form.getByLabel('处置时间')).not.toHaveCSS('color', disabledColor)
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(5)
  expect(requests.at(-1)).toMatchObject({ status: '样品已处置', from: range.from, to: range.to })
  await pickDateRange(page, form.getByLabel('处置时间'), `${range.from.slice(0, 8)}01`, `${range.from.slice(0, 8)}02`)
  await form.getByLabel('处置状态').selectOption('样品待处置')
  await expect(form.getByLabel('处置时间')).toBeDisabled()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(5)
  expect(requests.at(-1)).not.toHaveProperty('from'); expect(requests.at(-1)).not.toHaveProperty('to')
  await form.getByLabel('处置状态').selectOption('样品已处置')
  await expect(form.getByLabel('处置时间')).toHaveValue(`${range.from.slice(0, 8)}01 至 ${range.from.slice(0, 8)}02`)
  await form.getByLabel('处置状态').selectOption('')
  await form.getByLabel('查询内容').selectOption('reportCode')
  await form.getByLabel('包含').fill('BG2026090029')
  await form.getByLabel('处置要求').selectOption('中心处置')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  expect(requests.at(-1)).toMatchObject({ searchField: 'reportCode', keyword: 'BG2026090029', requirement: '中心处置', page: 1 })
  expect(requests.at(-1)).not.toHaveProperty('code')
  await page.reload()
  await expect(table).toContainText('SP2026090029')
  await expect(form.getByLabel('查询内容')).toHaveValue('reportCode')
  await expect(form.getByLabel('处置时间')).toBeDisabled()
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('disposal-filters-mobile-dark.png') })
  const darkDisabledBackground = await form.getByLabel('处置时间').evaluate(element => getComputedStyle(element).backgroundColor)
  await form.getByLabel('处置状态').selectOption('样品已处置')
  await expect(form.getByLabel('处置时间')).not.toHaveCSS('background-color', darkDisabledBackground)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('disposal shares storage layout and completes and reverses disposal through the server', async ({ page }, testInfo) => {
  await page.goto('/#/samples/disposal')
  const table = page.getByRole('table', { name: '样品处置列表', exact: true })
  const form = page.getByRole('form', { name: '样品处置查询', exact: true })
  await expect(table).toContainText('SP2026090029')
  await expect(form.getByLabel('处置状态').locator('option')).toHaveText(['全部', '样品待处置', '样品已处置'])
  await expect(table.getByRole('columnheader', { name: '检测方案', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '显示', exact: true }).click()
  const labels = ['样品编号', '委托编号', '检测方案', '样品/工程名称', '留置时间', '客户处置要求', '处置结果', '处置时间', '处置人', '处置状态', '合同编号', '委托单位', '委托单位地址', '委托人', '委托人电话', '生产单位', '备注', '邮寄地址']
  const menu = page.getByRole('dialog', { name: '样品处置显示列', exact: true })
  await expect(menu.getByRole('checkbox')).toHaveCount(18)
  for (const label of labels) await expect(menu.getByRole('checkbox', { name: label, exact: true })).toBeAttached()
  await menu.getByRole('button', { name: '完成', exact: true }).click()
  await expect(menu).toBeHidden()
  await table.getByRole('button', { name: 'SP2026090029 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '出库', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: '样品处置', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '样品处置', exact: true })
  await expect(modal.getByLabel('本样品客户处置要求')).toHaveValue('中心处置')
  await expect(modal.getByLabel('本样品客户处置要求')).toHaveAttribute('readonly', '')
  await expect(modal.getByLabel('处置人', { exact: false })).toHaveValue('演示用户')
  await expect(modal.getByLabel('处置时间')).toHaveValue(await page.evaluate(() => new Date().toLocaleDateString('sv-SE')))
  await modal.getByLabel('处置结果').fill('按客户要求处理')
  await modal.getByLabel('处置人').fill('不存在的人员')
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.locator('#disposal-name-error')).toContainText('未找到该处置人')
  await expect(modal.getByLabel('处置人')).toBeFocused()
  await expect(modal).not.toContainText('诊断编号')
  await expect(modal.getByLabel('处置结果')).toHaveValue('按客户要求处理')
  await modal.getByLabel('处置人').fill('演示用户')
  await page.route('**/samples/demo-yp-29/disposal-action', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '处置服务暂不可用' } } }), { times: 1 })
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('处置服务暂不可用')
  await expect(modal.getByLabel('处置结果')).toHaveValue('按客户要求处理')
  await expect(modal.getByRole('button', { name: '确认', exact: true })).toBeEnabled()
  await expect(modal).toHaveCSS('opacity', '1')
  await page.screenshot({ path: testInfo.outputPath('disposal-dialog-desktop.png') })
  let release = () => {}
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/samples/demo-yp-29/disposal-action', async route => { const response = await route.fetch(); await gate; await route.fulfill({ response }) }, { times: 1 })
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('button', { name: '正在提交…', exact: true })).toBeDisabled()
  await expect(modal.getByRole('button', { name: '取消', exact: true })).toBeDisabled()
  await expect(modal.getByLabel('处置人')).toBeDisabled()
  release()
  await expect(modal).toBeHidden()
  await expect(table.locator('tbody tr').filter({ hasText: 'SP2026090029' })).toContainText('样品已处置')
  await table.getByRole('button', { name: 'SP2026090029 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '样品处置', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '撤销处置', exact: true }).click()
  const undo = page.getByRole('dialog', { name: '撤销处置', exact: true })
  await expect(undo).toContainText('确认对这条样品执行“撤销处置”？')
  await expect(undo.getByRole('button', { name: '确认', exact: true })).toBeEnabled()
  await undo.getByRole('button', { name: '确认', exact: true }).click()
  await expect(undo).toBeHidden()
  await expect(table.locator('tbody tr').filter({ hasText: 'SP2026090029' })).toContainText('样品待处置')
  await expect(table.locator('tbody tr').filter({ hasText: 'SP2026090029' })).not.toContainText('按客户要求处理')
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await drawer.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true }).click()
  await expect(drawer.getByText('已选 1 项', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: '关闭', exact: true }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await table.getByRole('button', { name: 'SP2026090029', exact: true }).click()
  await expect(page.getByRole('heading', { name: '样品详情', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '返回样品处置', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await page.screenshot({ path: testInfo.outputPath('disposal-table-desktop.png') })
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await table.getByRole('button', { name: 'SP2026090029 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '样品处置', exact: true }).click()
  await expect(modal.getByLabel('处置结果')).toHaveValue('')
  await expect(modal).toHaveCSS('opacity', '1')
  await page.screenshot({ path: testInfo.outputPath('disposal-dialog-mobile-dark.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
