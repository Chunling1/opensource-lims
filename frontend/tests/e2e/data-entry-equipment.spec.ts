import { expect, test, type Page } from '@playwright/test'
import { checkOnlyWithControl } from './helpers/table-selection'

async function associatePressure(page: Page) {
  const dialog = page.getByRole('dialog', { name: '选择仪器设备', exact: true })
  await dialog.getByRole('button', { name: '新增关联', exact: true }).click()
  const add = page.getByRole('dialog', { name: '新增关联设备', exact: true })
  await expect(add.getByLabel('查询内容', { exact: true }).locator('option')).toHaveText(['档案号', '设备名称', '生产厂家', '检定单位', '放置单位'])
  await expect(add.getByLabel('所属部门', { exact: true }).locator('option')).toHaveText(['全部', '实验室', '第二实验室'])
  await expect(add.getByLabel('日期条件', { exact: true })).toHaveCount(0)
  await expect(add.getByLabel('设备分组', { exact: true }).locator('option')).toHaveText(['全部'])
  await expect(add.getByRole('columnheader')).toHaveText(['', '档案号', '设备名称', '规格型号', '生产厂家', '仪器出厂号', '周期', '设备状态', '所属部门', '放置地点', '检定单位', '备注'])
  await expect(page.locator('.modal-backdrop')).toHaveCount(1)
  await expect(add.getByLabel('选择 DEMO-001 多参数分析仪', { exact: true })).toBeDisabled()
  await add.getByLabel('包含', { exact: true }).fill('压力')
  await add.getByRole('button', { name: '查询', exact: true }).click()
  await checkOnlyWithControl(add.locator('tbody tr').first(), add.getByLabel('选择 DEMO-002 压力试验机', { exact: true }))
  await add.getByRole('button', { name: '确定', exact: true }).click()
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('status')).toContainText('关联设备已保存')
}

test('equipment transfer, plan association, search, cancel, persistence and readonly display', async ({ page }, info) => {
  await page.goto('/#/testing/data-entry/demo-yp-76')
  const field = page.getByLabel('试验设备', { exact: true })
  await expect(field).toHaveValue('')
  const dialog = page.getByRole('dialog', { name: '选择仪器设备', exact: true })
  const open = async () => { await page.getByRole('button', { name: '选择仪器设备', exact: true }).click(); await expect(dialog).toBeFocused() }
  const left = dialog.getByRole('region', { name: '关联设备', exact: true }), right = dialog.getByRole('region', { name: '已选设备', exact: true })
  await open()
  const initialLeft = await left.boundingBox(), initialRight = await right.boundingBox()
  expect(Math.abs(initialLeft!.width - initialRight!.width)).toBeLessThan(2)
  const query = dialog.getByRole('form', { name: '关联设备查询', exact: true })
  const queryBox = await query.boundingBox()
  expect(queryBox!.height).toBeLessThan(50)
  expect(queryBox!.y + queryBox!.height).toBeLessThanOrEqual(initialLeft!.y)
  expect(Math.abs((await left.locator('thead').boundingBox())!.y - (await right.locator('thead').boundingBox())!.y)).toBeLessThan(2)
  expect((await dialog.getByRole('button', { name: '移入', exact: true }).boundingBox())!.width).toBeLessThan(40)
  await expect(left).not.toContainText('温度记录仪')
  await checkOnlyWithControl(left.locator('tbody tr').first(), left.getByLabel('选择 DEMO-001 多参数分析仪', { exact: true }))
  await left.getByLabel('选择 DEMO-001 多参数分析仪', { exact: true }).uncheck()
  await left.getByLabel('全选当前页关联设备').check()
  await dialog.getByRole('button', { name: '移入', exact: true }).click()
  await expect(right.getByRole('row')).toHaveCount(2)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(field).toHaveValue('')
  await open()
  await associatePressure(page)
  await left.getByLabel('全选当前页关联设备').check()
  await dialog.getByRole('button', { name: '移入', exact: true }).click()
  await expect(dialog.locator('.modal-footer')).toContainText('已选 2 台设备')
  await query.getByLabel('档案号', { exact: true }).fill('不存在')
  await query.getByRole('button', { name: '查询', exact: true }).click()
  await expect(left).toContainText('暂无关联设备')
  await expect(right.getByRole('row')).toHaveCount(3)
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(field).toHaveValue('DEMO-002 压力试验机；DEMO-001 多参数分析仪')
  await open()
  await right.getByLabel('选择 DEMO-001 多参数分析仪', { exact: true }).check()
  await dialog.getByRole('button', { name: '移出', exact: true }).click()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(field).toHaveValue('DEMO-002 压力试验机')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('试验信息已保存。', { exact: true })).toBeVisible()
  await page.reload()
  await expect(field).toHaveValue('DEMO-002 压力试验机')
  for (const [width, theme] of [[1440, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width: 1440, height: 900 })
    if (await page.locator('html').getAttribute('data-bs-theme') !== theme) await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
    await page.setViewportSize({ width, height: 900 })
    await open()
    await expect.poll(() => dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeInViewport()
    const leftBox = await left.boundingBox(), rightBox = await right.boundingBox()
    if (width >= 992) {
      expect(Math.abs(leftBox!.y - rightBox!.y)).toBeLessThan(2)
      expect(Math.abs(leftBox!.width - rightBox!.width)).toBeLessThan(2)
      expect(rightBox!.x).toBeGreaterThan(leftBox!.x + leftBox!.width)
      await expect.poll(() => left.locator('table').evaluate(el => el.parentElement!.scrollWidth > el.parentElement!.clientWidth)).toBe(true)
    } else expect(rightBox!.y).toBeGreaterThan(leftBox!.y + leftBox!.height)
    await dialog.screenshot({ path: info.outputPath('equipment-' + width + '-' + theme + '.png') })
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
  }
  await page.goto('/#/testing/data-entry/demo-yp-76?mode=view')
  await expect(field).toHaveValue('DEMO-002 压力试验机')
  await expect(page.getByRole('button', { name: '选择仪器设备', exact: true })).toBeDisabled()
})

