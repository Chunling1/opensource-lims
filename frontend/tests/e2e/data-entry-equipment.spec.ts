test('large equipment lists scroll independently and retain checks across pages', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.route('**/samples/demo-yp-76/data-entry', async route => {
    const response = await route.fetch(), detail = await response.json()
    detail.options.equipment = Array.from({ length: 35 }, (_, index) => ({ id: 'test-' + index, code: 'TEST-' + index, name: '较长名称的测试仪器设备' + index, model: '测试规格型号', manufacturer: '测试设备生产厂家', serial: 'serial-' + index }))
    detail.equipmentConfig.associatedIds = detail.options.equipment.map((item: { id: string }) => item.id)
    await route.fulfill({ response, json: detail })
  })
  await page.goto('/#/testing/data-entry/demo-yp-76')
  await page.getByRole('button', { name: '选择仪器设备', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择仪器设备', exact: true })
  const left = dialog.getByRole('region', { name: '关联设备', exact: true })
  const right = dialog.getByRole('region', { name: '已选设备', exact: true })
  await left.getByLabel('全选当前页关联设备').check()
  await left.getByRole('button', { name: '下一页', exact: true }).click()
  await left.getByLabel('全选当前页关联设备').check()
  await dialog.getByRole('button', { name: '移入', exact: true }).click()
  await expect(dialog.locator('.modal-footer')).toContainText('已选 20 台设备')
  await left.getByLabel('关联设备每页条数').selectOption('50')
  await right.getByLabel('已选设备每页条数').selectOption('50')
  for (const panel of [left, right]) {
    const scroll = panel.locator('table').locator('..')
    await expect.poll(() => scroll.evaluate(el => el.scrollHeight > el.clientHeight && el.scrollWidth > el.clientWidth)).toBe(true)
    await scroll.evaluate(el => { el.scrollTop = el.scrollHeight; el.scrollLeft = el.scrollWidth })
    await expect.poll(() => scroll.evaluate(el => el.scrollTop > 0 && el.scrollLeft > 0)).toBe(true)
    await expect(panel.getByRole('button', { name: '下一页', exact: true })).toBeInViewport()
  }
  await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeInViewport()
})

test('unknown plan update result is reconciled without duplicate submission', async ({ page }) => {
  let submissions = 0
  await page.route('**/data-entry/equipment-defaults', async route => { submissions++; await route.fetch(); await route.abort() })
  await page.goto('/#/testing/data-entry/demo-yp-76')
  await page.getByRole('button', { name: '选择仪器设备', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择仪器设备', exact: true })
  const left = dialog.getByRole('region', { name: '关联设备', exact: true })
  await left.getByLabel('全选当前页关联设备').check()
  await dialog.getByRole('button', { name: '设为默认', exact: true }).click()
  await page.getByRole('dialog', { name: '设置默认设备', exact: true }).getByRole('button', { name: '确认设置', exact: true }).click()
  await page.getByRole('dialog', { name: '设置默认设备', exact: true }).getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '刷新核对', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await left.getByRole('cell', { name: '多参数分析仪', exact: true }).click()
  await expect(left.getByLabel('全选当前页关联设备')).toBeChecked()
  await dialog.getByRole('button', { name: '刷新核对', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeEnabled()
  await expect(left.getByRole('cell', { name: '是', exact: true })).toHaveCount(1)
  expect(submissions).toBe(1)
})
