import { expect, test } from '@playwright/test'

const list = '/commissions/review?scope=all&sSort=code&sDirection=asc'
for (const width of [1440, 390]) test(`batch quick review checks and confirms all samples at ${width}`, async ({ page }, info) => {
  test.setTimeout(90000)
  await page.setViewportSize({ width, height: 1000 })
  await page.goto(`/#${list}`)
  const select = async () => {
    for (const code of ['SP2026090002', 'SP2026090005']) await page.getByRole('checkbox', { name: `选择样品 ${code}`, exact: true }).check()
    await page.getByRole('button', { name: '快速评审', exact: true }).click()
  }
  await select()
  const dialog = page.getByRole('dialog', { name: '合同评审', exact: true })
  const approve = dialog.getByRole('button', { name: '通过', exact: true })
  const confirmed = dialog.getByRole('checkbox', { name: '我已阅读并确认全部样品的校核结果', exact: true })
  await expect(dialog).toContainText('已选择 2 个样品')
  await expect(approve).toBeDisabled()
  await expect(confirmed).toBeDisabled()
  await page.route('**/samples/batch-review/check', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '批量校验暂不可用' } } }), { times: 1 })
  await dialog.getByRole('button', { name: '校验', exact: true }).click()
  await expect(dialog).toContainText('批量校验暂不可用')
  await expect(approve).toBeDisabled()
  await dialog.getByRole('button', { name: '校验', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: /SP2026090002/ })).toBeVisible()
  await expect(dialog.getByRole('heading', { name: /SP2026090005/ })).toBeVisible()
  await confirmed.check()
  await expect(approve).toBeEnabled()
  await dialog.getByRole('checkbox', { name: '加盖CMA章', exact: true }).check()
  await expect(confirmed).not.toBeChecked()
  await expect(approve).toBeDisabled()
  await dialog.getByRole('button', { name: '校验', exact: true }).click()
  await confirmed.check()
  await page.screenshot({ path: info.outputPath(`batch-review-${width}.png`), fullPage: true, animations: 'disabled' })
  // Rejection uses the same selection without requiring verification.
  await dialog.getByRole('button', { name: '不通过', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: '快速评审', exact: true })).toBeDisabled()
  await select()
  await dialog.getByRole('button', { name: '校验', exact: true }).click()
  await confirmed.check()
  await approve.click()
  await expect(dialog).toBeHidden()
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  for (const code of ['SP2026090002', 'SP2026090005']) await expect(table).not.toContainText(code)
  for (const id of ['demo-yp-2', 'demo-yp-5']) {
    const saved = await (await page.request.get(`/api/registration/samples/${id}`, { headers: { 'X-Demo-Actor': 'admin' } })).json()
    expect(saved.reviewStatus).toBe('approved')
    expect(saved.contractReview.compliance.result.sampleId).toBe(id)
  }
  await expect(page).toHaveURL(`/#${list}`)
})

test('batch review refreshes changed samples and requires a new complete verification', async ({ page }) => {
  await page.goto(`/#${list}`)
  for (const code of ['SP2026090002', 'SP2026090005']) await page.getByRole('checkbox', { name: `选择样品 ${code}`, exact: true }).check()
  await page.getByRole('button', { name: '快速评审', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '合同评审', exact: true })
  const confirm = dialog.getByRole('checkbox', { name: '我已阅读并确认全部样品的校核结果', exact: true })
  await dialog.getByRole('button', { name: '校验', exact: true }).click()
  await confirm.check()
  const headers = { 'X-Demo-Actor': 'admin' }
  const sample = await (await page.request.get('/api/registration/samples/demo-yp-5', { headers })).json()
  await page.request.post('/api/registration/samples/demo-yp-5/actions', { headers, data: { actionId: 'unreview', version: sample.version } })
  const changed = await (await page.request.get('/api/registration/samples/demo-yp-5', { headers })).json()
  await page.request.post('/api/registration/samples/demo-yp-5/actions', { headers, data: { actionId: 'start-review', version: changed.version } })
  await dialog.getByRole('button', { name: '通过', exact: true }).click()
  await expect(dialog).toContainText('样品信息已发生变化')
  const untouched = await (await page.request.get('/api/registration/samples/demo-yp-2', { headers })).json()
  expect(untouched.reviewStatus).toBe('reviewed')
  await dialog.getByRole('button', { name: '刷新样品', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '通过', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '校验', exact: true }).click()
  await confirm.check()
  await dialog.getByRole('button', { name: '通过', exact: true }).click()
  await expect(dialog).toBeHidden()
})
