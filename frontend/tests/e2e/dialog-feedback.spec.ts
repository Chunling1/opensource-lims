import { test, expect } from '@playwright/test'

for (const width of [1440, 390]) test(`dialog operation failure uses a stable dismissible toast at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/equipment/groups')
  await page.route('**/quality/equipment/groups/save', route => route.fulfill({ status: 422, json: { error: { code: 'BUSINESS_RULE', message: '当前状态不允许保存。' } } }))
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新增设备分组', exact: true })
  await expect(dialog.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  await dialog.locator('#equipment-group-name').fill('测试分组')
  const submit = dialog.getByRole('button', { name: '保存', exact: true })
  const before = await submit.boundingBox()
  await submit.click()
  const toast = dialog.locator('.toast.show').filter({ hasText: '当前状态不允许保存。' })
  await expect(toast).toBeInViewport()
  await expect(toast).toHaveCSS('opacity', '1')
  await expect(dialog.locator('.modal-body .alert')).toHaveCount(0)
  expect((await submit.boundingBox())!.y).toBeCloseTo(before!.y, 0)
  expect(await toast.evaluate(element => !element.closest('.modal-body'))).toBe(true)
  await expect(toast.getByRole('button', { name: '关闭操作提示' })).toBeEnabled()
  await dialog.screenshot({ path: info.outputPath(`dialog-feedback-${width}.png`) })
  await toast.getByRole('button', { name: '关闭操作提示' }).click()
  await expect(toast).toHaveCount(0)
  await submit.click()
  await expect(toast).toBeInViewport()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.locator('.toast.show').filter({ hasText: '当前状态不允许保存。' })).toHaveCount(0)
})

test('existing personnel dialog system feedback retains retry and diagnostics in toast', async ({ page }) => {
  await page.goto('/#/quality/personnel/registration')
  await page.getByRole('table', { name: '人员登记列表', exact: true }).locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await page.route(/\/quality\/personnel\/[^/?]+$/, route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '详情暂时不可用' } } }), { times: 1 })
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '查看人员', exact: true }), toast = dialog.locator('.toast.show')
  await expect(toast).toContainText('详情暂时不可用')
  await expect(toast).toContainText('诊断编号')
  await expect(toast.locator('.alert')).toHaveCount(0)
  await toast.getByRole('button', { name: '重试', exact: true }).click()
  await expect(dialog.getByLabel('姓名', { exact: true })).toBeVisible()
  await expect(toast).toHaveCount(0)
})
