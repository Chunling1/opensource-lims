import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
for (const width of [1440, 390]) test('personnel profile tabs, user picker, records and attachments at ' + width, async ({ page }, info) => {
  test.setTimeout(120000); page.setDefaultTimeout(15000)
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/personnel/registration')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  let main = page.getByRole('dialog', { name: '新增人员', exact: true })
  await expect(main.getByRole('tab')).toHaveText(['基本信息', '获奖信息', '继续教育记录'])
  await expect(main.getByLabel('性别', { exact: true }).locator('option')).toHaveText(['男', '女'])
  await main.getByRole('button', { name: '选择政治面貌', exact: true }).click()
  const politicalOptions = main.getByLabel('政治面貌选项', { exact: true })
  await expect(politicalOptions.getByRole('button')).toHaveText(['党员', '团员', '民主党派', '群众'])
  await politicalOptions.getByRole('button', { name: '党员', exact: true }).click()
  await expect(main.getByLabel('政治面貌', { exact: true })).toHaveValue('党员')
  await main.getByLabel('人员编号', { exact: true }).fill('PROFILE-001')
  await main.getByLabel('曾用名', { exact: true }).fill('曾用名测试')
  await main.getByRole('button', { name: '选择人员', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择人员', exact: true })
  await expect(picker.getByRole('columnheader')).toHaveText(['', '用户账号', '姓名', '邮箱', '电话', '岗位', '上岗证号', '职务'])
  await picker.getByLabel('用户账号', { exact: true }).fill('ADMIN')
  await picker.getByLabel('姓名', { exact: true }).fill('演示')
  await picker.getByLabel('上岗证号', { exact: true }).fill('missing')
  await picker.getByRole('button', { name: '查询', exact: true }).click()
  await expect(picker).toContainText('没有符合条件的人员')
  await picker.getByLabel('上岗证号', { exact: true }).fill('')
  await picker.getByRole('button', { name: '查询', exact: true }).click()
  await picker.getByRole('radio', { name: '选择 演示用户（admin）', exact: true }).check()
  await picker.getByRole('button', { name: '确定', exact: true }).click()
  await expect(main.getByLabel('姓名', { exact: true })).toHaveValue('演示用户')
  await expect(main.getByLabel('曾用名', { exact: true })).toHaveValue('曾用名测试')
  await main.getByLabel('出生日期', { exact: true }).fill('1990-01-01')
  await main.getByLabel('出生日期', { exact: true }).press('Tab')
  await expect(main.getByLabel('年龄', { exact: true })).not.toHaveValue('')
  await main.getByLabel('身份证号码', { exact: true }).fill('012345678901234567')
  await main.getByLabel('政治面貌', { exact: true }).fill('自定义政治面貌')
  await main.getByLabel('学位', { exact: true }).fill('自定义学位')
  await main.getByLabel('出生地址', { exact: true }).fill('测试地址')
  await main.getByLabel('社保号', { exact: true }).fill('001122')
  await main.getByLabel('职称/资格', { exact: true }).fill('自定义资格')
  await main.getByLabel('岗位/职务', { exact: true }).fill('自定义岗位')
  await main.getByLabel('检测/业务范围', { exact: true }).fill('环境检测\n水质分析')
  async function upload(title: string, name: string) {
    const dialog = page.getByRole('dialog', { name: title, exact: true })
    await dialog.getByRole('button', { name: '完成', exact: true }).click({ trial: true })
    const before = (await dialog.locator('.modal-content').boundingBox())!
    expect(before.height).toBeLessThan(600)
    if (title === '学历附件') await dialog.screenshot({ path: info.outputPath('personnel-attachments-empty-' + width + '.png') })
    const chooser = page.waitForEvent('filechooser')
    const uploadArea = dialog.getByRole('button', { name: '上传附件', exact: true })
    if (width === 1440) await uploadArea.press('Enter')
    else await uploadArea.click()
    await (await chooser).setFiles({ name, mimeType: 'text/plain', buffer: Buffer.from('personnel evidence') })
    await expect(dialog.getByRole('button', { name, exact: true })).toBeVisible()
    await expect(dialog.locator('.filepond--file-status-main')).toHaveText('上传成功')
    const after = (await dialog.locator('.modal-content').boundingBox())!
    for (const key of ['x', 'y', 'width', 'height'] as const) expect(Math.abs(after[key] - before[key])).toBeLessThan(1)
    await expect(dialog.getByRole('button', { name: `下载附件 ${name}`, exact: true })).toBeVisible()
    if (title === '学历附件') await dialog.screenshot({ path: info.outputPath('personnel-attachments-' + width + '.png') })
    await dialog.getByRole('button', { name: '完成', exact: true }).click()
  }
  await main.getByRole('button', { name: '管理学历附件', exact: true }).click()
  await upload('学历附件', 'degree.txt')
  await main.locator('.modal-body').evaluate(el => { el.scrollTop = 0 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await main.screenshot({ path: info.outputPath('personnel-basic-' + width + '.png') })
  await main.getByRole('tab', { name: '获奖信息', exact: true }).click()
  await main.getByRole('button', { name: '新增', exact: true }).click()
  const award = page.getByRole('dialog', { name: '新增获奖情况', exact: true })
  await award.getByLabel('获奖名称', { exact: true }).fill('优秀奖')
  await award.getByLabel('获奖项目', { exact: true }).fill('检测项目')
  await award.getByLabel('颁奖单位', { exact: true }).fill('测试协会')
  await award.getByRole('button', { name: '保存', exact: true }).click()
  const awardTable = main.getByRole('table', { name: '获奖信息列表' })
  async function awardMenu(action: string) { await awardTable.getByRole('button', { name: '优秀奖 更多操作', exact: true }).click(); await page.getByRole('menuitem', { name: action, exact: true }).click() }
  await awardMenu('附件管理'); await upload('附件管理', 'award.txt')
  await awardMenu('修改')
  const editAward = page.getByRole('dialog', { name: '修改获奖情况', exact: true })
  await editAward.getByLabel('获奖项目', { exact: true }).fill('取消的修改')
  await editAward.getByRole('button', { name: '取消', exact: true }).click()
  const leaveAward = page.getByRole('dialog', { name: '放弃未保存内容', exact: true })
  await leaveAward.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(editAward.getByLabel('获奖项目', { exact: true })).toHaveValue('取消的修改')
  await editAward.getByRole('button', { name: '取消', exact: true }).click()
  await leaveAward.getByRole('button', { name: '放弃更改', exact: true }).click()
  await expect(awardTable).toContainText('检测项目')
  await main.getByRole('tab', { name: '继续教育记录', exact: true }).click()
  await main.getByRole('button', { name: '新增', exact: true }).click()
  const training = page.getByRole('dialog', { name: '新增继续教育记录', exact: true })
  await training.getByLabel('培训地点').fill('培训中心')
  await training.getByLabel('培训内容').fill('质量体系培训')
  await training.getByLabel('培训结果').fill('合格')
  await training.getByRole('button', { name: '保存', exact: true }).click()
  await expect(main.getByRole('table', { name: '继续教育记录列表' })).toContainText('质量体系培训')
  await main.screenshot({ path: info.outputPath('personnel-training-' + width + '.png') })
  await main.getByRole('button', { name: '保存', exact: true }).click()
  await expect(main).toBeHidden()
  await page.reload()
  const query = page.getByRole('form', { name: '人员登记查询', exact: true })
  await query.getByLabel('编号', { exact: true }).fill('PROFILE-001')
  await query.getByRole('button', { name: '查询', exact: true }).click()
  const table = page.getByRole('table', { name: '人员登记列表' }), row = table.getByRole('row').filter({ hasText: 'PROFILE-001' })
  await row.getByRole('button', { name: '演示用户 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  main = page.getByRole('dialog', { name: '查看人员', exact: true })
  await expect(main.getByLabel('曾用名')).toHaveValue('曾用名测试')
  await expect(main.getByLabel('学位', { exact: true })).toHaveValue('自定义学位')
  await expect(main.getByLabel('学位', { exact: true })).toHaveAttribute('readonly', '')
  await expect(main.getByRole('button', { name: '选择学位', exact: true })).toBeDisabled()
  await expect(main.getByRole('button', { name: '选择人员', exact: true })).toBeDisabled()
  await main.getByRole('button', { name: '管理学历附件', exact: true }).click()
  const attachments = page.getByRole('dialog', { name: '学历附件', exact: true })
  await expect(attachments.locator('input[type=file]')).toHaveCount(0)
  await expect(attachments.getByRole('button', { name: /^删除附件 / })).toHaveCount(0)
  const download = page.waitForEvent('download')
  await attachments.getByRole('button', { name: '下载附件 degree.txt', exact: true }).click()
  expect(await readFile((await (await download).path())!, 'utf8')).toBe('personnel evidence')
  await attachments.getByRole('button', { name: '关闭', exact: true }).click()
  await main.getByRole('tab', { name: '获奖信息', exact: true }).click()
  await expect(main.getByRole('table', { name: '获奖信息列表' })).toContainText('优秀奖')
  await expect(main.getByRole('button', { name: '新增', exact: true })).toHaveCount(0)
  await main.getByRole('tab', { name: '继续教育记录', exact: true }).click()
  await expect(main.getByRole('table', { name: '继续教育记录列表' })).toContainText('合格')
  await main.getByRole('button', { name: '关闭', exact: true }).click()
  await row.getByRole('button', { name: '演示用户 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  main = page.getByRole('dialog', { name: '编辑人员', exact: true })
  await expect(main.getByLabel('曾用名')).toHaveValue('曾用名测试')
  await main.getByRole('tab', { name: '获奖信息', exact: true }).click()
  async function storedAwardMenu(action: string) { await main.getByRole('table', { name: '获奖信息列表' }).getByRole('button', { name: '优秀奖 更多操作', exact: true }).click(); await page.getByRole('menuitem', { name: action, exact: true }).click() }
  await storedAwardMenu('修改')
  await editAward.getByLabel('获奖项目', { exact: true }).fill('修改后的项目')
  await editAward.getByRole('button', { name: '保存', exact: true }).click()
  await storedAwardMenu('查看')
  const viewAward = page.getByRole('dialog', { name: '查看获奖情况', exact: true })
  await expect(viewAward.getByLabel('获奖项目')).toHaveValue('修改后的项目')
  await expect(viewAward.getByLabel('获奖项目')).toBeDisabled()
  await viewAward.getByRole('button', { name: '关闭', exact: true }).click()
  await storedAwardMenu('附件管理')
  const awardAttachments = page.getByRole('dialog', { name: '附件管理', exact: true })
  await awardAttachments.getByRole('button', { name: '删除附件 award.txt', exact: true }).click()
  await page.getByRole('dialog', { name: '删除附件', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '删除附件', exact: true })).toBeHidden()
  await awardAttachments.getByRole('button', { name: '完成', exact: true }).click()
  await storedAwardMenu('删除')
  const deleteAward = page.getByRole('dialog', { name: '删除获奖情况', exact: true })
  await deleteAward.getByRole('button', { name: '取消', exact: true }).click()
  await expect(main.getByRole('table', { name: '获奖信息列表' })).toContainText('修改后的项目')
  await main.getByRole('tab', { name: '继续教育记录', exact: true }).click()
  async function trainingMenu(action: string) { await main.getByRole('table', { name: '继续教育记录列表' }).getByRole('button', { name: '质量体系培训 更多操作', exact: true }).click(); await page.getByRole('menuitem', { name: action, exact: true }).click() }
  await trainingMenu('修改')
  const editTraining = page.getByRole('dialog', { name: '修改继续教育记录', exact: true })
  await editTraining.getByLabel('培训结果').fill('优秀')
  await editTraining.getByRole('button', { name: '保存', exact: true }).click()
  await trainingMenu('查看')
  const viewTraining = page.getByRole('dialog', { name: '查看继续教育记录', exact: true })
  await expect(viewTraining.getByLabel('培训结果')).toHaveValue('优秀')
  await expect(viewTraining.getByLabel('培训结果')).toBeDisabled()
  await viewTraining.getByRole('button', { name: '关闭', exact: true }).click()
  await trainingMenu('附件管理'); await upload('附件管理', 'training.txt')
  await trainingMenu('删除')
  await page.getByRole('dialog', { name: '删除继续教育记录', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click()
  await main.getByRole('button', { name: '保存', exact: true }).click()
  await expect(main).toBeHidden()
  await row.getByRole('button', { name: '演示用户 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  await expect(main.getByLabel('曾用名')).toHaveValue('曾用名测试')
  await main.getByRole('tab', { name: '继续教育记录', exact: true }).click()
  await expect(main.getByRole('table', { name: '继续教育记录列表' })).not.toContainText('质量体系培训')
  await main.getByRole('tab', { name: '获奖信息', exact: true }).click()
  await expect(main.getByRole('table', { name: '获奖信息列表' })).toContainText('修改后的项目')
  await expect(main.getByRole('button', { name: '1 个附件', exact: true })).toHaveCount(0)
  await storedAwardMenu('删除')
  await deleteAward.getByRole('button', { name: '确认删除', exact: true }).click()
  await main.getByRole('button', { name: '保存', exact: true }).click()
  await expect(main).toBeHidden()
})
