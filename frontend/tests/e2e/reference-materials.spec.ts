async function search(page: Page, name: string) {
  const form = page.getByRole('form', { name: '标准物质登记查询', exact: true })
  await form.getByLabel('品名').fill(name); await form.getByRole('button', { name: '查询', exact: true }).click()
}
async function action(table: Locator, name: string) {
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await table.page().getByRole('menuitem', { name, exact: true }).click()
}
async function screenshot(page: Page, dialog: Locator, path: string) {
  await expect(dialog).toHaveCSS('opacity', '1'); await expect(dialog.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  for (const close of await page.getByRole('button', { name: '关闭系统提示', exact: true }).all()) if (await close.isVisible()) await close.click()
  await dialog.locator('.modal-body').first().evaluate(el => { el.scrollTop = 0 })
  await dialog.screenshot({ path })
  expect(await dialog.evaluate(el => el.scrollWidth <= innerWidth)).toBe(true)
}
