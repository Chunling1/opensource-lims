import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { toolbarButton, openToolbarExport } from './helpers/toolbar'

for (const width of [1440, 390]) test(`department ledger scope, view menu and toolbar at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/equipment/department-ledger?ownDepartment=0')
  const table = page.getByRole('table', { name: '设备台账列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(page.locator('.card-title', { hasText: '设备台账[部门]' })).toBeVisible()
  const toolbar = page.getByRole('group', { name: '设备台账工具栏', exact: true })
  for (const name of ['新增', '批量修改', '下载模板', '导入']) await expect(toolbar.getByRole('button', { name, exact: true })).toHaveCount(0)
  await expect(await toolbarButton(page, '设备台账', '分组关联')).toBeDisabled()
  // Dismiss an overflow menu before interacting with the query form.
  await page.keyboard.press('Escape')
  const form = page.getByRole('form', { name: '设备台账查询', exact: true })
  await form.getByRole('button', { name: /更多筛选/ }).click()
  const own = form.getByRole('checkbox', { name: '本部门设备', exact: true })
  await expect(own).toBeChecked(); await expect(own).toBeDisabled()
  await page.getByLabel('设备台账每页条数', { exact: true }).selectOption('50')
  const all = await (await page.request.post('/api/registration/quality/equipment/ledger/query', { headers: { 'X-Demo-Actor': 'admin' }, data: { pageSize: 50 } })).json()
  const expected = all.items.filter((row: { departmentId: string }) => row.departmentId === 'lab')
  await expect(table.locator('tbody tr')).toHaveCount(expected.length)
  for (const row of expected) await expect(table).toContainText(row.code)
  for (const row of all.items.filter((row: { departmentId: string }) => row.departmentId !== 'lab')) await expect(table).not.toContainText(row.code)
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['查看'])
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '查看设备', exact: true })
  await expect(dialog.getByLabel('档案号', { exact: true })).toBeDisabled()
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '返回', exact: true }).click()
  await table.locator('tbody tr').first().getByRole('checkbox').check()
  await (await toolbarButton(page, '设备台账', '分组关联')).click()
  await expect(page.getByRole('dialog', { name: '分组关联', exact: true })).toBeVisible()
  await page.getByRole('dialog', { name: '分组关联', exact: true }).getByRole('button', { name: '取消', exact: true }).click()
  await openToolbarExport(page, '设备台账')
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const download = await downloading, csv = await readFile((await download.path())!, 'utf8')
  expect(download.suggestedFilename()).toBe('设备台账[部门].csv')
  for (const row of all.items) expect(csv.includes(`"${row.code}"`)).toBe(row.departmentId === 'lab')
  await page.screenshot({ path: info.outputPath(`department-ledger-${width}.png`), fullPage: true })
  await page.reload()
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(own).toBeChecked(); await expect(own).toBeDisabled()
  await form.getByLabel('所属部门', { exact: true }).selectOption('lab2')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件')
})

test('switching ledger pages resets restrictions and write actions correctly', async ({ page }) => {
  await page.goto('/#/quality/equipment/department-ledger?ownDepartment=1')
  await expect(page.getByRole('table', { name: '设备台账列表', exact: true }).locator('tbody tr')).toHaveCount(10)
  await page.getByRole('link', { name: '设备台账', exact: true }).click()
  await expect(await toolbarButton(page, '设备台账', '新增')).toBeVisible()
  const form = page.getByRole('form', { name: '设备台账查询', exact: true })
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByRole('checkbox', { name: '本部门设备', exact: true })).toBeEnabled()
  await expect(form.getByRole('checkbox', { name: '本部门设备', exact: true })).not.toBeChecked()
  await page.getByRole('link', { name: '设备台账[部门]', exact: true }).click()
  await expect(page.getByRole('group', { name: '设备台账工具栏', exact: true }).getByRole('button', { name: '新增', exact: true })).toHaveCount(0)
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByRole('checkbox', { name: '本部门设备', exact: true })).toBeChecked()
  await expect(form.getByRole('checkbox', { name: '本部门设备', exact: true })).toBeDisabled()
})
