import { test, expect } from '@playwright/test'
import { toolbarButton } from './helpers/toolbar'

for (const width of [1440, 390]) test(`deleting equipment plans preserves the form, current page and selection at ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 950 })
  await page.goto('/#/quality/equipment/ledger')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新增设备', exact: true })
  await dialog.getByLabel('档案号', { exact: true }).fill('KEEP-FORM')
  await dialog.getByLabel('仪器设备名称', { exact: true }).fill('删除方案测试设备')
  await dialog.getByRole('tab', { name: '检测方案', exact: true }).click()
  await dialog.getByRole('button', { name: '选择方案', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择方案', exact: true })
  await picker.getByRole('checkbox', { name: '选择分组 温度校准实验室', exact: true }).check()
  await picker.getByRole('button', { name: '确定', exact: true }).click()
  const table = dialog.locator('table[aria-label="检测方案列表"]')
  await dialog.getByRole('button', { name: '下一页', exact: true }).click()
  const targetRow = table.locator('tbody tr').first()
  const name = await targetRow.locator('td').nth(2).innerText()
  await targetRow.getByRole('checkbox').check()
  await (await toolbarButton(page, '检测方案', '删除')).click()
  await expect(dialog).toBeVisible()
  const confirmation = page.getByRole('dialog', { name: '删除设备记录', exact: true })
  await expect(confirmation).toContainText('确认删除所选 1 条检测方案')
  await expect(dialog.getByRole('tab', { name: '检测方案', exact: true })).toBeVisible()
  await expect(table.locator('td').filter({ hasText: name }).first()).toBeVisible()
  await expect(confirmation).toBeFocused()
  await expect(confirmation.getByRole('button', { name: '确认删除', exact: true })).toBeInViewport()
  await expect(page.locator('.modal.show')).toHaveCount(1)
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  await expect(targetRow.getByRole('checkbox')).toBeChecked()
  await (await toolbarButton(page, '检测方案', '删除')).click()
  await confirmation.press('Escape')
  await expect(confirmation).toBeHidden()
  await expect(targetRow.getByRole('checkbox')).toBeChecked()
  await (await toolbarButton(page, '检测方案', '删除')).click()
  await confirmation.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(dialog).toBeVisible()
  await expect(table.getByRole('cell', { name, exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: '第 2 页', exact: true })).toHaveAttribute('aria-current', 'page')
  await dialog.getByRole('tab', { name: '基本信息', exact: true }).click()
  await expect(dialog.getByLabel('档案号', { exact: true })).toHaveValue('KEEP-FORM')
  await expect(dialog.getByLabel('仪器设备名称', { exact: true })).toHaveValue('删除方案测试设备')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
})
