test('loan columns, pagination and complete/selected exports survive tab switching', async ({ page }) => {
  await page.request.post('/api/registration/session')
  for (let i = 0; i < 12; i++) await create(page, `PAGE-LOAN-${String(i).padStart(2, '0')}`)
  await page.goto('/#/quality/equipment/loans'); await search(page, '可领用设备', 'PAGE-LOAN-')
  const table = page.getByRole('table', { name: '可领用设备列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await (await toolbarButton(page, '可领用设备', '显示')).click()
  const columns = page.getByRole('dialog', { name: '可领用设备显示列', exact: true })
  await columns.getByLabel('生产厂家').check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await table.locator('tbody tr').first().getByRole('checkbox').check()
  await page.getByRole('tab', { name: '待归还设备', exact: true }).click()
  await page.getByRole('tab', { name: '可领用设备', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(table.getByRole('columnheader', { name: '生产厂家', exact: true })).toBeVisible()
  await expect(table.locator('tbody input:checked')).toHaveCount(0)
  await openToolbarExport(page, '可领用设备'); let download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  let csv = await readFile((await (await download).path())!, 'utf8')
  expect(csv).toContain('PAGE-LOAN-00'); expect(csv).toContain('PAGE-LOAN-11'); expect(csv).toContain('所属部门')
  await table.locator('tbody tr').first().getByRole('checkbox').check()
  await openToolbarExport(page, '可领用设备'); download = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  csv = await readFile((await (await download).path())!, 'utf8')
  expect(csv).toContain('PAGE-LOAN-10'); expect(csv).not.toContain('PAGE-LOAN-11')
})
test('concurrent loans fail without partial success and reviewer is read-only', async ({ page }) => {
  await page.request.post('/api/registration/session'); await create(page, 'CONFLICT-LOAN-A'); await create(page, 'CONFLICT-LOAN-B')
  await page.goto('/#/quality/equipment/loans'); await search(page, '可领用设备', 'CONFLICT-LOAN-')
  const table = page.getByRole('table', { name: '可领用设备列表', exact: true })
  await table.getByRole('checkbox', { name: '全选当前页可领用设备', exact: true }).check()
  await (await toolbarButton(page, '可领用设备', '领用')).click()
  const dialog = page.getByRole('dialog', { name: '领用设备', exact: true })
  await expect(dialog.getByLabel('领用人')).toHaveValue('演示用户')
  const result = await (await page.request.post(`${base}/query`, { headers, data: { kind: 'available', code: 'CONFLICT-LOAN-A' } })).json(), row = result.items[0]
  expect((await page.request.post(`${base}/borrow`, { headers, data: { records: [{ id: row.id, version: row.version, equipmentVersion: row.equipmentVersion }], borrower: '演示用户', borrowedStatus: '正常', date: '2026-10-01', notes: '' } })).ok()).toBe(true)
  await dialog.getByLabel('备注', { exact: true }).fill('保留输入')
  await dialog.getByRole('button', { name: '确认领用', exact: true }).click()
  await expect(dialog).toContainText('已被领用')
  await expect(dialog.getByLabel('备注', { exact: true })).toHaveValue('保留输入')
  await expect(dialog.getByRole('button', { name: '确认领用', exact: true })).toBeDisabled()
  const available = await (await page.request.post(`${base}/query`, { headers, data: { kind: 'available', code: 'CONFLICT-LOAN-B' } })).json()
  expect(available.total).toBe(1)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.evaluate(() => localStorage.setItem('lims.identity.v1', 'reviewer')); await page.reload()
  await expect(page.getByRole('table', { name: '可领用设备列表', exact: true })).toBeVisible()
  await table.locator('tbody tr').first().getByRole('checkbox').check()
  await expect(await toolbarButton(page, '可领用设备', '领用')).toBeDisabled()
})
