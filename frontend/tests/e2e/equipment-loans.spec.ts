const base = '/api/registration/quality/equipment/loans', headers = { 'X-Demo-Actor': 'admin' }
async function create(page: Page, code: string) {
  const response = await page.request.post('/api/registration/quality/equipment/ledger/save', { headers, data: { ...emptyEquipment(), code, name: `测试${code}`, departmentId: 'lab', manufacturer: '领用测试厂', model: 'TEST-M', keeper: '保管员' } })
  expect(response.ok()).toBe(true); return response.json()
}
async function search(page: Page, label: string, code: string) {
  const form = page.getByRole('form', { name: `${label}查询`, exact: true })
  await form.getByLabel('设备编号', { exact: true }).fill(code)
  await form.getByRole('button', { name: '查询', exact: true }).click()
}
