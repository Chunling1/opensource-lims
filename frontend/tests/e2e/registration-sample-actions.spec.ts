import { test, expect } from '@playwright/test'
const root = '/commissions/registration'

test('sample toolbar and menus support selection, completion, reopening and voiding', async ({ page }) => {
  await page.goto(`/#${root}?current=demo-wt-1&sSort=code&sDirection=asc`)
  const region = page.getByRole('region', { name: '样品列表区域' })
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  await expect(table).toContainText('SP2026090001')
  const bulk = region.getByRole('button', { name: /^批量修改/ })
  await expect(bulk).toBeDisabled()
  await table.getByRole('checkbox', { name: '选择样品 SP2026090001', exact: true }).check()
  await expect(bulk).toHaveAccessibleName('批量修改（1）')
  await bulk.click()
  await expect(page.getByRole('heading', { name: '批量修改委托信息', exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: '委托人', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  const opener = table.getByRole('button', { name: 'SP2026090001 更多操作', exact: true })
  const menu = page.getByRole('menu', { name: 'SP2026090001 更多操作', exact: true })
  await opener.click()
  await expect(menu.getByRole('menuitem')).toHaveText(['查看', '编辑', '打印', '完成', '作废', '附件管理'])
  await menu.getByRole('menuitem', { name: '完成', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '完成', exact: true })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  await opener.click()
  await expect(menu.getByRole('menuitem', { name: '编辑', exact: true })).toBeDisabled()
  await menu.getByRole('menuitem', { name: '取消完成', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '取消完成', exact: true })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).toBeHidden()
  await opener.click()
  await expect(menu.getByRole('menuitem', { name: '编辑', exact: true })).toBeEnabled()
  await menu.getByRole('menuitem', { name: '作废', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '作废申请', exact: true })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  await opener.click()
  await expect(menu.getByRole('menuitem', { name: '完成', exact: true })).toBeVisible()
  await menu.getByRole('menuitem', { name: '作废', exact: true }).click()
  await expect(dialog).toContainText('确认对这条样品提交“作废申请”？')
  await expect(dialog).not.toContainText('作废后保留记录')
  await dialog.getByLabel('申请作废原因').fill('重复登记')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  await opener.click()
  await expect(menu.getByRole('menuitem')).toHaveText(['查看', '附件管理'])
  await expect(menu.getByRole('menuitem', { name: '完成', exact: true })).toHaveCount(0)
  await expect(menu.getByRole('menuitem', { name: '编辑', exact: true })).toHaveCount(0)
  await menu.press('Escape')
  await expect(table.getByRole('checkbox', { name: '选择样品 SP2026090001', exact: true })).toBeDisabled()
  await expect(bulk).toBeDisabled()
  await table.getByRole('checkbox', { name: '全选当前页样品', exact: true }).check()
  await expect(table.getByRole('checkbox', { name: '选择样品 SP2026090001', exact: true })).not.toBeChecked()
  const headers = { 'X-Demo-Actor': 'admin' }
  const row = await (await page.request.get('/api/registration/samples/demo-yp-1', { headers })).json()
  expect(row.status).toBe('void_pending')
  expect(row.dataStatus).toBe('作废申请中')
  expect(row.voidApplication).toMatchObject({ reason: '重复登记', previousStatus: 'pending', appliedBy: { id: 'admin' } })
  await expect(table.getByRole('row').filter({ hasText: 'SP2026090001' })).toContainText('作废申请中')
  expect((await page.request.get('/api/registration/samples/demo-yp-1/print-context', { headers })).status()).toBe(422)
  expect((await page.request.post('/api/registration/samples/demo-yp-1/prints', { headers, data: { documentType: 'sample', documentCode: row.code, type: 'product', layout: 'normal', copies: [1] } })).status()).toBe(422)
  expect(row.events.at(-1)).toMatchObject({ action: '提交作废申请', reason: '重复登记' })
  expect((await page.request.put('/api/registration/samples/demo-yp-1', { headers, data: { input: row, version: row.version } })).status()).toBe(422)
})

test('sample toolbar and menu fit a phone in dark mode', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/#${root}?current=demo-wt-1&sSort=code&sDirection=asc`)
  await page.getByRole('button', { name: '打开主题设置' }).click()
  await page.getByTestId('theme-label-mode-dark').click()
  await page.getByRole('button', { name: '关闭主题设置' }).click()
  await expect(page.locator('.offcanvas-backdrop')).toHaveCount(0)
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  await table.getByRole('checkbox', { name: '选择样品 SP2026090001', exact: true }).check()
  await expect(page.getByRole('button', { name: '批量修改（1）', exact: true })).toBeEnabled()
  await table.getByRole('button', { name: 'SP2026090001 更多操作', exact: true }).click()
  const menu = page.getByRole('menu', { name: 'SP2026090001 更多操作', exact: true })
  await expect(menu.getByRole('menuitem', { name: '作废', exact: true })).toBeVisible()
  const box = await menu.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(391)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: testInfo.outputPath('sample-actions-phone-dark.png') })
  await menu.getByRole('menuitem', { name: '作废', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '作废申请', exact: true })
  await expect(dialog.getByLabel('申请作废原因')).toBeVisible()
  await expect(dialog).toContainText('确认对这条样品提交“作废申请”？')
  await expect(dialog).not.toContainText('作废后保留记录')
  await expect(dialog.getByRole('button', { name: '确认', exact: true })).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('void-application-phone-dark.png') })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
})
