for (const width of [1440, 390]) test(`calibration shared columns and full/selected export at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/equipment/plans/calibration?from=&to=')
  const label = '计量器具周期检定计划', table = page.getByRole('table', { name: `${label}列表`, exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await (await toolbarButton(page, label, '显示')).click()
  const dialog = page.getByRole('dialog', { name: `${label}显示列`, exact: true })
  await expect(dialog.getByLabel('设备编号', { exact: true })).toBeDisabled()
  await dialog.getByLabel('规格型号', { exact: true }).uncheck()
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table.getByRole('columnheader', { name: '规格型号', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(table.getByRole('columnheader', { name: '规格型号', exact: true })).toHaveCount(0)
  await openToolbarExport(page, label)
  let download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  let csv = await readFile((await (await download).path())!, 'utf8')
  expect(csv).toContain('DEMO-024'); expect(csv).toContain('检定费用')
  await table.locator('tbody tr').first().getByRole('checkbox').check()
  await openToolbarExport(page, label)
  download = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  csv = await readFile((await (await download).path())!, 'utf8')
  expect(csv).toContain('DEMO-001'); expect(csv).not.toContain('DEMO-002')
  await (await toolbarButton(page, label, '显示')).click()
  await dialog.getByRole('button', { name: '恢复默认', exact: true }).click()
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table.getByRole('columnheader', { name: '规格型号', exact: true })).toHaveCount(1)
  await page.screenshot({ path: info.outputPath(`calibration-framework-${width}.png`) })
})

test('calibration version conflict preserves local input and reloads the current plan', async ({ page }) => {
  await page.goto('/#/quality/equipment/plans/calibration?value=DEMO-002&from=&to=')
  const table = page.getByRole('table', { name: '计量器具周期检定计划列表', exact: true })
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '检定', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '检定计量器具周期检定计划', exact: true })
  await dialog.getByLabel('备注').fill('本地未保存')
  const list = await (await page.request.post(`${endpoint}/query`, { headers, data: { value: 'DEMO-002' } })).json(), row = list.items[0]
  const values = Object.fromEntries(calibrationPlanFields.map(field => [field.key, row[field.key]]))
  const response = await page.request.post(`${endpoint}/save`, { headers, data: { id: row.id, version: row.version, equipmentVersion: row.equipmentVersion, values: { ...values, notes: '他人更新' } } })
  expect(response.ok()).toBe(true)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toContainText('已更新')
  await expect(dialog.getByLabel('备注')).toHaveValue('本地未保存')
  await expect(dialog.getByRole('button', { name: '提交', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(dialog.getByLabel('备注')).toHaveValue('他人更新')
})
