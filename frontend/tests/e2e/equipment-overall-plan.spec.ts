import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { emptyEquipment } from '../../src/types/quality/equipmentForm'
import { toolbarButton, openToolbarExport } from './helpers/toolbar'

for (const width of [1440, 390]) test(`overall plan view, edit, selective batch and output at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.request.post('/api/registration/session')
  const headers = { 'X-Demo-Actor': 'admin' }, endpoint = '/api/registration/quality/equipment/plans/overall'
  const ids: string[] = []
  for (let i = 1; i <= 3; i++) {
    const response = await page.request.post('/api/registration/quality/equipment/ledger/save', { headers, data: { ...emptyEquipment(), code: `OVERALL-TEST-${i}`, name: `总体计划测试设备${i}`, departmentId: 'lab', model: 'TEST-M', accuracy: String(i), range: '0～100' } })
    expect(response.ok()).toBe(true); ids.push((await response.json()).id)
  }
  await page.goto('/#/quality/equipment/plans/overall')
  const form = page.getByRole('form', { name: '设备总体计划查询', exact: true })
  const table = page.getByRole('table', { name: '设备总体计划列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(await toolbarButton(page, '设备总体计划', '批量修改')).toBeDisabled()
  await page.keyboard.press('Escape')
  await form.getByLabel('查询值').fill('OVERALL-TEST-')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await expect(table.getByRole('columnheader')).toHaveCount(10)
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['查看', '编辑'])
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '查看设备总体计划', exact: true })
  await expect(dialog.getByLabel('设备编号', { exact: true })).toHaveValue('OVERALL-TEST-1')
  await expect(dialog.getByLabel('量值溯源方法', { exact: true })).toBeDisabled()
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '返回', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '编辑设备总体计划', exact: true })
  await expect(dialog.getByLabel('设备编号', { exact: true })).toBeDisabled()
  await dialog.getByLabel('量值溯源方法', { exact: true }).fill('检定')
  await dialog.getByLabel('量值溯源机构', { exact: true }).fill('计量机构')
  await dialog.getByLabel('量值溯源周期', { exact: true }).fill('12个月')
  await dialog.getByLabel('是否要期间核查', { exact: true }).selectOption('是')
  await dialog.getByLabel('期间核查方法', { exact: true }).fill('标准物质核查')
  await dialog.getByLabel('期间核查间隔', { exact: true }).fill('6个月')
  await dialog.getByLabel('使用条件', { exact: true }).fill('室温')
  await dialog.getByLabel('维护项目', { exact: true }).fill('清洁')
  await dialog.getByLabel('维护时间间隔', { exact: true }).fill('每月')
  await dialog.getByLabel('控制措施', { exact: true }).fill('使用前检查')
  await expect(dialog.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  await dialog.screenshot({ path: info.outputPath(`overall-edit-${width}.png`) })
  expect(await dialog.evaluate(element => element.scrollWidth <= innerWidth)).toBe(true)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table).toContainText('12个月')
  await table.locator('tbody tr').nth(0).getByRole('checkbox').check()
  await expect(await toolbarButton(page, '设备总体计划', '批量修改')).toBeEnabled()
  await page.keyboard.press('Escape')
  await table.locator('tbody tr').nth(1).getByRole('checkbox').check()
  await table.locator('tbody tr').nth(0).getByText('OVERALL-TEST-1', { exact: true }).click()
  await expect(table.locator('tbody tr').nth(0).getByRole('checkbox')).toBeChecked()
  await (await toolbarButton(page, '设备总体计划', '批量修改')).click()
  dialog = page.getByRole('dialog', { name: '批量修改设备总体计划', exact: true })
  await expect(dialog).toContainText('已选 2 台设备')
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await expect(dialog.getByLabel('量值溯源方法', { exact: true })).toBeDisabled()
  await dialog.getByRole('checkbox', { name: '修改维护时间间隔', exact: true }).check()
  await dialog.getByLabel('维护时间间隔', { exact: true }).fill('每周')
  await dialog.getByRole('checkbox', { name: '修改控制措施', exact: true }).check()
  await expect(dialog.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  await dialog.screenshot({ path: info.outputPath(`overall-batch-${width}.png`) })
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table.getByText('每周', { exact: true })).toHaveCount(2)
  const rows = (await (await page.request.post(`${endpoint}/query`, { headers, data: { value: 'OVERALL-TEST-' } })).json()).items
  expect(rows[0]).toMatchObject({ traceMethod: '检定', traceCycle: '12个月', maintenanceInterval: '每周', controlMeasures: '' })
  expect(rows[1]).toMatchObject({ traceMethod: '', maintenanceInterval: '每周' })
  expect(rows[2]).toMatchObject({ maintenanceInterval: '' })
  await table.locator('tbody tr').first().getByRole('checkbox').check()
  await openToolbarExport(page, '设备总体计划')
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  const download = await downloading, csv = await readFile((await download.path())!, 'utf8')
  expect(csv).toContain('OVERALL-TEST-1'); expect(csv).toContain('每周'); expect(csv).not.toContain('OVERALL-TEST-2')
  if (width === 1440) {
    const popupPromise = page.waitForEvent('popup')
    await (await toolbarButton(page, '设备总体计划', '打印')).click()
    const popup = await popupPromise
    await expect.poll(() => popup.url(), { timeout: 30000 }).toContain('blob:')
    await popup.close()
  }
  await page.screenshot({ path: info.outputPath(`overall-list-${width}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await form.getByLabel('查询字段').selectOption('accuracy')
  await form.getByLabel('匹配方式').selectOption('gte')
  await form.getByLabel('查询值').fill('3')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('OVERALL-TEST-3')
  await expect(table).not.toContainText('OVERALL-TEST-1')
  await page.reload()
  await expect(form.getByLabel('查询字段')).toHaveValue('accuracy')
  await expect(table).toContainText('OVERALL-TEST-3')
})

test('overall plan batch conflict does not partially apply and keeps the draft', async ({ page }) => {
  await page.goto('/#/quality/equipment/plans/overall')
  const table = page.getByRole('table', { name: '设备总体计划列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  const headers = { 'X-Demo-Actor': 'admin' }, endpoint = '/api/registration/quality/equipment/plans/overall'
  const rows = (await (await page.request.post(`${endpoint}/query`, { headers, data: {} })).json()).items
  await table.locator('tbody tr').nth(0).getByRole('checkbox').check()
  await table.locator('tbody tr').nth(1).getByRole('checkbox').check()
  await (await toolbarButton(page, '设备总体计划', '批量修改')).click()
  const dialog = page.getByRole('dialog', { name: '批量修改设备总体计划', exact: true })
  await dialog.getByRole('checkbox', { name: '修改量值溯源方法', exact: true }).check()
  await dialog.getByLabel('量值溯源方法', { exact: true }).fill('草稿待保存')
  expect((await page.request.post(`${endpoint}/save`, { headers, data: { records: [rows[1]], changes: { traceCycle: '其他人修改' } } })).ok()).toBe(true)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toContainText('本次未修改任何记录')
  await expect(dialog.getByLabel('量值溯源方法', { exact: true })).toHaveValue('草稿待保存')
  const first = await (await page.request.post(`${endpoint}/detail`, { headers, data: { id: rows[0].id } })).json()
  expect(first.traceMethod).toBe(rows[0].traceMethod)
  await dialog.getByRole('button', { name: '返回并刷新列表', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(table).toContainText('其他人修改')
})
