import { test, expect } from '@playwright/test'

const root = '/commissions/registration'
const url = `/#${root}?cPage=2&sPage=2&scope=all&current=demo-wt-6&cColumns=code,name,status,contact&sSort=code&sDirection=asc`
for (const width of [1440, 390]) test(`view and cancel requery while preserving selections and scroll at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(url)
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  const samples = page.getByRole('table', { name: '样品列表', exact: true })
  await expect(samples.locator('tbody tr')).toHaveCount(10)
  const choice = samples.locator('tbody input:enabled').first()
  const label = await choice.getAttribute('aria-label')
  await choice.check()
  const link = table.getByRole('link', { name: 'WT202609006', exact: true })
  await link.scrollIntoViewIfNeeded()
  await link.click({ trial: true })
  const scroll = await page.evaluate(() => scrollY), originalUrl = page.url()
  const requests: string[] = []
  page.on('request', request => { if (/\/api\/registration\/(?:commissions\/query|samples\/query|commissions\/[^/]+\/summary)$/.test(request.url())) requests.push(request.url()) })
  await link.click()
  await expect(page.getByRole('heading', { name: '委托详情', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  await expect(page).toHaveURL(originalUrl)
  await expect(samples.getByLabel(label!, { exact: true })).toBeChecked()
  await expect(table.getByRole('columnheader', { name: '委托人', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '第 2 页', exact: true }).first()).toHaveAttribute('aria-current', 'page')
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(scroll)
  expect(requests.filter(path => path.endsWith('/commissions/query'))).toHaveLength(1)
  expect(requests.filter(path => path.endsWith('/samples/query'))).toHaveLength(1)
  await table.getByRole('button', { name: 'WT202609006 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '修改', exact: true }).click()
  await expect(page.getByRole('form', { name: '委托表单' })).toBeVisible()
  await page.getByLabel('项目名称', { exact: true }).fill('取消后不应保存的修改')
  await page.getByRole('link', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '放弃修改并离开', exact: true }).click()
  await expect(page).toHaveURL(originalUrl)
  await expect(samples.getByLabel(label!, { exact: true })).toBeChecked()
  await expect(table.getByRole('checkbox', { name: '选择委托 WT202609006', exact: true })).toBeChecked()
  expect(requests.filter(path => path.endsWith('/commissions/query'))).toHaveLength(2)
  expect(requests.filter(path => path.endsWith('/samples/query'))).toHaveLength(2)
})

test('saving an existing sample reloads lists without losing valid selections', async ({ page }) => {
  await page.goto(`/#${root}?scope=all&current=demo-wt-1&sSort=code&sDirection=asc`)
  const samples = page.getByRole('table', { name: '样品列表', exact: true })
  await samples.getByRole('checkbox', { name: '选择样品 SP2026090001', exact: true }).check()
  await samples.getByRole('button', { name: 'SP2026090001 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  await page.getByLabel('工程/产品名称', { exact: false }).fill('返回后更新的样品')
  const queries: string[] = []
  page.on('request', request => { if (/\/(commissions|samples)\/query$/.test(request.url())) queries.push(request.url()) })
  await page.getByRole('button', { name: '保存并返回', exact: true }).click()
  await expect(samples).toContainText('返回后更新的样品')
  await expect(samples.getByRole('checkbox', { name: '选择样品 SP2026090001', exact: true })).toBeChecked()
  expect(queries.some(path => path.endsWith('/samples/query'))).toBe(true)
  expect(queries.filter(path => path.endsWith('/commissions/query'))).toHaveLength(1)
})

test('saving a commission reloads both lists while retaining rows and sample selections', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(url)
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  const samples = page.getByRole('table', { name: '样品列表', exact: true })
  await expect(samples.locator('tbody tr')).toHaveCount(10)
  const choice = samples.locator('tbody input:enabled').first(), label = await choice.getAttribute('aria-label')
  await choice.check()
  const previousName = await table.locator('tbody tr').first().innerText()
  await table.getByRole('button', { name: 'WT202609006 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '修改', exact: true }).click()
  await page.getByLabel('项目名称', { exact: true }).fill('返回后更新的项目')
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const queries: string[] = []
  page.on('request', request => { if (/\/(commissions|samples)\/query$/.test(request.url())) queries.push(request.url()) })
  await page.route('**/commissions/query', async route => { await gate; await route.continue() })
  try {
    await page.getByRole('button', { name: '保存并返回', exact: true }).click()
    await expect(page).toHaveURL(/registration\?cPage=2/)
    const retained = page.locator('table[aria-label="委托列表"]')
    await expect(retained.locator('tbody tr').first()).toHaveText(previousName, { useInnerText: true })
    await expect(retained.locator('..').locator('..')).toHaveAttribute('aria-busy', 'true')
    await expect(samples.getByLabel(label!, { exact: true })).toBeChecked()
  } finally { release() }
  await expect(table).toContainText('返回后更新的项目')
  expect(queries.filter(path => path.endsWith('/samples/query'))).toHaveLength(1)
  expect(queries.filter(path => path.endsWith('/commissions/query'))).toHaveLength(1)
  await expect(samples.getByLabel(label!, { exact: true })).toBeChecked()
})

test('all returns query the backend, including saved edits and cancelled failed validation', async ({ page }) => {
  await page.goto(`/#${root}?cSearchField=name&cContains=园区地表水&current=demo-wt-1`)
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  await table.getByRole('button', { name: 'WT202609001 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '修改', exact: true }).click()
  await page.getByLabel('项目名称', { exact: true }).fill('不再符合原筛选')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('.toast.show')).toContainText('委托已保存。')
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  await expect(table.getByRole('link', { name: 'WT202609001', exact: true })).toHaveCount(0)
  await expect(page.locator('#commission-filter-contains')).toHaveValue('园区地表水')
  await page.goto(`/#${root}?current=demo-wt-2`)
  await table.getByRole('button', { name: 'WT202609002 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '修改', exact: true }).click()
  await page.route('**/commissions/demo-wt-2', route => route.request().method() === 'PUT' ? route.fulfill({ status: 422, json: { error: { code: 'VALIDATION', message: '请检查委托资料' } } }) : route.continue())
  const queries: string[] = []
  page.on('request', request => { if (/\/(commissions|samples)\/query$/.test(request.url())) queries.push(request.url()) })
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('.toast.show')).toContainText('请检查委托资料')
  await page.getByRole('link', { name: '取消', exact: true }).click()
  await expect(table.getByRole('link', { name: 'WT202609002', exact: true })).toBeVisible()
  expect(queries.filter(path => path.endsWith('/commissions/query'))).toHaveLength(1)
  expect(queries.filter(path => path.endsWith('/samples/query'))).toHaveLength(1)
})
