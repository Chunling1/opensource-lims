import { toolbarButton } from './helpers/toolbar'
import { test, expect } from '@playwright/test'
import { originalPdf } from '../helpers/originalPdf'

test('check report preview automatically loads the saved PDF and retries read-only failures', async ({ page }, info) => {
  const pdf = await originalPdf([595], 'Final report for checking')
  let failPreview = true, downloads = 0, writes = 0
  await page.route('**/samples/demo-yp-77/data-entry', async route => {
    const response = await route.fetch(), detail = await response.json()
    await route.fulfill({ response, json: { ...detail, reportStatus: 'ready', job: { id: 'check-preview-test', status: 'ready' } } })
  })
  await page.route('**/data-entry/report-tasks/check-preview-test/pdf', async route => {
    downloads++
    if (failPreview) await route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '报告预览暂时不可用。' } } })
    else await route.fulfill({ contentType: 'application/pdf', body: pdf })
  })
  page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/data-entry/')) writes++ })
  await page.goto('/#/testing/data-check/demo-yp-77')
  const preview = page.getByRole('region', { name: '报告预览', exact: true })
  await expect(preview).toContainText('报告预览暂时不可用。')
  failPreview = false
  await preview.getByRole('button', { name: '刷新预览', exact: true }).click()
  await expect(preview.locator('iframe')).toHaveAttribute('src', /^blob:/)
  await expect(preview.getByRole('link', { name: '新窗口预览', exact: true })).toBeVisible()
  await expect(preview.getByRole('button', { name: '打印', exact: true })).toBeEnabled()
  const download = page.waitForEvent('download')
  await preview.getByRole('button', { name: '下载', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('SP2026090077-最终报告.pdf')
  await page.getByRole('tab', { name: '原始记录', exact: true }).click()
  await expect(preview).toBeHidden()
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(preview.locator('iframe')).toHaveAttribute('src', /^blob:/)
  expect(downloads).toBe(3)
  expect(writes).toBe(0)
  await page.screenshot({ path: info.outputPath('data-check-saved-report.png'), fullPage: true })
})

