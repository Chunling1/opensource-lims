import { openReportFiles } from './helpers/reportFiles'
import { expect, test } from '@playwright/test'

const word = { name: '待确认报告.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('504b0304', 'hex') }

test('previous step generates once; a failed PDF load can be retried without regenerating the report', async ({ page }) => {
  let generations = 0
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/data-entry/combine')) generations++ })
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  await openReportFiles(page)
  await page.route('**/report-tasks/*/pdf', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '预览暂时无法加载。' } } }))
  await page.getByRole('button', { name: '预览报告', exact: true }).click()
  await expect(page.getByRole('heading', { name: '完整报告预览', level: 4 })).toBeVisible()
  await expect(page.getByRole('button', { name: '生成预览', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '重新加载预览', exact: true })).toBeEnabled()
  await expect(page.getByRole('tab', { name: '报告确认', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '报告确认', exact: true })).toBeDisabled()
  await page.unroute('**/report-tasks/*/pdf')
  await page.getByRole('button', { name: '重新加载预览', exact: true }).click()
  await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: '报告确认', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: '生成预览', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '生成预览', exact: true }).locator('.spinner-border')).toHaveCount(0)
  await expect(page.locator('#report-panel-preview')).not.toContainText('已用')
  await expect(page.getByRole('button', { name: '重新加载预览', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '报告预览', exact: true })).toHaveCount(0)
  expect(generations).toBe(1)
})

for (const target of ['上传文件', '报告预览']) {
  test(`initial ${target} navigation adopts the layout and preview navigation generates only once`, async ({ page }) => {
    const writes: { url: string; body: Record<string, unknown> }[] = []
    page.on('request', request => {
      if (request.method() === 'POST' && request.url().includes('/data-entry/')) writes.push({ url: request.url(), body: request.postDataJSON() })
    })
    await page.goto('/#/testing/data-entry/demo-yp-76/report')
    if (target === '上传文件') await page.getByLabel('首页版式', { exact: true }).selectOption('extended')
    const step = page.getByRole('tab', { name: target, exact: true })
    await step.focus()
    await page.keyboard.press('Enter')
    await expect(step).toHaveAttribute('aria-selected', 'true')
    if (target === '报告预览') await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
    const expectedWrites = target === '报告预览' ? 2 : 1
    expect(writes).toHaveLength(expectedWrites)
    if (target === '报告预览') expect(writes[1]!.url).toMatch(/\/combine$/)
    expect(writes[0]!.url).toMatch(/\/save$/)
    expect(writes[0]!.body).toMatchObject({ adoptLayout: true, layoutId: target === '上传文件' ? 'extended' : 'standard' })
    await page.reload()
    await page.getByRole('tab', { name: target, exact: true }).click()
    await expect(page.getByRole('tab', { name: target, exact: true })).toHaveAttribute('aria-selected', 'true')
    expect(writes).toHaveLength(expectedWrites)
    await page.goto('/#/testing/data-entry/demo-yp-76/report?mode=view')
    await page.getByRole('tab', { name: '报告模板', exact: true }).click()
    await expect(page.getByRole('button', { name: '上传文件', exact: true })).toBeDisabled()
    await expect(page.getByRole('tab', { name: '上传文件', exact: true })).toBeEnabled()
    await page.getByRole('tab', { name: target, exact: true }).click()
    await expect(page.getByRole('tab', { name: target, exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(page.locator('input[type="file"]')).toHaveCount(0)
    await expect(page.getByRole('button', { name: '删除', exact: true })).toHaveCount(0)
    expect(writes).toHaveLength(expectedWrites)
  })
}

test('step navigation preserves the choice after validation failure and retains pending files', async ({ page }) => {
  let writes = 0
  page.on('request', request => { if (request.method() === 'POST' && /data-entry\/(save|upload|combine)$/.test(request.url())) writes++ })
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  for (const name of ['报告模板', '上传文件', '报告预览', '报告确认']) await expect(page.getByRole('tab', { name, exact: true })).toBeVisible()
  await page.getByLabel('首页版式', { exact: true }).selectOption('extended')
  await page.route('**/data-entry/save', route => route.fulfill({ status: 422, json: { error: { code: 'VALIDATION', message: '请选择有效报告版式。', fieldErrors: { layoutId: '当前报告不支持此版式。' } } } }))
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  await expect(page.getByRole('tab', { name: '报告模板', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('region', { name: '报告模板', exact: true }).getByText('当前报告不支持此版式。', { exact: true })).toBeVisible()
  await expect(page.getByLabel('首页版式', { exact: true })).toHaveValue('extended')
  expect(writes).toBe(1)
  await page.unroute('**/data-entry/save')
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  await expect(page.getByText('当前首页版式：扩展版', { exact: true })).toBeVisible()
  await page.getByLabel('上传完整报告', { exact: false }).setInputFiles(word)
  const confirmation = page.getByRole('dialog', { name: '完整报告上传确认' })
  await confirmation.getByRole('button', { name: '关闭弹窗', exact: true }).click()
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await expect(page.getByLabel('首页版式', { exact: true })).toHaveValue('extended')
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  await page.getByLabel('上传完整报告', { exact: false }).setInputFiles(word)
  await expect(confirmation).toContainText('待确认报告.docx')
  await expect(confirmation).toContainText('（扩展版）首页版式一致')
  expect(writes).toBe(3)
  await expect(page.getByRole('button', { name: '保存', exact: true, includeHidden: true })).toHaveCount(0)
})

test('background final generation does not switch tabs or scroll; PDF survives switching and stale results are removed', async ({ page }) => {
  test.setTimeout(60000)
  let pdfRequests = 0
  page.on('request', request => { if (/report-tasks\/[^/]+\/pdf$/.test(request.url())) pdfRequests++ })
  await page.addInitScript(() => {
    const original = Element.prototype.scrollIntoView
    Element.prototype.scrollIntoView = function (...args) {
      if (this.id === 'entry-preview') document.documentElement.dataset.previewScrolled = 'true'
      original.apply(this, args)
    }
  })
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  await expect(page.getByRole('tab', { name: '报告模板', exact: true })).toHaveAttribute('aria-selected', 'true')
  await openReportFiles(page)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/samples/demo-yp-76/data-entry', async route => {
    const response = await route.fetch()
    await gate
    await route.fulfill({ response })
  })
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  const scrollY = await page.evaluate(() => window.scrollY)
  release()
  await expect(page.locator('#report-panel-preview').getByRole('button', { name: '生成预览', exact: true, includeHidden: true })).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByRole('tab', { name: '上传文件', exact: true })).toHaveAttribute('aria-selected', 'true')
  expect(pdfRequests).toBe(0)
  expect(await page.evaluate(() => window.scrollY)).toBe(scrollY)
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  const frame = page.getByTitle('完整报告预览', { exact: true })
  await expect(frame).toBeVisible()
  const url = await frame.getAttribute('src')
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await expect(frame).toHaveAttribute('src', url!)
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(frame).toHaveAttribute('src', url!)
  expect(pdfRequests).toBe(1)
  await expect(page.locator('html')).not.toHaveAttribute('data-preview-scrolled', 'true')
  await frame.evaluate(element => element.setAttribute('data-retained-preview', 'true'))
  await page.getByRole('button', { name: '收起预览', exact: true }).click()
  await expect(frame).toBeHidden()
  await expect(page.getByRole('button', { name: '展开预览', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(frame).toBeHidden()
  await page.getByRole('button', { name: '展开预览', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(frame).toBeVisible()
  await expect(frame).toHaveAttribute('data-retained-preview', 'true')
  await expect(frame).toHaveAttribute('src', url!)
  expect(pdfRequests).toBe(1)
  await page.getByRole('button', { name: '收起预览', exact: true }).click()
  await expect(page.getByRole('button', { name: '报告预览', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '重新加载预览', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '展开预览', exact: true }).click()
  await expect(frame).toBeVisible()
  expect(pdfRequests).toBe(1)
  await page.reload()
  await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(frame).toBeVisible()
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  await page.getByLabel('添加附加文件', { exact: false }).setInputFiles(word)
  await expect(page.getByRole('button', { name: word.name, exact: true })).toBeVisible()
  await expect(frame).toHaveCount(0)
  await expect(page.getByRole('tab', { name: '报告确认', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: '生成预览', exact: true })).toBeEnabled()
  await expect(frame).toHaveCount(0)
  await page.route('**/data-entry/combine', route => route.continue({ postData: JSON.stringify({ ...route.request().postDataJSON(), scenario: 'failure' }) }))
  await page.getByRole('button', { name: '生成预览', exact: true }).click()
  await expect(page.getByRole('button', { name: '生成预览', exact: true })).toBeEnabled()
  await expect(page.getByRole('tab', { name: '报告确认', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: '生成预览', exact: true })).toBeEnabled()
  await page.unroute('**/data-entry/combine')
  await page.getByRole('button', { name: '生成预览', exact: true }).click()
  await expect(frame).toBeVisible()
  await page.goto('/#/testing/data-entry/demo-yp-76/report?mode=view')
  await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(frame).toBeVisible()
  await expect(page.getByRole('button', { name: '下载', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '收起预览', exact: true }).click()
  await expect(frame).toBeHidden()
  await page.getByRole('button', { name: '展开预览', exact: true }).click()
  await expect(frame).toBeVisible()
})

test('template download continues on another tab and only a final task changes the default page', async ({ page }) => {
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  await expect(page.getByRole('tab', { name: '报告模板', exact: true })).toHaveAttribute('aria-selected', 'true')
  await openReportFiles(page)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/samples/demo-yp-76/data-entry', async route => { const response = await route.fetch(); await gate; await route.fulfill({ response }) })
  const downloaded = page.waitForEvent('download')
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await page.getByRole('button', { name: '下载模板', exact: true }).click()
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  release()
  expect((await downloaded).suggestedFilename()).toContain('standard')
  await expect(page.getByRole('tab', { name: '上传文件', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.reload()
  await expect(page.getByRole('tab', { name: '报告模板', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.route('**/data-entry/combine', route => route.continue({ postData: JSON.stringify({ ...route.request().postDataJSON(), scenario: 'slow' }) }))
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: '生成预览', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '生成预览', exact: true })).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByRole('button', { name: '生成预览', exact: true }).locator('.spinner-border')).toBeVisible()
  await expect(page.getByRole('tab', { name: '上传文件', exact: true })).toBeEnabled()
})

for (const width of [1440, 390]) {
  test(`report tabs and preview are accessible without horizontal overflow at ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/#/testing/data-entry/demo-yp-76/report')
    await openReportFiles(page)
    for (const theme of ['light', 'dark']) {
      await page.evaluate(theme => document.documentElement.setAttribute('data-bs-theme', theme), theme)
      for (const name of ['报告模板', '上传文件', '报告预览']) {
        const tab = page.getByRole('tab', { name, exact: true })
        await tab.focus()
        await page.keyboard.press('Enter')
        await expect(tab).toHaveAttribute('aria-selected', 'true')
        await expect(page.getByRole('tabpanel')).toHaveCount(1)
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
        await page.screenshot({ path: info.outputPath(`report-${name}-${width}-${theme}.png`), fullPage: true, animations: 'disabled' })
      }
    }
    await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
    await page.screenshot({ path: info.outputPath(`report-pdf-${width}.png`), fullPage: true, animations: 'disabled' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await expect(page.getByRole('button', { name: '打印', exact: true })).toBeEnabled()
    await expect(page.getByRole('link', { name: '新窗口预览', exact: true })).toBeVisible()
  })
}
