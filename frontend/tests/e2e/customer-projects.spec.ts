import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { toolbarButton, openToolbarExport } from './helpers/toolbar'
import { emptyProject, projectFields, projectSections } from '../../src/types/customers/projects'

for (const width of [1440, 390]) test(`project form create, save-and-new, copy, batch and view at ${width}`, async ({ page }, info) => {
  test.setTimeout(120000)
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/customers/projects')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  let form = page.getByRole('dialog', { name: '新增工程信息', exact: true })
  await expect(form.getByLabel('工程编号', { exact: true })).toBeDisabled()
  for (const section of projectSections) await expect(form.getByRole('heading', { name: section.title, exact: true })).toHaveCount(1)
  for (const field of projectFields) await expect(form.getByLabel(field.label, { exact: true })).toHaveCount(1)
  await form.getByLabel('工程名称', { exact: true }).fill('工程回归甲')
  await form.getByLabel('委托单位', { exact: true }).fill('自定义委托单位')
  await form.getByLabel('工程类型', { exact: true }).selectOption('建筑')
  await form.getByLabel('建筑性质', { exact: true }).selectOption('保障房')
  await form.getByLabel('建筑结构型式', { exact: true }).selectOption('框架结构')
  await form.getByLabel('见证人', { exact: true }).fill('见证甲')
  await form.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('dialog', { name: '放弃未保存内容', exact: true }).getByRole('button', { name: '继续编辑' }).click()
  await form.getByLabel('工程名称', { exact: true }).scrollIntoViewIfNeeded()
  await form.screenshot({ path: info.outputPath(`project-form-${width}.png`) })
  await form.getByRole('button', { name: '保存并新增', exact: true }).click()
  await expect(form.getByLabel('工程名称', { exact: true })).toHaveValue('')
  await expect(form.getByLabel('委托单位', { exact: true })).toHaveValue('')
  await form.getByRole('button', { name: '取消', exact: true }).click()
  const table = page.getByRole('table', { name: '工程列表', exact: true })
  const menu = async (name: string, action: string) => { await table.getByRole('row').filter({ hasText: name }).getByRole('button', { name: /更多操作/ }).click(); await page.getByRole('menuitem', { name: action, exact: true }).click() }
  await expect(table).toContainText('工程回归甲')
  await menu('工程回归甲', '编辑')
  form = page.getByRole('dialog', { name: '修改工程信息', exact: true })
  await expect(form.getByLabel('见证人', { exact: true })).toHaveValue('见证甲')
  const originalCode = await form.getByLabel('工程编号', { exact: true }).inputValue()
  await form.getByLabel('工程名称', { exact: true }).fill('工程回归副本')
  await form.getByRole('button', { name: '复制', exact: true }).click()
  form = page.getByRole('dialog', { name: '新增工程信息', exact: true })
  await expect(form.getByLabel('工程编号', { exact: true })).toHaveValue('')
  await expect(form.getByLabel('工程名称', { exact: true })).toHaveValue('工程回归副本')
  await page.route('**/customers/projects/save', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '临时保存失败' } } }), { times: 1 })
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(form).toContainText('临时保存失败')
  await expect(form.getByLabel('工程名称', { exact: true })).toHaveValue('工程回归副本')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(form).toBeHidden()
  await expect(table).toContainText('工程回归甲')
  await expect(table).toContainText('工程回归副本')
  await expect(table.getByRole('row').filter({ hasText: '工程回归副本' })).not.toContainText(originalCode)
  await table.getByRole('checkbox', { name: /全选当前页/ }).check()
  await (await toolbarButton(page, '工程', '批量修改')).click()
  const batch = page.getByRole('dialog', { name: '批量修改工程信息', exact: true })
  await expect(batch.getByLabel('施工单位', { exact: true })).toBeDisabled()
  await batch.getByLabel('修改施工单位', { exact: true }).check()
  await batch.getByLabel('施工单位', { exact: true }).fill('统一施工单位')
  await batch.getByRole('button', { name: '保存', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: '确认批量修改工程', exact: true })
  await expect(batch).toBeVisible()
  await expect(confirmation).toContainText('统一施工单位')
  await confirmation.getByRole('button', { name: '确认修改' }).click()
  await expect(batch).toBeHidden()
  await expect(table.getByRole('cell', { name: '统一施工单位', exact: true })).toHaveCount(2)
  await menu('工程回归甲', '查看')
  const view = page.getByRole('dialog', { name: '查看工程信息', exact: true })
  await expect(view.getByLabel('工程名称', { exact: true })).toBeDisabled()
  await expect(view.getByLabel('施工单位', { exact: true })).toHaveValue('统一施工单位')
  await expect(view.getByLabel('见证人', { exact: true })).toHaveValue('见证甲')
  await expect(view.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
  await view.getByRole('button', { name: '返回', exact: true }).click()
  await menu('工程回归副本', '删除')
  await page.getByRole('dialog', { name: '删除工程', exact: true }).getByRole('button', { name: '确认删除' }).click()
  await expect(table).not.toContainText('工程回归副本')
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath(`project-list-${width}.png`) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('project template, atomic import, filters, export and column persistence', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/#/customers/projects')
  await expect(page.getByRole('button', { name: '新增', exact: true })).toBeEnabled()
  const templateDownload = page.waitForEvent('download')
  await (await toolbarButton(page, '工程', '下载模板')).click()
  const header = await readFile((await (await templateDownload).path())!, 'utf8')
  expect(header).toContain('工程名称'); expect(header).toContain('抽样地点')
  const line = (name: string) => { const draft = { ...emptyProject(), name, supervisionNumber: '监督01', address: '测试地址' }; return projectFields.map(field => draft[field.key as keyof typeof draft] || '').join(',') }
  await (await toolbarButton(page, '工程', '导入')).click()
  const modal = page.getByRole('dialog', { name: '导入工程', exact: true })
  await modal.getByLabel('导入文件').setInputFiles({ name: 'bad.csv', mimeType: 'text/csv', buffer: Buffer.from(header.trimEnd() + '\r\n' + line('导入甲') + '\r\n' + line('')) })
  await modal.getByRole('button', { name: '导入', exact: true }).click()
  await expect(modal).toContainText('第 3 行')
  await modal.getByLabel('导入文件').setInputFiles({ name: 'valid.csv', mimeType: 'text/csv', buffer: Buffer.from(header.trimEnd() + '\r\n' + line('导入甲') + '\r\n' + line('导入乙')) })
  await modal.getByRole('button', { name: '导入', exact: true }).click()
  await expect(modal).toBeHidden()
  const table = page.getByRole('table', { name: '工程列表', exact: true })
  await expect(table.getByRole('row')).toHaveCount(3)
  await (await toolbarButton(page, '工程', '显示')).click()
  const columns = page.getByRole('dialog', { name: '工程显示列', exact: true })
  await columns.getByLabel('监督登记号', { exact: true }).uncheck()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await page.reload()
  await expect(table.getByRole('columnheader', { name: '监督登记号', exact: true })).toHaveCount(0)
  await page.getByRole('form', { name: '工程查询' }).getByLabel('工程名称').fill('导入甲')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.getByRole('row')).toHaveCount(2)
  await openToolbarExport(page, '工程')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const csv = await readFile((await (await download).path())!, 'utf8')
  expect(csv).toContain('导入甲'); expect(csv).not.toContain('导入乙'); expect(csv).toContain('监督01')
})
