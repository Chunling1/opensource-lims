  await table(page, '人员').getByRole('cell', { name: 'DEMO-001', exact: true }).click({ position: { x: 2, y: 2 } })
  await table(page, '上岗证').getByRole('cell', { name: 'DEMO-C001-1', exact: true }).click({ position: { x: 2, y: 2 } })
  await table(page, '核准项目').getByRole('cell', { name: 'DEMO-P1', exact: true }).click({ position: { x: 2, y: 2 } })
