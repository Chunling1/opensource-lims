import { test, expect } from '@playwright/test'
import { selectGeneralSamplePlan } from './helpers/sample-plan'

const root = '/commissions/registration'

test('completion and cancellation affect only one row and enforce completed commission read-only rules', async ({ page }) => {
  await page.goto(`/#${root}?current=demo-wt-1,demo-wt-2`)
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  const row = table.getByRole('row').filter({ hasText: 'WT202609001' })
  const other = table.getByRole('row').filter({ hasText: 'WT202609002' })
  const openMenu = async () => { await row.getByRole('button', { name: /更多操作/ }).click(); return page.getByRole('menu', { name: 'WT202609001 更多操作', exact: true }) }
  let menu = await openMenu()
  await expect(menu.getByRole('menuitem')).toHaveText(['查看', '打印', '修改', '新增样品', '完成', '附件管理'])
  await menu.getByRole('menuitem', { name: '完成', exact: true }).click()
  await page.getByRole('dialog', { name: '完成', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(row).toContainText('已完成')
  await expect(other).toContainText('未完成')
  await expect(table.getByRole('checkbox', { name: '选择委托 WT202609001', exact: true })).toBeChecked()
  await expect(table.getByRole('checkbox', { name: '选择委托 WT202609002', exact: true })).toBeChecked()
  menu = await openMenu()
  await expect(menu.getByRole('menuitem')).toHaveText(['查看', '打印', '修改', '新增样品', '取消完成', '附件管理'])
  await expect(menu.getByRole('menuitem', { name: '修改', exact: true })).toBeDisabled()
  await expect(menu.getByRole('menuitem', { name: '新增样品', exact: true })).toBeDisabled()
  await menu.getByRole('menuitem', { name: '查看', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '项目名称', exact: true })).toHaveAttribute('readonly', '')
  await expect(page.getByRole('link', { name: '修改委托', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('添加附件', { exact: false })).toHaveCount(0)
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  menu = await openMenu()
  await menu.getByRole('menuitem', { name: '取消完成', exact: true }).click()
  await page.getByRole('dialog', { name: '取消完成', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(row).toContainText('未完成')
  menu = await openMenu()
  await menu.getByRole('menuitem', { name: '修改', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '项目名称', exact: true })).toBeEditable()
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '委托状态', exact: true }).locator('option')).toHaveText(['全部状态', '未完成', '已完成'])
})

test('newly saved commissions can register a single sample without adding test projects to the commission form', async ({ page }) => {
  await page.goto(`/#${root}/commissions/new?returnTo=${encodeURIComponent(root + '?cSearchField=name&cContains=单条登记主流程')}`)
  await page.getByRole('textbox', { name: '项目名称', exact: true }).fill('单条登记主流程')
  await page.getByLabel('委托单位', { exact: true }).fill('新建委托单位')
  await page.getByRole('button', { name: '保存并返回', exact: true }).click()
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText('未完成')
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '新增样品', exact: true }).click()
  await page.getByRole('tab', { name: '委托信息', exact: true }).click()
  await expect(page.getByLabel('委托单位', { exact: true })).toHaveValue('新建委托单位')
  await page.getByRole('tab', { name: '样品信息', exact: true }).click()
  await page.getByLabel('工程/产品名称', { exact: false }).fill('新委托所属样品')
  await page.getByLabel('检测类别', { exact: false }).selectOption('委托')
  await selectGeneralSamplePlan(page)
  await page.getByRole('button', { name: '保存并返回', exact: true }).click()
  const validation = page.locator('.toast.show').filter({ hasText: '请选择有效检测项目。' })
  await expect(validation).toBeVisible()
  await expect(validation).toHaveClass(/toast-border-warning/)
  await expect(validation).toContainText('操作提示')
  await expect(validation).not.toContainText('诊断编号')
  await expect(validation.locator('.alert-danger')).toHaveCount(0)
  await expect(page.getByLabel('工程/产品名称', { exact: false })).toHaveValue('新委托所属样品')
  await validation.getByRole('button', { name: '关闭操作提示', exact: true }).click()
  await page.getByRole('button', { name: '选择检测项目', exact: true }).click()
  await page.getByRole('checkbox', { name: 'pH 值', exact: true }).check()
  await page.getByRole('dialog', { name: '选择检测项目' }).getByRole('button', { name: '确定', exact: true }).click()
  await page.route('**/api/registration/samples', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL', message: '保存暂时失败，请重试。' } } }))
  await page.getByRole('button', { name: '保存并返回', exact: true }).click()
  const systemError = page.locator('.toast.show').filter({ hasText: '保存暂时失败，请重试。' })
  await expect(systemError).toHaveClass(/toast-border-danger/)
  await expect(systemError).toContainText('系统提示')
  await expect(systemError).toContainText('诊断编号')
  await expect(systemError.getByRole('button', { name: '复制编号', exact: true })).toBeVisible()
  await page.unroute('**/api/registration/samples')
  await page.getByRole('button', { name: '保存并返回', exact: true }).click()
  await expect(table).toContainText('单条登记主流程')
  await table.locator('tbody').getByRole('checkbox').check()
  await expect(page.getByRole('table', { name: '样品列表', exact: true })).toContainText('新委托所属样品')
})
