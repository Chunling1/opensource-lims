  await page.goto(`/#${root}?current=demo-wt-1&cColumns=code,name`)
  const row = page.getByRole('table', { name: '委托列表', exact: true }).getByRole('row').filter({ hasText: 'WT202609001' })
  await row.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '打印', exact: true }).click()
  await page.getByLabel('委托单类型', { exact: true }).selectOption('product')
  await page.getByLabel('第一联', { exact: true }).check()
  await page.getByLabel('第四联', { exact: true }).check()
  await page.getByLabel('第二联', { exact: true }).uncheck()
  await page.getByLabel('第三联', { exact: true }).uncheck()
