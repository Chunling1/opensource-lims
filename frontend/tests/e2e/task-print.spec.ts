import { test, expect, type Page } from '@playwright/test'
const headers = { 'X-Demo-Actor': 'admin' }
const path = '/testing/assignment/demo-yp-59/print'
async function scenario(page: Page, value: string) {
  let posts = 0
  await page.route('**/samples/*/task-prints', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    posts++
    expect(Object.keys(route.request().postDataJSON())).toEqual(['version'])
    await route.continue({ postData: JSON.stringify({ ...route.request().postDataJSON(), scenario: value }) })
  })
  return () => posts
}
test('explicit generation restores after navigation, downloads PDF and preserves list context', async ({ page }, info) => {
  test.setTimeout(60000)
  const posts = await scenario(page, 'normal')
  await page.goto('/#/testing/assignment')
  const table = page.getByRole('table', { name: '检测任务分配列表', exact: true })
  await table.getByRole('button', { name: 'SP2026090051 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '打印任务单', exact: true })).toBeEnabled()
  await page.keyboard.press('Escape')
  await page.getByRole('form', { name: '检测任务分配条件', exact: true }).getByLabel('数据状态', { exact: true }).selectOption('任务分配完成')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await table.getByRole('button', { name: 'SP2026090059 更多操作', exact: true }).click()
  const listUrl = page.url()
  await page.getByRole('menuitem', { name: '打印任务单', exact: true }).click()
  await expect(page.getByRole('heading', { name: '打印任务单', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '生成任务单', exact: true })).toBeVisible()
  expect(posts()).toBe(0)
  await expect(page.getByLabel('委托单类型')).toHaveCount(0)
  await page.getByRole('button', { name: '生成并预览', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: '已加入生成队列' })).toBeVisible()
  await expect(page.getByRole('button', { name: '生成并预览', exact: true })).toBeDisabled()
  const jobUrl = page.url()
  await page.getByRole('link', { name: '返回检测任务分配', exact: true }).first().click()
  await expect(page).toHaveURL(listUrl)
  await page.goto('/#' + path)
  await expect(page).toHaveURL(/task=/)
  await page.reload()
  await expect(page.getByTitle('任务单 PDF 预览')).toBeVisible({ timeout: 25000 })
  expect(posts()).toBe(1)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载 PDF', exact: true }).click()
  const file = await download
  expect(file.suggestedFilename()).toBe('SP2026090059-任务单.pdf')
  await file.saveAs(info.outputPath('task-sheet.pdf'))
  const pdf = page.getByTitle('任务单 PDF 预览')
  await expect(page.getByRole('link', { name: '在新标签页查看 PDF' })).toHaveAttribute('href', (await pdf.getAttribute('src'))!)
  await expect(page.getByRole('button', { name: '重新生成并预览', exact: true })).toBeEnabled()
  await page.evaluate(() => { document.querySelector('iframe')!.contentWindow!.print = () => document.body.setAttribute('data-print-called', 'true') })
  await page.getByRole('button', { name: '打印', exact: true }).click()
  await expect(page.locator('body')).toHaveAttribute('data-print-called', 'true')
  await page.getByRole('tab', { name: '生成记录', exact: true }).click()
  await expect(page.getByRole('table', { name: '任务单生成记录' })).toContainText('当前版本')
  for (const [width, theme] of [[1440, 'light'], [390, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(t => document.documentElement.setAttribute('data-bs-theme', t), theme)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`task-print-${width}-${theme}.png`), fullPage: true })
    await page.getByRole('tab', { name: '预览与打印', exact: true }).click()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`task-preview-${width}-${theme}.png`), fullPage: true })
    await page.getByRole('tab', { name: '生成记录', exact: true }).click()
  }
  const undo = await page.request.post('/api/registration/samples/demo-yp-59/assignment-action', { headers, data: { action: 'undo', version: 1 } })
  expect(undo.ok()).toBe(true)
  await page.goto('/#' + path)
  await expect(page.getByRole('heading', { name: '生成任务单', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '生成并预览', exact: true })).toBeEnabled()
  await page.getByRole('tab', { name: '生成记录', exact: true }).click()
  await expect(page.getByRole('table', { name: '任务单生成记录' })).toContainText('历史版本')
  await page.goto(jobUrl)
  await expect(page.getByText('历史版本：此文件对应生成时的分配信息，不代表当前分配结果。')).toBeVisible()
  await expect(page.getByTitle('任务单 PDF 预览')).toBeVisible()
  await page.goto('/#' + path)
  await page.getByRole('button', { name: '生成并预览', exact: true }).click()
  await expect(page.getByRole('heading', { name: '已加入生成队列' })).toBeVisible()
  await page.reload()
  await expect(page.getByTitle('任务单 PDF 预览')).toBeVisible({ timeout: 25000 })
  expect(posts()).toBe(2)
  await page.getByRole('tab', { name: '生成记录', exact: true }).click()
  const history = page.getByRole('table', { name: '任务单生成记录' })
  await expect(history.getByRole('button', { name: '预览', exact: true })).toHaveCount(2)
  await expect(history).toContainText('当前版本')
  await expect(history).toContainText('历史版本')
})
test('unassigned task opens from its row menu and generates without assignment', async ({ page }) => {
  const posts = await scenario(page, 'normal')
  await page.goto('/#/testing/assignment')
  await page.getByRole('button', { name: 'SP2026090051 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '打印任务单', exact: true }).click()
  await expect(page.getByRole('button', { name: '生成并预览', exact: true })).toBeEnabled()
  expect(posts()).toBe(0)
  const before = await (await page.request.get('/api/registration/samples/demo-yp-51', { headers })).json()
  await page.getByRole('button', { name: '生成并预览', exact: true }).click()
  await expect(page.getByTitle('任务单 PDF 预览')).toBeVisible({ timeout: 25000 })
  expect(posts()).toBe(1)
  expect(await (await page.request.get('/api/registration/samples/demo-yp-51', { headers })).json()).toEqual(before)
})
for (const [value, title] of [['failure', '生成失败'], ['expired', '文件已过期']] as const) test(`task print ${value} allows explicit regeneration only`, async ({ page }) => {
  const posts = await scenario(page, value)
  await page.goto('/#' + path)
  await page.getByRole('button', { name: '生成并预览', exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible({ timeout: 25000 })
  expect(posts()).toBe(1)
  await expect(page.getByRole('button', { name: '重新生成', exact: true })).toBeEnabled()
  await expect(page.getByTitle('任务单 PDF 预览')).toHaveCount(0)
})
test('status network errors retry reads without resubmitting', async ({ page }) => {
  const posts = await scenario(page, 'slow')
  await page.goto('/#' + path)
  await page.getByRole('button', { name: '生成并预览', exact: true }).click()
  await expect(page.getByRole('heading', { name: '已加入生成队列' })).toBeVisible()
  await page.route('**/task-print-context', route => route.abort())
  await expect(page.getByText('暂时无法获取进度，后台任务可能仍在运行。', { exact: false })).toBeVisible({ timeout: 10000 })
  await page.getByRole('button', { name: '刷新状态', exact: true }).click()
  expect(posts()).toBe(1)
  await page.unroute('**/task-print-context')
  await page.getByRole('button', { name: '刷新状态', exact: true }).click()
  await expect(page.getByRole('button', { name: '刷新状态', exact: true })).toHaveCount(0)
  expect(posts()).toBe(1)
})
