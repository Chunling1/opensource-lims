import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { clientYearRange } from '../../src/services/common/date'
import { pickDateRange, pickRangeDay } from './helpers/dateRange'

const root = '/#/commissions/query'
test('advanced commission query is independent, cancelable and survives navigation and export', async ({ page }, testInfo) => {
  const requests: Record<string, unknown>[] = []
  page.on('request', r => { if (r.url().endsWith('/commissions/query')) requests.push(r.postDataJSON()) })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${root}?cSearchField=code&cContains=WT202609005&cStatus=已完成&current=demo-wt-5`)
  const form = page.getByRole('form', { name: '委托查询', exact: true })
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  const region = page.getByRole('region', { name: '委托列表区域', exact: true })
  const dialog = page.getByRole('dialog', { name: '委托高级查询', exact: true })
  const open = () => form.getByRole('button', { name: '高级', exact: true }).click()
  await expect(table).toContainText('WT202609005')
  const before = requests.length
  await open()
  await expect(dialog.getByRole('textbox')).toHaveCount(9)
  for (const label of ['委托编号', '样品/工程名称', '委托单位', '委托人', '委托经办人']) await expect(dialog.getByLabel(label, { exact: true })).toBeVisible()
  await expect(dialog.getByLabel('委托日期', { exact: true })).toBeDisabled()
  await expect(dialog.getByLabel('委托状态')).toHaveValue('')
  for (const label of ['合同号', '工程备案编号', '工程编码（交易中心）']) await expect(dialog.getByLabel(label, { exact: true })).toBeVisible()
  await dialog.getByLabel('委托编号', { exact: true }).fill('unsubmitted')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  expect(requests).toHaveLength(before)
  await open()
  await expect(dialog.getByLabel('委托编号', { exact: true })).toHaveValue('')
  await dialog.getByLabel('委托编号', { exact: true }).fill('wt202609001')
  await dialog.getByLabel('委托人', { exact: true }).fill('张经理')
  await dialog.screenshot({ path: testInfo.outputPath('advanced-desktop.png') })
  await dialog.getByLabel('委托人', { exact: true }).press('Enter')
  await expect(dialog).toBeHidden()
  await expect(table).toContainText('WT202609001')
  await expect(table).not.toContainText('WT202609005')
  expect(page.url()).not.toContain('current=')
  expect(requests.at(-1)).toMatchObject({ commissionAdvanced: { code: 'wt202609001', contact: '张经理' }, page: 1 })
  for (const key of ['from', 'to', 'status', 'searchField', 'contains', 'commissionCode']) expect(requests.at(-1)).not.toHaveProperty(key)
  await expect(form.getByLabel('包含')).toHaveValue('WT202609005')
  await expect(form.getByLabel('委托状态')).toHaveValue('已完成')
  await region.getByRole('button', { name: '导出', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await region.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const csv = await readFile((await (await downloading).path())!, 'utf8')
  expect(csv.split('\r\n')).toHaveLength(2)
  expect(csv).toContain('WT202609001')
  await table.getByRole('link', { name: 'WT202609001', exact: true }).click()
  await page.getByRole('link', { name: '返回委托查询', exact: true }).click()
  await page.reload()
  await expect(table).toContainText('WT202609001')
  await open()
  await expect(dialog.getByLabel('委托编号', { exact: true })).toHaveValue('wt202609001')
  await dialog.getByLabel('委托编号', { exact: true }).fill('WT202609002')
  await dialog.getByRole('button', { name: '关闭弹窗' }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('WT202609005')
  expect(requests.at(-1)).not.toHaveProperty('commissionAdvanced')
  await open()
  await expect(dialog.getByLabel('委托编号', { exact: true })).toHaveValue('wt202609001')
  await dialog.getByLabel('委托编号', { exact: true }).fill('')
  await dialog.getByLabel('委托人', { exact: true }).fill('')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(5)
  await region.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page).toHaveURL(/cPage=2/)
  expect(requests.at(-1)).toMatchObject({ commissionAdvanced: {}, page: 2 })
})

test('advanced dates, failure retry and mobile modal keep independent drafts', async ({ page }, testInfo) => {
  await page.goto(root)
  const form = page.getByRole('form', { name: '委托查询', exact: true })
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  const dialog = page.getByRole('dialog', { name: '委托高级查询', exact: true })
  const range = clientYearRange()
  await expect(table.locator('tbody tr')).toHaveCount(5)
  await form.getByRole('button', { name: '高级', exact: true }).click()
  await dialog.getByLabel('按委托日期查询').check()
  const dates = dialog.getByLabel('委托日期', { exact: true })
  await expect(dates).toHaveValue(`${range.from} 至 ${range.to}`)
  await dates.click()
  await pickRangeDay(page, '2000-01-01')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('请选择结束日期')
  await dates.click(); await pickRangeDay(page, '2000-12-31')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的委托')
  await expect(form.getByLabel('委托日期')).toHaveValue(`${range.from} 至 ${range.to}`)
  await form.getByRole('button', { name: '高级', exact: true }).click()
  await expect(dates).toHaveValue('2000-01-01 至 2000-12-31')
  await pickDateRange(page, dates, range.to, range.to)
  let fail = true
  await page.route('**/commissions/query', async route => {
    if (fail) { fail = false; await route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '高级查询暂时失败' } } }); return }
    await route.continue()
  })
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByText('高级查询暂时失败', { exact: true })).toBeVisible()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: /重试/ }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  for (const [width, theme] of [[390, 'dark'], [320, 'light']] as const) {
    await page.setViewportSize({ width, height: 844 })
    await page.evaluate(theme => document.documentElement.setAttribute('data-bs-theme', theme), theme)
    await form.getByRole('button', { name: '高级', exact: true }).click()
    await dialog.getByLabel('委托日期', { exact: true }).scrollIntoViewIfNeeded()
    await dates.click()
    const calendar = page.locator('.flatpickr-calendar.open')
    await expect(calendar).toBeVisible()
    const box = await calendar.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(width + 1)
    await page.screenshot({ animations: 'disabled', path: testInfo.outputPath(`advanced-${width}-${theme}.png`) })
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
})

test('advanced fields match basic content options and combine with their own status using AND', async ({ page }) => {
  await page.goto(`${root}?cQueryMode=advanced`)
  const form = page.getByRole('form', { name: '委托查询', exact: true })
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  const dialog = page.getByRole('dialog', { name: '委托高级查询', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(5)
  await form.getByRole('button', { name: '高级', exact: true }).click()
  const labels = await form.getByLabel('查询内容').locator('option').allTextContents()
  for (const label of labels.filter(label => label !== '全部')) await expect(dialog.getByRole('textbox', { name: label, exact: true })).toBeVisible()
  await dialog.getByLabel('委托编号', { exact: true }).fill('WT202609001')
  await dialog.getByLabel('委托经办人', { exact: true }).fill('李受理')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的委托')
  await form.getByRole('button', { name: '高级', exact: true }).click()
  await dialog.getByLabel('委托经办人', { exact: true }).fill('演示')
  await dialog.getByLabel('委托状态').selectOption('已完成')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的委托')
  await form.getByRole('button', { name: '高级', exact: true }).click()
  await dialog.getByLabel('委托状态').selectOption('未完成')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('WT202609001')
  await page.reload()
  await form.getByRole('button', { name: '高级', exact: true }).click()
  await expect(dialog.getByLabel('委托经办人')).toHaveValue('演示')
  await expect(dialog.getByLabel('委托状态')).toHaveValue('未完成')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await form.getByLabel('包含').fill('李受理')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).not.toContainText('WT202609001')
  await expect(table).toContainText('李受理')
})


test('extra advanced fields are submitted to the backend and restored without constraining basic queries', async ({ page }) => {
  const requests: Record<string, unknown>[] = []
  page.on('request', r => { if (r.url().endsWith('/commissions/query')) requests.push(r.postDataJSON()) })
  await page.goto(root)
  const form = page.getByRole('form', { name: '委托查询', exact: true })
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  const dialog = page.getByRole('dialog', { name: '委托高级查询', exact: true })
  await form.getByRole('button', { name: '高级', exact: true }).click()
  const values = { contract: 'Contract-ABC', projectRegistrationCode: 'Record-ABC', projectTradingCode: 'Trading-ABC' }
  for (const [key, value] of Object.entries(values)) await dialog.locator(`#commission-advanced-${key}`).fill(value)
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的委托')
  expect(requests.at(-1)).toMatchObject({ commissionAdvanced: values })
  await page.reload()
  await form.getByRole('button', { name: '高级', exact: true }).click()
  for (const [key, value] of Object.entries(values)) await expect(dialog.locator(`#commission-advanced-${key}`)).toHaveValue(value)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(5)
  expect(requests.at(-1)).not.toHaveProperty('commissionAdvanced')
})
