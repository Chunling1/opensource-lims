import { expect, test, type Page } from '@playwright/test'

const sampleForm = '/#/commissions/registration/samples/new?commissionId=demo-wt-1'
async function selectBases(page: Page) {
  await page.goto(sampleForm)
  await expect(page.getByRole('button', { name: '选择检测依据', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '选择检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '选择检测方案', exact: true })
  await plans.getByRole('button', { name: '风速、压力校准实验室', exact: true }).click()
  await plans.getByRole('radio', { name: '选择 压力校准', exact: true }).check()
  await plans.getByRole('button', { name: '确定', exact: true }).click()
  await page.getByRole('button', { name: '选择检测依据', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择检测依据', exact: true })
  for (const code of ['001', '002', '003', '004']) await dialog.getByRole('checkbox', { name: `选择 STD-SY-${code}-2026`, exact: true }).check()
  await dialog.getByLabel('英文书名号', { exact: true }).check()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '检测依据', exact: true })).toBeEditable()
}

const labels = ['001', '002', '003', '004'].map((code, index) => `STD-SY-${code}-2026<压力校准技术规范（${index + 1}）>`)

test('protected textarea edits separators, preserves them on save and retains unchanged pairs on reselection', async ({ page }, testInfo) => {
  await selectBases(page)
  const field = page.getByRole('textbox', { name: '检测依据', exact: true })
  await expect(field).toHaveValue(labels.join('；'))
  await field.focus()
  await field.evaluate((element, start) => (element as HTMLTextAreaElement).setSelectionRange(start, start + 1), labels[0]!.length)
  await field.press('Enter')
  const formatted = labels[0] + '\n' + labels[1] + '；' + labels[2] + '；' + labels[3]
  await expect(field).toHaveValue(formatted)
  await page.getByRole('button', { name: '选择检测依据', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择检测依据', exact: true })
  await dialog.getByRole('button', { name: '清空', exact: true }).click()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(field).toHaveValue(formatted)
  const mixed = labels[0] + '\n' + labels[1] + '、 ' + labels[2] + ';' + labels[3]
  await field.fill(mixed)
  await page.getByLabel('工程/产品名称', { exact: false }).fill('分隔符编辑验证')
  await page.getByLabel('检测类别', { exact: false }).selectOption('委托')
  const request = page.waitForRequest(r => r.url().endsWith('/samples') && r.method() === 'POST')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  expect((await request).postDataJSON().input.details.testBasisSeparators).toEqual(['\n', '、 ', ';'])
  await expect(page).toHaveURL(/samples\/[^/]+\/edit/)
  await page.reload()
  await expect(field).toHaveValue(mixed)
  for (const [width, theme] of [[1440, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.evaluate(t => document.documentElement.setAttribute('data-bs-theme', t), theme)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('region', { name: '检测设置', exact: true }).screenshot({ path: testInfo.outputPath(`basis-text-${width}.png`) })
  }
  await page.getByRole('button', { name: '选择检测依据', exact: true }).click()
  await dialog.getByRole('checkbox', { name: '选择 STD-SY-002-2026', exact: true }).uncheck()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(field).toHaveValue(labels[0] + '；' + labels[2] + ';' + labels[3])
  await page.getByRole('button', { name: '清除检测依据', exact: true }).click()
  await expect(field).toHaveValue('')
  await expect(field).not.toBeEditable()
})

test('rejects content changes and extra standards, supports composition, and blocks empty separators on save', async ({ page }) => {
  await selectBases(page)
  const field = page.getByRole('textbox', { name: '检测依据', exact: true })
  const original = labels.join('；')
  for (const bad of [original.replace('001', '999'), original.replace('压力', '温度'), original + '；列表外标准', labels.slice(1).join('；'), labels.join('---')]) {
    await field.fill(bad)
    await expect(field).toHaveValue(original)
  }
  await expect(page.locator('.toast.show')).toContainText('只能修改检测依据之间的分隔符')
  await field.focus()
  await field.evaluate((el, position) => (el as HTMLTextAreaElement).setSelectionRange(position, position + 1), labels[0]!.length)
  await field.dispatchEvent('compositionstart')
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  const composed = labels[0] + '、' + labels.slice(1).join('；')
  await field.evaluate((el, value) => { (el as HTMLTextAreaElement).value = value }, composed)
  await field.dispatchEvent('input', { isComposing: true })
  await field.dispatchEvent('compositionend', { data: '、' })
  await expect(field).toHaveValue(composed)
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeEnabled()
  await field.fill(labels[0] + labels.slice(1).join('；'))
  await expect.poll(() => field.evaluate(el => (el as HTMLTextAreaElement).validationMessage)).toContain('请在每两项')
  await page.getByLabel('工程/产品名称', { exact: false }).fill('空分隔符校验')
  await page.getByLabel('检测类别', { exact: false }).selectOption('委托')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page).toHaveURL(/samples\/new/)
  await field.fill(original)
  await expect.poll(() => field.evaluate(el => (el as HTMLTextAreaElement).validationMessage)).toBe('')
  await page.getByRole('button', { name: '选择检测依据', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择检测依据', exact: true })
  await page.route('**/test-bases/resolve', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '确认失败，请重试' } } }))
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(dialog.getByText('确认失败，请重试', { exact: true })).toBeVisible()
  await expect(field).toHaveValue(original)
  await page.unroute('**/test-bases/resolve')
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '清除检测方案', exact: true }).click()
  await expect(field).toBeDisabled()
  await expect(field).toHaveValue('')
})
