import { expect, test } from '@playwright/test'

test('missing originals can be acknowledged without bypassing completion checks', async ({ page }) => {
  await page.goto('/#/testing/data-entry')
  const root = '/api/registration/samples/demo-yp-76/data-entry', headers = { 'X-Demo-Actor': 'admin' }
  await expect(page.getByRole('table', { name: '检测数据录入列表', exact: true })).toContainText('SP2026090076')
  const detail = await (await page.request.get(root, { headers })).json()
  const savedResponse = await page.request.post(`${root}/save`, { headers, data: { version: detail.version, sampleVersion: detail.sample.version, requestId: crypto.randomUUID(), form: { ...detail.form, conclusion: '符合要求', conclusionStatus: '合格', tester1Id: 'analyst', tester2Id: '', testDates: [{ kind: 'range', from: '2026-09-01', to: '2026-09-02' }] } } })
  expect(savedResponse.ok()).toBe(true)
  const saved = await savedResponse.json()
  expect((await page.request.post(`${root}/combine`, { headers, data: { version: saved.version, sampleVersion: saved.sample.version, requestId: crypto.randomUUID() } })).ok()).toBe(true)
  await expect.poll(async () => (await (await page.request.get(root, { headers })).json()).reportStatus).toBe('ready')
  await page.reload()
  const row = page.getByRole('row').filter({ hasText: 'SP2026090076' })
  const open = async () => { await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click(); await page.getByRole('menuitem', { name: '录入完成', exact: true }).click() }
  const dialog = page.getByRole('dialog', { name: '录入完成', exact: true })
  await open()
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.locator('.toast.show.toast-border-warning')).toContainText('尚未上传原始记录，是否继续完成录入？')
  await expect(dialog.getByText(/诊断编号/)).toHaveCount(0)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(row).toBeVisible()
  expect((await (await page.request.get(root, { headers })).json()).sample.dataStatus).toBe('检测数据录入中')
  await open()
  await expect(dialog.getByRole('button', { name: '继续完成', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByRole('button', { name: '继续完成', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(row).toHaveCount(0)
  expect((await (await page.request.get(root, { headers })).json()).sample.dataStatus).toBe('检测数据录入完成')
})

test('completion validation uses business feedback while system failures retain diagnostics', async ({ page }, info) => {
  await page.goto('/#/testing/data-entry')
  const row = page.getByRole('row').filter({ hasText: 'SP2026090076' })
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '录入完成', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '录入完成', exact: true })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.locator('.toast.show.toast-border-warning')).toContainText('请检查试验信息。')
  await expect(dialog.locator('.toast.show.toast-border-warning')).toContainText('结论：完成录入前请填写此项。')
  await expect(dialog.locator('.toast.show.toast-border-warning')).toContainText('第 1 项试验日期：请完整填写开始和结束日期。')
  await expect(dialog.getByText(/诊断编号/)).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: '复制编号', exact: true })).toHaveCount(0)
  await dialog.screenshot({ path: info.outputPath('completion-validation.png') })
  let systemFailure = false
  await page.route('**/data-entry/complete', route => route.fulfill({ status: systemFailure ? 500 : 422, contentType: 'application/json', json: { error: { code: systemFailure ? 'INTERNAL' : 'BUSINESS_RULE', message: systemFailure ? '暂时无法完成操作，请稍后重试。' : '请先生成最新最终报告，再完成录入。' } } }))
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.locator('.toast.show.toast-border-warning')).toContainText('请先生成最新最终报告')
  await expect(dialog.getByText(/诊断编号/)).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: '打开数据录入，检查并补充资料', exact: true })).toBeVisible()
  systemFailure = true
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.locator('.toast.show.toast-border-danger')).toContainText('暂时无法完成操作')
  await expect(dialog.getByText(/诊断编号/)).toBeVisible()
  await expect(dialog.getByRole('button', { name: '打开数据录入，检查并补充资料', exact: true })).toHaveCount(0)
})
