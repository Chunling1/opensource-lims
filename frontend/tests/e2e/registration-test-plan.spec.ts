import { test, expect } from '@playwright/test'
import { selectGeneralSamplePlan } from './helpers/sample-plan'

test('test plan picker expands remote branches, selects one item, searches and cancels safely', async ({ page }, testInfo) => {
  const queries: { parentId?: string; keyword?: string; page?: number }[] = []
  page.on('request', request => { if (request.url().endsWith('/test-plans/query')) queries.push(request.postDataJSON()) })
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  const field = page.getByRole('textbox', { name: '检测方案', exact: true })
  await expect(field).toHaveAttribute('readonly', '')
  await page.getByRole('button', { name: '选择检测方案', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择检测方案', exact: true })
  const confirm = dialog.getByRole('button', { name: '确定', exact: true })
  await expect(dialog.getByRole('button', { name: '风速、压力校准实验室', exact: true })).toBeVisible()
  await expect(confirm).toBeDisabled()
  await expect(dialog.getByRole('radio')).toHaveCount(0)
  expect(queries).toHaveLength(1)
  await dialog.getByRole('button', { name: '风速、压力校准实验室', exact: true }).click()
  const choices = dialog.getByRole('radio')
  await choices.first().check()
  await choices.first().press('ArrowDown')
  await expect(choices.nth(1)).toBeChecked()
  await expect(dialog.locator('input[type="radio"]:checked')).toHaveCount(1)
  await choices.nth(1).click()
  await expect(choices.nth(1)).toBeChecked()
  await dialog.getByRole('radio', { name: '选择 压力校准', exact: true }).check()
  await dialog.getByRole('radio', { name: '选择 风速仪校准', exact: true }).check()
  await expect(dialog.getByRole('radio', { name: '选择 压力校准', exact: true })).not.toBeChecked()
  await expect(field).toHaveValue('')
  expect(queries.at(-1)?.parentId).toBe('pressure')
  await page.screenshot({ path: testInfo.outputPath('test-plan-tree.png') })
  const cachedQueries = queries.length
  await confirm.click()
  await expect(field).toHaveValue('风速仪校准（FS）')
  await page.getByRole('button', { name: '选择检测方案', exact: true }).click()
  await confirm.click()
  await expect(field).toHaveValue('风速仪校准（FS）')
  await page.getByRole('button', { name: '选择检测方案', exact: true }).click()
  await dialog.getByRole('button', { name: '风速、压力校准实验室', exact: true }).click()
  await expect(dialog.getByRole('radio', { name: '选择 风速仪校准', exact: true })).toBeChecked()
  expect(queries).toHaveLength(cachedQueries)
  await dialog.getByRole('button', { name: '温度校准实验室', exact: true }).click()
  await dialog.getByRole('navigation', { name: '分组检测方案分页' }).getByRole('button', { name: '第 2 页', exact: true }).click()
  await expect(dialog.getByRole('radio', { name: '选择 温度计校准（11）', exact: true })).toBeVisible()
  expect(queries.at(-1)).toMatchObject({ parentId: 'temperature', page: 2 })
  const cachedCount = queries.length
  const temperature = dialog.getByRole('button', { name: '温度校准实验室', exact: true })
  await temperature.click()
  await expect(dialog.getByRole('radio', { name: '选择 温度计校准（11）', exact: true })).toHaveCount(0)
  await temperature.click()
  await expect(dialog.getByRole('radio', { name: '选择 温度计校准（11）', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '所有项目', exact: true }).click()
  await dialog.getByRole('button', { name: '所有项目', exact: true }).click()
  await expect(dialog.getByRole('radio', { name: '选择 温度计校准（11）', exact: true })).toBeVisible()
  expect(queries).toHaveLength(cachedCount)
  const count = queries.length
  await dialog.getByLabel('检测项目名称', { exact: true }).fill('压力')
  expect(queries).toHaveLength(count)
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByRole('radio')).toHaveCount(1)
  await dialog.getByRole('radio', { name: '选择 压力校准', exact: true }).check()
  for (const [width, theme] of [[1440, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width, height: 844 })
    await page.evaluate(value => document.documentElement.setAttribute('data-bs-theme', value), theme)
    await expect.poll(() => dialog.locator('.modal-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    await expect(confirm).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath(`test-plan-${width}-${theme}.png`) })
  }
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(field).toHaveValue('风速仪校准（FS）')
  await page.getByRole('button', { name: '清除检测方案', exact: true }).click()
  await expect(field).toHaveValue('')
})

test('test plan loading failures can retry and empty searches can reset', async ({ page }) => {
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  await page.route('**/test-plans/query', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '方案查询暂不可用' } } }))
  await page.getByRole('button', { name: '选择检测方案', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择检测方案', exact: true })
  await expect(dialog.getByText('方案查询暂不可用')).toBeVisible()
  await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await page.unroute('**/test-plans/query')
  await dialog.getByRole('button', { name: '重试', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '温度校准实验室', exact: true })).toBeVisible()
  await dialog.getByLabel('检测项目名称', { exact: true }).fill('没有这个方案')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByText('没有符合条件的检测方案')).toBeVisible()
  await dialog.getByLabel('检测项目名称', { exact: true }).fill('')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '温度校准实验室', exact: true })).toBeVisible()
})


test('a plan is required before creation and becomes read-only immediately after first save', async ({ page }) => {
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  const field = page.getByRole('textbox', { name: '检测方案', exact: true })
  await expect(field).toHaveAttribute('aria-required', 'true')
  await page.getByLabel('工程/产品名称', { exact: false }).fill('必选方案测试样品')
  await page.getByLabel('检测类别', { exact: false }).selectOption('委托')
  let submissions = 0
  page.on('request', request => { if (request.url().endsWith('/api/registration/samples') && request.method() === 'POST') submissions++ })
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.locator('#sample-testPlan-error')).toHaveText('请选择检测方案。')
  await expect(field).toHaveAttribute('aria-invalid', 'true')
  await expect(field).toBeFocused()
  expect(submissions).toBe(0)
  await selectGeneralSamplePlan(page)
  await expect(page.locator('#sample-testPlan-error')).toHaveCount(0)
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page).toHaveURL(/samples\/[^/]+\/edit/)
  expect(submissions).toBe(1)
  await expect(field).toHaveValue('常规检测方案（CG）')
  await expect(field).toHaveAttribute('readonly', '')
  await expect(page.getByRole('button', { name: /选择检测方案|清除检测方案/ })).toHaveCount(0)
  await page.getByLabel('工程/产品名称', { exact: false }).fill('修改其他字段')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('样品已保存。', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('工程/产品名称', { exact: false })).toHaveValue('修改其他字段')
  await expect(field).toHaveValue('常规检测方案（CG）')
  await expect(page.getByRole('button', { name: /选择检测方案|清除检测方案/ })).toHaveCount(0)
})

