import { test, expect } from '@playwright/test'

test('equipment plan search stays available while the selection catalogue loads', async ({ page }) => {
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/quality/equipment/ledger/plan-selection', async route => {
    await pending
    await route.continue()
  }, { times: 1 })
  await page.goto('/#/quality/equipment/ledger')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新增设备', exact: true })
  await expect(dialog.getByLabel('档案号', { exact: true })).toBeVisible()
  await dialog.getByRole('tab', { name: '检测方案', exact: true }).click()
  await dialog.getByRole('button', { name: '选择方案', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择方案', exact: true })
  try {
    await expect(picker.getByRole('form', { name: '检测方案查询' })).toBeVisible()
    await expect(picker.getByText('正在加载…', { exact: true })).toBeVisible()
    await expect(picker.getByRole('button', { name: '返回', exact: true })).toBeEnabled()
    await expect(picker.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
    await picker.getByLabel('方案名称或代码').fill('WD026')
    await picker.getByRole('button', { name: '查询', exact: true }).click()
  } finally { release() }
  await expect(picker.getByRole('checkbox', { name: '选择 温度计校准（26）', exact: true })).toBeVisible()
  await expect(picker.getByLabel('方案名称或代码')).toHaveValue('WD026')
  await expect(picker.getByText('正在加载…', { exact: true })).toHaveCount(0)
})

test('equipment plan tree keeps selections across search and pages, updates locally and cancels draft changes', async ({ page }) => {
  const selections: unknown[] = []
  page.on('request', request => { if (request.url().endsWith('/quality/equipment/ledger/plan-selection')) selections.push(request.postDataJSON()) })
  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto('/#/quality/equipment/ledger')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新增设备', exact: true })
  await dialog.getByLabel('档案号', { exact: true }).fill('TREE-PLANS')
  await dialog.getByLabel('仪器设备名称', { exact: true }).fill('树形方案关联设备')
  await dialog.getByRole('tab', { name: '检测方案', exact: true }).click()
  await dialog.getByRole('button', { name: '选择方案', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择方案', exact: true })
  const group = picker.getByRole('checkbox', { name: '选择分组 温度校准实验室', exact: true })
  await group.click()
  await expect(picker.getByRole('status').filter({ hasText: '已选' })).toHaveText('已选 26 个方案')
  await picker.getByRole('button', { name: '温度校准实验室', exact: true }).click()
  const branch = picker.locator('#plan-group-temperature')
  await expect(branch.getByRole('checkbox', { name: '选择 温度计校准（1）', exact: true })).toBeChecked()
  await branch.getByRole('button', { name: '下一页', exact: true }).click()
  const eleventh = branch.getByRole('checkbox', { name: '选择 温度计校准（11）', exact: true })
  await expect(eleventh).toBeChecked()
  await eleventh.click()
  await expect(picker.getByRole('status').filter({ hasText: '已选' })).toHaveText('已选 25 个方案')
  expect(await group.evaluate((el: HTMLInputElement) => el.indeterminate)).toBe(true)
  await picker.getByLabel('方案名称或代码').fill('WD026')
  await picker.getByRole('button', { name: '查询', exact: true }).click()
  const last = picker.getByRole('checkbox', { name: '选择 温度计校准（26）', exact: true })
  await expect(last).toBeChecked()
  await last.click()
  expect(selections).toHaveLength(1)
  await expect(picker.getByText('正在更新选择…', { exact: true })).toHaveCount(0)
  await expect(picker.getByRole('status').filter({ hasText: '已选' })).toHaveText('已选 24 个方案')
  await picker.getByRole('button', { name: '确定', exact: true }).click()
  await expect(dialog.getByRole('cell', { name: '温度计校准（1）', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '选择方案', exact: true }).click()
  await expect(picker.getByRole('status').filter({ hasText: '已选' })).toHaveText('已选 24 个方案')
  const all = picker.getByRole('checkbox', { name: '选择全部检测方案', exact: true })
  await all.click()
  await expect(all).toBeChecked()
  await all.click()
  await expect(picker.getByRole('status').filter({ hasText: '已选' })).toHaveText('已选 0 个方案')
  await picker.getByRole('button', { name: '返回', exact: true }).click()
  await dialog.getByRole('button', { name: '选择方案', exact: true }).click()
  await expect(picker.getByRole('status').filter({ hasText: '已选' })).toHaveText('已选 24 个方案')
  await picker.getByRole('button', { name: '返回', exact: true }).click()
  const saving = page.waitForResponse(r => r.url().endsWith('/quality/equipment/ledger/save') && r.status() === 200)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  const saved = await (await saving).json()
  expect(saved.profile.projects).toHaveLength(24)
  expect(saved.profile.projects.map((p: { id: string }) => p.id)).not.toContain('temperature-11')
  expect(saved.profile.projects.map((p: { id: string }) => p.id)).not.toContain('temperature-26')
})
