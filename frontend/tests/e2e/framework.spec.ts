import { test, expect } from '@playwright/test'

test('hover pin and Galaxy effective options match the template without losing preferences', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  await page.getByLabel('工程/产品名称', { exact: false }).fill('保留未提交样品')
  await page.getByRole('button', { name: '打开主题设置' }).click()
  await page.getByTestId('theme-label-size-sm-hover').click()
  await page.getByRole('button', { name: '关闭主题设置' }).click()
  await page.locator('.app-menu').hover()
  const pin = page.getByRole('button', { name: '固定菜单展开' })
  await pin.click()
  await expect(page.locator('html')).toHaveAttribute('data-sidebar-size', 'sm-hover-active')
  await expect(pin).toBeVisible()
  await pin.click()
  await expect(page.locator('html')).toHaveAttribute('data-sidebar-size', 'sm-hover')
  await page.getByRole('button', { name: '打开主题设置' }).click()
  await page.getByTestId('theme-label-sidebar-light').click()
  await page.getByTestId('theme-label-theme-galaxy').click()
  await expect(page.getByTestId('theme-mode-dark')).toBeChecked()
  await expect(page.getByTestId('theme-mode-light')).toBeEnabled()
  await expect(page.getByTestId('theme-sidebar-dark')).toBeChecked()
  await expect(page.getByTestId('theme-sidebar-light')).toBeEnabled()
  await page.getByTestId('theme-label-body-img-2').click()
  await page.getByRole('button', { name: '关闭主题设置' }).click()
  await expect(page.locator('.page-title-box')).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await page.getByRole('button', { name: '打开主题设置' }).click()
  await page.getByTestId('theme-label-theme-default').click()
  await expect(page.getByTestId('theme-mode-light')).toBeChecked()
  await expect(page.getByTestId('theme-sidebar-light')).toBeChecked()
  await page.getByRole('button', { name: '关闭主题设置' }).click()
  await expect(page.getByLabel('工程/产品名称', { exact: false })).toHaveValue('保留未提交样品')
})

test('demo notification content does not navigate or change with sample mutations', async ({ page }) => {
  await page.goto('/#/dashboard')
  await page.getByRole('button', { name: '通知消息', exact: true }).click()
  await page.locator('#notificationDropdown .notification-item').first().click()
  await expect(page).toHaveURL(/#\/dashboard$/)
  await expect(page.locator('#notificationDropdown .dropdown-menu')).toBeVisible()
  const badge = page.locator('#notificationDropdown .topbar-badge')
  const before = await badge.textContent()
  await page.keyboard.press('Escape')
  await page.evaluate(async () => {
    const path = '/src/services/samples/sampleService.ts'
    const { sampleService } = await import(path)
    const sample = (await sampleService.list({ status: 'pending' })).items[0]
    await sampleService.receive(sample.id)
  })
  await expect(badge).toHaveText(before!)
  await page.getByRole('button', { name: '通知消息', exact: true }).click()
  await expect(page.locator('#notificationDropdown .notification-item')).toHaveCount(3)
})

