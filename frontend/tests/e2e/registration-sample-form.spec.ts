import { expect, test } from '@playwright/test'
import { sampleDateKeys } from '../../src/types/commissions/sampleForm'

test.use({ timezoneId: 'Asia/Shanghai' })

test('sample registration saves the screenshot fields and restores them without remounting', async ({ page }, testInfo) => {
  await page.clock.setFixedTime(new Date('2031-01-01T18:00:00Z'))
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  const form = page.getByRole('form', { name: '样品表单' })
  const reportNumber = form.getByLabel('报告编号', { exact: true })
  await expect(reportNumber).toHaveAttribute('readonly', '')
  await expect(reportNumber).toHaveAttribute('placeholder', '保存后自动生成')
  await expect(form.getByLabel('委托编号', { exact: true })).toHaveValue('WT202609001')
  await form.getByRole('tab', { name: '委托信息', exact: true }).click()
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(form.getByRole('textbox', { name: '检测方案', exact: true })).toBeFocused()
  await form.getByRole('tab', { name: '样品信息', exact: true }).click()
  await form.getByLabel('工程/产品名称', { exact: false }).fill('样品表单完整信息')
  await form.getByLabel('检测类别', { exact: false }).selectOption('委托')
  await form.getByRole('button', { name: '选择检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '选择检测方案', exact: true })
  await plans.getByRole('button', { name: '综合检测部', exact: true }).click()
  await plans.getByRole('radio', { name: '选择 常规检测方案', exact: true }).check()
  await plans.getByRole('button', { name: '确定', exact: true }).click()
  await form.getByRole('button', { name: '选择检测依据', exact: true }).click()
  const bases = page.getByRole('dialog', { name: '选择检测依据', exact: true })
  await bases.getByRole('checkbox', { name: '选择 STD-CG-001-2026', exact: true }).check()
  await bases.getByRole('button', { name: '确定', exact: true }).click()
  const planBox = await form.getByRole('textbox', { name: '检测方案', exact: true }).boundingBox()
  const tabsBox = await form.getByRole('tablist').boundingBox()
  expect(planBox!.y + planBox!.height).toBeLessThan(tabsBox!.y)
  for (const key of sampleDateKeys) await expect(form.locator(`#sample-${key}`)).toHaveValue('2031-01-02')
  for (const label of ['是否复检', '初检样品编号', '初检报告编号', '内部委托', '样品资料', '工程部位', '委托单位', '数量', '单位']) await expect(form.getByLabel(label, { exact: true })).toHaveCount(0)
  await expect(form.getByLabel('是否加急', { exact: true })).toHaveValue('false')
  await form.getByLabel('是否加急', { exact: true }).selectOption({ label: '是' })
  await form.getByLabel('任务单领取人', { exact: true }).selectOption('李受理')
  const additionalFields = { '编号': 'FILTER-01', '生产日期': '2026-09-07', '规格型号': '595×595×46', '要求试验日期': '2026-09-25', '样品数量': '2' }
  const testingLocation = form.getByLabel('检测地点', { exact: true })
  const locationToggle = form.getByRole('button', { name: '选择检测地点', exact: true })
  await locationToggle.click()
  await form.getByRole('checkbox', { name: '现场', exact: true }).check()
  await expect(testingLocation).toHaveValue('现场')
  await expect(locationToggle).toHaveAttribute('aria-expanded', 'true')
  await form.getByRole('checkbox', { name: '实验室', exact: true }).check()
  await expect(testingLocation).toHaveValue('现场；实验室')
  await locationToggle.click()
  await testingLocation.fill('实验室；北京市示例站点B区检测现场')
  await locationToggle.click()
  await expect(form.getByRole('checkbox', { name: '实验室', exact: true })).toBeChecked()
  await expect(form.getByRole('checkbox', { name: '现场', exact: true })).not.toBeChecked()
  await form.getByRole('checkbox', { name: '实验室', exact: true }).uncheck()
  await expect(testingLocation).toHaveValue('北京市示例站点B区检测现场')
  await form.getByRole('checkbox', { name: '现场', exact: true }).check()
  await form.getByRole('checkbox', { name: '实验室', exact: true }).check()
  await locationToggle.click()
  for (const [label, value] of Object.entries(additionalFields)) await form.getByLabel(label, { exact: true }).fill(value)
  await form.getByRole('button', { name: '选择生产单位', exact: true }).click()
  const manufacturers = page.getByRole('dialog', { name: '选择生产厂家', exact: true })
  await manufacturers.getByRole('checkbox', { name: '选择 示范空调设备有限公司（001）', exact: true }).check()
  await manufacturers.getByRole('button', { name: '确定', exact: true }).click()
  await expect(form.getByLabel('生产单位', { exact: true })).toHaveValue('示范空调设备有限公司（001）')
  await form.getByLabel('生产单位', { exact: true }).fill('生产单位自行编辑')
  await form.getByLabel('报告格式', { exact: true }).selectOption('product')
  await form.getByLabel('报告标题', { exact: true }).selectOption('default_lab')
  await form.getByLabel('上传商标图片', { exact: true }).setInputFiles({ name: '商标.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a0n8AAAAASUVORK5CYII=', 'base64') })
  await expect(form.getByAltText('商标图片', { exact: true })).toBeVisible()
  await form.getByLabel('交费情况', { exact: true }).selectOption('委托时缴纳')
  await form.getByLabel('样品处理方式', { exact: true }).selectOption('中心处置')
  await form.getByLabel('报告形式', { exact: true }).selectOption('纸质')
  await form.getByRole('checkbox', { name: '是否使用评定标准', exact: true }).check()
  await form.getByRole('button', { name: '选择评定标准', exact: true }).click()
  const assessmentPicker = page.getByRole('dialog', { name: '选择评定标准', exact: true })
  for (const code of ['002', '003']) await assessmentPicker.getByRole('checkbox', { name: `选择 STD-CG-${code}-2026`, exact: true }).check()
  await assessmentPicker.getByRole('button', { name: '确定', exact: true }).click()
  const assessmentField = form.getByRole('textbox', { name: '是否使用评定标准', exact: true })
  const assessmentText = 'STD-CG-002-2026《常规检测方案技术规范（2）》\nSTD-CG-003-2026《常规检测方案技术规范（3）》'
  await expect(assessmentField).toBeEditable()
  await assessmentField.fill(assessmentText)
  await assessmentField.fill('自行新增的标准')
  await expect(assessmentField).toHaveValue(assessmentText)
  await form.getByRole('button', { name: '选择评定标准', exact: true }).click()
  await assessmentPicker.getByRole('button', { name: '清空', exact: true }).click()
  await assessmentPicker.getByRole('button', { name: '取消', exact: true }).click()
  await expect(assessmentField).toHaveValue(assessmentText)
  await form.getByLabel('抽样单位', { exact: true }).fill('抽样单位甲')
  await form.getByLabel('抽样数量', { exact: true }).fill('2.5')
  await form.getByLabel('标准价格', { exact: true }).fill('125.50')
  await form.getByLabel('已缴费（元）', { exact: true }).fill('0')
  await form.getByLabel('备注（内部）', { exact: true }).fill('内部说明')
  await form.getByRole('checkbox', { name: '报告承诺时间（对外）', exact: true }).check()
  await form.getByRole('textbox', { name: '邮寄地址', exact: true }).fill('测试路 10 号')
  await form.getByLabel('报告交付份数', { exact: true }).fill('3')
  await form.getByRole('tab', { name: '委托信息', exact: true }).click()
  await expect(form.getByRole('textbox', { name: '检测方案', exact: true })).toBeVisible()
  await expect(form.getByRole('textbox', { name: '检测方案', exact: true })).toHaveValue('常规检测方案（CG）')
  await expect(form.getByRole('group', { name: '检测依据', exact: true })).toBeVisible()
  await expect(form.getByRole('textbox', { name: '检测依据', exact: true })).toHaveValue('STD-CG-001-2026《常规检测方案技术规范（1）》')
  await expect(form.getByLabel('项目名称', { exact: true })).toBeEditable()
  await form.getByRole('tab', { name: '样品信息', exact: true }).click()
  const request = page.waitForRequest(r => r.url().endsWith('/samples') && r.method() === 'POST')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  expect((await request).postDataJSON().input.details).toMatchObject({ testPlanId: 'general-1', testPlan: '常规检测方案', testBasisIds: ['general-1-basis-1'], standardPrice: '125.50', paidAmount: '0', samplingQuantity: '2.5', internalNotes: '内部说明', reportCopies: '3', useAssessmentStandard: true })
  await expect(page).toHaveURL(/samples\/[^/]+\/edit/)
  await expect(page.getByText('样品已保存。', { exact: true })).toBeVisible()
  await expect(form.getByLabel('样品编号', { exact: true })).toHaveValue(/^SP/)
  await expect(reportNumber).toHaveValue(/^BG\d+$/)
  const assignedReportNumber = await reportNumber.inputValue()
  await page.reload()
  await expect(reportNumber).toHaveValue(assignedReportNumber)
  await expect(form.getByLabel('送样日期', { exact: true })).toHaveValue('2031-01-02')
  await expect(form.locator('#sample-internalDueDate')).toHaveValue('')
  await form.getByRole('checkbox', { name: '报告承诺时间（内部）', exact: true }).check()
  await expect(form.locator('#sample-internalDueDate')).toHaveValue('2031-01-02')
  await expect(form.getByRole('textbox', { name: '检测方案', exact: true })).toHaveValue('常规检测方案（CG）')
  await expect(form.getByRole('textbox', { name: '检测依据', exact: true })).toHaveValue('STD-CG-001-2026《常规检测方案技术规范（1）》')
  await expect(assessmentField).toHaveValue(assessmentText)
  await expect(form.getByLabel('抽样单位', { exact: true })).toHaveValue('抽样单位甲')
  await expect(testingLocation).toHaveValue('北京市示例站点B区检测现场；现场；实验室')
  await expect(form.getByLabel('是否加急', { exact: true })).toHaveValue('true')
  await expect(form.getByLabel('任务单领取人', { exact: true })).toHaveValue('李受理')
  await expect(form.getByLabel('标准价格', { exact: true })).toHaveValue('125.50')
  await expect(form.getByLabel('备注（内部）', { exact: true })).toHaveValue('内部说明')
  for (const [label, value] of Object.entries(additionalFields)) await expect(form.getByLabel(label, { exact: true })).toHaveValue(value)
  await expect(form.getByLabel('生产单位', { exact: true })).toHaveValue('生产单位自行编辑')
  await expect(form.getByLabel('报告标题', { exact: true })).toHaveValue('default_lab')
  await expect(form.getByAltText('商标图片', { exact: true })).toBeVisible()
  await form.getByRole('button', { name: '删除商标图片', exact: true }).click()
  await expect(form.getByAltText('商标图片', { exact: true })).toHaveCount(0)
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('样品已保存。', { exact: true })).toBeVisible()
  await page.reload()
  await expect(form.getByAltText('商标图片', { exact: true })).toHaveCount(0)
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.evaluate(() => window.scrollTo(0, 0))
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`sample-form-${width}.png`), fullPage: true })
  }
  await expect(form.getByRole('button', { name: '保存并继续新增', exact: true })).toHaveCount(0)
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  await expect(page).toHaveURL(/samples\/new\?/)
  await expect(form.getByLabel('工程/产品名称', { exact: false })).toHaveValue('')
  for (const key of sampleDateKeys) await expect(form.locator(`#sample-${key}`)).toHaveValue('2031-01-02')
  await expect(reportNumber).toHaveValue('')
  await expect(form.getByLabel('是否加急', { exact: true })).toHaveValue('false')
  await expect(form.getByLabel('任务单领取人', { exact: true })).toHaveValue('')
  await expect(assessmentField).toBeDisabled()
  await expect(assessmentField).toHaveValue('')
  await expect(form.getByLabel('委托编号', { exact: true })).toHaveValue('WT202609001')
})
