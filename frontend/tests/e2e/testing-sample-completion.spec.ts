import { toolbarButton } from './helpers/toolbar'
import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) test(`completion list filters, columns and handling actions at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/testing/sample-completion')
  const table = page.getByRole('table', { name: '检毕样品处理列表', exact: true })
  const form = page.getByRole('form', { name: '检毕样品处理条件', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await expect(form.getByLabel('处理状态', { exact: true })).toHaveValue('样品待处理')
  await expect(form.getByLabel('处置状态', { exact: true })).toBeDisabled()
  await expect(form.getByLabel('处理时间', { exact: true })).toBeDisabled()
  await (await toolbarButton(page, '检毕样品处理', '显示')).click()
  const columns = page.getByRole('dialog', { name: '检毕样品处理显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(16)
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  const row = table.getByRole('row').filter({ hasText: 'SP2026090029' })
  await row.getByRole('button', { name: 'SP2026090029 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['样品处理', '撤销样品处理'])
  await expect(page.getByRole('menuitem', { name: '撤销样品处理', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '样品处理', exact: true }).click()
  const operation = page.getByRole('dialog', { name: '检毕样品处理', exact: true })
  await expect(operation.getByLabel('本样品客户处置要求')).toHaveAttribute('readonly', '')
  await expect(operation.getByLabel('留置时间', { exact: true })).toBeDisabled()
  await expect(operation.getByLabel('处置结果')).toBeEditable()
  await expect(operation.locator('.form-label')).toHaveText(['本样品客户处置要求', '留置时间', '处置结果 *'])
  await page.screenshot({ path: info.outputPath(`sample-completion-dialog-${width}.png`), fullPage: true, animations: 'disabled' })
  await operation.getByRole('button', { name: '取消', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await plans.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true }).click()
  await plans.getByRole('button', { name: '关闭', exact: true }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(row).toBeVisible()
  await page.screenshot({ path: info.outputPath(`sample-completion-${width}.png`), fullPage: true, animations: 'disabled' })
  await form.getByLabel('样品编号', { exact: true }).fill('不存在')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.goto('/#/testing/sample-completion?processingStatus=样品已处理&disposalStatus=样品已处置')
  await expect(table.locator('tbody tr')).toHaveCount(5)
  await expect(form.getByLabel('处置状态', { exact: true })).toBeEnabled()
  await expect(form.getByLabel('处理时间', { exact: true })).toBeEnabled()
  const disposed = table.getByRole('row').filter({ hasText: 'SP2026090030' })
  await disposed.getByRole('button', { name: 'SP2026090030 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '样品处理', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '撤销样品处理', exact: true }).click()
  const undo = page.getByRole('dialog', { name: '撤销样品处理', exact: true })
  await expect(undo).toContainText('撤销后恢复为“样品待处理”')
  await undo.getByRole('button', { name: '取消', exact: true }).click()
  await expect(undo).toBeHidden()
  await page.goto('/#/testing/sample-completion?code=SP2026090029')
  await row.getByRole('button', { name: 'SP2026090029 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '样品处理', exact: true }).click()
  await operation.getByLabel('处置结果').fill('  ')
  await operation.getByRole('button', { name: '确定', exact: true }).click()
  await expect(operation).toContainText('请填写处置结果')
  await operation.getByLabel('处置结果').fill('检毕留样，等待统一处置')
  await operation.getByRole('button', { name: '确定', exact: true }).click()
  await expect(operation).toBeHidden()
  await expect(row).toHaveCount(0)
  await expect(page.getByRole('status').filter({ hasText: '样品处理成功' })).toBeVisible()
  await form.getByLabel('处理状态', { exact: true }).selectOption('样品已处理')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toContainText('检毕留样，等待统一处置')
  await row.getByRole('button', { name: 'SP2026090029 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '撤销样品处理', exact: true }).click()
  await undo.getByRole('button', { name: '确定', exact: true }).click()
  await expect(undo).toBeHidden()
  await expect(row).toHaveCount(0)
  await form.getByLabel('处理状态', { exact: true }).selectOption('样品待处理')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toBeVisible()
  await expect(row).not.toContainText('检毕留样，等待统一处置')
})
