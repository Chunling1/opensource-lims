import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { toolbarButton, openToolbarExport } from './helpers/toolbar'
for (const width of [1440, 390]) test(`standard categories CRUD, export and isolation at ${width}`, async ({ page }, info) => {
  test.setTimeout(60000)
  await page.request.post('/api/registration/session')
  await page.goto('/#/quality/standards/groups')
  await page.setViewportSize({ width, height: 1000 })
  const table = page.getByRole('table', { name: '标准分组定义列表', exact: true })
  await expect(table).toContainText('国家标准')
  await expect(table.getByRole('columnheader', { name: '部门名称', exact: true })).toBeVisible()
  await expect(table.getByRole('columnheader', { name: '列表项值', exact: true })).toBeVisible()
  await (await toolbarButton(page, '标准分组定义', '新增')).click()
  let dialog = page.getByRole('dialog', { name: '新增标准分组', exact: true })
  await expect(dialog.getByLabel('部门', { exact: true })).toHaveValue('实验室')
  await expect(dialog.getByLabel('部门', { exact: true })).toBeDisabled()
  await expect(dialog.locator('.modal-body')).toHaveAttribute('aria-busy', 'false')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.locator('[data-field-feedback]')).toBeVisible()
  await dialog.getByLabel('列表项值').fill('新建测试类别')
  await expect(dialog.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  await dialog.screenshot({ path: info.outputPath(`group-new-${width}.png`) })
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table).toContainText('新建测试类别')
  const form = page.getByRole('form', { name: '标准分组定义查询', exact: true })
  await form.getByLabel('列表项值').fill('新建测试类别')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await table.locator('tbody tr').getByRole('checkbox').check()
  await table.locator('tbody tr').getByText('新建测试类别', { exact: true }).click()
  await expect(table.locator('tbody tr').getByRole('checkbox')).toBeChecked()
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '查看标准分组', exact: true })
  await expect(dialog.getByLabel('列表项值')).toHaveValue('新建测试类别')
  await expect(dialog.getByLabel('列表项值')).toBeDisabled()
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '返回', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '编辑标准分组', exact: true })
  await expect(dialog.getByLabel('列表项值')).toHaveValue('新建测试类别')
  await dialog.getByLabel('列表项值').fill('新建测试类别（编辑）')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table).toContainText('新建测试类别（编辑）')
  const headers = { 'X-Demo-Actor': 'admin' }
  const groupsBefore = await (await page.request.post('/api/registration/quality/equipment/groups/query', { headers, data: {} })).json()
  expect(groupsBefore.items.some((item: { name: string }) => item.name === '新建测试类别（编辑）')).toBe(false)
  await table.locator('tbody tr').getByRole('checkbox').check()
  await openToolbarExport(page, '标准分组定义')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  const result = await download
  expect(result.suggestedFilename()).toBe('标准分组定义.csv')
  expect(await readFile((await result.path())!, 'utf8')).toContain('新建测试类别（编辑）')
  await page.screenshot({ path: info.outputPath(`group-list-${width}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '删除标准分组', exact: true })
  await expect(dialog).toContainText('新建测试类别（编辑）')
  await expect(dialog.locator('.modal-body')).toHaveAttribute('aria-busy', 'false')
  await expect(dialog.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  await dialog.screenshot({ path: info.outputPath(`group-delete-${width}.png`) })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden(); await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table).toContainText('新建测试类别（编辑）')
  await table.getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '删除', exact: true }).click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(table).toContainText('暂无符合条件')
  const groupsAfter = await (await page.request.post('/api/registration/quality/equipment/groups/query', { headers, data: {} })).json()
  expect(groupsAfter).toEqual(groupsBefore)
  await page.reload()
  await expect(table).toContainText('暂无符合条件')
})


test('standard category page switches safely and reviewers are read only', async ({ page }) => {
  await page.request.post('/api/registration/session')
  await page.goto('/#/quality/equipment/groups')
  let table = page.getByRole('table', { name: '设备分组定义列表', exact: true })
  await expect(table).toContainText('实验室设备（示例）')
  await table.locator('tbody tr').first().getByRole('checkbox').check()
  await page.evaluate(() => { location.hash = '/quality/standards/groups' })
  table = page.getByRole('table', { name: '标准分组定义列表', exact: true })
  await expect(table).toContainText('国家标准')
  await expect(table).not.toContainText('实验室设备（示例）')
  await expect(table.locator('tbody input:checked')).toHaveCount(0)
  await page.evaluate(() => localStorage.setItem('lims.identity.v1', 'reviewer')); await page.reload()
  await expect(table).toContainText('国家标准')
  await expect(await toolbarButton(page, '标准分组定义', '新增')).toBeDisabled()
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem', { name: '编辑', exact: true })).toBeDisabled()
  await expect(page.getByRole('menuitem', { name: '删除', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '查看标准分组', exact: true })
  await expect(dialog.getByLabel('列表项值')).toBeDisabled()
})
