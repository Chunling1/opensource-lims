import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
for (const width of [1440, 390]) test(`external application shares layout and persists extra fields at ${width}`, async ({ page }, info) => {
  test.setTimeout(90000)
  await page.setViewportSize({ width, height: 1050 })
  await page.goto('/#/reports/changes/external')
  const query = page.getByRole('form', { name: '外部申请查询', exact: true })
  await expect(query.getByLabel('申请时间')).toBeVisible()
  await query.getByRole('button', { name: /更多筛选/ }).click()
  await expect(query.getByLabel('审批状态').locator('option')).toHaveText(['全部', '申请中', '待审批', '退回', '不通过', '审批通过'])
  const table = page.getByRole('table', { name: '外部申请列表', exact: true })
  await expect(table.getByRole('columnheader').filter({ hasText: '收费金额' })).toHaveCount(0)
  await page.getByRole('button', { name: '新增', exact: true }).click()
  let modal = page.getByRole('dialog', { name: '新增申请', exact: true })
  await modal.getByRole('button', { name: '选择报告', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择报告', exact: true })
  await picker.getByRole('checkbox', { name: '选择 SP2026090092', exact: true }).check()
  await picker.getByRole('button', { name: '移入', exact: true }).click()
  await picker.getByRole('button', { name: '确认', exact: true }).click()
  await modal.getByLabel('更改责任方').fill('委托单位')
  await modal.getByRole('button', { name: '选择', exact: true }).click()
  const people = page.getByRole('dialog', { name: '选择处理人', exact: true })
  await expect(people.getByLabel('人员范围', { exact: true })).toHaveValue('department')
  await expect(people.getByRole('table', { name: '可选人员列表' }).getByRole('columnheader')).toHaveText(['', '工号', '姓名', '所属部门', '上岗证号', '联系电话'])
  await people.getByLabel('人员范围', { exact: true }).selectOption('all')
  await expect(people.getByLabel('人员每页条数')).toBeEnabled()
  await people.getByLabel('人员每页条数').selectOption('20')
  await expect(people.getByRole('radio', { name: '选择 第二实验室检测员（other）', exact: true })).toBeVisible()
  await people.getByLabel('姓名或工号').fill('ADMIN')
  await people.getByRole('button', { name: '查询', exact: true }).click()
  await expect(people.locator('tbody tr')).toHaveCount(1)
  await people.getByRole('radio', { name: '选择 演示用户（admin）', exact: true }).check()
  await expect(page.locator('.modal.show')).toHaveCount(1)
  await expect(page.locator('.modal-backdrop')).toHaveCount(1)
  expect(await people.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await people.screenshot({ path: info.outputPath(`external-handler-${width}.png`) })
  await people.getByRole('button', { name: '确定', exact: true }).click()
  await expect(modal.getByLabel('指定处理人')).toHaveValue('演示用户')
  await modal.getByRole('button', { name: '选择', exact: true }).click()
  await expect(people.getByLabel('人员范围', { exact: true })).toHaveValue('all')
  await expect(people.getByRole('radio', { name: '选择 演示用户（admin）', exact: true })).toBeChecked()
  await people.getByRole('radio', { name: '选择 张受理（business）', exact: true }).check()
  await page.keyboard.press('Escape')
  await expect(modal.getByRole('button', { name: '选择', exact: true })).toBeFocused()
  await expect(modal.getByLabel('更改责任方')).toHaveValue('委托单位')
  await expect(modal.getByLabel('指定处理人')).toHaveValue('演示用户')
  await modal.getByLabel('收费金额').fill('125.50')
  await modal.getByRole('group', { name: '申请单位是否为委托单位', exact: true }).getByRole('radio', { name: '是', exact: true }).check()
  await modal.getByLabel('更改前内容').fill('原委托信息')
  await modal.getByLabel('更改后内容').fill('更正后信息')
  await modal.getByLabel('更改原因').fill('客户申请修正')
  await expect(modal.getByLabel(/原报告(?:发放|收回)(?:原件|复印件)/)).toHaveCount(0)
  await modal.getByRole('group', { name: '原报告是否全部收回', exact: true }).getByRole('radio', { name: '否', exact: true }).check()
  await modal.getByRole('button', { name: '附件', exact: true }).click()
  await modal.locator('input[type=file]').setInputFiles({ name: 'proof.txt', mimeType: 'text/plain', buffer: Buffer.from('external evidence') })
  await expect(modal.getByRole('button', { name: 'proof.txt', exact: true })).toBeVisible()
  await expect(modal.getByRole('button', { name: '保存', exact: true })).toBeEnabled()
  await modal.getByRole('button', { name: '附件', exact: true }).click()
  await modal.locator('.modal-body').evaluate(e => { e.scrollTop = 0 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath(`external-new-${width}.png`), fullPage: true })
  await modal.getByRole('button', { name: '保存', exact: true }).click()
  await expect(modal).toBeHidden()
  const row = table.getByRole('row').filter({ hasText: 'SP2026090092' })
  await expect(row).toContainText('申请中')
  const code = (await row.locator('td').nth(1).innerText()).trim()
  async function action(name: string) {
    await row.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
    await expect(page.getByRole('menuitem')).toHaveText(['新增', '修改', '查看', '撤销', '删除'])
    await page.getByRole('menuitem', { name, exact: true }).click()
  }
  await page.reload()
  await action('修改')
  modal = page.getByRole('dialog', { name: '修改申请', exact: true })
  await expect(modal.getByLabel('收费金额')).toHaveValue('125.5')
  await expect(modal.getByLabel('更改前内容')).toHaveValue('原委托信息')
  await expect(modal.getByLabel('指定处理人')).toHaveValue('演示用户')
  await expect(modal.getByRole('group', { name: '原报告是否全部收回', exact: true }).getByRole('radio', { name: '否', exact: true })).toBeChecked()
  await modal.getByRole('group', { name: '原报告是否全部收回', exact: true }).getByRole('radio', { name: '是', exact: true }).check()
  await modal.getByRole('group', { name: '是否需要收费', exact: true }).getByRole('radio', { name: '否', exact: true }).check()
  await expect(modal.getByLabel('收费金额')).toHaveValue('0')
  await expect(modal.getByLabel('收费金额')).toBeDisabled()
  await modal.getByRole('button', { name: '提交', exact: true }).click()
  await expect(modal).toBeHidden()
  await expect(row).toContainText('待审批')
  await action('查看')
  modal = page.getByRole('dialog', { name: '查看申请', exact: true })
  await expect(modal.getByLabel('更改责任方')).toBeDisabled()
  await expect(modal.getByRole('group', { name: '原报告是否全部收回', exact: true }).getByRole('radio', { name: '是', exact: true })).toBeChecked()
  await modal.getByRole('button', { name: '附件', exact: true }).click()
  await expect(modal.locator('input[type=file]')).toHaveCount(0)
  const downloaded = page.waitForEvent('download')
  await modal.getByRole('button', { name: 'proof.txt', exact: true }).click()
  expect(await readFile((await (await downloaded).path())!, 'utf8')).toBe('external evidence')
  await modal.getByRole('button', { name: '返回', exact: true }).click()
  await action('撤销')
  modal = page.getByRole('dialog', { name: '撤销申请', exact: true })
  await modal.getByLabel('撤回原因').fill('调整申请')
  await modal.getByRole('button', { name: '确认撤销', exact: true }).click()
  await expect(modal).toBeHidden()
  await expect(row).toContainText('申请中')
  await page.goto('/#/reports/changes/internal')
  const internal = page.getByRole('table', { name: '内部申请列表', exact: true })
  await expect(internal).not.toContainText(code)
  await page.goto('/#/reports/changes/external')
  await expect(row).toContainText(code)
  await action('删除')
  await page.getByRole('dialog', { name: '删除申请', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(row).toHaveCount(0)
})
