import { expect, test } from '@playwright/test'
import { checkOnlyWithControl } from './helpers/table-selection'

test('standards require a plan, preserve multi-page selections and clear only when the plan changes', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  const field = page.getByRole('textbox', { name: '检测依据', exact: true })
  await expect(field).toHaveAttribute('rows', '1')
  const open = page.getByRole('button', { name: '选择检测依据', exact: true })
  const plans = page.getByRole('dialog', { name: '选择检测方案', exact: true })
  const choosePlan = async (name: string) => {
    await page.getByRole('button', { name: '选择检测方案', exact: true }).click()
    await plans.getByRole('button', { name: '风速、压力校准实验室', exact: true }).click()
    await plans.getByRole('radio', { name: `选择 ${name}`, exact: true }).check()
    await plans.getByRole('button', { name: '确定', exact: true }).click()
  }
  await expect(open).toBeDisabled(); await expect(field).toBeDisabled()
  await choosePlan('压力校准')
  await open.click()
  const dialog = page.getByRole('dialog', { name: '选择检测依据', exact: true })
  const table = dialog.getByRole('table', { name: '可选检测依据列表', exact: true })
  await expect(table.locator('thead th')).toHaveText(['', '受控号', '标准资质类别', '标准编号', '标准名称', '类别', '存放地点', '实施日期', '作废日期', '延期时间（天）', '替换标准号', '备注'])
  await checkOnlyWithControl(table.locator('tbody tr').first(), table.getByRole('checkbox', { name: '选择 STD-SY-001-2026', exact: true }))
  await table.locator('tbody tr').first().locator('td').nth(1).click({ position: { x: 2, y: 2 } })
  await expect(table.getByRole('checkbox', { name: '选择 STD-SY-001-2026', exact: true })).toBeChecked()
  await dialog.getByRole('button', { name: '第 2 页', exact: true }).click()
  await table.getByRole('checkbox', { name: '选择 STD-SY-012-2026', exact: true }).check()
  await table.getByRole('checkbox', { name: '全选本页检测依据', exact: true }).check()
  await expect(table.locator('tbody input:checked')).toHaveCount(10)
  await table.getByRole('checkbox', { name: '全选本页检测依据', exact: true }).uncheck()
  await expect(table.locator('tbody input:checked')).toHaveCount(0)
  await table.getByRole('checkbox', { name: '选择 STD-SY-012-2026', exact: true }).check()
  await dialog.getByLabel('英文书名号', { exact: true }).check()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(field).toHaveValue(/STD-SY-001-2026<压力校准技术规范（1）>/)
  await expect(field).toHaveValue(/STD-SY-012-2026<压力校准技术规范（12）>/)
  await open.click()
  await expect(dialog.getByLabel('英文书名号', { exact: true })).toBeChecked()
  await expect(table.getByRole('checkbox', { name: '选择 STD-SY-001-2026', exact: true })).toBeChecked()
  await table.getByRole('checkbox', { name: '选择 STD-SY-001-2026', exact: true }).uncheck()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(field).toHaveValue(/STD-SY-001-2026/)
  await choosePlan('压力校准')
  await expect(field).toHaveValue(/STD-SY-001-2026/)
  await choosePlan('风速仪校准')
  await expect(field).toHaveValue('')
  await open.click()
  await expect(table).toContainText('STD-FS-001-2026')
  await dialog.getByRole('button', { name: /更多筛选/ }).click()
  for (const [width, theme] of [[1440, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width, height: 844 })
    await page.evaluate(t => document.documentElement.setAttribute('data-bs-theme', t), theme)
    await expect.poll(() => dialog.locator('.modal-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeInViewport()
    const toolbar = dialog.getByRole('form', { name: '检测依据查询' }), pagination = dialog.getByRole('navigation', { name: '检测依据分页' })
    const before = await toolbar.boundingBox(), pages = await pagination.boundingBox()
    await dialog.locator('.modal-body').evaluate(el => { el.scrollLeft = el.scrollWidth; el.scrollTop = el.scrollHeight })
    expect((await toolbar.boundingBox())?.y).toBe(before?.y)
    expect((await pagination.boundingBox())?.y).toBe(pages?.y)
    await dialog.locator('.modal-body').evaluate(el => { el.scrollTop = 0 })
    await expect(table.getByRole('columnheader', { name: '备注', exact: true })).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath(`test-basis-${width}-${theme}.png`) })
    if (width === 390) {
      await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeInViewport()
      await expect.poll(() => dialog.locator('.modal-body').evaluate(el => el.clientHeight)).toBeGreaterThan(80)
      await page.screenshot({ path: testInfo.outputPath('test-basis-mobile-expanded.png') })
    }
  }
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '清除检测方案', exact: true }).click()
  await expect(open).toBeDisabled()
})

test('standard filters submit to the backend, failed queries retry and stale requests cannot replace newer results', async ({ page }) => {
  const queries: Record<string, unknown>[] = []
  page.on('request', request => { if (request.url().endsWith('/test-bases/query')) queries.push(request.postDataJSON()) })
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  await page.getByRole('button', { name: '选择检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '选择检测方案', exact: true })
  await plans.getByRole('button', { name: '风速、压力校准实验室', exact: true }).click()
  await plans.getByRole('radio', { name: '选择 压力校准', exact: true }).check()
  await plans.getByRole('button', { name: '确定', exact: true }).click()
  await page.route('**/test-bases/query', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '标准查询暂不可用' } } }))
  await page.getByRole('button', { name: '选择检测依据', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择检测依据', exact: true })
  await expect(dialog.getByText('标准查询暂不可用')).toBeVisible()
  await page.unroute('**/test-bases/query')
  await dialog.getByRole('button', { name: '重试', exact: true }).click()
  const table = dialog.getByRole('table', { name: '可选检测依据列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  const before = queries.length
  await dialog.getByRole('button', { name: /更多筛选/ }).click()
  const searchField = dialog.getByLabel('查询内容', { exact: true })
  const contains = dialog.getByLabel('包含', { exact: true })
  const qualification = dialog.getByLabel('标准资质类别', { exact: true })
  await expect(searchField.locator('option')).toHaveText(['标准编号', '标准名称', '受控号'])
  await expect(qualification.locator('option')).toHaveText(['全部', '一单一库+CNAS+CMA', 'CNAS', 'CMA'])
  await expect(dialog.getByLabel('排序', { exact: true })).toHaveCount(0)
  await expect(dialog.getByLabel('部门类别', { exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('textbox')).toHaveCount(1)
  await contains.fill('sy-001')
  await qualification.selectOption('一单一库+CNAS+CMA')
  await dialog.getByLabel('类别', { exact: true }).selectOption('校准类')
  expect(queries).toHaveLength(before)
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  expect(queries.at(-1)).toMatchObject({ code: 'sy-001', qualification: '一单一库+CNAS+CMA', departmentCategory: '校准类', planId: 'pressure-2', page: 1 })
  expect(queries.at(-1)).not.toHaveProperty('category')
  expect(queries.at(-1)).not.toHaveProperty('sort')
  await qualification.selectOption('')
  await dialog.getByLabel('类别', { exact: true }).selectOption('')
  for (const [key, value, expected] of [['name', '技术规范（2）', 'STD-SY-002-2026'], ['controlNumber', 'sk-sy-003', 'STD-SY-003-2026']] as const) {
    await searchField.selectOption(key)
    await contains.fill(value)
    await dialog.getByRole('button', { name: '查询', exact: true }).click()
    await expect(table.locator('tbody tr')).toHaveCount(1)
    await expect(table).toContainText(expected)
    expect(queries.at(-1)).toHaveProperty(key, value)
    expect(queries.at(-1)).not.toHaveProperty('code')
    if (key === 'controlNumber') expect(queries.at(-1)).not.toHaveProperty('name')
  }
  await contains.fill('不存在的标准')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByText('没有符合条件的检测依据', { exact: true })).toBeVisible()
  await expect(qualification.locator('option')).toHaveText(['全部', '一单一库+CNAS+CMA', 'CNAS', 'CMA'])
  await searchField.selectOption('code')
  await contains.fill('')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  let release!: () => void
  const delayed = new Promise<void>(resolve => { release = resolve })
  await page.route('**/test-bases/query', async route => {
    const response = await route.fetch()
    if (route.request().postDataJSON().code === 'sy-002') await delayed
    await route.fulfill({ response }).catch(() => {})
  })
  await contains.fill('sy-002')
  const request = page.waitForRequest(r => r.url().endsWith('/test-bases/query') && r.postDataJSON().code === 'sy-002')
  await dialog.getByRole('button', { name: '查询', exact: true }).click(); await request
  await contains.fill('sy-003')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('STD-SY-003-2026')
  release()
  await expect(table).not.toContainText('STD-SY-002-2026')
})
