  await form.getByRole('button', { name: '新增关联合同' }).click()
  await expect(table.getByRole('checkbox', { name: /^选择可选合同 / }).first()).toBeDisabled()
  await picker.press('Escape')
  await expect(picker).toBeHidden()
  await expect(form).toBeVisible()
  await form.getByRole('button', { name: '取消', exact: true }).click()
  const leave = page.getByRole('dialog', { name: '放弃未保存内容', exact: true })
  await leave.getByRole('button', { name: '继续编辑' }).click()
