test('data entry void menu reuses sample application dialog and preserves cancellation', async ({ page }) => {
  await page.goto('/#/testing/data-entry')
  const table = page.getByRole('table', { name: '检测数据录入列表', exact: true })
  const row = table.getByRole('row').filter({ hasText: 'SP2026090076' })
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '报告预览', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: '作废', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '作废申请', exact: true })
  await expect(dialog).toContainText('确认对这条样品提交“作废申请”？')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  expect(await dialog.getByLabel('申请作废原因').evaluate((element: HTMLTextAreaElement) => element.validity.valueMissing)).toBe(true)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '作废', exact: true }).click()
  await dialog.getByLabel('申请作废原因').fill('重复登记，申请作废')
  const response = page.waitForResponse(response => response.url().endsWith('/samples/demo-yp-76/actions') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  const result = await response
  expect(result.ok()).toBe(true)
  expect(await result.json()).toMatchObject({ status: 'void_pending', dataStatus: '作废申请中', voidApplication: { reason: '重复登记，申请作废' } })
  await expect(dialog).toBeHidden()
  await expect(table).not.toContainText('SP2026090076')
})

