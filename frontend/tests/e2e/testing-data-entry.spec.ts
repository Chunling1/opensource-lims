test('data entry API export, invalid queries and completed attachment permissions', async ({ page }) => {
  await page.goto('/#/testing/data-entry')
  await expect(page.getByRole('table', { name: '检测数据录入列表', exact: true })).toContainText('SP2026090076')
  const request = page.request
  const headers = { 'X-Demo-Actor': 'admin' }, root = '/api/registration/samples'
  const result = await request.post(`${root}/data-entry/query`, { headers, data: { status: '检测数据录入完成' } })
  expect(result.status()).toBe(200)
  expect((await result.json()).items[0]).toMatchObject({ id: 'demo-yp-77', canReturn: true })
  const initial = await request.post(`${root}/data-entry/query`, { headers, data: { status: '检测数据录入中' } })
  const sample = (await initial.json()).items[0]
  const form = page.getByRole('form', { name: '检测数据录入条件', exact: true })
  const table = page.getByRole('table', { name: '检测数据录入列表', exact: true })
  for (const field of ['reportCode', 'commissionCode']) {
    await form.getByLabel('查询内容').selectOption(field)
    await form.getByLabel('包含', { exact: true }).fill(sample[field].toLowerCase())
    await form.getByRole('button', { name: '查询', exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`searchField=${field}`))
    await expect(table).toContainText(sample.code)
    await page.reload()
    await expect(form.getByLabel('查询内容')).toHaveValue(field)
    await expect(table).toContainText(sample.code)
    await form.getByLabel('包含', { exact: true }).fill('不存在的编号')
    await form.getByRole('button', { name: '查询', exact: true }).click()
    await expect(table).not.toContainText(sample.code)
  }
  const csv = await request.post(`${root}/data-entry/export`, { headers, data: { status: '检测数据录入完成' } })
  expect(csv.status()).toBe(200)
  expect(await csv.text()).toContain('SP2026090077')
  expect(await csv.text()).not.toContain('SP2026090076')
  const invalid = await request.post(`${root}/data-entry/query`, { headers, data: { searchField: 'subprojectName' } })
  expect(invalid.status()).toBe(400)
  const denied = await request.post(`${root}/data-entry/query`, { headers: { 'X-Demo-Actor': 'business' }, data: {} })
  expect(denied.status()).toBe(403)
  const scoped = await request.post(`${root}/data-entry/query`, { headers: { 'X-Demo-Actor': 'other' }, data: {} })
  expect((await scoped.json()).total).toBe(0)
  const files = await request.get(`${root}/demo-yp-77/attachments`, { headers })
  expect(files.status()).toBe(200)
  expect((await files.json()).canManageAttachments).toBe(false)
})
