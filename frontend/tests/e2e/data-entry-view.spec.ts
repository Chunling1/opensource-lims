import { expect, test } from '@playwright/test'

for (const width of [1440, 390]) test(`view data reuses check layout without approval actions at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/testing/data-entry')
  const row = page.getByRole('row').filter({ hasText: 'SP2026090076' })
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '查看数据', exact: true }).click()
  await expect(page.getByRole('tab')).toHaveText(['委托信息', '样品信息', '试验信息', '原始记录', '报告预览'])
  await expect(page.getByRole('tab', { name: '试验信息', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(page.getByRole('region', { name: '报告预览', exact: true })).toContainText('暂无可预览报告')
  for (const name of ['校核', '保存', '报告填写', '附件管理']) await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '查看附件', exact: true }).click()
  const attachments = page.getByRole('dialog', { name: '查看附件', exact: true })
  await expect(attachments).toBeVisible()
  await expect(attachments.locator('input[type=file]')).toHaveCount(0)
  await attachments.getByRole('button', { name: '关闭', exact: true }).first().click()
  await page.screenshot({ path: info.outputPath(`entry-view-${width}.png`), fullPage: true, animations: 'disabled' })
  await page.getByRole('tab', { name: '原始记录', exact: true }).click()
  await expect(page.getByRole('region', { name: '原始记录预览', exact: true })).toContainText('暂无可预览原始记录')
  await expect(page.locator('input[type=file]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '上传记录', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: '试验信息', exact: true }).click()
  await expect(page.getByLabel('结论', { exact: true })).not.toBeEditable()
  await page.getByRole('button', { name: '返回检测数据录入', exact: true }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'SP2026090076 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '数据录入', exact: true }).click()
  await expect(page.getByRole('tab', { name: '试验信息', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('#trial-conclusion')).toBeEditable()
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeVisible()
})
