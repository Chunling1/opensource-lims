import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('task query matches screenshot fields and states, plan filters and print return preserve the list', async ({ page }, info) => {
  test.setTimeout(60000)
  let generated = 0
  await page.route('**/samples/*/task-prints', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    generated++
    await route.continue({ postData: JSON.stringify({ ...route.request().postDataJSON(), scenario: 'normal' }) })
  })
  await page.goto('/#/testing/task-query')
  const form = page.getByRole('form', { name: '检测任务查询条件', exact: true }), table = page.getByRole('table', { name: '检测任务查询列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(form.getByLabel('数据状态')).toHaveValue('')
  await expect(form.getByLabel('数据状态').locator('option')).toHaveText(['全部', '委托登记完成', '委托复核中', '委托复核完成', '样品入库中', '样品入库完成', '样品出库中', '样品出库完成', '样品待领取', '样品已领取', '任务分配中', '任务分配完成', '任务处理中', '任务处理完成', '检测数据录入中'])
  await expect(form.getByRole('button', { name: /更多筛选/ })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: '显示', exact: true }).click()
  const columns = page.getByRole('dialog', { name: '检测任务查询显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(17)
  await expect(columns.getByRole('checkbox', { name: '样品类型', exact: true })).toBeChecked()
  await expect(columns.getByRole('checkbox', { name: '指定主检人', exact: true })).not.toBeChecked()
  await expect(columns.getByRole('checkbox', { name: '检测方案', exact: true })).not.toBeChecked()
  await expect(columns.getByRole('checkbox', { name: '项目名称', exact: true })).not.toBeChecked()
  await columns.getByRole('checkbox', { name: '项目名称', exact: true }).check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await drawer.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true }).click()
  await expect(drawer.getByText('已选 1 项', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: '关闭', exact: true }).click()
  await form.getByLabel('数据状态').selectOption('任务分配中')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(9)
  await table.getByRole('button', { name: 'SP2026090051 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['退回委托', '打印任务单'])
  const url = page.url()
  await page.getByRole('menuitem', { name: '打印任务单', exact: true }).click()
  await expect(page.getByRole('heading', { name: '生成任务单', exact: true })).toBeVisible()
  expect(generated).toBe(0)
  await page.getByRole('button', { name: '生成并预览', exact: true }).click()
  await expect(page.getByTitle('任务单 PDF 预览')).toBeVisible({ timeout: 25000 })
  expect(generated).toBe(1)
  await page.getByRole('link', { name: '返回检测任务查询', exact: true }).first().click()
  await expect(page).toHaveURL(url)
  await expect(table.getByRole('columnheader', { name: '项目名称', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '检测方案', exact: true })).toContainText('已选 1 项')
  await page.getByRole('button', { name: '导出', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const file = await download, csv = await readFile((await file.path())!, 'utf8')
  expect(file.suggestedFilename()).toBe('检测任务查询.csv')
  expect(csv).toContain('SP2026090051'); expect(csv).not.toContain('SP2026090020')
  await page.screenshot({ path: info.outputPath('task-query-desktop.png') })
})

test('task return validates fields and preserves input until a single successful submission', async ({ page }, info) => {
  await page.goto('/#/testing/task-query?status=任务分配完成')
  const table = page.getByRole('table', { name: '检测任务查询列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await table.locator('tbody input[type=checkbox]').first().check()
  await table.getByRole('button', { name: 'SP2026090059 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '退回委托', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '退回委托', exact: true })
  await expect(modal.getByRole('radio', { name: '委托信息错误', exact: true })).toBeChecked()
  await modal.getByLabel('退回原因').fill(' ')
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.locator('#task-return-reason-error')).toBeVisible()
  await expect(modal).not.toContainText('诊断编号')
  await modal.getByRole('radio', { name: '任务分配错误', exact: true }).check()
  await modal.getByLabel('退回原因').fill('分配信息错误')
  await modal.getByLabel('补充说明').fill('请重新核对')
  await modal.getByLabel('退回时间').fill('2026-09-26'); await modal.getByLabel('退回时间').press('Tab')
  await page.route('**/samples/demo-yp-59/task-return', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '退回服务暂不可用' } } }), { times: 1 })
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('退回服务暂不可用')
  await expect(modal.getByLabel('退回原因')).toHaveValue('分配信息错误')
  await expect(modal.getByLabel('补充说明')).toHaveValue('请重新核对')
  let release = () => {}
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/samples/demo-yp-59/task-return', async route => { const response = await route.fetch(); await gate; await route.fulfill({ response }) }, { times: 1 })
  const response = page.waitForResponse(response => response.url().endsWith('/samples/demo-yp-59/task-return'))
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('button', { name: '正在提交…', exact: true })).toBeDisabled()
  await expect(modal.getByRole('button', { name: '取消', exact: true })).toBeDisabled()
  release()
  expect(await (await response).json()).toMatchObject({ dataStatus: '完成登记', reviewStatus: 'unreviewed', taskReturns: [{ reason: '分配信息错误', details: '请重新核对', date: '2026-09-26' }] })
  await expect(modal).toBeHidden()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(table.locator('tbody input:checked')).toHaveCount(0)
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await table.getByRole('button', { name: /更多操作$/ }).first().click()
  await page.getByRole('menuitem', { name: '退回委托', exact: true }).click()
  await expect(modal).toBeFocused()
  await page.screenshot({ path: info.outputPath('task-return-mobile-dark.png') })
  await page.keyboard.press('Escape'); await expect(modal).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('task return conflict requires refresh and pre-assignment stages allow return but disable printing', async ({ page }) => {
  await page.goto('/#/testing/task-query?status=任务分配中')
  const table = page.getByRole('table', { name: '检测任务查询列表', exact: true })
  await table.getByRole('button', { name: 'SP2026090051 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '退回委托', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '退回委托', exact: true })
  await modal.getByLabel('退回原因').fill('委托信息错误')
  const response = await page.request.post('/api/registration/samples/demo-yp-51/task-return', { headers: { 'X-Demo-Actor': 'admin' }, data: { version: 1, returned: { type: 'commission', reason: '另一操作', details: '', date: '2026-09-27' } } })
  expect(response.ok()).toBe(true)
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('记录已更新')
  await expect(modal.getByRole('button', { name: '确认', exact: true })).toBeDisabled()
  await expect(modal.getByLabel('退回原因')).toHaveValue('委托信息错误')
  await modal.getByRole('button', { name: '刷新列表', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(8)
  const form = page.getByRole('form', { name: '检测任务查询条件', exact: true })
  await form.getByLabel('数据状态').selectOption('样品已领取')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await table.getByRole('button', { name: 'SP2026090021 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '退回委托', exact: true })).toBeEnabled()
  await expect(page.getByRole('menuitem', { name: '打印任务单', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '退回委托', exact: true }).click()
  await modal.getByLabel('退回原因').fill('领取后发现委托信息错误')
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal).toBeHidden()
  await expect(table).not.toContainText('SP2026090021')
})
