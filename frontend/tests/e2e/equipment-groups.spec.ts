import { test, expect, type Page } from '@playwright/test'
import { emptyEquipment, type EquipmentRecord } from '../../src/types/quality/equipmentForm'
import { toolbarButton } from './helpers/toolbar'

const base = '/api/registration/quality/equipment/ledger', headers = { 'X-Demo-Actor': 'admin' }
async function setup(page: Page) {
  await page.request.post('/api/registration/session')
  const records: EquipmentRecord[] = []
  for (let i = 1; i <= 3; i++) {
    const response = await page.request.post(`${base}/save`, { headers, data: { ...emptyEquipment(), code: `GROUP-DEMO-${i}`, name: `分组设备${i}`, departmentId: 'lab' } })
    expect(response.ok()).toBe(true); records.push(await response.json())
  }
  const context = async (ids = records.map(row => row.id)) => (await page.request.post(`${base}/group-context`, { headers, data: { ids } })).json()
  const all = await context()
  expect((await page.request.post(`${base}/group-associations`, { headers, data: { ...all, groups: [{ ...all.groups[0], state: 'checked' }] } })).ok()).toBe(true)
  const first = await context([records[0].id])
  expect((await page.request.post(`${base}/group-associations`, { headers, data: { ...first, groups: [{ ...first.groups[1], state: 'checked' }] } })).ok()).toBe(true)
  await page.goto('/#/quality/equipment/ledger?code=GROUP-DEMO')
  const table = page.getByRole('table', { name: '设备台账列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  return { records, table, context }
}

for (const width of [1440, 390]) test(`group association tri-state and deferred save at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  const { records, table, context } = await setup(page)
  await expect(await toolbarButton(page, '设备台账', '分组关联')).toBeDisabled()
  await table.locator('tbody tr').nth(0).getByRole('checkbox').check()
  await table.locator('tbody tr').nth(1).getByRole('checkbox').check()
  const open = async () => (await toolbarButton(page, '设备台账', '分组关联')).click()
  await open()
  const dialog = page.getByRole('dialog', { name: '分组关联', exact: true })
  const boxes = dialog.getByRole('checkbox')
  await expect(boxes).toHaveCount(3)
  await expect(dialog.getByRole('columnheader')).toHaveText(['分组名称'])
  await expect(boxes.nth(0)).toBeChecked()
  await expect(boxes.nth(1)).toHaveAttribute('aria-checked', 'mixed')
  expect(await boxes.nth(1).evaluate((el: HTMLInputElement) => el.indeterminate)).toBe(true)
  await expect(boxes.nth(2)).not.toBeChecked()
  await dialog.locator('tbody tr').nth(1).locator('td').click({ position: { x: 250, y: 15 } })
  await expect(boxes.nth(1)).toHaveAttribute('aria-checked', 'mixed')
  await dialog.screenshot({ path: info.outputPath(`equipment-groups-${width}.png`) })
  const bounds = (await dialog.locator('.modal-content').boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
  const before = await context()
  await boxes.nth(1).click()
  await expect(boxes.nth(1)).toHaveAttribute('aria-checked', 'true')
  await boxes.nth(1).click()
  await expect(boxes.nth(1)).toHaveAttribute('aria-checked', 'false')
  expect(await context()).toEqual(before)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  const leave = page.getByRole('dialog', { name: '放弃未保存内容', exact: true })
  await leave.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(boxes.nth(1)).toHaveAttribute('aria-checked', 'false')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await leave.getByRole('button', { name: '放弃更改', exact: true }).click()
  await expect(dialog).toBeHidden()
  await open()
  await expect(boxes.nth(1)).toHaveAttribute('aria-checked', 'mixed')
  await boxes.nth(0).uncheck()
  await boxes.nth(2).check()
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/ledger/group-associations', async route => { await pending; await route.continue() }, { times: 1 })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  try { await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeDisabled() } finally { release() }
  await expect(dialog).toBeHidden()
  expect((await context([records[0].id])).groups.map((g: { state: string }) => g.state)).toEqual(['unchecked', 'checked', 'checked'])
  expect((await context([records[1].id])).groups.map((g: { state: string }) => g.state)).toEqual(['unchecked', 'unchecked', 'checked'])
  expect((await context([records[2].id])).groups.map((g: { state: string }) => g.state)).toEqual(['checked', 'unchecked', 'unchecked'])
  await page.reload()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await table.locator('tbody tr').nth(0).getByRole('checkbox').check()
  await table.locator('tbody tr').nth(1).getByRole('checkbox').check()
  await open()
  await expect(boxes.nth(0)).not.toBeChecked()
  await expect(boxes.nth(1)).toHaveAttribute('aria-checked', 'mixed')
  await expect(boxes.nth(2)).toBeChecked()
})

test('group save failure retains choices and conflicts require reloading', async ({ page }) => {
  const { records, table, context } = await setup(page)
  await table.locator('thead').getByRole('checkbox').check()
  await (await toolbarButton(page, '设备台账', '分组关联')).click()
  const dialog = page.getByRole('dialog', { name: '分组关联', exact: true }), boxes = dialog.getByRole('checkbox')
  await boxes.nth(2).check()
  await page.route('**/ledger/group-associations', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '暂时无法保存' } } }), { times: 1 })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('暂时无法保存')
  await expect(boxes.nth(2)).toBeChecked()
  const latest = await (await page.request.get(`${base}/${records[1].id}/detail`, { headers })).json()
  expect((await page.request.post(`${base}/${latest.id}/save`, { headers, data: { ...latest, keeper: '其他人' } })).ok()).toBe(true)
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('本次未修改任何关联')
  await expect(dialog.getByRole('button', { name: '确认', exact: true })).toBeDisabled()
  expect((await context()).groups[2].state).toBe('unchecked')
  await dialog.getByRole('button', { name: '重新加载分组状态', exact: true }).click()
  await expect(boxes.nth(2)).not.toBeChecked()
  await boxes.nth(2).check()
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).toBeHidden()
  expect((await context()).groups[2].state).toBe('checked')
})
