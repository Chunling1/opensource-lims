import { toolbarButton, openToolbarExport } from './helpers/toolbar'
import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { personnelFields } from '../../src/types/quality/personnel'
const csv = (rows: Record<string, string>[]) => '\uFEFF' + [personnelFields.map(f => f.label), ...rows.map(r => personnelFields.map(f => r[f.key] || ''))].map(row => row.map(v => `"${v.replaceAll('"', '""')}"`).join(',')).join('\r\n')
for (const width of [1440, 390]) test(`personnel registration CRUD, template, import and export at ${width}`, async ({ page }, info) => {
  test.setTimeout(120000)
  page.setDefaultTimeout(15000)
  await page.setViewportSize({ width, height: 950 })
  await page.goto('/#/quality/personnel/registration')
  const query = page.getByRole('form', { name: '人员登记查询' }), table = page.getByRole('table', { name: '人员登记列表' })
  for (const label of ['姓名', '编号', '毕业院校', '所学专业']) await expect(query.getByLabel(label, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新增', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '新增人员', exact: true })
  await dialog.getByLabel('姓名', { exact: true }).fill('测试登记人员')
  await dialog.getByLabel('人员编号', { exact: true }).fill('00001')
  await dialog.getByLabel('职称/资格', { exact: true }).fill('工程师')
  await dialog.getByLabel('岗位/职务', { exact: true }).fill('技术员')
  await dialog.getByLabel('毕业院校', { exact: true }).fill('测试院校')
  await dialog.getByLabel('所学专业', { exact: true }).fill('环境检测')
  await dialog.getByLabel('身份证号码', { exact: true }).fill('012345678901234567')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  const savedToast = page.getByRole('status').filter({ hasText: '人员已保存。' })
  await expect(savedToast).toBeVisible()
  await expect(savedToast).toHaveClass(/toast-border-success/)
  let row = table.getByRole('row').filter({ hasText: '测试登记人员' })
  await expect(row).toBeVisible()
  async function action(label: string) {
    await row.getByRole('button', { name: /更多操作/ }).click()
    await expect(page.getByRole('menuitem')).toHaveText(['编辑', '查看', '删除'])
    await page.getByRole('menuitem', { name: label, exact: true }).click()
  }
  await action('编辑')
  dialog = page.getByRole('dialog', { name: '编辑人员', exact: true })
  await expect(dialog.getByLabel('身份证号码')).toHaveValue('012345678901234567')
  await dialog.getByLabel('岗位/职务', { exact: true }).fill('检测员')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(row).toContainText('检测员')
  await action('查看')
  dialog = page.getByRole('dialog', { name: '查看人员', exact: true })
  await expect(dialog.getByLabel('姓名', { exact: true })).toBeDisabled()
  await expect(dialog.getByLabel('岗位/职务', { exact: true })).toHaveValue('检测员')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  const templateEvent = page.waitForEvent('download')
  await (await toolbarButton(page, '人员登记', '下载模板')).click()
  const template = await templateEvent
  expect(template.suggestedFilename()).toBe('人员登记导入模板.csv')
  const header = await readFile((await template.path())!, 'utf8')
  for (const f of personnelFields) expect(header).toContain(f.label)
  const imported = Array.from({ length: 11 }, (_, i) => ({ name: `导入人员${i}`, code: `IMP${i}`, gender: '女', qualification: '工程师', position: '检测员', department: '实验室', school: '导入大学', major: '化学', birthDate: '1990-01-01' }))
  await (await toolbarButton(page, '人员登记', '导入')).click()
  dialog = page.getByRole('dialog', { name: '导入人员', exact: true })
  await dialog.getByLabel('导入文件').setInputFiles({ name: '人员.csv', mimeType: 'text/csv', buffer: Buffer.from(csv([imported[0]!, imported[0]!])) })
  await dialog.getByRole('button', { name: '导入', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('第 3 行')
  await dialog.getByLabel('导入文件').setInputFiles({ name: '人员.csv', mimeType: 'text/csv', buffer: Buffer.from(csv(imported)) })
  await dialog.getByRole('button', { name: '导入', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('status').filter({ hasText: '成功导入 11 条' })).toBeVisible()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await page.getByLabel('人员登记每页条数').selectOption('20')
  await expect(table.locator('tbody tr')).toHaveCount(20)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath(`personnel-${width}.png`), fullPage: true })
  await query.getByLabel('姓名', { exact: true }).fill('测试登记')
  await query.getByLabel('编号', { exact: true }).fill('00001')
  await query.getByLabel('毕业院校', { exact: true }).fill('测试院校')
  await query.getByLabel('所学专业', { exact: true }).fill('环境检测')
  await query.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await page.reload()
  await expect(query.getByLabel('编号', { exact: true })).toHaveValue('00001')
  row = table.getByRole('row').filter({ hasText: '测试登记人员' })
  await row.getByRole('checkbox').check()
  await openToolbarExport(page, '人员登记')
  const exportedEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  const exported = await exportedEvent, data = await readFile((await exported.path())!, 'utf8')
  expect(data).toContain('测试登记人员'); expect(data).toContain('012345678901234567'); expect(data).not.toContain('导入人员0')
  await (await toolbarButton(page, '人员登记', '显示')).click()
  const columns = page.getByRole('dialog', { name: '人员登记显示列' })
  await expect(columns.getByRole('checkbox')).toHaveCount(20)
  await columns.getByRole('checkbox', { name: '毕业院校', exact: true }).check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await expect(table.getByRole('columnheader', { name: /毕业院校/ })).toBeVisible()
  await action('删除')
  dialog = page.getByRole('dialog', { name: '删除人员', exact: true })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(row).toBeVisible()
  await action('删除')
  await dialog.getByRole('button', { name: '删除', exact: true }).click()
  await expect(row).toHaveCount(0)
})
