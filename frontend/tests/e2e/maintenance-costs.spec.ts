import { expect, test, type Page, type Locator } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { toolbarButton, openToolbarExport } from './helpers/toolbar'
const base = '/api/registration/quality/equipment/maintenance-costs', headers = { 'X-Demo-Actor': 'admin' }
async function search(page: Page, name: string, quantity = '') {
  const form = page.getByRole('form', { name: '设备维护费用查询', exact: true })
  await form.getByLabel('维护项目').fill(name); await form.getByLabel('数量', { exact: true }).fill(quantity)
  await form.getByRole('button', { name: '查询', exact: true }).click()
}
async function action(table: Locator, name: string) {
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await table.page().getByRole('menuitem', { name, exact: true }).click()
}
