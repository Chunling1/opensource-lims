test('maintenanceCosts template, atomic import, pagination, conflict and readonly menus', async ({ page }) => {
  await page.request.post('/api/registration/session'); await page.goto('/#/quality/equipment/maintenance-costs')
  await expect(page.getByRole('table', { name: '设备维护费用列表', exact: true })).toBeVisible()
  await (await toolbarButton(page, '设备维护费用', '下载模板')).click()
  // API and UI use the same template; verify import against those exact headers.
  const template = await (await page.request.post(`${base}/template`, { headers, data: {} })).text()
  expect(template).toContain('总金额')
  await (await toolbarButton(page, '设备维护费用', '导入')).click()
  const importing = page.getByRole('dialog', { name: '导入设备维护费用', exact: true })
  const csv = template.trimEnd() + '\r\n' + Array.from({ length: 12 }, (_, i) => `IMPORT-${String(i).padStart(2, '0')},2026-10-07,2.5,2,,实验室,批量导入`).join('\r\n')
  await importing.getByLabel('导入文件').setInputFiles({ name: '耗材.csv', mimeType: 'text/csv', buffer: Buffer.from(csv + '\r\n错误数据') })
  await importing.getByRole('button', { name: '导入', exact: true }).click(); await expect(importing.locator('[data-field-feedback]')).toContainText('第 14 行')
  expect((await (await page.request.post(`${base}/query`, { headers, data: { name: 'IMPORT-' } })).json()).total).toBe(0)
  await importing.getByLabel('导入文件').setInputFiles({ name: '耗材.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await importing.getByRole('button', { name: '导入', exact: true }).click(); await expect(importing).toBeHidden()
  await search(page, 'IMPORT-'); const table = page.getByRole('table', { name: '设备维护费用列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10); await page.getByRole('button', { name: '下一页', exact: true }).click(); await expect(table.locator('tbody tr')).toHaveCount(2)
  await search(page, 'IMPORT-00'); await action(table, '编辑')
  const dialog = page.getByRole('dialog', { name: '编辑设备维护费用', exact: true }); await expect(dialog.getByLabel('维护项目')).toHaveValue('IMPORT-00')
  const row = (await (await page.request.post(`${base}/query`, { headers, data: { name: 'IMPORT-00' } })).json()).items[0]
  expect((await page.request.post(`${base}/save`, { headers, data: { ...row, notes: '并发更新' } })).ok()).toBe(true)
  await dialog.getByRole('button', { name: '保存', exact: true }).click(); await expect(dialog).toContainText('设备维护费用记录已更新')
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '重新加载', exact: true }).click(); await expect(dialog.getByLabel('备注')).toHaveValue('并发更新')
  await dialog.getByRole('button', { name: '取消', exact: true }).click(); await expect(dialog).toBeHidden()
  await page.evaluate(() => localStorage.setItem('lims.identity.v1', 'reviewer')); await page.reload(); await expect(table).toBeVisible()
  await expect(await toolbarButton(page, '设备维护费用', '新增')).toBeDisabled(); await expect(await toolbarButton(page, '设备维护费用', '导入')).toBeDisabled()
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem', { name: '编辑', exact: true })).toBeDisabled(); await expect(page.getByRole('menuitem', { name: '删除', exact: true })).toBeDisabled()
  await expect(page.getByRole('menuitem', { name: '查看', exact: true })).toBeEnabled()
})
