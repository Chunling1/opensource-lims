test('queries are submitted over HTTP and selection determines the server sample scope', async ({ page }) => {
  const queries: { kind: string; data: Record<string, unknown> }[] = []
  page.on('request', request => {
    const kind = new URL(request.url()).pathname.match(/\/api\/registration\/(commissions|samples)\/query$/)?.[1]
    if (kind) queries.push({ kind, data: request.postDataJSON() })
  })
  await page.goto(`/#${root}`)
  const commissions = page.getByRole('table', { name: '委托列表', exact: true }), samples = page.getByRole('table', { name: '样品列表', exact: true })
  await expect(commissions.locator('tbody tr')).toHaveCount(5)
  await expect(page.getByText('请选择委托', { exact: true })).toBeVisible()
  expect(queries.filter(q => q.kind === 'samples')).toHaveLength(0)
  await page.getByRole('tab', { name: '全部样品', exact: true }).click()
  await expect(samples.locator('tbody tr')).toHaveCount(10)
  const initialCount = queries.filter(q => q.kind === 'commissions').length
  const filter = page.getByRole('form', { name: '委托查询' })
  await filter.getByLabel('查询内容', { exact: true }).selectOption('code')
  await filter.getByLabel('包含', { exact: true }).fill('WT202609014')
  expect(queries.filter(q => q.kind === 'commissions')).toHaveLength(initialCount)
  await filter.getByRole('button', { name: '查询', exact: true }).click()
  await expect(commissions.locator('tbody tr')).toHaveCount(1)
  await expect(commissions).toContainText('WT202609014')
  expect(queries.filter(q => q.kind === 'commissions').at(-1)?.data).toMatchObject({ searchField: 'code', contains: 'WT202609014' })
  await samples.getByRole('checkbox', { name: '全选当前页样品' }).check()
  await commissions.getByRole('checkbox', { name: '选择委托 WT202609014', exact: true }).check()
  await expect(samples.locator('tbody tr')).toHaveCount(5)
  await expect(samples.getByRole('checkbox', { name: '全选当前页样品' })).not.toBeChecked()
  expect(queries.filter(q => q.kind === 'samples').at(-1)?.data.commissionIds).toEqual(['demo-wt-14'])
  await expect(samples.getByRole('columnheader', { name: '委托编号', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: '全部样品', exact: true }).click()
  await expect(samples.locator('tbody tr')).toHaveCount(10)
  expect(queries.filter(q => q.kind === 'samples').at(-1)?.data).not.toHaveProperty('commissionIds')
  expect(await page.evaluate(() => sessionStorage.getItem('lims.registration.demo.v1'))).toBeNull()
})

