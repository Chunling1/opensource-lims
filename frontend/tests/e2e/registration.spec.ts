const root = '/commissions/registration'
for (const width of [1440, 390]) test(`sample pagination and tabs preserve scroll at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 800 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`/#${root}?current=demo-wt-1&scope=all&sSort=code&sDirection=asc`)
  const samples = page.getByRole('table', { name: '样品列表', exact: true })
  await expect(samples.locator('tbody tr')).toHaveCount(10)
  const next = page.getByRole('navigation', { name: '样品分页' }).getByRole('button', { name: '下一页', exact: true })
  await next.scrollIntoViewIfNeeded()
  const beforePage = await page.evaluate(() => scrollY)
  expect(beforePage).toBeGreaterThan(300)
  let release: () => void = () => {}, started: () => void = () => {}
  const delayed = new Promise<void>(resolve => { release = resolve }), requested = new Promise<void>(resolve => { started = resolve })
  await page.route('**/api/registration/samples/query', async route => {
    const response = await route.fetch()
    if (route.request().postDataJSON().page === 2) { started(); await delayed }
    await route.fulfill({ response })
  })
  await next.click(); await requested
  await expect(page.getByRole('status', { name: '正在加载样品', exact: true })).toBeVisible()
  const loading = page.getByRole('region', { name: '样品列表区域', exact: true }).getByRole('status').filter({ hasText: '正在加载…' })
  await expect(loading).toBeVisible()
  await expect(loading).toBeInViewport()
  await expect(page.locator('table[aria-label="样品列表"] tbody input:enabled')).toHaveCount(0)
  expect(Math.abs(await page.evaluate(() => scrollY) - beforePage)).toBeLessThan(5)
  await expect(page.locator('table[aria-label="样品列表"] tbody')).toHaveCSS('opacity', '0.25')
  await expect(page.locator('table[aria-label="样品列表"] tbody tr').first()).toBeVisible()
  await expect(page.locator('table[aria-label="样品列表"] tbody tr').first()).toContainText('SP2026090001')
  release()
  await expect(samples.locator('tbody tr').first()).toContainText('SP2026090011')
  await expect(loading).toHaveCount(0)
  await expect(samples.locator('tbody')).toHaveCSS('opacity', '1')
  expect(Math.abs(await page.evaluate(() => scrollY) - beforePage)).toBeLessThan(5)
  await page.unroute('**/api/registration/samples/query')

  const region = page.getByRole('region', { name: '样品列表区域', exact: true })
  await region.evaluate(element => window.scrollTo({ top: scrollY + element.getBoundingClientRect().top - 100, behavior: 'instant' }))
  const beforeTab = await page.evaluate(() => scrollY)
  await page.getByRole('tab', { name: '当前委托', exact: true }).click()
  await expect(samples.locator('tbody tr')).toHaveCount(6)
  // Fewer compact rows can shorten the document below the previous scroll offset.
  const expectedTabScroll = await page.evaluate(previous => Math.min(previous, document.documentElement.scrollHeight - innerHeight), beforeTab)
  expect(Math.abs(await page.evaluate(() => scrollY) - expectedTabScroll)).toBeLessThan(5)
  const beforeAllTab = await page.evaluate(() => scrollY)
  await page.getByRole('tab', { name: '全部样品', exact: true }).click()
  await expect(samples.locator('tbody tr')).toHaveCount(10)
  expect(Math.abs(await page.evaluate(() => scrollY) - beforeAllTab)).toBeLessThan(5)
  await samples.getByRole('button', { name: 'SP2026090001 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  await expect(page.getByRole('heading', { name: '样品详情', exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(0)
})

