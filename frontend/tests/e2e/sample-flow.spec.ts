import { test, expect } from '@playwright/test'
import { pickDateRange } from './helpers/dateRange'

test('flow query has read-only rows, all screenshot fields, scoped plans and stage-dependent dates', async ({ page }, testInfo) => {
  const requests: Record<string, unknown>[] = []
  page.on('request', request => { if (request.url().endsWith('/samples/flow/query')) requests.push(request.postDataJSON()) })
  await page.goto('/#/samples/flow')
  const table = page.getByRole('table', { name: '样品流转查询列表', exact: true }), form = page.getByRole('form', { name: '样品流转查询条件', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(form.getByLabel('流转状态').locator('option')).toHaveText(['全部', '样品已入库', '样品已出库', '样品已领取', '检测已完成', '样品待处置', '样品已处置'])
  const range = await page.evaluate(() => {
    const today = new Date(), from = new Date(today.getFullYear() - 1, today.getMonth(), 1)
    from.setDate(Math.min(today.getDate(), new Date(today.getFullYear() - 1, today.getMonth() + 1, 0).getDate()))
    return `${from.toLocaleDateString('sv-SE')} 至 ${today.toLocaleDateString('sv-SE')}`
  })
  for (const name of ['入库时间', '出库时间', '领样时间', '处置时间']) {
    await expect(form.getByLabel(name)).toBeDisabled()
    await expect(form.getByLabel(name)).toHaveValue(range)
  }
  await expect(table.getByRole('columnheader', { name: '操作', exact: true })).toHaveCount(0)
  await expect(table.getByRole('button', { name: /更多操作/ })).toHaveCount(0)
  await expect(table.getByRole('columnheader', { name: '检测方案', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '显示', exact: true }).click()
  const menu = page.getByRole('dialog', { name: '样品流转查询显示列', exact: true })
  await expect(menu.getByRole('checkbox')).toHaveCount(26)
  await expect(menu).toHaveCSS('opacity', '1')
  const desktopChoices = await menu.locator('.modal-body .form-check').evaluateAll(elements => elements.slice(0, 4).map(element => element.getBoundingClientRect().top))
  expect(Math.max(...desktopChoices.slice(0, 3)) - Math.min(...desktopChoices.slice(0, 3))).toBeLessThan(2)
  expect(desktopChoices[3]!).toBeGreaterThan(desktopChoices[0]!)
  await menu.screenshot({ path: testInfo.outputPath('columns-desktop.png') })
  for (const name of ['回库人', '回库时间', '样品/工程名称', '处置结果', '合同编号', '委托编号', '邮寄地址']) await expect(menu.getByRole('checkbox', { name, exact: true })).toBeAttached()
  await menu.getByRole('checkbox', { name: '回库人', exact: true }).check()
  await menu.getByRole('button', { name: '完成', exact: true }).click()
  await expect(menu).toBeHidden()
  await expect(table.getByRole('columnheader', { name: '回库人', exact: true })).toBeVisible()
  await form.getByLabel('流转状态').selectOption('样品待处置')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(5)
  expect(requests.at(-1)).toMatchObject({ status: '样品待处置', page: 1 })
  expect(requests.at(-1)).not.toHaveProperty('from')
  expect(Object.keys(requests.at(-1)!.dates as object)).toEqual(['inbound', 'outbound', 'collection'])
  await expect(form.getByLabel('处置时间')).toBeDisabled()
  await table.locator('tbody input[type=checkbox]').first().check()
  await form.getByLabel('样品编号').fill('SP2026090029')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table.locator('tbody input[type=checkbox]')).not.toBeChecked()
  await page.reload()
  await expect(form.getByLabel('样品编号')).toHaveValue('SP2026090029')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await drawer.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true }).click()
  await expect(drawer.getByText('已选 1 项', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: '关闭', exact: true }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(form.getByRole('button', { name: '查询', exact: true })).toBeEnabled()
  expect(requests.at(-1)).toMatchObject({ plans: { groupIds: [], planIds: ['general-1'] } })
  await page.getByRole('button', { name: '导出', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('样品流转查询.csv')
  await page.screenshot({ path: testInfo.outputPath('flow-desktop.png') })
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('flow-mobile-dark.png') })
  const toolbar = page.getByRole('group', { name: '样品流转查询工具栏', exact: true })
  await toolbar.getByRole('button', { name: '样品流转查询更多操作', exact: true }).click()
  await toolbar.getByRole('button', { name: '显示', exact: true }).click()
  await expect(menu).toHaveCSS('opacity', '1')
  const mobileChoices = await menu.locator('.modal-body .form-check').evaluateAll(elements => elements.slice(0, 3).map(element => element.getBoundingClientRect().top))
  expect(Math.abs(mobileChoices[0]! - mobileChoices[1]!)).toBeLessThan(2)
  expect(mobileChoices[2]!).toBeGreaterThan(mobileChoices[0]!)
  await menu.getByRole('checkbox', { name: '邮寄地址', exact: true }).scrollIntoViewIfNeeded()
  await expect(menu.getByRole('button', { name: '恢复默认', exact: true })).toBeInViewport()
  await expect(menu.getByRole('button', { name: '完成', exact: true })).toBeInViewport()
  await menu.screenshot({ path: testInfo.outputPath('columns-mobile-dark.png') })
  await menu.getByRole('button', { name: '完成', exact: true }).click()
  await expect(menu).toBeHidden()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
})

test('flow date ranges accumulate by stage, preserve independent dates and submit only enabled ranges', async ({ page }, testInfo) => {
  const requests: Record<string, any>[] = []
  page.on('request', request => { if (request.url().endsWith('/samples/flow/query')) requests.push(request.postDataJSON()) })
  await page.goto('/#/samples/flow')
  const form = page.getByRole('form', { name: '样品流转查询条件' }), table = page.getByRole('table', { name: '样品流转查询列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(form.getByLabel('入库时间')).toBeHidden()
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByLabel('入库时间')).toBeVisible()
  const labels = ['入库时间', '出库时间', '领样时间', '处置时间']
  const more = form.getByRole('button', { name: /更多筛选/ })
  await expect(more).toHaveAttribute('aria-expanded', 'true')
  const before = requests.length
  for (const [status, count] of [['样品已入库', 1], ['样品已出库', 2], ['样品已领取', 3], ['检测已完成', 3], ['样品待处置', 3], ['样品已处置', 4], ['', 0]] as const) {
    await form.getByLabel('流转状态').selectOption(status)
    for (const [index, label] of labels.entries()) {
      if (index < count) await expect(form.getByLabel(label)).toBeEnabled()
      else await expect(form.getByLabel(label)).toBeDisabled()
    }
  }
  expect(requests.length).toBe(before)
  const response = await page.request.post('/api/registration/samples/flow/query', { headers: { 'X-Demo-Actor': 'admin' }, data: { code: 'SP2026090030' } })
  const row = (await response.json()).items[0]
  await form.getByLabel('流转状态').selectOption('样品已处置')
  const keys = ['inbound', 'outbound', 'collection', 'disposal'] as const
  for (const [index, key] of keys.entries()) await pickDateRange(page, form.getByLabel(labels[index]!), row[`${key}Date`], row[`${key}Date`])
  await more.click()
  await expect(form.getByLabel('入库时间')).toBeHidden()
  await expect(more).toContainText('（4）')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText(row.code)
  for (const key of keys) expect(requests.at(-1)!.dates[key]).toEqual({ from: row[`${key}Date`], to: row[`${key}Date`] })
  await page.reload()
  await expect(table).toContainText(row.code)
  await more.click()
  for (const [index, key] of keys.entries()) await expect(form.getByLabel(labels[index]!)).toHaveValue(`${row[`${key}Date`]} 至 ${row[`${key}Date`]}`)
  await form.getByLabel('流转状态').selectOption('样品已出库')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(form.getByRole('button', { name: '查询', exact: true })).toBeEnabled()
  expect(Object.keys(requests.at(-1)!.dates)).toEqual(['inbound', 'outbound'])
  await form.getByLabel('流转状态').selectOption('样品已处置')
  await expect(form.getByLabel('处置时间')).toHaveValue(`${row.disposalDate} 至 ${row.disposalDate}`)
  await page.screenshot({ path: testInfo.outputPath('flow-enabled-dates.png') })
  await form.getByLabel('流转状态').selectOption('')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  expect(requests.at(-1)!.dates).toEqual({})
})
