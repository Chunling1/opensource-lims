import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('pickup copies assignment filters and exposes the screenshot columns with only a pickup action', async ({ page }, info) => {
  const queries: Record<string, unknown>[] = [], writes: string[] = []
  page.on('request', request => {
    if (request.url().endsWith('/samples/pickup/query')) queries.push(request.postDataJSON())
    if (request.method() === 'POST' && /\/(assignment-action|outbound-action|pickup-action)$/.test(request.url())) writes.push(request.url())
  })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/#/testing/sample-pickup')
  const form = page.getByRole('form', { name: '检测样品领取条件', exact: true }), table = page.getByRole('table', { name: '检测样品领取列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await expect(form.getByLabel('数据状态').locator('option')).toHaveText(['全部', '样品待领取', '样品已领取'])
  await expect(form.getByLabel('数据状态')).toHaveValue('样品待领取')
  await expect(form.getByLabel('查询内容').locator('option')).toHaveText(['样品编号', '委托编号', '委托单位', '项目名称', '工程地址', '委托人', '数据录入人', '报告标题'])
  await expect(form.getByRole('button', { name: /更多筛选/ })).toHaveAttribute('aria-expanded', 'false')
  await expect(form.getByLabel('结论状态')).toBeHidden()
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByLabel('结论状态').locator('option')).toHaveText(['全部', '不判定', '复检', '合格', '不合格'])
  await expect(form.getByLabel('日期字段').locator('option')).toHaveText(['委托日期', '要求试验日期'])
  await page.getByRole('button', { name: '显示', exact: true }).click()
  const columns = page.getByRole('dialog', { name: '检测样品领取显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(12)
  for (const name of ['样品编号', '报告编号', '样品/工程名称', '检测参数', '当前数据状态', '样品类型', '委托日期']) await expect(columns.getByRole('checkbox', { name, exact: true })).toBeChecked()
  for (const name of ['指定主检人', '检测方案', '报告标题', '分配人', '要求试验日期']) await expect(columns.getByRole('checkbox', { name, exact: true })).not.toBeChecked()
  await columns.getByRole('checkbox', { name: '报告编号', exact: true }).uncheck()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await expect(table.getByRole('columnheader', { name: '报告编号', exact: true })).toHaveCount(0)
  await table.getByRole('button', { name: 'SP2026090020 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['领取样品'])
  await page.getByRole('menuitem', { name: '领取样品', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '领取样品', exact: true })
  await expect(dialog).toContainText('SP2026090020')
  await expect(dialog.getByLabel('领样员工号')).toHaveValue('admin')
  await expect(dialog.getByLabel('领样员姓名')).toHaveValue('演示用户')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  expect(writes).toHaveLength(0)
  await page.screenshot({ path: info.outputPath('pickup-desktop.png'), fullPage: true })
  const count = queries.length
  await form.getByLabel('数据状态').selectOption('样品已领取')
  await expect(table).toContainText('SP2026090020')
  expect(queries).toHaveLength(count)
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('SP2026090021')
  await expect(table).not.toContainText('SP2026090020')
  await page.reload()
  await expect(form.getByLabel('数据状态')).toHaveValue('样品已领取')
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await expect(table.getByRole('columnheader', { name: '报告编号', exact: true })).toHaveCount(0)
  await form.getByLabel('包含', { exact: true }).fill('SP2026090021')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: '导出', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const file = await download
  expect(file.suggestedFilename()).toBe('检测样品领取.csv')
  const csv = await readFile((await file.path())!, 'utf8')
  expect(csv).toContain('SP2026090021'); expect(csv).not.toContain('SP2026090024')
  expect(queries.at(-1)).toMatchObject({ status: '样品已领取', contains: 'SP2026090021', dateField: 'commissionDate' })
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('pickup-mobile-dark.png'), fullPage: true })
  await table.getByRole('button', { name: 'SP2026090021 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['领取样品'])
  await expect(page.getByRole('menuitem', { name: '领取样品', exact: true })).toBeDisabled()
  expect(writes).toHaveLength(0)
})

test('pickup query errors can retry and do not fall back to assignment data', async ({ page }) => {
  await page.route('**/samples/pickup/query', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '领取列表暂时不可用' } } }), { times: 1 })
  await page.goto('/#/testing/sample-pickup')
  const table = page.getByRole('table', { name: '检测样品领取列表', exact: true })
  await expect(page.getByText('领取列表暂时不可用', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await expect(table).not.toContainText('SP2026090051')
})
