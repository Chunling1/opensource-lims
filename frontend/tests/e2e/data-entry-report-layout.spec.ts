import { openReportFiles } from './helpers/reportFiles'
import { expect, test } from '@playwright/test'
const word = (name: string) => ({ name, mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('504b0304', 'hex') })

test.beforeEach(async ({ page }) => {
  await page.request.post('/api/registration/session')
  const root = '/api/registration/samples/demo-yp-76/data-entry', headers = { 'X-Demo-Actor': 'admin' }
  const detail = await (await page.request.get(root, { headers })).json()
  expect((await page.request.post(root + '/save', { headers, data: { version: detail.version, sampleVersion: detail.sample.version, requestId: crypto.randomUUID(), form: { ...detail.form, conclusion: '符合要求', conclusionStatus: '合格', tester1Id: 'analyst', testDates: [{ kind: 'range', from: '2026-09-01', to: '2026-09-02' }] } } })).ok()).toBe(true)
})

test('upload confirms and saves the current layout without a separate review workflow', async ({ page }) => {
  await page.goto('/#/testing/data-entry/demo-yp-76?tab=report')
  const layout = page.getByLabel('首页版式', { exact: true })
  await layout.selectOption('extended')
  await openReportFiles(page)
  await page.getByLabel('上传完整报告', { exact: false }).setInputFiles(word('完整报告.docx'))
  await page.getByRole('button', { name: '确认上传', exact: true }).click()
  await expect(page.getByRole('button', { name: '完整报告.docx', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await expect(layout).toHaveValue('extended')
  await layout.selectOption('standard')
  await page.getByRole('button', { name: '确认切换', exact: true }).click()
  await expect(layout).toHaveValue('standard')
  await expect(page.getByRole('button', { name: '完整报告.docx', exact: true })).toHaveCount(0)
})

test('one layout confirmation clears the complete report, keeps appendices, and cancellation changes nothing', async ({ page }, info) => {
  await page.goto('/#/testing/data-entry/demo-yp-76?tab=report')
  const layout = page.getByLabel('首页版式', { exact: true })
  await layout.selectOption('extended')
  await expect(page.getByRole('button', { name: '确认切换', exact: true })).toHaveCount(0)
  await layout.selectOption('standard')
  const downloaded = page.waitForEvent('download')
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await page.getByRole('button', { name: '下载模板', exact: true }).click()
  await downloaded
  await openReportFiles(page)
  await page.getByLabel('上传完整报告', { exact: false }).setInputFiles(word('完整报告.docx'))
  await page.getByRole('button', { name: '确认上传', exact: true }).click()
  await expect(page.getByRole('button', { name: '完整报告.docx', exact: true })).toBeVisible()
  await page.getByLabel('添加附加文件', { exact: false }).setInputFiles([word('附加一.docx'), word('附加二.docx')])
  await expect(page.getByRole('button', { name: '附加二.docx', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
  const previewUrl = await page.getByTitle('完整报告预览', { exact: true }).getAttribute('src')
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await expect(layout).toBeEnabled()
  await layout.selectOption('extended')
  await expect(page.getByText('首页版式将切换为“扩展版”，已上传的完整报告将被清空，附加文件保留。请按新首页版式重新上传完整报告，或直接使用系统生成的报告。', { exact: true })).toBeVisible()
  await expect(layout).toHaveValue('standard')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await openReportFiles(page)
  await expect(page.getByRole('button', { name: '完整报告.docx', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
  await expect(page.getByTitle('完整报告预览', { exact: true })).toHaveAttribute('src', previewUrl!)
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await layout.selectOption('extended')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => document.documentElement.setAttribute('data-bs-theme', 'dark'))
  await page.screenshot({ path: info.outputPath('layout-confirmation-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: '确认切换', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(layout).toHaveValue('extended')
  await expect(page.getByRole('button', { name: '完整报告.docx', exact: true })).toHaveCount(0)
  await expect(page.getByTitle('完整报告预览', { exact: true })).toHaveCount(0)
  await openReportFiles(page)
  await expect(page.getByRole('button', { name: '附加一.docx', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '附加二.docx', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await expect(layout).toHaveValue('extended')
  await expect(page.getByRole('button', { name: '完整报告.docx', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '取消更换', exact: true })).toHaveCount(0)
  await page.goto('/#/testing/data-entry/demo-yp-76?tab=report&mode=view')
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await expect(layout).toBeDisabled()
})

test('failed or uncertain layout changes retain files or reconcile without repeated clearing', async ({ page }) => {
  await page.goto('/#/testing/data-entry/demo-yp-76?tab=report')
  const layout = page.getByLabel('首页版式', { exact: true })
  await openReportFiles(page)
  await page.getByLabel('上传完整报告', { exact: false }).setInputFiles(word('原报告.docx'))
  await page.getByRole('button', { name: '确认上传', exact: true }).click()
  await expect(page.getByRole('button', { name: '原报告.docx', exact: true })).toBeVisible()
  await page.route('**/data-entry/change-report-layout', route => route.fulfill({ status: 422, contentType: 'application/json', body: JSON.stringify({ error: { code: 'BUSINESS_RULE', message: '暂时不能切换版式。' } }) }))
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await layout.selectOption('extended')
  await page.getByRole('button', { name: '确认切换', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '切换首页版式', exact: true }).getByText('暂时不能切换版式。', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '原报告.docx', exact: true, includeHidden: true })).toHaveCount(1)
  await expect(layout).toHaveValue('standard')
  await page.unroute('**/data-entry/change-report-layout')
  let changes = 0
  await page.route('**/data-entry/change-report-layout', async route => { changes++; await route.fetch(); await route.abort() })
  await page.getByRole('button', { name: '确认切换', exact: true }).click()
  await page.getByRole('button', { name: '刷新核对', exact: true }).click()
  await expect(layout).toHaveValue('extended')
  await expect(page.getByRole('button', { name: '原报告.docx', exact: true })).toHaveCount(0)
  expect(changes).toBe(1)
})
