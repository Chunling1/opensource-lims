import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const headings = ['样品编号', '委托编号', '报告编号', '委托经办人', '样品登记人', '样品类型', '样品/工程名称', '检测参数', '数据状态', '检测方案', '委托单位', '项目名称', '标准价格费用', '折扣价格费用', '实际价格费用', '附件']
const defaults = ['样品编号', '报告编号', '样品登记人', '样品类型', '样品/工程名称', '检测参数', '数据状态', '委托单位']
const allColumns = 'code,commissionCode,reportCode,commissionOwner,owner,sampleType,name,parameters,dataStatus,testPlan,customer,projectName,standardPrice,discountPrice,actualPrice,attachmentCount'

for (const workspace of ['registration', 'review']) test(`${workspace} shows sample plan, project and live attachment presence`, async ({ page }) => {
  await page.goto(`/#/commissions/${workspace}?scope=all&sSort=code&sDirection=asc&sColumns=${allColumns}`)
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  await expect(table.locator('tbody tr').first()).toBeVisible()
  await expect(table.locator('thead th')).toHaveText(['', ...headings, ''])
  const row = table.locator('tbody tr').first(), cells = row.locator('td')
  const link = row.getByRole('link').first(), href = await link.getAttribute('href')
  const id = href!.split('/samples/')[1]!.split('?')[0]!
  const record = await (await page.request.get(`/api/registration/samples/${id}`, { headers: { 'X-Demo-Actor': 'admin' } })).json()
  await expect(cells.nth(10)).toHaveText(record.details?.testPlan || '—')
  await expect(cells.nth(12)).toHaveText(record.commissionInfo.name || '—')
  await expect(cells.nth(16)).toHaveText('')
  let queries = 0
  page.on('request', request => { if (/\/api\/registration\/(samples|commissions)\/query$/.test(new URL(request.url()).pathname)) queries++ })
  await row.getByRole('button', { name: /更多操作$/ }).click()
  await page.getByRole('menuitem', { name: '附件管理', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '附件', exact: true })
  await dialog.getByLabel('添加附件', { exact: false }).setInputFiles({ name: '列表附件.txt', mimeType: 'text/plain', buffer: Buffer.from('sample') })
  await expect(cells.nth(16)).toHaveText('有')
  await dialog.getByRole('button', { name: '删除附件 列表附件.txt', exact: true }).click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(cells.nth(16)).toHaveText('')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(dialog).toBeHidden()
  expect(queries).toBe(0)
  await page.reload()
  await expect(table.locator('tbody tr').first()).toBeVisible()
  await expect(cells.nth(16)).toHaveText('')
})

test('sample column visibility persists independently without reloading rows or changing export', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/#/commissions/registration?scope=all&sPage=2&sSort=code&sDirection=asc&cColumns=code,customer&savedSample=demo-sp-11')
  const region = page.getByRole('region', { name: '样品列表区域', exact: true })
  const table = region.getByRole('table', { name: '样品列表', exact: true })
  await expect(table.locator('tbody tr').first()).toContainText('SP2026090011')
  await expect(table.locator('thead th')).toHaveText(['', ...defaults, ''])
  await expect(region.getByRole('status', { name: '正在加载样品', exact: true })).toHaveCount(0)
  const selection = table.locator('tbody tr').first().getByRole('checkbox')
  await selection.check()
  await region.evaluate(element => window.scrollTo({ top: scrollY + element.getBoundingClientRect().top - 120, behavior: 'instant' }))
  let queries = 0
  page.on('request', request => { if (/\/api\/registration\/(samples|commissions)\/query$/.test(new URL(request.url()).pathname)) queries++ })
  await region.getByRole('button', { name: '显示', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '样品显示列', exact: true }).getByRole('checkbox', { name: '样品编号', exact: true })).toBeDisabled()
  await page.getByRole('dialog', { name: '样品显示列', exact: true }).getByRole('checkbox', { name: '报告编号', exact: true }).scrollIntoViewIfNeeded()
  const scrollBefore = await page.evaluate(() => scrollY)
  await page.getByRole('dialog', { name: '样品显示列', exact: true }).getByRole('checkbox', { name: '报告编号', exact: true }).uncheck()
  await page.getByRole('dialog', { name: '样品显示列', exact: true }).getByRole('checkbox', { name: '委托编号', exact: true }).check()
  await expect(table.getByRole('columnheader', { name: '报告编号', exact: true })).toHaveCount(0)
  await expect(table.getByRole('columnheader', { name: '委托编号', exact: true })).toHaveCount(1)
  await expect(selection).toBeChecked()
  expect(Math.abs(await page.evaluate(() => scrollY) - scrollBefore)).toBeLessThan(5)
  expect(queries).toBe(0)
  expect(new URLSearchParams(page.url().split('?')[1]).get('sPage')).toBe('2')
  const commissionHeaders = page.getByRole('table', { name: '委托列表', exact: true }).locator('thead th')
  expect((await commissionHeaders.allTextContents()).slice(1, -1).map(text => text.trim())).toEqual(['委托编号', '委托单位'])
  await page.getByRole('dialog', { name: '样品显示列', exact: true }).getByRole('button', { name: '完成', exact: true }).click()
  await region.getByRole('button', { name: '导出', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await region.getByRole('button', { name: '导出已选记录（1）', exact: true }).click()
  const csv = await readFile((await (await downloading).path())!, 'utf8')
  expect(csv.replace(/^\uFEFF/, '').split('\r\n')[0]).toBe(headings.map(value => `"${value}"`).join(','))
  expect(csv.split('\r\n')).toHaveLength(2)
  await page.reload()
  await expect(table.locator('tbody tr').first()).toContainText('SP2026090011')
  await expect(table.getByRole('columnheader', { name: '报告编号', exact: true })).toHaveCount(0)
  await table.getByRole('link', { name: 'SP2026090011', exact: true }).click()
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  await expect(table.locator('tbody tr').first()).toContainText('SP2026090011')
  await expect(table.getByRole('columnheader', { name: '报告编号', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 900 })
  await page.evaluate(() => document.documentElement.setAttribute('data-bs-theme', 'dark'))
  await region.getByRole('button', { name: '样品更多操作', exact: true }).click()
  await region.getByRole('button', { name: '显示', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '样品显示列', exact: true })
  await dialog.getByRole('button', { name: '恢复默认', exact: true }).click()
  await dialog.getByRole('button', { name: '完成', exact: true }).click()
  await expect(dialog).toBeHidden()
  expect((await table.locator('thead th').allTextContents()).slice(1, -1).map(text => text.trim())).toEqual(defaults)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(new URLSearchParams(page.url().split('?')[1]).has('sColumns')).toBe(false)
})

test('sample columns preserve selection, paging, links and internal horizontal scrolling', async ({ page }, testInfo) => {
  const parameters = '阻力；耐水性能（水渗透比、水雾发生总时间、水雾发生总质量）；'.repeat(20)
  await page.route('**/api/registration/samples/query', async route => {
    const response = await route.fetch(), data = await response.json()
    if (data.items[0]) Object.assign(data.items[0], { name: '长样品工程名称'.repeat(12), testPlan: '检测方案'.repeat(20), projectName: '项目名称'.repeat(20), parameters, customer: '单位甲；单位乙；单位丙'.repeat(8), standardPrice: 0, discountPrice: 12.5 })
    await route.fulfill({ response, json: data })
  })
  await page.goto(`/#/commissions/registration?scope=all&sSort=code&sDirection=asc&sColumns=${allColumns}`)
  const table = page.getByRole('table', { name: '样品列表', exact: true }), region = page.getByRole('region', { name: '样品列表区域', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  const headers = await table.locator('thead th').allTextContents()
  expect(headers.slice(1, -1).map(value => value.trim())).toEqual(headings)
  const first = table.locator('tbody tr').first(), cells = first.locator('td')
  await expect(cells.nth(3)).toHaveText('BG2026090001')
  await expect(cells.nth(6)).toHaveText('原始样品')
  await expect(cells.nth(9)).toHaveText('委托登记中')
  await expect(cells.nth(8)).toHaveText(Array.from(parameters).slice(0, 20).join('') + '…')
  await expect(cells.nth(8).locator('span')).toHaveAttribute('title', parameters)
  expect(await cells.nth(8).evaluate(node => node.getBoundingClientRect().width)).toBeLessThan(350)
  await expect(cells.nth(13)).toHaveText('0.00')
  await expect(cells.nth(14)).toHaveText('12.50')
  await expect(cells.nth(15)).toHaveText('—')
  await expect(cells.nth(16)).toHaveText('')
  await first.getByRole('checkbox').check()
  await expect(region.getByRole('link', { name: /打印标签/ })).toHaveCount(0)
  await expect(region.getByRole('button', { name: '批量修改（1）', exact: true })).toBeVisible()
  for (const [width, theme] of [[1440, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(value => document.documentElement.setAttribute('data-bs-theme', value), theme)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    for (const index of [7, 10, 11, 12]) {
      await expect(cells.nth(index)).toHaveCSS('white-space', 'normal')
      expect(await cells.nth(index).evaluate(node => node.getBoundingClientRect().width)).toBeGreaterThanOrEqual(160)
      expect(await cells.nth(index).evaluate(node => { const range = document.createRange(); range.selectNodeContents(node); return range.getBoundingClientRect().height / parseFloat(getComputedStyle(node).lineHeight) })).toBeGreaterThan(1.5)
    }
    for (const index of [1, 3, 5, 8, 9, 13]) await expect(cells.nth(index)).toHaveCSS('white-space', 'nowrap')
    await expect(cells.nth(13)).toHaveCSS('text-align', 'right')
    const scrolling = table.locator('..')
    expect(await scrolling.evaluate(node => node.scrollWidth > node.clientWidth)).toBe(true)
    await first.scrollIntoViewIfNeeded()
    await scrolling.evaluate(node => { node.scrollLeft = node.scrollWidth })
    await expect(cells.nth(16)).toBeInViewport()
    await scrolling.screenshot({ path: testInfo.outputPath(`sample-columns-${width}-${theme}.png`) })
    await scrolling.evaluate(node => { node.scrollLeft = 0 })
  }
  await region.getByRole('button', { name: '样品更多操作', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出已选记录（1）', exact: true }).click()
  const csv = await readFile((await (await downloading).path())!, 'utf8')
  expect(csv.replace(/^\uFEFF/, '').split('\r\n')[0]).toBe(headings.map(value => `"${value}"`).join(','))
  expect(csv.split('\r\n')).toHaveLength(2)
  await page.getByRole('navigation', { name: '样品分页' }).getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table.locator('tbody tr').first()).toContainText('SP2026090011')
  await table.getByRole('button', { name: '样品编号', exact: true }).click()
  await expect(table.getByRole('columnheader', { name: '样品编号', exact: true })).toHaveAttribute('aria-sort', 'descending')
  await table.getByRole('link', { name: /^SP/ }).first().click()
  await expect(page.getByRole('heading', { name: '样品详情', exact: true })).toBeVisible()
})
