import { test, expect } from '@playwright/test'

test('undo assignment confirms, handles retry and clears selection after a single accepted write', async ({ page }, testInfo) => {
  await page.goto('/#/testing/assignment')
  const table = page.getByRole('table', { name: '检测任务分配列表', exact: true })
  const form = page.getByRole('form', { name: '检测任务分配条件' })
  await table.getByRole('button', { name: 'SP2026090051 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '撤销分配', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await form.getByLabel('数据状态').selectOption('任务分配完成')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(3)
  const rows = (await (await page.request.post('/api/registration/samples/assignment/query', { headers: { 'X-Demo-Actor': 'admin' }, data: { status: '任务分配完成' } })).json()).items
  const target = rows[0]
  const open = async () => {
    await table.getByRole('button', { name: `${target.code} 更多操作`, exact: true }).click()
    await page.getByRole('menuitem', { name: '撤销分配', exact: true }).click()
  }
  const modal = page.getByRole('dialog', { name: '撤销分配', exact: true })
  const posts: unknown[] = []
  page.on('request', request => { if (request.url().endsWith('/assignment-action')) posts.push(request.postDataJSON()) })
  await open()
  await expect(modal).toContainText(target.code)
  await expect(modal).toContainText(target.name)
  await expect(modal).toContainText('恢复为“任务分配中”')
  await expect(modal.locator('input')).toHaveCount(0)
  await modal.getByRole('button', { name: '取消', exact: true }).click()
  await expect(modal).toBeHidden()
  expect(posts).toHaveLength(0)
  await table.getByRole('checkbox', { name: `选择检测任务分配 ${target.code}`, exact: true }).check()
  await open()
  await expect(modal).toHaveCSS('opacity', '1')
  await page.screenshot({ path: testInfo.outputPath('undo-assignment-desktop.png') })
  await page.route(`**/samples/${target.id}/assignment-action`, route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '撤销服务暂不可用' } } }), { times: 1 })
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('撤销服务暂不可用')
  let release = () => {}
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route(`**/samples/${target.id}/assignment-action`, async route => { const response = await route.fetch(); await gate; await route.fulfill({ response }) }, { times: 1 })
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('button', { name: '正在提交…', exact: true })).toBeDisabled()
  await expect(modal.getByRole('button', { name: '取消', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(modal).toBeVisible()
  release()
  await expect(modal).toBeHidden()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(table).not.toContainText(target.code)
  await expect(table.locator('tbody input:checked')).toHaveCount(0)
  expect(posts).toEqual([{ action: 'undo', version: target.version }, { action: 'undo', version: target.version }])
  await form.getByLabel('数据状态').selectOption('任务分配中')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await table.getByRole('button', { name: `${target.code} 更多操作`, exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '分配', exact: true })).toBeEnabled()
  await expect(page.getByRole('menuitem', { name: '撤销分配', exact: true })).toBeDisabled()
})

test('undo assignment requires refresh after a stale version and fits mobile dark theme', async ({ page }, testInfo) => {
  await page.goto('/#/testing/assignment?status=任务分配完成')
  const table = page.getByRole('table', { name: '检测任务分配列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(3)
  const target = (await (await page.request.post('/api/registration/samples/assignment/query', { headers: { 'X-Demo-Actor': 'admin' }, data: { status: '任务分配完成' } })).json()).items[0]
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await table.getByRole('button', { name: `${target.code} 更多操作`, exact: true }).click()
  await page.getByRole('menuitem', { name: '撤销分配', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '撤销分配', exact: true })
  await expect(modal).toBeVisible()
  await expect(modal).toHaveCSS('opacity', '1')
  await page.screenshot({ path: testInfo.outputPath('undo-assignment-mobile-dark.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  expect((await page.request.post(`/api/registration/samples/${target.id}/assignment-action`, { headers: { 'X-Demo-Actor': 'admin' }, data: { action: 'undo', version: target.version } })).ok()).toBe(true)
  await modal.getByRole('button', { name: '确认', exact: true }).click()
  await expect(modal.getByRole('alert')).toContainText('记录已更新')
  await expect(modal.getByRole('button', { name: '确认', exact: true })).toBeDisabled()
  await modal.getByRole('button', { name: '刷新列表', exact: true }).click()
  await expect(modal).toBeHidden()
  await expect(table).not.toContainText(target.code)
})

