test('delivery information can be closed while loading and retried after failure', async ({ page }) => {
  await page.goto('/#/reports/distribution')
  let release!: () => void, requests = 0
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/reports/lifecycle/*/distribution-detail', async route => {
    if (++requests === 1) { await pending; await route.abort().catch(() => {}); return }
    if (requests === 2) { await route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '发放信息暂时不可用' } } }); return }
    await route.continue()
  })
  const open = async () => {
    await page.getByRole('button', { name: 'SP2026090092 更多操作', exact: true }).click()
    await page.getByRole('menuitem', { name: '发放', exact: true }).click()
  }
  await open()
  const dialog = page.getByRole('dialog', { name: '报告发放', exact: true })
  await expect(dialog.getByRole('status')).toHaveText('正在加载发放信息…')
  await expect(dialog.getByRole('button', { name: '确认', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  release()
  await open()
  await expect(dialog).toContainText('发放信息暂时不可用')
  await expect(dialog.getByRole('button', { name: '确认', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '重试', exact: true }).click()
  await expect(dialog.getByRole('table', { name: '费用清单' })).toContainText('SP2026090092')
  await expect(dialog.getByRole('button', { name: '确认', exact: true })).toBeEnabled()
})

