test('postal delivery details appear in rows and export and undo retains history', async ({ page }) => {
  await page.goto('/#/reports/distribution?columns=code,distributionStatus,recipient,deliveryMethod,trackingNumber,mailingAddress')
  const row = page.getByRole('row').filter({ hasText: 'SP2026090092' })
  await row.getByRole('button', { name: 'SP2026090092 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '发放', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '报告发放', exact: true })
  await dialog.getByLabel('领取人', { exact: true }).fill('邮寄客户')
  await dialog.getByLabel('领取方式', { exact: true }).selectOption('邮寄')
  await dialog.getByLabel('快递单号').fill('SF20261002')
  await dialog.getByLabel('邮寄地址').fill('客户收件地址')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(row).toContainText('SF20261002')
  await expect(row).toContainText('客户收件地址')
  const filters = page.getByRole('form', { name: '报告发放条件', exact: true })
  await filters.getByRole('button', { name: /更多筛选/ }).click()
  await filters.getByLabel('领取方式').selectOption('邮寄')
  await filters.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090091' })).toHaveCount(0)
  await row.getByRole('button', { name: 'SP2026090092 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '撤销发放', exact: true }).click()
  const undo = page.getByRole('dialog', { name: '撤销发放', exact: true })
  await undo.getByLabel('撤销原因').fill('修正登记')
  await undo.getByRole('button', { name: '确认', exact: true }).click()
  await expect(undo).toBeHidden()
  await expect(row).toHaveCount(0)
  await filters.getByLabel('领取方式').selectOption('')
  await filters.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toContainText('未发放')
  await expect(row).not.toContainText('SF20261002')
})
