import { toolbarButton, openToolbarExport } from './helpers/toolbar'
import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const code = 'SP2026090096'
const location = '/#/reports/query?searchField=code&contains=SP2026090096'
async function action(page: Page, name: string) {
  await page.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  await page.getByRole('menuitem', { name, exact: true }).click()
}
for (const width of [1440, 390]) test(`report query columns, filters, actions and export at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 960 })
  await page.goto(location)
  const form = page.getByRole('form', { name: '报告查询条件' }), table = page.getByRole('table', { name: '报告查询列表', exact: true })
  await expect(table).toContainText(code)
  await expect(table).toContainText('报告发放完成')
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByLabel('日期字段')).toHaveValue('commissionDate')
  await expect(form.getByLabel('日期字段').locator('option')).toHaveText(['委托日期', '试验开始日期', '试验结束日期', '校核日期', '审核日期', '批准日期', '归档日期', '打印日期'])
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await expect(plans.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true })).toBeVisible()
  await plans.getByRole('button', { name: '关闭', exact: true }).click()
  await (await toolbarButton(page, '报告查询', '显示')).click()
  const columns = page.getByRole('dialog', { name: '报告查询显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(53)
  for (const label of ['外部ERP项目编号', '外部ERP合同编号', '合同类型', '归档人', '检测数据完成日期', '打印次数', '不合格参数']) await expect(columns.getByLabel(label, { exact: true })).toBeAttached()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await table.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['报告预览', '查看数据', '查看附件', '作废'])
  await page.getByRole('menuitem', { name: '报告预览', exact: true }).click()
  const preview = page.getByRole('dialog', { name: '报告预览', exact: true })
  await expect(preview.locator('iframe')).toHaveAttribute('src', /^blob:/)
  await preview.getByRole('button', { name: '关闭', exact: true }).click()
  await action(page, '查看附件')
  const attachments = page.getByRole('dialog', { name: '查看附件', exact: true })
  await expect(attachments).toBeVisible()
  await attachments.getByRole('button', { name: '关闭', exact: true }).click()
  await table.getByRole('checkbox', { name: `选择报告查询 ${code}`, exact: true }).check()
  await openToolbarExport(page, '报告查询')
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  const file = await downloading, csv = await readFile((await file.path())!, 'utf8')
  expect(csv).toContain(code); expect(csv).not.toContain('SP2026090095'); expect(csv).toContain('"外部ERP项目编号","外部ERP合同编号","合同类型"')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath(`query-${width}.png`), fullPage: true })
})
test('report query reuses readonly data and void application', async ({ page }) => {
  await page.goto(location)
  await action(page, '查看数据')
  await expect(page).toHaveURL(/reports\/query\/demo-yp-96/)
  await expect(page.getByRole('heading', { name: '查看检测数据', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '返回报告查询', exact: true }).click()
  await expect(page.getByLabel('包含', { exact: true })).toHaveValue(code)
  await action(page, '作废')
  const dialog = page.getByRole('dialog', { name: '作废申请', exact: true })
  await dialog.getByLabel('申请作废原因').fill('报告查询提交作废申请')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('table', { name: '报告查询列表', exact: true })).toContainText('委托作废申请中')
  await page.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '作废', exact: true })).toBeDisabled()
})
