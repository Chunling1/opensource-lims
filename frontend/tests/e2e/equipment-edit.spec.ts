import { test, expect } from '@playwright/test'

for (const width of [1440, 390]) test(`equipment row edit and view reuse the creation form at ${width}`, async ({ page }) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/equipment/ledger')
  const table = page.getByRole('table', { name: '设备台账列表', exact: true })
  const row = table.getByRole('row').filter({ hasText: 'DEMO-001' })
  const open = async (name: string) => {
    await row.getByRole('button', { name: /更多操作/ }).click()
    await page.getByRole('menuitem', { name, exact: true }).click()
  }
  await open('编辑')
  const edit = page.getByRole('dialog', { name: '编辑设备', exact: true })
  await expect(edit.getByRole('tab')).toHaveCount(7)
  await expect(edit.getByLabel('档案号', { exact: true })).toHaveValue('DEMO-001')
  await edit.getByLabel('仪器设备名称', { exact: true }).fill('不应保存的设备名')
  await edit.getByRole('button', { name: '取消', exact: true }).click()
  await expect(row).not.toContainText('不应保存的设备名')
  await open('编辑')
  await expect(edit.getByLabel('仪器设备名称', { exact: true })).not.toHaveValue('不应保存的设备名')
  await edit.getByLabel('仪器设备名称', { exact: true }).fill('已编辑的设备')
  await edit.getByRole('tab', { name: '维修维护记录', exact: true }).click()
  await edit.getByRole('button', { name: '新增', exact: true }).click()
  const maintenance = page.getByRole('dialog', { name: '新增维修维护记录', exact: true })
  await maintenance.getByLabel('维修人员', { exact: true }).fill('测试维修人')
  await maintenance.getByLabel('维修维护内容', { exact: true }).fill('更换探头')
  await maintenance.getByRole('button', { name: '确认', exact: true }).click()
  await edit.getByRole('tab', { name: '基本信息', exact: true }).click()
  await edit.getByRole('button', { name: '管理说明书附件', exact: true }).click()
  const files = page.getByRole('dialog', { name: '说明书附件', exact: true })
  await files.locator('input[type=file]').setInputFiles({ name: '原说明书.txt', mimeType: 'text/plain', buffer: Buffer.from('original') })
  await expect(files.getByRole('button', { name: '下载附件 原说明书.txt', exact: true })).toBeEnabled()
  await files.getByRole('button', { name: '完成', exact: true }).click()
  await page.route('**/quality/equipment/ledger/*/save', route => route.fulfill({ status: 503, json: { error: { code: 'INTERNAL', message: '编辑暂时失败' } } }), { times: 1 })
  await edit.getByRole('button', { name: '保存', exact: true }).click()
  await expect(edit.getByRole('alert')).toContainText('编辑暂时失败')
  await expect(edit.getByLabel('仪器设备名称', { exact: true })).toHaveValue('已编辑的设备')
  const firstResponse = page.waitForResponse(response => /\/quality\/equipment\/ledger\/[^/]+\/save$/.test(response.url()) && response.ok())
  await edit.getByRole('button', { name: '保存', exact: true }).click()
  const first = await (await firstResponse).json()
  await expect(edit).toBeHidden()
  await expect(row).toContainText('已编辑的设备')
  await open('编辑')
  await expect(edit.getByLabel('仪器设备名称', { exact: true })).toHaveValue('已编辑的设备')
  await edit.getByRole('button', { name: '管理说明书附件', exact: true }).click()
  await expect(files.getByRole('button', { name: '下载附件 原说明书.txt', exact: true })).toBeEnabled()
  await files.locator('input[type=file]').setInputFiles({ name: '补充说明书.txt', mimeType: 'text/plain', buffer: Buffer.from('additional') })
  await expect(files.getByRole('button', { name: '下载附件 补充说明书.txt', exact: true })).toBeEnabled()
  await files.getByRole('button', { name: '完成', exact: true }).click()
  const secondResponse = page.waitForResponse(response => /\/quality\/equipment\/ledger\/[^/]+\/save$/.test(response.url()) && response.ok())
  await edit.getByRole('button', { name: '保存', exact: true }).click()
  const second = await (await secondResponse).json()
  expect(second.id).toBe(first.id)
  expect(second.version).toBe(first.version + 1)
  expect(second.profile.maintenance).toEqual(first.profile.maintenance)
  expect(second.profile.attachments.manual).toHaveLength(2)
  expect(second.profile.attachments.manual[0]).toEqual(first.profile.attachments.manual[0])
  await expect(edit).toBeHidden()
  await page.reload()
  await open('查看')
  const view = page.getByRole('dialog', { name: '查看设备', exact: true })
  await expect(view.getByRole('tab')).toHaveCount(7)
  await expect(view.getByLabel('仪器设备名称', { exact: true })).toHaveValue('已编辑的设备')
  await expect(view.getByLabel('仪器设备名称', { exact: true })).toBeDisabled()
  await expect(view.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
  await view.getByRole('tab', { name: '维修维护记录', exact: true }).click()
  await expect(view.getByRole('cell', { name: '更换探头', exact: true })).toBeVisible()
  await expect(view.getByRole('button', { name: '新增', exact: true })).toHaveCount(0)
  await view.getByRole('tab', { name: '基本信息', exact: true }).click()
  await view.getByRole('button', { name: '管理说明书附件', exact: true }).click()
  await expect(files.locator('input[type=file]')).toHaveCount(0)
  const download = page.waitForEvent('download')
  await files.getByRole('button', { name: '下载附件 原说明书.txt', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('原说明书.txt')
})
