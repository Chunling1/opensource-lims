import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { emptyEquipment } from '../../src/types/quality/equipmentForm'
import { toolbarButton, openToolbarExport } from './helpers/toolbar'

for (const width of [1440, 390]) test(`monthly calibration filters, menu-free table and exports at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.request.post('/api/registration/session')
  const headers = { 'X-Demo-Actor': 'admin' }
  for (let i = 1; i <= 13; i++) {
    const data = { ...emptyEquipment(), code: `MONTH-${String(i).padStart(2, '0')}`, name: `月检设备${i}`, serial: `SN-${i}`, manufacturer: '月检厂商', departmentId: i % 2 ? 'lab' : 'lab2', plannedTestDate: i === 13 ? '2024-03-01' : i === 12 ? '2024-02-29' : '2024-02-01', actualTestDate: '2024-02-01' }
    expect((await page.request.post('/api/registration/quality/equipment/ledger/save', { headers, data })).ok()).toBe(true)
  }
  await page.goto('/#/quality/equipment/monthly-calibration')
  const form = page.getByRole('form', { name: '月检定计划查询', exact: true }), table = page.getByRole('table', { name: '月检定计划列表', exact: true })
  const today = await page.evaluate(() => ({ year: new Date().getFullYear(), month: new Date().getMonth() + 1 }))
  const period = form.getByLabel('年月', { exact: true })
  await expect(period).toHaveValue(`${today.year}-${String(today.month).padStart(2, '0')}`)
  await expect(form.getByLabel('生产厂家', { exact: true })).toBeHidden()
  await period.click()
  const picker = page.locator('.flatpickr-calendar.open')
  await expect(picker.locator('.flatpickr-monthSelect-months')).toBeVisible()
  expect(await period.evaluate(element => (element as HTMLInputElement & { _flatpickr: { loadedPlugins: string[] } })._flatpickr.loadedPlugins)).toContain('monthSelect')
  await expect(picker.getByRole('button', { name: /月$/, exact: false })).toHaveCount(12)
  await picker.getByRole('spinbutton', { name: '年份', exact: true }).fill('2024')
  await picker.getByRole('spinbutton', { name: '年份', exact: true }).press('Enter')
  // Reopen if Flatpickr closes after confirming the year with Enter.
  await period.click()
  await picker.locator('[aria-label="上一年"]').click()
  await expect(picker.getByRole('spinbutton', { name: '年份', exact: true })).toHaveValue('2023')
  await picker.locator('[aria-label="下一年"]').click()
  await expect(picker.getByRole('spinbutton', { name: '年份', exact: true })).toHaveValue('2024')
  await picker.screenshot({ path: info.outputPath(`month-picker-${width}.png`) })
  await picker.getByRole('button', { name: '2月', exact: true }).click()
  await expect(period).toHaveValue('2024-02')
  await expect(picker).toHaveCount(0)
  await period.click()
  await expect(picker.getByRole('button', { name: '2月', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(picker.getByRole('button', { name: '2月', exact: true })).toHaveClass(/bg-primary/)
  await period.press('Escape')
  await form.getByLabel('档案号', { exact: true }).fill('MONTH-')
  await expect(form.getByRole('button', { name: '查询', exact: true })).toBeEnabled()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(table.getByRole('columnheader')).toHaveCount(8)
  await expect(table.getByRole('button', { name: /更多操作/ })).toHaveCount(0)
  const toolbar = page.getByRole('group', { name: '月检定计划工具栏', exact: true })
  for (const name of ['新增', '批量修改', '分组关联', '下载模板', '导入']) await expect(toolbar.getByRole('button', { name, exact: true, includeHidden: true })).toHaveCount(0)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(table).toContainText('MONTH-12')
  await page.getByLabel('月检定计划每页条数', { exact: true }).selectOption('20')
  await expect(table.locator('tbody tr')).toHaveCount(12)
  await table.locator('tbody tr').first().getByRole('checkbox').check()
  await openToolbarExport(page, '月检定计划')
  let downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  let download = await downloading, csv = await readFile((await download.path())!, 'utf8')
  expect(csv).toContain('MONTH-01'); expect(csv).not.toContain('MONTH-02')
  await openToolbarExport(page, '月检定计划')
  downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出查询结果', exact: true }).click()
  download = await downloading; csv = await readFile((await download.path())!, 'utf8')
  expect(download.suggestedFilename()).toBe('月检定计划-2024-02.csv')
  expect(csv).toContain('MONTH-12'); expect(csv).not.toContain('MONTH-13')
  await (await toolbarButton(page, '月检定计划', '显示')).click()
  const columns = page.getByRole('dialog', { name: '月检定计划显示列' })
  await columns.getByRole('checkbox', { name: '计划检定/测试日期', exact: true }).check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await expect(columns).toBeHidden()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(table.getByRole('columnheader', { name: /计划检定/ })).toBeVisible()
  await page.screenshot({ path: info.outputPath(`monthly-${width}.png`), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await form.screenshot({ path: info.outputPath(`monthly-filters-${width}.png`) })
  await expect(form.getByLabel('设备状态', { exact: true })).toHaveCount(0)
  await expect(form.getByLabel('日期范围', { exact: true })).toHaveCount(0)
  await form.getByRole('checkbox', { name: '本部门设备', exact: true }).check()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(6)
  await form.getByLabel('仪器设备名称', { exact: true }).fill('月检设备1')
  await form.getByLabel('生产厂家', { exact: true }).fill('月检厂商')
  await form.getByLabel('仪器出厂号', { exact: true }).fill('SN-11')
  await form.getByLabel('所属部门', { exact: true }).selectOption('lab')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText('MONTH-11')
  await page.reload()
  await expect(period).toHaveValue('2024-02')
  await expect(table).toContainText('MONTH-11')
})
