import { expect, test, type Page } from '@playwright/test'

async function menu(page: Page, code: string, label: string) {
  const row = page.getByRole('row').filter({ hasText: code })
  await row.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  return page.getByRole('menuitem', { name: label, exact: true })
}
test('paper printing and distribution require explicit confirmations and preserve reversal history', async ({ page }) => {
  await page.goto('/#/reports/print')
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090093' })).toHaveCount(0)
  await (await menu(page, 'SP2026090091', '预览')).click()
  const preview = page.getByRole('dialog', { name: '报告预览', exact: true })
  await expect(preview.locator('iframe')).toHaveAttribute('src', /^blob:/)
  await preview.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090091' })).toContainText('报告打印中')
  await (await menu(page, 'SP2026090091', '打印完成')).click()
  const complete = page.getByRole('dialog', { name: '打印完成', exact: true })
  await expect(complete).toContainText('确认打印完成')
  await complete.getByRole('checkbox').check()
  await complete.getByRole('button', { name: '确认', exact: true }).click()
  await expect(complete).toBeHidden()
  await page.goto('/#/reports/distribution')
  await (await menu(page, 'SP2026090091', '发放')).click()
  const delivery = page.getByRole('dialog', { name: '报告发放', exact: true })
  await delivery.getByLabel('领取人', { exact: true }).fill('张客户')
  await delivery.getByLabel('领取方式', { exact: true }).selectOption('邮寄')
  await delivery.getByRole('button', { name: '确认', exact: true }).click()
  await expect(delivery).toBeHidden()
  await page.goto('/#/reports/print?status=&printStatus=')
  await expect(await menu(page, 'SP2026090091', '撤销打印完成')).toBeDisabled()
  await page.goto('/#/reports/archive')
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090091' })).toBeVisible()
  await page.goto('/#/reports/distribution')
  await (await menu(page, 'SP2026090091', '撤销发放')).click()
  const undo = page.getByRole('dialog', { name: '撤销发放', exact: true })
  await undo.getByLabel('撤销原因').fill('修正发放登记')
  await undo.getByRole('button', { name: '确认', exact: true }).click()
  await expect(undo).toBeHidden()
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090091' })).toContainText('未发放')
})

test('electronic signing retries, downloads and distributes without a print action', async ({ page }) => {
  await page.goto('/#/reports/signing')
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090091' })).toHaveCount(0)
  await expect(await menu(page, 'SP2026090094', '下载报告')).toBeDisabled()
  await page.getByRole('heading', { name: '报告签章', exact: true }).first().click()
  await (await menu(page, 'SP2026090094', '预览')).click()
  const preview = page.getByRole('dialog', { name: '报告预览', exact: true })
  await expect(preview).toContainText('未签章')
  await expect(preview.getByRole('button', { name: '下载', exact: true })).toHaveCount(0)
  await preview.getByRole('button', { name: '关闭', exact: true }).click()
  await (await menu(page, 'SP2026090094', '重试签章')).click()
  await page.getByRole('dialog', { name: '重试签章', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090094' })).toContainText('签章完成', { timeout: 15000 })
  const download = page.waitForEvent('download')
  await (await menu(page, 'SP2026090094', '下载报告')).click()
  expect((await download).suggestedFilename()).toBe('BG2026090094.pdf')
  await page.goto('/#/reports/distribution')
  await (await menu(page, 'SP2026090094', '发放')).click()
  const delivery = page.getByRole('dialog', { name: '报告发放', exact: true })
  await expect(delivery.getByRole('table', { name: '费用清单' })).toBeVisible()
  await expect(delivery.getByLabel('快递单号')).toBeDisabled()
  await expect(delivery.getByLabel('邮寄地址')).toBeDisabled()
  await expect(delivery.getByLabel('领取日期')).toBeVisible()
  await expect(delivery.getByLabel('领取方式').locator('option')).toHaveText(['自取', '邮寄', '其他'])
  await expect(delivery.getByLabel('领取方式')).toHaveValue('其他')
  await expect(delivery.getByLabel('领取方式')).toBeDisabled()
  await delivery.getByLabel('领取人', { exact: true }).fill('李客户')
  await delivery.getByLabel('备注').fill('文件交付')
  await delivery.getByRole('button', { name: '确认', exact: true }).click()
  await expect(delivery).toBeHidden()
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090094' })).toContainText('已发放')
  await menu(page, 'SP2026090094', '下载报告')
  await expect(page.getByRole('menuitem', { name: '打印', exact: true })).toHaveCount(0)
  const response = await page.request.post('/api/registration/reports/lifecycle/query', { headers: { 'X-Demo-Actor': 'admin' }, data: { queue: 'distribution', keyword: 'SP2026090094' } })
  expect((await response.json()).items[0].printStatus).toBe('不适用')
})

test('approval inherits the sample form and rejects the retired editing endpoint', async ({ page }) => {
  await page.request.post('/api/registration/session')
  await page.goto('/#/reports/approval/demo-yp-88')
  const headers = { 'X-Demo-Actor': 'admin' }, samplePath = '/api/registration/samples/demo-yp-88'
  const sample = await (await page.request.get(samplePath, { headers })).json()
  const expectedForm = sample.details.reportForm || '纸质'
  await expect(page.getByLabel('报告形式', { exact: true })).toHaveText(expectedForm)
  await expect(page.getByRole('button', { name: '保存形式', exact: true })).toHaveCount(0)
  const denied = await page.request.post(`${samplePath}/report-form`, { headers, data: { version: sample.version, form: '电子' } })
  expect(denied.status()).toBe(403)
  expect((await denied.json()).error.code).toBe('FORBIDDEN')
  expect(await (await page.request.get(samplePath, { headers })).json()).toEqual(sample)
  const check = await (await page.request.post(`${samplePath}/report-compliance-check`, { headers, data: { version: sample.version, stage: 'approval' } })).json()
  const response = await page.request.post(`${samplePath}/report-check-action`, { headers, data: { version: sample.version, stage: 'approval', action: 'check', confirmation: { nextAction: 'next', reviewCheckId: check.id, readConfirmed: true } } })
  expect(response.ok()).toBe(true)
  const approved = await response.json()
  const changed = await page.request.post(`${samplePath}/report-form`, { headers, data: { version: approved.version, form: '电子' } })
  expect(changed.status()).toBe(403)
  expect((await (await page.request.get(samplePath, { headers })).json()).details.reportForm || '纸质').toBe(expectedForm)
  await page.goto('/#/reports/print')
  await expect(page.getByRole('row').filter({ hasText: 'SP2026090088' })).toBeVisible()
})

