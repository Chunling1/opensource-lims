import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const table = (page: Page, label: string) => page.getByRole('table', { name: `${label}列表`, exact: true })
const dialog = (page: Page, title: string) => page.getByRole('dialog', { name: title, exact: true })
async function action(page: Page, label: string, number: string, name: string) {
  await table(page, label).getByRole('button', { name: `${number} 更多操作`, exact: true }).click()
  await page.getByRole('menuitem', { name, exact: true }).click()
}

for (const width of [1440, 390]) test(`delete confirmations cancel safely and remove only their owner at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/personnel/certificates')
  await table(page, '人员').getByRole('cell', { name: 'DEMO-001', exact: true }).click()
  for (const number of ['DEMO-C001-1', 'DEMO-C001-2']) await table(page, '上岗证').getByLabel(`选择上岗证 ${number}`, { exact: true }).check()
  const projects = page.getByRole('region', { name: '核准项目区域', exact: true })
  await expect(projects).toContainText('共 12 条')
  await table(page, '核准项目').getByLabel('选择核准项目 DEMO-C001-1 · DEMO-P1', { exact: true }).check()
  await action(page, '核准项目', 'DEMO-C001-1 · DEMO-P1', '删除')
  const projectDelete = dialog(page, '删除核准检测项目')
  await expect(projectDelete).toContainText('核准检测项目1（示例）')
  await expect(projectDelete).toContainText('演示人员01 · DEMO-C001-1')
  await page.screenshot({ path: info.outputPath(`delete-project-${width}.png`) })
  await projectDelete.getByRole('button', { name: '取消', exact: true }).click()
  await expect(projects).toContainText('共 12 条')
  await action(page, '核准项目', 'DEMO-C001-1 · DEMO-P1', '删除')
  await projectDelete.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(projects).toContainText('共 11 条')
  await expect(table(page, '核准项目').getByRole('checkbox', { checked: true })).toHaveCount(0)
  await expect(table(page, '上岗证').getByLabel('选择上岗证 DEMO-C001-1', { exact: true })).toBeChecked()
  await action(page, '上岗证', 'DEMO-C001-1', '删除')
  const certificateDelete = dialog(page, '删除上岗证')
  await expect(certificateDelete).toContainText('演示人员01 的上岗证“DEMO-C001-1”')
  await expect(certificateDelete).toContainText('5 个核准项目和 1 个附件')
  await certificateDelete.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('region', { name: '上岗证区域', exact: true })).toContainText('共 6 条')
  await action(page, '上岗证', 'DEMO-C001-1', '删除')
  await expect(certificateDelete).toHaveCSS('opacity', '1')
  await expect(certificateDelete.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  await page.screenshot({ path: info.outputPath(`delete-certificate-${width}.png`) })
  const box = (await certificateDelete.locator('.modal-content').boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(width)
  await certificateDelete.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(table(page, '上岗证').getByRole('cell', { name: 'DEMO-C001-1', exact: true })).toHaveCount(0)
  await expect(table(page, '上岗证').getByLabel('选择上岗证 DEMO-C001-2', { exact: true })).toBeChecked()
  await expect(projects).toContainText('共 6 条')
  await expect(table(page, '核准项目').getByRole('cell', { name: 'DEMO-P1', exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '全部核准项目', exact: true }).click()
  await expect(projects).toContainText('共 426 条')
  await page.getByRole('tab', { name: '全部上岗证', exact: true }).click()
  await expect(page.getByRole('region', { name: '上岗证区域', exact: true })).toContainText('共 71 条')
})

test('add project header uses selected certificates and creates independent rows for every owner', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/#/quality/personnel/certificates')
  const region = page.getByRole('region', { name: '核准项目区域', exact: true })
  const add = region.getByRole('button', { name: '新增项目', exact: true })
  await expect(add).toBeDisabled()
  await page.getByRole('tab', { name: '全部核准项目', exact: true }).click()
  await expect(add).toBeDisabled()
  await page.getByRole('tab', { name: '全部上岗证', exact: true }).click()
  await page.getByLabel('上岗证每页条数', { exact: true }).selectOption('10')
  for (const number of ['DEMO-C001-1', 'DEMO-C002-1']) await table(page, '上岗证').getByLabel(`选择上岗证 ${number}`, { exact: true }).check()
  await table(page, '上岗证').getByRole('button', { name: 'DEMO-C001-1 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '新增核准检测项目', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await add.click()
  const form = dialog(page, '新增核准检测项目')
  await expect(form).toContainText('已选 2 张')
  await expect(form).toContainText('演示人员01 · DEMO-C001-1；演示人员02 · DEMO-C002-1')
  await form.getByRole('textbox', { name: '核准项目代码', exact: true }).fill('CANCELLED')
  await form.getByRole('button', { name: '取消', exact: true }).click()
  await expect(region).toContainText('共 432 条')
  await add.click()
  await form.getByRole('textbox', { name: '核准项目代码', exact: true }).fill('BATCH-P')
  await form.getByRole('textbox', { name: '核准检测项目', exact: true }).fill('共同项目')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(region).toContainText('共 434 条')
  await region.getByLabel('项目代码', { exact: true }).fill('BATCH-P')
  await region.getByRole('button', { name: '查询', exact: true }).click()
  await expect(region).toContainText('共 2 条')
  const rows = table(page, '核准项目').getByRole('row').filter({ hasText: 'BATCH-P' })
  await expect(rows).toHaveCount(2)
  await expect(rows.nth(0)).toContainText('DEMO-C001-1')
  await expect(rows.nth(1)).toContainText('DEMO-C002-1')
  await action(page, '核准项目', 'DEMO-C001-1 · BATCH-P', '编辑')
  await dialog(page, '编辑核准检测项目').getByRole('textbox', { name: '核准检测项目', exact: true }).fill('仅编辑第一个')
  await dialog(page, '编辑核准检测项目').getByRole('button', { name: '保存', exact: true }).click()
  await expect(rows.nth(0)).toContainText('仅编辑第一个')
  await expect(rows.nth(1)).toContainText('共同项目')
  await table(page, '上岗证').getByLabel('全选当前页上岗证', { exact: true }).check()
  await add.click()
  await expect(form).toContainText('已选 10 张')
  await form.getByRole('textbox', { name: '核准项目代码', exact: true }).fill('ALL-P')
  await form.getByRole('textbox', { name: '核准检测项目', exact: true }).fill('当前页批量项目')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await region.getByLabel('项目代码', { exact: true }).fill('ALL-P')
  await region.getByRole('button', { name: '查询', exact: true }).click()
  await expect(region).toContainText('共 10 条')
  await page.getByLabel('核准项目每页条数', { exact: true }).selectOption('20')
  await expect(table(page, '核准项目').getByRole('row').filter({ hasText: 'ALL-P' })).toHaveCount(10)
  await table(page, '上岗证').getByLabel('全选当前页上岗证', { exact: true }).uncheck()
  await expect(add).toBeDisabled()
})

for (const width of [1440, 390]) test(`certificate forms preserve ownership and attachment drafts at ${width}px`, async ({ page }, info) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/personnel/certificates')
  await table(page, '人员').getByRole('cell', { name: 'DEMO-001', exact: true }).click()
  await page.getByRole('button', { name: '新增上岗证', exact: true }).click()
  const form = dialog(page, '新增上岗证')
  await expect(form).toContainText('演示人员01 · DEMO-001')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(form).toBeVisible()
  await form.getByLabel('上岗证类别', { exact: true }).fill('材料检测上岗证')
  await form.getByRole('textbox', { name: '上岗证号', exact: true }).fill('TEST-CERT-001')
  await form.getByLabel('备注', { exact: true }).fill('测试备注')
  const bounds = await form.locator('input, textarea, button').filter({ visible: true }).evaluateAll(elements => elements.map(el => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right } }))
  bounds.forEach(box => { expect(box.left).toBeGreaterThanOrEqual(0); expect(box.right).toBeLessThanOrEqual(width) })
  await page.screenshot({ path: info.outputPath(`certificate-form-${width}.png`) })
  await form.getByRole('button', { name: '管理上岗证附件', exact: true }).click()
  const attachments = dialog(page, '上岗证附件')
  await expect(attachments.getByRole('button', { name: '返回', exact: true })).toBeVisible()
  await attachments.locator('input[type=file]').setInputFiles({ name: '证书.txt', mimeType: 'text/plain', buffer: Buffer.from('certificate draft attachment') })
  await expect(attachments.getByRole('button', { name: '下载附件 证书.txt', exact: true })).toBeVisible()
  await expect(attachments.locator('.filepond--file-status-main')).toHaveText('上传成功')
  await attachments.getByRole('button', { name: '完成', exact: true }).click()
  await expect(form.getByLabel('备注', { exact: true })).toHaveValue('测试备注')
  await expect(form).toContainText('1 个附件')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(form).toBeHidden()
  await expect(table(page, '上岗证').getByRole('cell', { name: 'TEST-CERT-001', exact: true })).toBeVisible()
  await action(page, '上岗证', 'TEST-CERT-001', '编辑')
  const edit = dialog(page, '编辑上岗证')
  await expect(edit.getByLabel('备注', { exact: true })).toHaveValue('测试备注')
  await edit.getByRole('button', { name: '管理上岗证附件', exact: true }).click()
  const download = page.waitForEvent('download')
  await attachments.getByRole('button', { name: '下载附件 证书.txt', exact: true }).click()
  expect(await readFile((await (await download).path())!, 'utf8')).toBe('certificate draft attachment')
  await attachments.getByRole('button', { name: '删除附件 证书.txt', exact: true }).click()
  await page.getByRole('dialog', { name: '删除附件', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '删除附件', exact: true })).toBeHidden()
  await attachments.getByRole('button', { name: '完成', exact: true }).click()
  await edit.getByRole('textbox', { name: '上岗证号', exact: true }).fill('CANCELLED')
  await edit.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('dialog', { name: '放弃未保存内容', exact: true }).getByRole('button', { name: '放弃更改', exact: true }).click()
  await action(page, '上岗证', 'TEST-CERT-001', '编辑')
  await expect(edit).toContainText('1 个附件')
  await edit.getByRole('button', { name: '取消', exact: true }).click()
  await table(page, '上岗证').getByRole('cell', { name: 'TEST-CERT-001', exact: true }).click()
  await page.getByRole('button', { name: '新增项目', exact: true }).click()
  const project = dialog(page, '新增核准检测项目')
  await expect(project).toContainText('演示人员01 · TEST-CERT-001')
  await project.getByRole('textbox', { name: '核准项目代码', exact: true }).fill('TEST-P-001')
  await project.getByRole('textbox', { name: '核准检测项目', exact: true }).fill('材料强度检测')
  await project.getByLabel('类别', { exact: true }).fill('检测类（示例）')
  await page.screenshot({ path: info.outputPath(`approved-project-form-${width}.png`) })
  await project.getByRole('button', { name: '保存', exact: true }).click()
  await expect(table(page, '核准项目').getByRole('cell', { name: 'TEST-P-001', exact: true })).toBeVisible()
  await table(page, '上岗证').getByRole('cell', { name: 'DEMO-C001-1', exact: true }).click()
  await expect(table(page, '核准项目').getByRole('cell', { name: 'TEST-P-001', exact: true })).toHaveCount(0)
  await table(page, '上岗证').getByRole('cell', { name: 'TEST-CERT-001', exact: true }).click()
  await expect(table(page, '核准项目').getByRole('cell', { name: 'TEST-P-001', exact: true })).toBeVisible()
  await action(page, '核准项目', 'TEST-CERT-001 · TEST-P-001', '编辑')
  await dialog(page, '编辑核准检测项目').getByRole('textbox', { name: '核准检测项目', exact: true }).fill('编辑后的检测项目')
  await dialog(page, '编辑核准检测项目').getByRole('button', { name: '保存', exact: true }).click()
  await expect(table(page, '核准项目')).toContainText('编辑后的检测项目')
  await action(page, '上岗证', 'TEST-CERT-001', '编辑')
  await edit.getByRole('textbox', { name: '上岗证号', exact: true }).fill('TEST-CERT-002')
  await edit.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('tab', { name: '全部核准项目', exact: true }).click()
  await expect(table(page, '核准项目').getByRole('row').filter({ hasText: 'TEST-P-001' })).toContainText('TEST-CERT-002')
  await page.reload()
  await page.getByRole('tab', { name: '全部上岗证', exact: true }).click()
  await expect(page.getByRole('region', { name: '上岗证区域', exact: true })).toContainText('共 73 条')
  await action(page, '上岗证', 'TEST-CERT-002', '编辑')
  await expect(edit).toContainText('1 个附件')
  await expect(edit.getByLabel('备注', { exact: true })).toHaveValue('测试备注')
})
