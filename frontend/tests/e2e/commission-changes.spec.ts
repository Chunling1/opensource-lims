  await page.goto(`/#${list}`)
  const table = page.getByRole('table', { name: '委托更改列表', exact: true })
  await expect(table).toContainText('SP2026090061')
  const original = await (await page.request.get(`${api}/samples/demo-yp-61`, { headers })).json()
  const parent = await (await page.request.get(`${api}/commissions/${original.commissionId}`, { headers })).json()
  await table.getByRole('button', { name: 'SP2026090061 更多操作', exact: true }).click()
