  await expect(page.getByRole('button', { name: '选择检测方案', exact: true })).toHaveCount(0)
  await page.getByLabel('工程/产品名称', { exact: false }).fill('更正后的样品名称')
  await page.getByRole('button', { name: '保存并返回', exact: true }).click()
  await expect(page).toHaveURL(`/#${list}`)
  await expect(table).toContainText('更正后的样品名称')
  const saved = await (await page.request.get(`${api}/samples/demo-yp-61`, { headers })).json()
  expect(saved.dataStatus).toBe('委托更改中')
  await table.getByRole('button', { name: 'SP2026090061 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '完成', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '完成', exact: true })
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(table).toContainText('SP2026090061')
  await table.getByRole('button', { name: 'SP2026090061 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '完成', exact: true }).click()
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
