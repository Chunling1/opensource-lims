import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { commissionChangeColumns } from '../../src/types/commissions/commissionChanges'

const root = '/commissions/changes', api = '/api/registration', headers = { 'X-Demo-Actor': 'admin' }

async function openAttachments(page: Page) {
  await page.getByRole('button', { name: 'SP2026090061 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '附件管理', exact: true }).click()
  return page.getByRole('dialog', { name: '附件', exact: true })
}

for (const width of [1440, 390]) test(`change list attachments preserve filters and selection at ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto(`/#${root}?sort=code&direction=asc&source=${encodeURIComponent('问题处理')}&size=20&columns=code,attachmentCount`)
  const selected = page.getByRole('checkbox', { name: '选择委托更改 SP2026090061', exact: true })
  await selected.check()
  const attachmentCell = page.getByRole('table', { name: '委托更改列表', exact: true }).getByRole('row').filter({ hasText: 'SP2026090061' }).locator('td').nth(-2)
  await expect(attachmentCell).toHaveText('')
  const before = await (await page.request.get(`${api}/samples/demo-yp-61`, { headers })).json()
  const url = page.url(), dialog = await openAttachments(page), reloads: string[] = []
  page.on('request', request => { if (request.url().endsWith('/samples/changes/query')) reloads.push(request.url()) })
  const file = { name: 'change.txt', mimeType: 'text/plain', buffer: Buffer.from('change attachment') }
  const upload = dialog.getByLabel('添加附件', { exact: false })
  await upload.setInputFiles(file)
  await expect(dialog.getByRole('button', { name: file.name, exact: true })).toBeVisible()
  await expect(attachmentCell).toHaveText('有')
  const download = page.waitForEvent('download')
  await dialog.getByRole('button', { name: file.name, exact: true }).click()
  expect((await download).suggestedFilename()).toBe(file.name)
  await dialog.getByRole('button', { name: `删除附件 ${file.name}`, exact: true }).click()
  await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(dialog.getByRole('button', { name: file.name, exact: true })).toHaveCount(0)
  await expect(attachmentCell).toHaveText('')
  await upload.setInputFiles(file)
  await expect(dialog.getByRole('button', { name: file.name, exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: '关闭', exact: true })).toBeEnabled()
  for (const theme of ['light', 'dark']) {
    await page.evaluate(value => document.documentElement.setAttribute('data-bs-theme', value), theme)
    await expect(upload).toBeInViewport()
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`changes-attachments-${width}-${theme}.png`) })
  }
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(selected).toBeChecked()
  expect(page.url()).toBe(url)
  expect(reloads).toEqual([])
  const saved = await (await page.request.get(`${api}/samples/demo-yp-61`, { headers })).json()
  expect(saved).toEqual({ ...before, attachments: saved.attachments, events: saved.events, version: before.version + 3 })
  await openAttachments(page)
  await expect(dialog.getByRole('button', { name: file.name, exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: 'SP2026090061 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '更改', exact: true }).click()
  await expect(page.getByRole('form', { name: '样品表单', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: '样品附件', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: '返回委托更改', exact: true }).click()
  await page.getByRole('button', { name: 'SP2026090061 更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '完成', exact: true }).click()
  const confirm = page.getByRole('dialog', { name: '完成', exact: true })
  await confirm.getByRole('button', { name: '确认', exact: true }).click()
  await expect(confirm).toBeHidden()
  await expect(page.getByRole('table', { name: '委托更改列表', exact: true })).not.toContainText('SP2026090061')
  const completed = await (await page.request.get(`${api}/samples/demo-yp-61`, { headers })).json()
  expect(completed.attachments).toEqual(saved.attachments)
})

test('change list attachments honor backend read-only permission', async ({ page }) => {
  await page.goto(`/#${root}?sort=code&direction=asc`)
  await page.route('**/samples/demo-yp-61/attachments', async route => {
    const response = await route.fetch()
    await route.fulfill({ response, json: { ...await response.json(), canManageAttachments: false, attachments: [{ id: 'history', name: 'history.txt', type: 'text/plain', size: 1, dataUrl: 'data:text/plain;base64,YQ==' }] } })
  })
  const dialog = await openAttachments(page)
  await expect(dialog.getByText('当前样品仅支持查看和下载附件。', { exact: true })).toBeVisible()
  await expect(dialog.getByLabel('添加附件', { exact: false })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: /删除附件/ })).toHaveCount(0)
  const download = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'history.txt', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('history.txt')
})

