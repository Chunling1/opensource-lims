import { expect, test } from '@playwright/test'

for (const stage of [
  { key: 'review', label: '审核', id: '85', receiver: '王复核（reviewer）' },
  { key: 'approval', label: '批准', id: '88', receiver: '陈批准（approver）' },
]) for (const width of [1440, 390]) test(`report ${stage.key} complete flow at ${width}`, async ({ page }, info) => {
  test.setTimeout(90000)
  const title = `报告${stage.label}`, root = `/reports/${stage.key}`, code = `SP20260900${stage.id}`
  await page.setViewportSize({ width, height: 1000 })
  await page.goto(`/#${root}`)
  const table = page.getByRole('table', { name: `${title}列表`, exact: true })
  const form = page.getByRole('form', { name: `${title}条件`, exact: true })
  const row = table.getByRole('row').filter({ hasText: code })
  await expect(row).toBeVisible()
  await expect(table.getByRole('columnheader', { name: `${stage.label}人`, exact: true })).toBeVisible()
  await expect(form.getByLabel('数据状态', { exact: true })).toHaveValue(`${title}中`)
  await form.getByRole('button', { name: /更多筛选/ }).click()
  await expect(form.getByLabel('状态', { exact: true })).toHaveValue(`未${stage.label}`)
  await expect(form.getByLabel('日期字段').locator('option')).toHaveText([`${stage.label}日期`, ...(stage.key === 'approval' ? ['审核日期'] : []), '试验开始日期', '试验结束日期', '委托日期'])
  await expect(form.getByLabel('日期字段')).toHaveValue(stage.key === 'approval' ? 'reportReviewDate' : 'testEndDate')
  await page.screenshot({ path: info.outputPath(`${stage.key}-list-${width}.png`), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await expect(plans.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true })).toBeVisible()
  await plans.getByRole('button', { name: '关闭', exact: true }).click()
  await row.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText([stage.label, ...(stage.key === 'approval' ? [] : [`撤销${stage.label}`]), '作废', '查看任务处理记录', '查看附件'])
  await page.getByRole('menuitem', { name: stage.label, exact: true }).click()
  await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: '原始记录', exact: true }).click()
  await expect(page.locator('input[type=file]')).toHaveCount(0)
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await page.getByRole('button', { name: stage.label, exact: true }).click()
  const decision = page.getByRole('dialog', { name: title, exact: true })
  await expect(decision.getByRole('button', { name: '通过', exact: true })).toBeDisabled()
  await decision.getByRole('button', { name: '校验', exact: true }).click()
  await decision.getByRole('checkbox', { name: `我已阅读并确认上述${stage.label}结果`, exact: true }).check()
  await page.screenshot({ path: info.outputPath(`${stage.key}-decision-${width}.png`), fullPage: true, animations: 'disabled' })
  await decision.getByRole('button', { name: '通过', exact: true }).click()
  const next = page.getByRole('dialog', { name: '确认下一步', exact: true })
  await expect(next.getByRole('radio', { name: '下一步', exact: true })).toBeChecked()
  await next.getByRole('radio', { name: `转交${stage.label}`, exact: true }).check()
  await expect(next.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await next.getByRole('button', { name: '选择接收人', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择接收人', exact: true })
  await picker.getByLabel('人员范围', { exact: true }).selectOption('all')
  await picker.getByRole('radio', { name: `选择 ${stage.receiver}`, exact: true }).check()
  await picker.getByRole('button', { name: '确定', exact: true }).click()
  await next.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`${root}$`))
  await expect(row).toBeVisible()
  await page.goto(`/#${root}/demo-yp-${stage.id}`)
  await page.getByRole('button', { name: stage.label, exact: true }).click()
  await decision.getByRole('button', { name: '校验', exact: true }).click()
  await decision.getByRole('checkbox').check()
  await decision.getByRole('button', { name: '通过', exact: true }).click()
  await next.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`${root}$`))
  await page.goto(`/#${root}?status=${title}完成&checkStatus=已${stage.label}`)
  await expect(row).toContainText('演示用户')
  await row.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  if (stage.key === 'approval') {
    await expect(page.getByRole('menuitem', { name: '撤销批准', exact: true })).toHaveCount(0)
    await expect(page.getByRole('menuitem', { name: '批准', exact: true })).toBeDisabled()
    return
  }
  await page.getByRole('menuitem', { name: `撤销${stage.label}`, exact: true }).click()
  const undo = page.getByRole('dialog', { name: `撤销${stage.label}`, exact: true })
  await expect(undo).toContainText(`恢复为${title}中`)
  await undo.getByRole('button', { name: '确认', exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.goto(`/#${root}/demo-yp-${stage.id}`)
  await page.getByRole('button', { name: stage.label, exact: true }).click()
  await decision.getByRole('button', { name: '不通过', exact: true }).click()
  const issue = page.getByRole('dialog', { name: '问题处理', exact: true })
  await issue.getByRole('radio', { name: '其他问题', exact: true }).check()
  await expect(issue.getByRole('textbox', { name: '退回原因', exact: true })).toHaveValue('')
  await issue.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`${root}$`))
  await page.goto('/#/commissions/changes')
  await expect(page.getByRole('row').filter({ hasText: code })).toContainText('问题处理中')
})

test('sidebar navigation switches between all three report stages', async ({ page }) => {
  await page.goto('/#/reports/check')
  await page.getByRole('link', { name: '报告管理', exact: true }).click()
  for (const label of ['报告审核', '报告批准', '报告校核']) {
    await page.getByRole('link', { name: label, exact: true }).click()
    await expect(page.getByRole('table', { name: `${label}列表`, exact: true })).toBeVisible()
  }
})
