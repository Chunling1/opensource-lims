import { test, expect } from '@playwright/test'
import { selectGeneralSamplePlan } from './helpers/sample-plan'

test('sample commission information is copied once, editable and saved independently', async ({ page }, testInfo) => {
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  const form = page.getByRole('form', { name: '样品表单' })
  const orderTab = form.getByRole('tab', { name: '委托信息', exact: true })
  const sampleTab = form.getByRole('tab', { name: '样品信息', exact: true })
  const orderPanel = form.getByRole('tabpanel', { name: '委托信息', exact: true })
  await orderTab.click()
  await expect(orderPanel.getByLabel('委托编号', { exact: true })).toHaveValue('WT202609001')
  await expect(orderPanel.getByLabel('项目名称', { exact: true })).toHaveValue('园区地表水例行检测（第 1 批）')
  await expect(orderPanel.getByLabel('委托单位法人', { exact: true })).toHaveCount(0)
  await orderPanel.getByLabel('项目名称', { exact: true }).fill('本样品工程信息')
  await orderPanel.getByRole('button', { name: '清除委托单位', exact: true }).click()
  await orderPanel.getByLabel('委托单位', { exact: true }).fill('本样品的委托单位')
  await orderPanel.getByLabel('委托人', { exact: true }).fill('本样品委托人')
  await orderPanel.getByLabel('委托单位地址', { exact: true }).fill('样品地址 1 号')
  await orderPanel.getByLabel('发票类型', { exact: true }).selectOption('增值税专用发票')
  await orderPanel.getByLabel('账号', { exact: true }).fill('12345')
  await sampleTab.click()
  await expect(form.getByRole('tabpanel', { name: '样品信息', exact: true }).getByLabel('委托单位', { exact: true })).toHaveCount(0)
  await form.getByLabel('工程/产品名称', { exact: false }).fill('独立委托副本样品')
  await form.getByLabel('检测类别', { exact: false }).selectOption('委托')
  await selectGeneralSamplePlan(page)
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page).toHaveURL(/samples\/[^/]+\/edit/)
  const savedUrl = page.url()
  await page.goto('/#/commissions/registration/commissions/demo-wt-1/edit')
  const parent = page.getByRole('form', { name: '委托表单' })
  await expect(parent.getByLabel('项目名称', { exact: true })).toHaveValue('园区地表水例行检测（第 1 批）')
  await expect(parent.getByLabel('委托单位', { exact: true })).toHaveValue('华清环境检测中心')
  await parent.getByLabel('项目名称', { exact: true }).fill('原委托后来修改的项目')
  await parent.getByRole('button', { name: '清除委托单位', exact: true }).click()
  await parent.getByLabel('委托单位', { exact: true }).fill('原委托后来修改的单位')
  await parent.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('委托已保存。', { exact: true })).toBeVisible()
  await page.goto(savedUrl)
  await orderTab.click()
  await expect(orderPanel.getByLabel('项目名称', { exact: true })).toHaveValue('本样品工程信息')
  await expect(orderPanel.getByLabel('委托单位', { exact: true })).toHaveValue('本样品的委托单位')
  await expect(orderPanel.getByLabel('委托人', { exact: true })).toHaveValue('本样品委托人')
  await expect(orderPanel.getByLabel('账号', { exact: true })).toHaveValue('12345')
  await orderPanel.getByLabel('委托人电话', { exact: true }).fill('10086')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('样品已保存。', { exact: true })).toBeVisible()
  await page.reload(); await orderTab.click()
  await expect(orderPanel.getByLabel('委托人电话', { exact: true })).toHaveValue('10086')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: testInfo.outputPath('sample-commission-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('sample-commission-mobile.png'), fullPage: true })
})
