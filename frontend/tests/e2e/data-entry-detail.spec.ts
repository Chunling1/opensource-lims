test('responsive entry tabs, themes, keyboard, and uncertain save preserves input', async ({ page }, info) => {
  test.setTimeout(60000)
  await page.goto('/#/testing/data-entry/demo-yp-76')
  await expect(page.locator('#trial-conclusion')).toBeVisible()
  await page.getByRole('button', { name: '添加日期', exact: true }).click()
  await pickDateRange(page, page.locator('#trial-date-1'), '2026-09-08', '2026-09-08')
  await expect(page.locator('#trial-date-1')).toHaveValue('2026-09-08 至 2026-09-08')
  await page.getByRole('button', { name: '添加日期', exact: true }).click()
  await pickDateRange(page, page.locator('#trial-date-2'), '2026-09-15', '2026-09-17')
  for (const width of [1440, 1024, 390]) {
    for (const theme of ['light', 'dark']) {
      await page.setViewportSize({ width: 1440, height: 1000 })
      if (await page.locator('html').getAttribute('data-bs-theme') !== theme) await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
      await expect(page.locator('html')).toHaveAttribute('data-bs-theme', theme)
      await page.setViewportSize({ width, height: 1000 })
      for (const name of ['委托信息', '样品信息', '试验信息', '原始记录']) {
        await page.getByRole('tab', { name, exact: true }).click()
        await expect(page.getByRole('button', { name: '保存', exact: true })).toBeVisible()
        await expect(page.getByRole('button', { name: '返回', exact: true })).toBeVisible()
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
        await page.screenshot({ path: info.outputPath(`entry-${name}-${width}-${theme}.png`), fullPage: true })
      }
    }
  }
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('试验信息已保存。', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('tab', { name: '试验信息', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('#trial-date-2')).toHaveValue('2026-09-15 至 2026-09-17')
  await page.locator('#trial-conclusion').fill('网络异常时保留内容')
  await page.route('**/data-entry/save', route => route.abort())
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('button', { name: '刷新核对', exact: true })).toBeVisible()
  await expect(page.locator('#trial-conclusion')).toHaveValue('网络异常时保留内容')
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await page.unroute('**/data-entry/save')
  await page.getByRole('button', { name: '刷新核对', exact: true }).click()
  await expect(page.locator('#trial-conclusion')).toHaveValue('网络异常时保留内容')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('试验信息已保存。', { exact: true })).toBeVisible()
})


