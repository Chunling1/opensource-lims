import { test, expect } from '@playwright/test'
import { clientYearRange } from '../../src/services/common/date'
import { pickDateRange } from './helpers/dateRange'

test('commission number is part of the shared selector and range layout fits all three workspaces', async ({ page }, testInfo) => {
  const range = clientYearRange()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/#/commissions/registration?cFrom=&cTo=')
  const form = page.getByRole('form', { name: '委托查询', exact: true })
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(5)
  await expect(form.getByLabel('委托编号', { exact: true })).toHaveCount(0)
  await expect(form.getByLabel('查询内容', { exact: true }).locator('option')).toHaveText(['全部', '委托编号', '样品/工程名称', '委托单位', '委托人', '委托经办人'])
  const requests: Record<string, unknown>[] = []
  page.on('request', r => { if (r.url().endsWith('/commissions/query')) requests.push(r.postDataJSON()) })
  await form.getByLabel('查询内容', { exact: true }).selectOption('code')
  await form.getByLabel('包含', { exact: true }).fill('wt202609001')
  expect(requests).toHaveLength(0)
  await form.getByLabel('包含', { exact: true }).press('Enter')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText('WT202609001')
  expect(requests.at(-1)).toMatchObject({ searchField: 'code', contains: 'wt202609001' })
  expect(requests.at(-1)).not.toHaveProperty('commissionCode')
  await expect(page).toHaveURL(/cSearchField=code/)
  await page.reload()
  await expect(form.getByLabel('查询内容', { exact: true })).toHaveValue('code')
  await expect(form.getByLabel('包含', { exact: true })).toHaveValue('wt202609001')
  await form.getByLabel('查询内容', { exact: true }).selectOption('all')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('WT202609001')
  await expect(form.getByRole('button', { name: '更多筛选', exact: true })).toHaveCount(0)
  const dates = form.getByLabel('委托日期', { exact: true })
  const count = requests.length
  await pickDateRange(page, dates, range.from, range.to)
  expect(requests).toHaveLength(count)
  await expect(dates).toHaveValue(`${range.from} 至 ${range.to}`)
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await table.getByRole('link', { name: 'WT202609001', exact: true }).click()
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  await expect(dates).toHaveValue(`${range.from} 至 ${range.to}`)
  for (const [path, width, theme] of [['registration', 1440, 'light'], ['query', 1280, 'light'], ['review', 390, 'dark'], ['query', 320, 'light']] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(`/#/commissions/${path}`)
    await page.evaluate(t => document.documentElement.setAttribute('data-bs-theme', t), theme)
    await expect(form.getByLabel('查询内容').locator('option[value="code"]')).toHaveText('委托编号')
    await expect(dates).toBeVisible()
    await expect(form.getByLabel('委托状态')).toBeVisible()
    await expect(form.getByRole('button', { name: '更多筛选', exact: true })).toHaveCount(0)
    if (width >= 1280) {
      const controls = [form.getByLabel('查询内容'), form.getByLabel('包含'), form.getByLabel('委托状态'), dates, form.getByRole('button', { name: '查询', exact: true })]
      const boxes = await Promise.all(controls.map(control => control.boundingBox()))
      expect(Math.max(...boxes.map(box => box!.y)) - Math.min(...boxes.map(box => box!.y))).toBeLessThan(2)
      await form.screenshot({ path: testInfo.outputPath(`commission-filter-one-row-${width}.png`) })
    }
    await dates.click()
    const calendar = page.locator('.flatpickr-calendar.open')
    await expect(calendar).toBeVisible()
    const box = await calendar.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(width + 1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.screenshot({ animations: 'disabled', path: testInfo.outputPath(`commission-range-${path}-${width}.png`) })
    await page.keyboard.press('Escape')
  }
})

test('legacy number links and combined conditions stay visible, clearable and canonicalize on submission', async ({ page }) => {
  const range = clientYearRange()
  const form = page.getByRole('form', { name: '委托查询', exact: true })
  const table = page.getByRole('table', { name: '委托列表', exact: true })
  await page.goto('/#/commissions/registration?cFrom=&cTo=&cKeyword=wt202609001&cSearchField=contract&cContains=obsolete&cAdvanced=1')
  await expect(table).toContainText('WT202609001')
  await expect(form.getByLabel('查询内容')).toHaveValue('code')
  await expect(form.getByLabel('包含')).toHaveValue('wt202609001')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page).toHaveURL(/cSearchField=code/)
  expect(page.url()).not.toMatch(/cKeyword=|cCode=/)
  await page.goto('/#/commissions/registration?cFrom=2000-01-01&cTo=&cCode=WT20260900&cSearchField=contact&cContains=张经理&cAdvanced=1')
  await expect(form.getByLabel('委托日期', { exact: true })).toHaveValue(`${range.from} 至 ${range.to}`)
  await expect(form.getByText('委托编号包含：WT20260900', { exact: true })).toBeVisible()
  await expect(form.getByLabel('查询内容')).toHaveValue('contact')
  await expect(form.getByLabel('包含')).toHaveValue('张经理')
  await form.getByRole('button', { name: '移除委托编号条件', exact: true }).click()
  await form.getByRole('button', { name: '查询', exact: true }).click()
  expect(page.url()).not.toContain('cCode=')
  await expect(form.getByText(/委托编号包含：/)).toHaveCount(0)
  await page.reload()
  await expect(form.getByLabel('委托日期', { exact: true })).toHaveValue(`${range.from} 至 ${range.to}`)
})
