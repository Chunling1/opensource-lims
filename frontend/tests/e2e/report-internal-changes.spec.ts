import { toolbarButton } from './helpers/toolbar'
import { expect, test } from '@playwright/test'
import { checkOnlyWithControl } from './helpers/table-selection'

for (const width of [1440, 390]) test(`internal applications use report query layout and CRUD at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 950 })
  await page.goto('/#/reports/changes/internal')
  const query = page.getByRole('form', { name: '内部申请查询' })
  await expect(query.getByLabel('申请人', { exact: true })).toBeHidden()
  await query.getByRole('button', { name: /更多筛选/ }).click()
  for (const field of ['申请时间', '申请单号', '申请部门', '申请人', '样品编号', '审批状态']) await expect(query.getByLabel(field, { exact: true })).toBeVisible()
  await expect(query.getByLabel('排序')).toHaveCount(0)
  await expect(query.getByLabel('审批状态').locator('option')).toHaveText(['全部', '申请中', '待审批', '退回', '不通过', '审批通过'])
  if (width === 1440) {
    const tops = await query.locator('label').evaluateAll(labels => [...new Set(labels.map(l => Math.round(l.getBoundingClientRect().top)))])
    expect(tops).toHaveLength(2)
  }
  const table = page.getByRole('table', { name: '内部申请列表', exact: true })
  await expect(table.getByRole('columnheader').filter({ hasText: '更改责任方' })).toHaveCount(0)
  await (await toolbarButton(page, '内部申请', '显示')).click()
  const columnMenu = page.getByRole('dialog', { name: '内部申请显示列', exact: true })
  for (const label of ['申请部门', '更改责任方', '更改前内容', '更改后内容', '是否需要收费', '收费金额', '撤回原因']) await expect(columnMenu.getByRole('checkbox', { name: label, exact: true })).not.toBeChecked()
  await columnMenu.getByRole('checkbox', { name: '撤回原因', exact: true }).check()
  await columnMenu.getByRole('button', { name: '完成', exact: true }).click()
  await page.getByRole('button', { name: '新增', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '新增申请', exact: true })
  await expect(dialog.getByLabel('样品编号', { exact: true })).toHaveAttribute('readonly', '')
  await expect(dialog.getByLabel('更改责任方')).toHaveCount(0)
  await expect(dialog.getByLabel('更改前内容')).toHaveCount(0)
  await expect(dialog.getByLabel('收费金额')).toHaveCount(0)
  await expect(dialog.getByLabel('更改原因')).toHaveJSProperty('tagName', 'INPUT')
  await expect(dialog.getByLabel('更改原因')).toHaveAttribute('type', 'text')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.locator('#change-report-error')).toHaveText('请选择报告。')
  await expect(dialog).not.toContainText('诊断编号')
  await expect(dialog.getByRole('button', { name: '选择报告', exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: '选择报告', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择报告', exact: true })
  await picker.getByRole('checkbox', { name: '选择 SP2026090092', exact: true }).check()
  await picker.getByRole('button', { name: '移入', exact: true }).click()
  await picker.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.getByLabel('原报告编号')).toHaveValue('BG2026090092')
  await expect(dialog.getByLabel('样品编号', { exact: true })).toHaveValue('SP2026090092')
  await expect(dialog.locator('#change-report-error')).toHaveCount(0)
  await dialog.getByRole('button', { name: '提交', exact: true }).click()
  await expect(dialog.locator('#change-reason-error')).toHaveText('请填写更改原因。')
  await expect(dialog.getByLabel('更改原因')).toBeFocused()
  await expect(dialog).not.toContainText('诊断编号')
  await expect(dialog.getByLabel('申请人', { exact: true })).toHaveValue('演示用户')
  await expect(dialog.getByLabel('申请日期')).toHaveAttribute('readonly', '')
  await expect(dialog.getByRole('group', { name: '更改类型' }).getByRole('radio')).toHaveCount(4)
  await dialog.getByRole('radio', { name: '委托信息更改和检测数据更改', exact: true }).check()
  await dialog.getByLabel('更改原因').fill('内部核查修正')
  await expect(dialog.locator('#change-reason-error')).toHaveCount(0)
  await expect(dialog).toHaveCSS('opacity', '1')
  await page.screenshot({ path: info.outputPath(`internal-new-${width}.png`), fullPage: true })
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  const row = table.getByRole('row').filter({ hasText: 'SP2026090092' })
  await expect(row).toContainText('申请中')
  const code = (await row.locator('td').nth(1).innerText()).trim()
  const menu = async (name: string) => {
    await row.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
    await expect(page.getByRole('menuitem')).toHaveText(['新增', '修改', '查看', '撤销', '删除'])
    await page.getByRole('menuitem', { name, exact: true }).click()
  }
  await menu('修改')
  dialog = page.getByRole('dialog', { name: '修改申请', exact: true })
  await expect(dialog.getByLabel('更改原因')).toHaveValue('内部核查修正')
  await expect(dialog.getByRole('radio', { name: '委托信息更改和检测数据更改', exact: true })).toBeChecked()
  await dialog.getByLabel('更改原因').fill('补充内容')
  await dialog.getByRole('radio', { name: '补充报告', exact: true }).check()
  await dialog.getByRole('button', { name: '提交', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(row).toContainText('待审批')
  await menu('查看')
  dialog = page.getByRole('dialog', { name: '查看申请', exact: true })
  await expect(dialog.getByLabel('更改原因')).toBeDisabled()
  await expect(dialog.getByRole('radio', { name: '补充报告', exact: true })).toBeChecked()
  await expect(dialog.getByRole('button', { name: '提交', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '返回', exact: true }).click()
  await menu('撤销')
  dialog = page.getByRole('dialog', { name: '撤销申请', exact: true })
  await dialog.getByLabel('撤回原因').fill('调整申请')
  await dialog.getByRole('button', { name: /确认撤销|确认删除/, exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(row).toContainText('申请中')
  await expect(row).toContainText('调整申请')
  await query.getByLabel('审批状态').selectOption('申请中')
  await query.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toBeVisible()
  await page.reload()
  await expect(query.getByLabel('审批状态')).toHaveValue('申请中')
  await expect(row).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath(`internal-list-${width}.png`), fullPage: true })
  await menu('删除')
  dialog = page.getByRole('dialog', { name: '删除申请', exact: true })
  await dialog.getByRole('button', { name: /确认撤销|确认删除/, exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(row).toHaveCount(0)
})

for (const width of [1440, 390]) test(`report picker transfers across pages and preserves confirmed selection at ${width}`, async ({ page }, info) => {
  const rows = Array.from({ length: 25 }, (_, i) => ({ id: `picker-${i}`, version: 1, releaseId: `release-${i}`, code: `SP${String(i).padStart(3, '0')}`, reportCode: `BG${String(i).padStart(3, '0')}`, name: `样品 ${i}`, commissionCode: i < 24 ? 'WT001' : 'WT002', commissionId: i < 24 ? 'commission-1' : 'commission-2', contractCode: 'HT001' }))
  const queries: Record<string, string>[] = []
  await page.route('**/reports/internal-changes/candidates', route => {
    const q = route.request().postDataJSON(); queries.push(q)
    return route.fulfill({ json: rows.filter(r => r.commissionCode.includes(q.commissionCode) && r.reportCode.includes(q.reportCode)) })
  })
  await page.setViewportSize({ width, height: 950 })
  await page.goto('/#/reports/changes/internal')
  await page.getByRole('button', { name: '新增', exact: true }).click()
  const application = page.getByRole('dialog', { name: '新增申请', exact: true })
  await application.getByLabel('更改原因').fill('保留已填原因')
  await application.getByRole('button', { name: '选择报告', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择报告', exact: true })
  const left = picker.getByRole('table', { name: '未选报告列表', exact: true })
  const right = picker.getByRole('table', { name: '已选报告列表', exact: true })
  await expect(left.getByRole('columnheader')).toHaveText(['', '合同编号', '报告编号', '样品编号', '委托编号'])
  await expect(left.locator('tbody tr')).toHaveCount(10)
  await checkOnlyWithControl(left.locator('tbody tr').first(), left.getByRole('checkbox', { name: '选择 SP000', exact: true }))
  await picker.getByRole('button', { name: '移入', exact: true }).click()
  await expect(right).toContainText('SP000')
  await checkOnlyWithControl(right.locator('tbody tr').first(), right.getByRole('checkbox', { name: '选择 SP000', exact: true }))
  await right.getByRole('checkbox', { name: '选择 SP000', exact: true }).uncheck()
  await expect(left).not.toContainText('SP000')
  await picker.getByRole('navigation', { name: '未选报告分页', exact: true }).getByRole('button', { name: '下一页' }).click()
  await left.getByRole('checkbox', { name: '选择 SP011', exact: true }).check()
  await picker.getByRole('button', { name: '移入', exact: true }).click()
  await expect(right.locator('tbody tr')).toHaveCount(2)
  await picker.getByRole('navigation', { name: '未选报告分页', exact: true }).getByRole('button', { name: '下一页' }).click()
  await expect(left.getByRole('checkbox', { name: '选择 SP024', exact: true })).toBeDisabled()
  await picker.getByLabel('委托编号', { exact: true }).fill('WT001')
  await picker.getByLabel('报告编号', { exact: true }).fill('BG02')
  await picker.getByRole('button', { name: '查询', exact: true }).click()
  await expect(left.locator('tbody tr')).toHaveCount(4)
  expect(queries.at(-1)).toEqual({ commissionCode: 'WT001', reportCode: 'BG02' })
  await expect(right.locator('tbody tr')).toHaveCount(2)
  await left.getByRole('checkbox', { name: '全选当前页未选报告', exact: true }).check()
  await picker.getByRole('button', { name: '移入', exact: true }).click()
  await expect(right.locator('tbody tr')).toHaveCount(6)
  await right.getByRole('checkbox', { name: '选择 SP020', exact: true }).check()
  await picker.getByRole('button', { name: '移出', exact: true }).click()
  await expect(left).toContainText('SP020')
  await expect(right.locator('tbody tr')).toHaveCount(5)
  await picker.getByLabel('已选报告每页条数').selectOption('20')
  await expect(picker).toHaveCSS('opacity', '1')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath(`report-picker-${width}.png`), fullPage: true })
  await picker.getByRole('button', { name: '确认', exact: true }).click()
  await expect(application.getByLabel('原报告编号')).toHaveValue('BG000、BG011、BG021、BG022、BG023')
  await expect(application.getByLabel('更改原因')).toHaveValue('保留已填原因')
  await application.getByRole('button', { name: '选择报告', exact: true }).click()
  await right.getByRole('checkbox', { name: '全选当前页已选报告', exact: true }).check()
  await picker.getByRole('button', { name: '移出', exact: true }).click()
  await expect(right).toContainText('暂无已选报告')
  await picker.getByRole('button', { name: '返回', exact: true }).click()
  await expect(application.getByLabel('原报告编号')).toHaveValue('BG000、BG011、BG021、BG022、BG023')
  await application.getByRole('button', { name: '取消', exact: true }).click()
  await expect(application).toBeHidden()
})
