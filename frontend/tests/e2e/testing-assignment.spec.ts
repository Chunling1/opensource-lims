import { test, expect } from '@playwright/test'

test('assignment filters, screenshot columns and row actions use the shared layout', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const requests: Record<string, unknown>[] = []
  page.on('request', request => { if (request.url().endsWith('/samples/assignment/query')) requests.push(request.postDataJSON()) })
  await page.goto('/#/testing/assignment')
  const form = page.getByRole('form', { name: '检测任务分配条件', exact: true })
  const table = page.getByRole('table', { name: '检测任务分配列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(9)
  const more = form.getByRole('button', { name: /更多筛选/ })
  await expect(more).toHaveAttribute('aria-expanded', 'false')
  await expect(form.getByLabel('结论状态')).toBeHidden()
  await expect(more).toContainText('（1）')
  await expect(form.getByLabel('查询内容').locator('option')).toHaveText(['样品编号', '委托编号', '委托单位', '项目名称', '工程地址', '委托人', '数据录入人', '报告标题'])
  await expect(form.getByLabel('数据状态').locator('option')).toHaveText(['全部', '任务分配中', '任务分配完成'])
  await expect(form.getByLabel('样品类型').locator('option')).toHaveText(['全部', '原始样品', '英文报告样品', '分项/阶段性报告样品', '补充报告'])
  await expect(form.getByLabel('结论状态').locator('option')).toHaveText(['全部', '不判定', '复检', '合格', '不合格'])
  await expect(form.getByLabel('日期字段').locator('option')).toHaveText(['委托日期', '要求试验日期'])
  await page.screenshot({ path: testInfo.outputPath('assignment-desktop.png') })
  await page.getByRole('button', { name: '显示', exact: true }).click()
  const columns = page.getByRole('dialog', { name: '检测任务分配显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(20)
  const attachment = columns.getByRole('checkbox', { name: '附件', exact: true })
  await expect(attachment).not.toBeChecked()
  await expect(table.getByRole('columnheader', { name: '附件', exact: true })).toHaveCount(0)
  await attachment.check()
  await expect(table.locator('thead th').nth(-2)).toHaveText('附件')
  await expect(table.locator('tbody tr').first().locator('td').nth(-2)).toHaveText('')
  await attachment.uncheck()
  for (const name of ['分配人', '数据录入人', '检测人1', '检测人2', '工程地址', '约定检测日期']) await expect(columns.getByRole('checkbox', { name, exact: true })).toBeVisible()
  await columns.getByRole('checkbox', { name: '委托编号', exact: true }).check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await expect(table.getByRole('columnheader', { name: '委托编号', exact: true })).toBeVisible()
  await table.getByRole('button', { name: 'SP2026090051 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['分配', '自动分配', '撤销分配', '打印任务单', '任务处理记录', '附件管理'])
  await page.keyboard.press('Escape')
  await form.getByLabel('数据状态').selectOption('')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await table.getByRole('checkbox').nth(1).check()
  await form.getByLabel('查询内容').selectOption('commissionCode')
  await form.getByLabel('包含', { exact: true }).fill('WT202609009')
  await more.focus()
  await more.press('Enter')
  await expect(form.getByLabel('结论状态')).toBeVisible()
  await form.getByLabel('结论状态').selectOption('不判定')
  await form.getByLabel('日期字段').selectOption('requestedTestDate')
  await more.click()
  await expect(form.getByLabel('结论状态')).toBeHidden()
  await expect(more).toContainText('（2）')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('SP2026090051')
  await expect(table.locator('tbody input:checked')).toHaveCount(0)
  expect(requests.at(-1)).toMatchObject({ searchField: 'commissionCode', contains: 'WT202609009', dateField: 'requestedTestDate', conclusion: '不判定', status: '', page: 1 })
  await page.reload()
  await expect(form.getByLabel('包含', { exact: true })).toHaveValue('WT202609009')
  await expect(table).toContainText('SP2026090051')
  await more.click()
  await expect(form.getByLabel('结论状态')).toHaveValue('不判定')
  await expect(form.getByLabel('日期字段')).toHaveValue('requestedTestDate')
  await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('assignment-dark.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(form.getByRole('button', { name: '查询', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('assignment-mobile-dark.png') })
})
