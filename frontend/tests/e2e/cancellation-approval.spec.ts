import { expect, test } from '@playwright/test'
import { cancellationColumns } from '../../src/types/commissions/cancellationApproval'
const root = '/commissions/cancellation-approval'
const api = '/api/registration', headers = { 'X-Demo-Actor': 'admin' }

test('cancellation queue shares list controls, filters results, and shows completed decisions read-only', async ({ page }, testInfo) => {
  await page.goto(`/#${root}`)
  const table = page.getByRole('table', { name: '作废审批列表', exact: true })
  await expect(page.getByRole('table')).toHaveCount(1)
  await expect(table.locator('tbody tr')).toHaveCount(3)
  await expect(table.locator('thead th')).toHaveText(['', '审批结果', '委托编号', '样品编号', '报告编号', '样品/工程名称', '申请人', '申请原因', '申请日期', ''])
  await expect(table.getByRole('row').filter({ hasText: 'SP2026090052' })).toContainText('地表水样 52')
  const form = page.getByRole('form', { name: '作废审批查询' })
  await expect(form.getByLabel('数据状态')).toHaveValue('申请中')
  await expect(form.getByLabel('数据状态').locator('option')).toHaveText(['全部', '申请中', '申请通过', '申请不通过'])
  await expect(page.getByRole('combobox', { name: '作废审批每页条数' }).locator('option')).toHaveText(['10', '20', '50'])
  await page.getByRole('button', { name: '显示', exact: true }).click()
  for (const column of cancellationColumns) {
    const check = page.getByRole('checkbox', { name: column.label, exact: true }).filter({ visible: true })
    if (!await check.isChecked()) await check.check()
  }
  await expect(table.locator('thead th')).toHaveText(['', ...cancellationColumns.map(c => c.label), ''])
  const sample = await (await page.request.get(`${api}/samples/demo-yp-52`, { headers })).json()
  await expect(table.getByRole('row').filter({ hasText: sample.code }).locator('td').nth(5)).toHaveText(sample.details?.testPlan || '—')
  await page.getByRole('button', { name: '恢复默认', exact: true }).click()
  await page.getByRole('dialog', { name: '作废审批显示列', exact: true }).getByRole('button', { name: '完成', exact: true }).click()
  await expect(table.getByRole('columnheader', { name: '检测方案', exact: true })).toHaveCount(0)
  await form.getByLabel('数据状态').selectOption('申请不通过')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await table.getByRole('button', { name: 'SP2026090057 更多操作' }).click()
  await page.getByRole('menuitem', { name: '查看审批结果' }).click()
  const result = page.getByRole('dialog', { name: '审批结果', exact: true })
  await expect(result).toContainText('示例审批：申请依据不足，请与客户确认。')
  await expect(result.getByRole('button', { name: '通过', exact: true })).toHaveCount(0)
  await result.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(result).toBeHidden()
  await form.getByLabel('数据状态').selectOption('')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(5)
  for (const width of [1440, 390]) {
    if (width === 390) await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
    await page.setViewportSize({ width, height: 950 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect.poll(() => table.locator('thead button').first().evaluate(el => getComputedStyle(el).color)).toBe(width === 390 ? 'rgb(255, 255, 255)' : 'rgb(33, 37, 41)')
    await page.screenshot({ path: testInfo.outputPath(`cancellation-${width}.png`), fullPage: true })
  }
})

test('approval and rejection are persisted by the backend and approval failures keep the draft', async ({ page }, testInfo) => {
  await page.goto(`/#${root}`)
  const table = page.getByRole('table', { name: '作废审批列表', exact: true })
  await expect(table).toContainText('SP2026090052')
  const original = await (await page.request.get(`${api}/samples/demo-yp-52`, { headers })).json()
  const parent = await (await page.request.get(`${api}/commissions/${original.commissionId}`, { headers })).json()
  await table.getByRole('button', { name: 'SP2026090052 更多操作' }).click()
  await expect(page.getByRole('menu').getByRole('menuitem')).toHaveText(['审批'])
  await page.getByRole('menuitem', { name: '审批', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '作废审批', exact: true })
  await expect(dialog).toContainText(original.voidApplication.reason)
  await dialog.getByRole('button', { name: '不通过', exact: true }).click()
  await expect(dialog.getByText('请填写审批不通过原因。', { exact: true })).toBeVisible()
  await dialog.getByLabel('审批不通过原因', { exact: true }).fill('需要补充客户确认资料')
  await page.route('**/samples/demo-yp-52/cancellation-approval', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '审批暂不可用' } } }), { times: 1 })
  await dialog.getByRole('button', { name: '不通过', exact: true }).click()
  await expect(dialog.getByText('审批暂不可用', { exact: true })).toBeVisible()
  await expect(dialog.getByLabel('审批不通过原因', { exact: true })).toHaveValue('需要补充客户确认资料')
  await page.screenshot({ path: testInfo.outputPath('approval-dialog.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('approval-dialog-390.png'), fullPage: true })
  await page.setViewportSize({ width: 1440, height: 950 })
  await dialog.getByRole('button', { name: '不通过', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(table).not.toContainText(original.code)
  const rejected = await (await page.request.get(`${api}/samples/demo-yp-52`, { headers })).json()
  expect(rejected.status).toBe(original.voidApplication.previousStatus)
  expect(rejected.dataStatus).toBe(original.voidApplication.previousDataStatus)
  expect(rejected.voidApplication.rejectionReason).toBe('需要补充客户确认资料')
  expect(await (await page.request.get(`${api}/commissions/${original.commissionId}`, { headers })).json()).toEqual(parent)
  await table.getByRole('button', { name: 'SP2026090060 更多操作' }).click()
  await page.getByRole('menuitem', { name: '审批', exact: true }).click()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(table).toContainText('SP2026090060')
  await table.getByRole('button', { name: 'SP2026090060 更多操作' }).click()
  await page.getByRole('menuitem', { name: '审批', exact: true }).click()
  await dialog.getByRole('button', { name: '通过', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(table).not.toContainText('SP2026090060')
  const approved = await (await page.request.get(`${api}/samples/demo-yp-60`, { headers })).json()
  expect(approved.status).toBe('voided'); expect(approved.voidApplication.decision).toBe('approved')
})

test('query retry and identity changes do not expose old approval rows or an open draft', async ({ page }) => {
  await page.route('**/samples/cancellation-approvals/query', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '查询暂不可用' } } }), { times: 1 })
  await page.goto(`/#${root}`)
  await expect(page.getByText('查询暂不可用', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '重试', exact: true }).click()
  const table = page.getByRole('table', { name: '作废审批列表', exact: true })
  await expect(table).toContainText('SP2026090052')
  await table.getByRole('button', { name: 'SP2026090052 更多操作' }).click()
  await page.getByRole('menuitem', { name: '审批', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '作废审批', exact: true })
  await dialog.getByLabel('审批不通过原因', { exact: true }).fill('原身份草稿')
  await page.evaluate(async () => { const path = '/src/stores/session.ts'; await (await import(path)).switchIdentity('business') })
  await expect(dialog).toBeHidden()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(table).not.toContainText('SP2026090042')
  await table.getByRole('button', { name: 'SP2026090052 更多操作' }).click()
  await expect(page.getByRole('menuitem', { name: '审批', exact: true })).toBeDisabled()
})
