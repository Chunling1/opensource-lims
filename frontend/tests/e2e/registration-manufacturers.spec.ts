import { expect, test } from '@playwright/test'
import { checkOnlyWithControl } from './helpers/table-selection'

test('manufacturer picker filters, retains selections across pages and commits only on confirmation', async ({ page }, testInfo) => {
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  const field = page.getByLabel('生产单位', { exact: true })
  const open = page.getByRole('button', { name: '选择生产单位', exact: true })
  const dialog = page.getByRole('dialog', { name: '选择生产厂家', exact: true })
  const first = '示范空调设备有限公司（001）', second = '示范通风设备有限公司（011）'
  await open.click()
  await expect(dialog.getByRole('columnheader', { name: '厂家（产地）代号', exact: true })).toBeVisible()
  await checkOnlyWithControl(dialog.getByRole('table').locator('tbody tr').first(), dialog.getByRole('checkbox', { name: `选择 ${first}`, exact: true }))
  await dialog.getByRole('table').locator('tbody tr').first().locator('td').nth(1).click({ position: { x: 2, y: 2 } })
  await expect(dialog.getByRole('checkbox', { name: `选择 ${first}`, exact: true })).toBeChecked()
  await dialog.getByRole('checkbox', { name: `选择 ${first}`, exact: true }).uncheck()
  await expect(dialog.getByRole('checkbox', { name: `选择 ${first}`, exact: true })).not.toBeChecked()
  await dialog.getByRole('checkbox', { name: `选择 ${first}`, exact: true }).check()
  await dialog.getByRole('button', { name: '下一页', exact: true }).click()
  await dialog.getByRole('checkbox', { name: `选择 ${second}`, exact: true }).check()
  await dialog.getByLabel('厂家代号', { exact: true }).fill('CJ001')
  await dialog.getByLabel('厂家名称', { exact: true }).fill('空调设备')
  await dialog.getByLabel('厂家类型', { exact: true }).selectOption('空调')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: `选择 ${first}`, exact: true })).toBeChecked()
  await expect(dialog.getByRole('table').locator('tbody tr')).toHaveCount(1)
  await expect(dialog.getByText('已选 2 家', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(field).toHaveValue(`${first}；${second}`)
  await open.click()
  await expect(dialog.getByRole('table').locator('tbody tr')).toHaveCount(10)
  await expect(dialog.getByRole('checkbox', { name: `选择 ${first}`, exact: true })).toBeChecked()
  await dialog.getByRole('checkbox', { name: '全选本页', exact: true }).check()
  await expect(dialog.getByText('已选 11 家', { exact: true })).toBeVisible()
  await dialog.getByRole('checkbox', { name: '全选本页', exact: true }).uncheck()
  await expect(dialog.getByText('已选 1 家', { exact: true })).toBeVisible()
  for (const [width, theme] of [[1440, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(value => document.documentElement.setAttribute('data-bs-theme', value), theme)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeInViewport()
    await dialog.screenshot({ path: testInfo.outputPath(`manufacturer-${width}-${theme}.png`) })
  }
  await dialog.getByRole('button', { name: '返回', exact: true }).click()
  await expect(field).toHaveValue(`${first}；${second}`)
  await field.fill('自行编辑的生产单位')
  await expect(field).toHaveValue('自行编辑的生产单位')
})

test('manufacturer query failures can be retried without losing pending selections', async ({ page }) => {
  await page.goto('/#/commissions/registration/samples/new?commissionId=demo-wt-1')
  const dialog = page.getByRole('dialog', { name: '选择生产厂家', exact: true })
  await page.getByRole('button', { name: '选择生产单位', exact: true }).click()
  await dialog.getByRole('checkbox', { name: '选择 示范空调设备有限公司（001）', exact: true }).check()
  await page.route('**/api/registration/manufacturers/query', route => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: '厂家列表暂不可用' } } }))
  await dialog.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(dialog.getByText('厂家列表暂不可用', { exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await page.unroute('**/api/registration/manufacturers/query')
  await dialog.getByRole('button', { name: '重试', exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: '选择 示范通风设备有限公司（011）', exact: true })).toBeVisible()
  await expect(dialog.getByText('已选 1 家', { exact: true })).toBeVisible()
  await dialog.getByLabel('厂家名称', { exact: true }).fill('不存在的厂家')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByText('没有符合条件的厂家')).toBeVisible()
  await dialog.getByLabel('厂家名称', { exact: true }).fill('')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: '选择 示范空调设备有限公司（001）', exact: true })).toBeChecked()
})
