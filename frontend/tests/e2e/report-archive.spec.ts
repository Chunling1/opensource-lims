import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function action(page: Page, code: string, name: string) {
  await page.getByRole('button', { name: `${code} 更多操作`, exact: true }).click()
  await page.getByRole('menuitem', { name, exact: true }).click()
}

test('archive shares the print list, archives and reverses with readonly actor and preserves filters', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/#/reports/archive')
  const table = page.getByRole('table', { name: '报告归档列表', exact: true })
  await expect(table).toContainText('SP2026090095')
  await expect(table).toContainText('SP2026090096')
  await expect(table).not.toContainText('SP2026090093')
  const filters = page.getByRole('form', { name: '报告归档条件', exact: true })
  await expect(filters.getByLabel('查询内容')).toHaveValue('code')
  await expect(filters.getByLabel('归档状态').locator('option')).toHaveText(['全部', '报告归档中', '报告已归档'])
  await page.getByRole('button', { name: '显示', exact: true }).click()
  const columns = page.getByRole('dialog', { name: '报告归档显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(19)
  for (const name of ['样品/工程名称', '检测方案', '项目名称', '归档人', '归档日期']) await expect(columns.getByLabel(name, { exact: true })).toBeVisible()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await filters.getByRole('button', { name: /更多筛选/ }).click()
  await expect(filters.getByLabel('日期字段')).toHaveValue('approvalDate')
  await expect(filters.getByLabel('日期字段').locator('option')).toHaveText(['批准日期', '归档日期', '委托日期'])
  await page.getByRole('button', { name: '检测方案', exact: true }).click()
  const plans = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  await expect(plans.getByRole('checkbox', { name: '选择分组 综合检测部', exact: true })).toBeVisible()
  await plans.getByRole('button', { name: '关闭', exact: true }).click()
  await action(page, 'SP2026090095', '归档')
  const dialog = page.getByRole('dialog', { name: '报告归档', exact: true })
  await expect(dialog.getByLabel('归档人')).toHaveValue('演示用户')
  await expect(dialog.getByLabel('归档人')).toHaveAttribute('readonly', '')
  await dialog.getByLabel('归档日期').fill('2026-10-01')
  await expect(dialog).toHaveCSS('opacity', '1')
  await page.screenshot({ path: info.outputPath('archive-dialog.png'), fullPage: true })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(table).not.toContainText('SP2026090095')
  await filters.getByLabel('归档状态').selectOption('已归档')
  await filters.getByRole('button', { name: '查询', exact: true }).click()
  const row = table.getByRole('row').filter({ hasText: 'SP2026090095' })
  await expect(row).toContainText('2026-10-01')
  await expect(row).toContainText('演示用户')
  await row.getByRole('button', { name: 'SP2026090095 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['归档', '撤销归档', '打印报告', '打印任务单', '打印委托书'])
  await page.getByRole('menuitem', { name: '撤销归档', exact: true }).click()
  const undo = page.getByRole('dialog', { name: '撤销归档', exact: true })
  await undo.getByRole('button', { name: '确认', exact: true }).click()
  await expect(undo).toBeHidden()
  await expect(table).not.toContainText('SP2026090095')
})

test('archive reuses task and commission print pages and exports the selected electronic report', async ({ page }) => {
  const url = '/#/reports/archive?contains=SP2026090096&searchField=code&archiveStatus='
  await page.goto(url)
  await action(page, 'SP2026090096', '打印任务单')
  await expect(page).toHaveURL(/reports\/archive\/demo-yp-96\/print-task/)
  await expect(page.getByRole('heading', { name: '打印任务单', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '生成并预览', exact: true })).toBeEnabled()
  await page.getByRole('link', { name: '返回报告归档', exact: true }).first().click()
  await expect(page.getByLabel('包含', { exact: true })).toHaveValue('SP2026090096')
  await action(page, 'SP2026090096', '打印委托书')
  await expect(page.getByRole('heading', { name: '打印委托书', exact: true })).toBeVisible()
  await expect(page.getByRole('form', { name: '打印选项' })).toBeVisible()
  await page.getByRole('link', { name: '返回报告归档', exact: true }).first().click()
  await expect(page.getByLabel('包含', { exact: true })).toHaveValue('SP2026090096')
  await page.getByRole('checkbox', { name: '选择报告归档 SP2026090096', exact: true }).check()
  await page.getByRole('button', { name: '导出', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出已选记录/ }).click()
  const file = await download
  expect(file.suggestedFilename()).toBe('报告归档.csv')
  const csv = await readFile((await file.path())!, 'utf8')
  expect(csv).toContain('SP2026090096')
  expect(csv).not.toContain('SP2026090095')
  expect(csv).toContain('"归档人","归档日期"')
})

