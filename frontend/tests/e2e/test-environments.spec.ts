test('environment latest save and readonly access', async ({ page }) => {
  await page.request.post('/api/registration/session')
  await page.goto('/#/quality/environment')
  const table = page.getByRole('table', { name: '检测试验环境列表', exact: true })
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑试验环境', exact: true })
  await expect(dialog.getByLabel('试验环境描述')).toHaveValue('恒温恒湿试验室（示例）')
  const headers = { 'X-Demo-Actor': 'admin' }
  const row = await (await page.request.post('/api/registration/quality/environment/detail', { headers, data: { id: 'environment-1' } })).json()
  const result = await page.request.post('/api/registration/quality/environment/save', { headers, data: { ...row, name: '其他操作人修改' } })
  expect(result.ok()).toBe(true)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.evaluate(() => localStorage.setItem('lims.identity.v1', 'reviewer')); await page.reload()
  await expect(table).toContainText('恒温恒湿试验室（示例）')
  await expect(await toolbarButton(page, '检测试验环境', '新增')).toBeDisabled()
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem', { name: '编辑', exact: true })).toBeDisabled()
  await expect(page.getByRole('menuitem', { name: '删除', exact: true })).toBeDisabled()
})

for (const height of [720, 900]) test(`plan picker keeps equal panels and independent scrolling at ${height}`, async ({ page }, info) => {
  await page.request.post('/api/registration/session')
  await page.setViewportSize({ width: 1440, height })
  await page.goto('/#/quality/environment')
  const table = page.getByRole('table', { name: '检测试验环境列表', exact: true })
  await expect(table).toContainText('恒温恒湿试验室（示例）')
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await page.getByRole('menuitem', { name: '编辑', exact: true }).click()
  await page.getByRole('dialog', { name: '编辑试验环境', exact: true }).getByRole('button', { name: '关联检测方案', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '关联检测方案', exact: true })
  const left = picker.getByRole('region', { name: '未关联检测方案', exact: true }), right = picker.getByRole('region', { name: '已关联检测方案', exact: true })
  await expect(right.getByRole('table')).toContainText('热湿性能检测')
  await expect(picker.locator('.modal-dialog')).toHaveCSS('transform', 'none')
  const dimensions = await picker.evaluate(root => {
    const body = root.querySelector('.modal-body')!, panels = [...root.querySelectorAll('section .card')].map(el => el.getBoundingClientRect()), footers = [...root.querySelectorAll('section nav')].map(el => el.getBoundingClientRect())
    return { overflow: body.scrollHeight - body.clientHeight, panelHeights: panels.map(box => box.height), footerTops: footers.map(box => box.top), queryInBody: !!body.querySelector('form') }
  })
  expect(dimensions.queryInBody).toBe(false)
  expect(dimensions.overflow).toBeLessThanOrEqual(1)
  expect(Math.abs(dimensions.panelHeights[0]! - dimensions.panelHeights[1]!)).toBeLessThanOrEqual(1)
  expect(Math.abs(dimensions.footerTops[0]! - dimensions.footerTops[1]!)).toBeLessThanOrEqual(1)
  await left.getByRole('combobox').selectOption('50')
  expect(await left.locator('.overflow-auto').evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  expect(await picker.locator('.modal-body').evaluate(el => el.scrollHeight - el.clientHeight)).toBeLessThanOrEqual(1)
  await left.getByRole('table').locator('tbody tr').first().getByRole('checkbox').check()
  await expect(left.getByRole('table').locator('tbody tr').first()).toHaveClass(/table-active/)
  await picker.getByRole('button', { name: '移入', exact: true }).click()
  await expect(picker.locator('.modal-footer')).toContainText('已选 3 个检测方案')
  await picker.screenshot({ path: info.outputPath(`plan-picker-layout-${height}.png`) })
})
