  await picker.getByRole('button', { name: '移出', exact: true }).click()
  await expect(right).not.toContainText('热湿性能检测')
  await left.locator('tbody tr').filter({ hasText: '热湿性能检测' }).getByRole('checkbox').check()
  await picker.getByRole('button', { name: '移入', exact: true }).click()
