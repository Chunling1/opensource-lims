test('equipment type reference protection, concurrent edits, pagination and readonly menus', async ({ page }) => {
  await page.request.post('/api/registration/session')
  for (let index = 0; index < 12; index++) expect((await page.request.post(`${base}/save`, { headers, data: { name: `E2E-TYPE-${String(index).padStart(2, '0')}`, lendable: true, notes: '' } })).ok()).toBe(true)
  await page.goto('/#/quality/equipment/types'); await search(page, 'E2E-TYPE-')
  const table = page.getByRole('table', { name: '设备类型列表', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await page.getByRole('button', { name: '下一页', exact: true }).click(); await expect(table.locator('tbody tr')).toHaveCount(2)
  await search(page, 'E2E-TYPE-00'); await action(table, '编辑')
  const dialog = page.getByRole('dialog', { name: '编辑设备类型', exact: true }); await expect(dialog.getByLabel('设备类型')).toHaveValue('E2E-TYPE-00')
  const row = (await (await page.request.post(`${base}/query`, { headers, data: { name: 'E2E-TYPE-00' } })).json()).items[0]
  expect((await page.request.post(`${base}/save`, { headers, data: { ...row, notes: '并发更新' } })).ok()).toBe(true)
  await dialog.getByRole('button', { name: '保存', exact: true }).click(); await expect(dialog).toContainText('设备类型已更新')
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '重新加载', exact: true }).click(); await expect(dialog.getByLabel('备注')).toHaveValue('并发更新')
  await dialog.getByRole('button', { name: '取消', exact: true }).click(); await expect(dialog).toBeHidden()
  const device = emptyEquipment(); device.profile.equipmentType = row.name
  expect((await page.request.post('/api/registration/quality/equipment/ledger/save', { headers, data: { ...device, code: 'TYPE-REF', name: '类型引用设备', departmentId: 'lab' } })).ok()).toBe(true)
  await search(page, 'E2E-TYPE-00'); await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem', { name: '删除', exact: true })).toBeDisabled()
  await page.evaluate(() => localStorage.setItem('lims.identity.v1', 'reviewer')); await page.reload()
  await expect(table).toBeVisible(); await expect(await toolbarButton(page, '设备类型', '新增')).toBeDisabled()
  await table.locator('tbody tr').first().getByRole('button', { name: /更多操作/ }).click()
  await expect(page.getByRole('menuitem', { name: '编辑', exact: true })).toBeDisabled(); await expect(page.getByRole('menuitem', { name: '删除', exact: true })).toBeDisabled()
  await expect(page.getByRole('menuitem', { name: '查看', exact: true })).toBeEnabled()
})
