import { expect, test, type Page } from '@playwright/test'
import { checkOnlyWithControl } from './helpers/table-selection'

async function open(page: Page, label: string) {
  await page.getByRole('button', { name: `选择${label}`, exact: true }).click()
  const dialog = page.getByRole('dialog', { name: `选择${label}`, exact: true })
  await expect(dialog.getByRole('table', { name: '可选人员列表' })).toBeVisible()
  await expect(dialog).toBeFocused()
  return dialog
}
test('personnel scopes, search, cancellation, duplicate prevention and saved IDs', async ({ page }) => {
  await page.goto('/#/testing/data-entry/demo-yp-76')
  await expect(page.locator('#trial-tester1Id')).toHaveValue('李检测（analyst）')
  let dialog = await open(page, '试验人1')
  await expect(dialog.getByLabel('人员范围', { exact: true })).toHaveValue('preset')
  await dialog.getByLabel('人员范围', { exact: true }).selectOption('all')
  const other = dialog.getByRole('radio', { name: '选择 第二实验室检测员（other）', exact: true })
  await checkOnlyWithControl(other.locator('xpath=ancestor::tr'), other)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(page.locator('#trial-tester1Id')).toHaveValue('李检测（analyst）')
  dialog = await open(page, '试验人1')
  await expect(dialog.getByLabel('人员范围', { exact: true })).toHaveValue('all')
  await dialog.getByLabel('姓名或工号').fill('OTHER')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await expect(dialog.locator('tbody tr')).toHaveCount(1)
  await dialog.getByRole('radio', { name: '选择 第二实验室检测员（other）', exact: true }).check()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.locator('#trial-tester1Id')).toHaveValue('第二实验室检测员（other）')
  dialog = await open(page, '试验人2')
  await expect(dialog.getByLabel('人员范围', { exact: true })).toHaveValue('all')
  await expect(dialog.getByRole('radio', { name: /选择 第二实验室检测员.*已选为另一位/ })).toBeDisabled()
  await dialog.getByRole('radio', { name: '选择 李检测（analyst）', exact: true }).check()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  dialog = await open(page, '指定审核人')
  await expect(dialog.getByLabel('人员范围', { exact: true })).toHaveValue('department')
  await expect(dialog).toContainText('未配置此角色的预设人员')
  await dialog.getByLabel('人员范围', { exact: true }).selectOption('preset')
  await expect(dialog).toContainText('没有符合条件的人员')
  await dialog.getByLabel('人员范围', { exact: true }).selectOption('department')
  await dialog.getByRole('radio', { name: '选择 王复核（reviewer）', exact: true }).check()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  dialog = await open(page, '指定批准人')
  await expect(dialog.getByRole('radio', { name: /选择 李检测/ })).toHaveCount(0)
  await dialog.getByRole('radio', { name: '选择 陈批准（approver）', exact: true }).check()
  await dialog.getByRole('button', { name: '确定', exact: true }).click()
  await page.getByRole('button', { name: '清除指定批准人', exact: true }).click()
  await expect(page.locator('#trial-approverId')).toHaveValue('')
  await page.getByRole('tab', { name: '样品信息', exact: true }).click()
  await page.getByRole('tab', { name: '试验信息', exact: true }).click()
  dialog = await open(page, '试验人1')
  await expect(dialog.getByLabel('人员范围', { exact: true })).toHaveValue('all')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: '选择试验人1', exact: true })).toBeFocused()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText('试验信息已保存。', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('#trial-tester1Id')).toHaveValue('第二实验室检测员（other）')
  await expect(page.locator('#trial-tester2Id')).toHaveValue('李检测（analyst）')
  await expect(page.locator('#trial-reviewerId')).toHaveValue('王复核（reviewer）')
  await page.goto('/#/testing/data-entry/demo-yp-76?mode=view')
  for (const field of ['试验人1', '试验人2', '指定审核人', '指定批准人']) {
    await expect(page.getByRole('button', { name: `选择${field}`, exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: `清除${field}`, exact: true })).toBeDisabled()
  }
})

test('personnel dialog themes, mobile layout, paging controls and query failures', async ({ page }, info) => {
  await page.goto('/#/testing/data-entry/demo-yp-76')
  for (const [width, theme] of [[1440, 'light'], [390, 'dark']] as const) {
    await page.setViewportSize({ width: 1440, height: 900 })
    if (await page.locator('html').getAttribute('data-bs-theme') !== theme) await page.getByRole('button', { name: '切换明暗模式', exact: true }).click()
    await page.setViewportSize({ width, height: 900 })
    const dialog = await open(page, '试验人1')
    await dialog.getByLabel('人员范围', { exact: true }).selectOption('all')
    await dialog.getByLabel('人员每页条数').selectOption('20')
    await expect(dialog.getByLabel('人员每页条数')).toHaveValue('20')
    await expect(dialog.getByRole('table')).toContainText('第二实验室')
    await expect.poll(() => dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await dialog.screenshot({ path: info.outputPath(`people-${width}-${theme}.png`) })
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  }
  await page.route('**/data-entry/people/query', route => route.abort())
  await page.getByRole('button', { name: '选择试验人1', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '选择试验人1', exact: true })
  await expect(dialog.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('#trial-tester1Id')).toHaveValue('李检测（analyst）')
})
