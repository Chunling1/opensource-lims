import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { clientYearRange } from '../../src/services/common/date'
import { pickDateRange, pickRangeDay } from './helpers/dateRange'

test('sample selector, state, type and range filter consistently for list, export and navigation', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/#/commissions/registration?scope=all&current=demo-wt-1&sSort=code&sDirection=asc')
  const form = page.getByRole('form', { name: '样品查询', exact: true })
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  const region = page.getByRole('region', { name: '样品列表区域', exact: true })
  const field = form.getByLabel('查询内容'), input = form.getByLabel('包含'), dates = form.getByLabel('委托日期', { exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(field.locator('option')).toHaveText(['全部', '样品编号', '报告编号', '样品登记人'])
  await expect(form.getByLabel('数据状态').locator('option')).toHaveText(['全部状态', '委托登记中', '完成登记'])
  await expect(form.getByLabel('样品类型').locator('option')).toHaveText(['全部类型', '原始样品', '英文报告样品', '分项/阶段性报告样品', '补充报告'])
  await expect(form.getByRole('button', { name: '更多筛选', exact: true })).toHaveCount(0)
  const range = clientYearRange()
  await expect(dates).toHaveValue(`${range.from} 至 ${range.to}`)
  const requests: Record<string, unknown>[] = []
  page.on('request', request => { if (request.url().endsWith('/samples/query')) requests.push(request.postDataJSON()) })
  for (const [selection, text] of [['code', 'sp2026090005'], ['reportCode', 'bg2026090005'], ['all', 'bg2026090005']] as const) {
    await field.selectOption(selection)
    await input.fill(text)
    const before = requests.length
    await input.press('Enter')
    await expect.poll(() => requests.length).toBeGreaterThan(before)
    await expect(table.locator('tbody tr')).toHaveCount(1)
    await expect(table).toContainText('SP2026090005')
    expect(requests.at(-1)).toMatchObject({ searchField: selection, contains: text })
  }
  await field.selectOption('owner'); await input.fill('演示')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await field.selectOption('reportCode'); await input.fill('bg2026090005')
  await form.getByLabel('数据状态').selectOption('完成登记')
  await form.getByLabel('样品类型').selectOption('英文报告样品')
  await input.press('Enter')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  expect(requests.at(-1)).toMatchObject({ searchField: 'reportCode', contains: 'bg2026090005', dataStatus: '完成登记', sampleType: '英文报告样品', commissionFrom: range.from, commissionTo: range.to, page: 1 })
  await region.getByRole('button', { name: '导出', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await region.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const csv = await readFile((await (await downloading).path())!, 'utf8')
  expect(csv.split('\r\n')).toHaveLength(2)
  expect(csv).toContain('SP2026090005')
  const url = page.url()
  await table.getByRole('link', { name: 'SP2026090005', exact: true }).click()
  await page.getByRole('link', { name: '返回委托登记', exact: true }).click()
  await expect(page).toHaveURL(url)
  await expect(field).toHaveValue('reportCode'); await expect(input).toHaveValue('bg2026090005')
  await page.reload()
  await expect(table).toContainText('SP2026090005')
  await page.getByRole('tab', { name: '当前委托', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  await input.fill('')
  await form.getByLabel('数据状态').selectOption('')
  await form.getByLabel('样品类型').selectOption('')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(6)
  for (const [path, width, theme] of [['registration', 1440, 'light'], ['query', 1280, 'light'], ['review', 390, 'dark'], ['query', 320, 'light']] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(`/#/commissions/${path}?scope=all`)
    await page.evaluate(value => document.documentElement.setAttribute('data-bs-theme', value), theme)
    await form.scrollIntoViewIfNeeded()
    await expect(dates).toBeVisible()
    await expect(form.getByRole('button', { name: '更多筛选', exact: true })).toHaveCount(0)
    if (width >= 1280) expect((await input.boundingBox())!.width).toBeGreaterThanOrEqual(150)
    if (width >= 1440) {
      const boxes = await Promise.all([field, input, form.getByLabel('数据状态'), form.getByLabel('样品类型'), dates, form.getByRole('button', { name: '查询', exact: true })].map(control => control.boundingBox()))
      expect(Math.max(...boxes.map(box => box!.y)) - Math.min(...boxes.map(box => box!.y))).toBeLessThan(2)
    }
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await form.screenshot({ path: testInfo.outputPath(`sample-filters-${width}-${theme}.png`) })
    if (path === 'query') {
      await expect(field.locator('option')).toHaveText(['委托经办人', '样品登记人', '合同评审人', '委托单位', '工程/产品名称', '委托人', '生产单位'])
      const status = form.getByLabel('数据状态')
      await expect(status.locator('option')).toHaveText([
        '全部', '委托登记中', '委托登记完成', '合同评审中', '合同评审完成',
        '样品入库中', '样品入库完成', '样品出库中', '样品出库完成', '样品待领取', '样品已领取',
        '任务分配中', '任务分配完成', '任务处理中', '任务处理完成',
        '检测数据录入中', '检测数据录入完成', '检测数据校核中', '检测数据校核完成',
        '报告校核中', '报告校核完成', '报告审核中', '报告审核完成', '报告批准中', '报告批准完成',
        '报告打印中', '报告打印完成', '委托更改中', '检测更改中', '报告更改中',
        '委托作废申请中', '委托已作废', '报告更改审批中', '任务已取消', '终止',
      ])
      await status.selectOption({ label: '委托登记完成' })
      await form.getByRole('button', { name: '查询', exact: true }).click()
      await expect(page).toHaveURL(/sDataStatus=/)
      await expect(table.locator('tbody tr')).toHaveCount(10)
      expect(requests.at(-1)).toMatchObject({ workspace: 'query', dataStatus: '完成登记' })
      await page.reload()
      await expect(status).toHaveValue('完成登记')
      await status.selectOption({ label: '报告批准中' })
      await form.getByRole('button', { name: '查询', exact: true }).click()
      await expect(table).toContainText('暂无符合条件的样品')
      expect(requests.at(-1)).toMatchObject({ workspace: 'query', dataStatus: '报告批准中' })
    } else if (path === 'review') {
      await expect(field.locator('option')).toHaveText(['全部', '样品编号', '报告编号', '样品登记人'])
      await expect(form.getByLabel('数据状态').locator('option')).toHaveText(['全部', '合同评审中', '合同评审完成'])
    }

  }
})

test('sample legacy links keep visible conditions and date ranges cannot be cleared or partially submitted', async ({ page }) => {
  await page.goto('/#/commissions/registration?scope=all&sAdvanced=1&sKeyword=SP2026090005&sReportCode=BG2026090005&sOwner=演示&sStatus=voided&sDataStatus=合同评审中&sCommissionFrom=&sCommissionTo=')
  const form = page.getByRole('form', { name: '样品查询', exact: true })
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  const dates = form.getByLabel('委托日期', { exact: true }), range = clientYearRange()
  await expect(table).toContainText('SP2026090005')
  await expect(form.getByLabel('数据状态')).toHaveValue('')
  await expect(form.getByLabel('查询内容')).toHaveValue('code')
  await expect(form.getByLabel('包含')).toHaveValue('SP2026090005')
  await expect(form.getByText('报告编号包含：BG2026090005', { exact: true })).toBeVisible()
  await expect(form.getByText('样品登记人包含：演示', { exact: true })).toBeVisible()
  await form.getByRole('button', { name: '移除报告编号条件', exact: true }).click()
  await form.getByRole('button', { name: '移除样品登记人条件', exact: true }).click()
  await dates.press('Delete'); await dates.press('Backspace')
  await expect(dates).toHaveValue(`${range.from} 至 ${range.to}`)
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page).toHaveURL(/sSearchField=code/)
  expect(page.url()).not.toMatch(/sKeyword=|sCode=|sReportCode=|sOwner=|sAdvanced=|sStatus=|sDataStatus=/)
  await page.reload()
  await expect(dates).toHaveValue(`${range.from} 至 ${range.to}`)
  await dates.click(); await pickRangeDay(page, '2000-01-01')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('请选择结束日期')
  await dates.click()
  await pickRangeDay(page, '2000-12-31')
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
  await pickDateRange(page, dates, range.from, range.to)
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('SP2026090005')
})

test('inquiry reviewer filter searches backend records, exports and restores before withdrawal', async ({ page }) => {
  await page.goto('/#/commissions/query?scope=all&sSearchField=code&sContains=missing&sCode=missing&sReportCode=missing')
  const form = page.getByRole('form', { name: '样品查询', exact: true })
  const table = page.getByRole('table', { name: '样品列表', exact: true })
  const headers = { 'X-Demo-Actor': 'admin' }
  await expect(table.locator('tbody tr')).toHaveCount(10)
  await expect(form.getByLabel('查询内容')).toHaveValue('commissionOwner')
  await expect(form.getByLabel('包含')).toHaveValue('')
  const sample = await (await page.request.get('/api/registration/samples/demo-yp-2', { headers })).json()
  const started = await page.request.post('/api/registration/samples/demo-yp-2/actions', { headers, data: { actionId: 'start-review', version: sample.version } })
  expect(started.ok()).toBe(true)
  await form.getByLabel('查询内容').selectOption('reviewer')
  await form.getByLabel('包含').fill('演示')
  await form.getByLabel('包含').press('Enter')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(table).toContainText('SP2026090002')
  expect(page.url()).not.toMatch(/sCode=|sReportCode=/)
  const region = page.getByRole('region', { name: '样品列表区域', exact: true })
  await region.getByRole('button', { name: '导出', exact: true }).click()
  const downloading = page.waitForEvent('download')
  await region.getByRole('button', { name: '导出查询结果', exact: true }).click()
  const csv = await readFile((await (await downloading).path())!, 'utf8')
  expect(csv.split('\r\n')).toHaveLength(2)
  expect(csv).toContain('SP2026090002')
  await table.getByRole('link', { name: 'SP2026090002', exact: true }).click()
  await page.getByRole('link', { name: '返回委托查询', exact: true }).click()
  await page.reload()
  await expect(form.getByLabel('查询内容')).toHaveValue('reviewer')
  await expect(form.getByLabel('包含')).toHaveValue('演示')
  const reviewed = await started.json()
  expect((await page.request.post('/api/registration/samples/demo-yp-2/actions', { headers, data: { actionId: 'unreview', version: reviewed.version } })).ok()).toBe(true)
  await form.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table).toContainText('暂无符合条件的样品')
})
