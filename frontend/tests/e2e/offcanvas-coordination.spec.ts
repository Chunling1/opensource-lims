import { expect, test } from '@playwright/test'

test('plan and theme drawers switch exclusively and retain automatically applied selections', async ({ page }) => {
  await page.goto('/#/samples/inbound')
  const picker = page.getByRole('dialog', { name: '筛选检测方案', exact: true })
  const theme = page.getByRole('dialog', { name: '主题与布局', exact: true })
  await page.locator('#inbound-plans').click()
  await picker.getByRole('checkbox', { name: '选择分组 温度校准实验室', exact: true }).click()
  await expect(picker.getByText('已选 26 项', { exact: true })).toBeVisible()
  await picker.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(picker).toBeHidden()
  await page.locator('#inbound-plans').click()
  await picker.getByRole('checkbox', { name: '选择分组 风速、压力校准实验室', exact: true }).click()
  await expect(picker.getByText('已选 29 项', { exact: true })).toBeVisible()
  await page.evaluate(() => {
    const counts: number[] = []
    Object.assign(window, { drawerCounts: counts })
    new MutationObserver(() => counts.push(Math.max(document.querySelectorAll('.offcanvas[aria-modal="true"]').length, document.querySelectorAll('.offcanvas-backdrop').length))).observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['aria-modal'] })
    // Normal clicks are blocked by the backdrop; exercise the programmatic entry point too.
    document.querySelector<HTMLButtonElement>('[aria-label="打开主题设置"]')!.click()
  })
  await expect(picker).toBeHidden()
  await expect(theme).toHaveClass(/\bshow\b/)
  await expect(page.locator('.offcanvas-backdrop')).toHaveCount(1)
  await expect(page.locator('#inbound-plans')).toContainText('已选 29 项')
  await page.evaluate(() => document.querySelector<HTMLButtonElement>('#inbound-plans')!.click())
  await expect(theme).toBeHidden()
  await expect(picker).toHaveClass(/\bshow\b/)
  await expect(picker.getByText('已选 29 项', { exact: true })).toBeVisible()
  await expect(picker.getByRole('checkbox', { name: '选择分组 风速、压力校准实验室', exact: true })).toBeChecked()
  await picker.press('Escape')
  await expect(picker).toBeHidden()
  await expect(page.locator('.offcanvas-backdrop')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.body.style.overflow)).toBe('')
  await expect(page.locator('#inbound-plans')).toBeFocused()
  await page.getByRole('button', { name: '打开主题设置', exact: true }).click()
  await expect(theme).toHaveClass(/\bshow\b/)
  await theme.press('Escape')
  await expect(theme).toBeHidden()
  await expect(page.getByRole('button', { name: '打开主题设置', exact: true })).toBeFocused()
  expect(await page.evaluate(() => Math.max(...(window as unknown as { drawerCounts: number[] }).drawerCounts))).toBe(1)
})

test('opening transitions tolerate switching, early Escape and route unmount without leftover locks', async ({ page }) => {
  await page.goto('/#/samples/inbound')
  await expect(page.locator('#inbound-plans')).toBeEnabled()
  const picker = page.locator('.offcanvas[aria-label="筛选检测方案"]')
  const theme = page.locator('#theme-settings-offcanvas')
  await page.locator('#inbound-plans').click()
  await expect(picker).toHaveClass(/\bshowing\b/)
  await page.evaluate(() => document.querySelector<HTMLButtonElement>('[aria-label="打开主题设置"]')!.click())
  await expect(theme).toHaveClass(/\bshow\b/)
  await expect(picker).toBeHidden()
  await theme.press('Escape')
  await expect(page.locator('.offcanvas-backdrop')).toHaveCount(0)
  await page.locator('#inbound-plans').click()
  await expect(picker).toHaveClass(/\bshowing\b/)
  await picker.dispatchEvent('keydown', { key: 'Escape' })
  await expect(picker).toBeHidden()
  await expect(page.locator('.offcanvas-backdrop')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.body.style.overflow)).toBe('')
  await page.locator('#inbound-plans').click()
  await expect(picker).toHaveClass(/\bshowing\b/)
  await page.evaluate(() => { location.hash = '/dashboard' })
  await expect(picker).toHaveCount(0)
  await expect(page.locator('.offcanvas-backdrop')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.body.style.overflow)).toBe('')
  await page.getByRole('button', { name: '打开主题设置', exact: true }).click()
  await expect(theme).toHaveClass(/\bshow\b/)
  await theme.press('Escape')
  await expect(page.locator('.offcanvas-backdrop')).toHaveCount(0)
})
