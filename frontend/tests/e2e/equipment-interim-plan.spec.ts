  await picker.getByLabel('查询值', { exact: true }).fill('INTERIM-TEST')
  await expect(picker.getByRole('button', { name: '查询', exact: true })).toBeEnabled()
  await picker.getByRole('button', { name: '查询', exact: true }).click()
