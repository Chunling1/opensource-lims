  await page.keyboard.press('ArrowRight')
  await expect(yearPicker.getByRole('button', { name: String(originalYear + 1), exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(yearField).toHaveValue(String(originalYear + 1))
  await expect(yearPicker).toBeHidden()
  await yearField.press('Enter')
  await yearPicker.getByRole('button', { name: '下一组年份' }).click()
  await yearPicker.getByRole('button', { name: '上一组年份' }).click()
  await expect(yearPicker.getByRole('button', { name: String(originalYear + 1), exact: true })).toHaveAttribute('aria-pressed', 'true')
  const yearBounds = await yearPicker.boundingBox()
  expect(yearBounds!.x).toBeGreaterThanOrEqual(0)
  expect(yearBounds!.x + yearBounds!.width).toBeLessThanOrEqual(width)
  await yearPicker.screenshot({ path: info.outputPath(`year-picker-${width}.png`) })
  await page.keyboard.press('Escape')
  await expect(yearPicker).toBeHidden()
  await expect(dialog).toBeVisible()
  await expect(yearField).toBeFocused()
  await dialog.getByLabel('核查方法').fill('标准物质核查')
  await dialog.getByRole('button', { name: '选择设备', exact: true }).click()
