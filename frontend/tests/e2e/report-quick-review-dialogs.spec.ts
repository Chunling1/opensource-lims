import { test, expect } from '@playwright/test'
for (const width of [1440, 390]) test(`quick review preserves layers, inputs and focus at ${width}`, async ({ page }, info) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width, height: 1000 })
  await page.request.post('/api/registration/session')
  await page.goto('/#/reports/check')
  const table = page.getByRole('table', { name: '报告校核列表', exact: true })
  await table.getByRole('row').filter({ hasText: 'SP2026090082' }).getByRole('checkbox').check()
  await page.getByRole('button', { name: '快速校核', exact: true }).click()
  const parent = page.getByRole('dialog', { name: '快速校核', exact: true })
  await parent.getByRole('button', { name: '校验', exact: true }).click()
  const checked = parent.getByRole('checkbox', { name: '我已阅读并确认全部样品的校核结果', exact: true })
  await checked.check()
  const pass = parent.getByRole('button', { name: '通过', exact: true })
  await pass.click()
  const next = page.getByRole('dialog', { name: '确认下一步', exact: true })
  await expect(parent).toBeVisible(); await expect(checked).toBeChecked()
  await next.getByRole('radio', { name: '转交校核', exact: true }).check()
  await next.getByRole('button', { name: '选择接收人', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择接收人', exact: true })
  await expect(picker.getByRole('radio', { name: '选择 王复核（reviewer）', exact: true })).toBeVisible()
  await expect(parent).toBeVisible(); await expect(next).toBeVisible()
  await picker.press('Escape'); await expect(picker).toBeHidden()
  await expect(next).toBeVisible()
  await next.press('Escape'); await expect(next).toBeHidden(); await expect(pass).toBeFocused()
  await expect(checked).toBeChecked()
  await parent.getByRole('button', { name: '不通过', exact: true }).click()
  const issue = page.getByRole('dialog', { name: '问题处理', exact: true })
  await issue.getByRole('radio', { name: '其他问题', exact: true }).check()
  await issue.getByLabel('退回原因').fill('需补充原始记录')
  await issue.getByRole('button', { name: '取消', exact: true }).click()
  await parent.getByRole('button', { name: '不通过', exact: true }).click()
  await expect(issue.getByLabel('退回原因')).toHaveValue('需补充原始记录')
  let release!: () => void, calls = 0
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/samples/report-batch/submit', async route => {
    calls++
    if (calls > 1) return route.continue()
    await gate
    await route.fulfill({ status: 500, json: { error: { code: 'INTERNAL', message: '本次提交失败，请重试' } } })
  })
  try {
    await issue.getByRole('button', { name: '确定', exact: true }).click()
    await expect(issue.getByRole('button', { name: '正在提交…', exact: true })).toBeDisabled()
    await expect(issue.getByRole('button', { name: '关闭弹窗', exact: true })).toBeDisabled()
    await issue.press('Escape'); await expect(issue).toBeVisible()
    expect(calls).toBe(1)
  } finally { release() }
  await expect(issue.getByText('本次提交失败，请重试', { exact: true })).toBeVisible()
  await expect(issue.getByLabel('退回原因')).toHaveValue('需补充原始记录')
  await expect(parent).toBeVisible()
  await page.screenshot({ path: info.outputPath(`layered-review-${width}.png`), fullPage: true })
  await issue.getByRole('button', { name: '确定', exact: true }).click()
  await expect(issue).toBeHidden(); await expect(parent).toBeHidden()
})
