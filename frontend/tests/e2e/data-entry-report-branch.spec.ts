import { expect, test } from '@playwright/test'
import { openReportFiles } from './helpers/reportFiles'

test('adopting a layout previews a system-only report without downloading or uploading, and switching invalidates it', async ({ page }) => {
  const actions: string[] = []
  page.on('request', request => { if (request.method() === 'POST' && /data-entry\/(save|combine|template-tasks|upload)$/.test(request.url())) actions.push(request.url().split('/').pop()!) })
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  await page.getByLabel('首页版式', { exact: true }).selectOption('extended')
  await openReportFiles(page)
  await page.getByRole('button', { name: '预览报告', exact: true }).click()
  const frame = page.getByTitle('完整报告预览', { exact: true })
  await expect(frame).toBeVisible()
  expect(actions).toEqual(['save', 'combine'])
  await page.reload()
  await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(frame).toBeVisible()
  const oldUrl = await frame.getAttribute('src')
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await page.getByLabel('首页版式', { exact: true }).selectOption('standard')
  await expect(page.getByText('首页版式将切换为“标准版”，旧模板及报告预览将失效。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByLabel('首页版式', { exact: true })).toHaveValue('extended')
  await openReportFiles(page)
  await page.getByRole('button', { name: '预览报告', exact: true }).click()
  await expect(frame).toHaveAttribute('src', oldUrl!)
  expect(actions).toEqual(['save', 'combine'])
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await page.getByLabel('首页版式', { exact: true }).selectOption('standard')
  await page.getByRole('button', { name: '确认切换', exact: true }).click()
  await expect(page.getByRole('button', { name: '上传文件', exact: true })).toBeEnabled()
  await expect(frame).toHaveCount(0)
  await expect(page.getByRole('tab', { name: '报告模板', exact: true })).toHaveAttribute('aria-selected', 'true')
  await openReportFiles(page)
  await page.getByRole('button', { name: '预览报告', exact: true }).click()
  await expect(frame).toBeVisible()
  expect(actions).toEqual(['save', 'combine', 'combine'])
})

test('appendices survive a layout switch in order and remain included in the direct preview route', async ({ page }) => {
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  await openReportFiles(page)
  const word = (name: string) => ({ name, mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('504b0304', 'hex') })
  await page.getByLabel('添加附加文件', { exact: false }).setInputFiles([word('附加一.docx'), word('附加二.docx')])
  await expect(page.getByRole('button', { name: '附加二.docx', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('tab', { name: '上传文件', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await expect(page.getByRole('button', { name: '上传文件', exact: true })).toBeVisible()
  await page.getByLabel('首页版式', { exact: true }).selectOption('extended')
  await expect(page.getByText('首页版式将切换为“扩展版”，已上传的附加文件及顺序将保留，请核对其是否适用。旧模板及报告预览将失效。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '确认切换', exact: true }).click()
  await openReportFiles(page)
  await expect(page.locator('[data-attachment-file]')).toHaveCount(2)
  await page.getByRole('button', { name: '预览报告', exact: true }).click()
  await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  await expect(page.getByRole('button', { name: /^附加[一二]\.docx$/ })).toHaveText(['附加一.docx', '附加二.docx'])
  await expect(page.getByText('当前首页版式：扩展版', { exact: true })).toBeVisible()
})

test('uncertain adoption is reconciled before preview without duplicate saving; readonly has no first-entry gate', async ({ page }) => {
  await page.goto('/#/testing/data-entry/demo-yp-76/report?mode=view')
  await page.getByRole('tab', { name: '报告预览', exact: true }).click()
  await expect(page.getByText('报告未生成', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '生成预览', exact: true })).toBeDisabled()
  await page.getByRole('tab', { name: '上传文件', exact: true }).click()
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await expect(page.getByRole('button', { name: '下载模板', exact: true })).toBeDisabled()
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  let saves = 0, combines = 0
  await page.route('**/data-entry/save', async route => { saves++; await route.fetch(); await route.abort() })
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/combine')) combines++ })
  await page.getByRole('button', { name: '上传文件', exact: true }).click()
  await expect(page.getByRole('tab', { name: '报告模板', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: '刷新核对', exact: true }).click()
  await expect(page.getByRole('button', { name: '上传文件', exact: true })).toBeEnabled()
  expect(saves).toBe(1)
  expect(combines).toBe(0)
  await openReportFiles(page)
  await page.getByRole('button', { name: '预览报告', exact: true }).click()
  await expect(page.getByTitle('完整报告预览', { exact: true })).toBeVisible()
  expect(saves).toBe(1)
  expect(combines).toBe(1)
})
