test('record attachment conflict refreshes its own version and late sample state prevents writes', async ({ page }) => {
  await page.goto(list); await action(page, '任务处理记录')
  const records = page.getByRole('dialog', { name: '任务处理记录', exact: true })
  await records.getByRole('button', { name: '新增记录', exact: true }).click()
  const create = page.getByRole('dialog', { name: '新增记录', exact: true })
  await create.getByLabel('处理内容').fill('附件冲突'); await create.getByRole('button', { name: '保存', exact: true }).click()
  await recordAction(page, '附件管理')
  const attachments = page.getByRole('dialog', { name: '处理记录附件', exact: true })
  const result = await (await page.request.post(`${api}/samples/${id}/task-processing-records/query`, { headers, data: {} })).json()
  const record = result.items[0], fileApi = `${api}/samples/${id}/task-processing-records/${record.id}/attachments`
  expect((await page.request.post(fileApi, { headers, data: { version: record.version, file: { name: '另一个窗口.txt', type: 'text/plain', size: 1, dataUrl: 'data:text/plain;base64,YQ==' } } })).ok()).toBe(true)
  await attachments.getByLabel('添加附件', { exact: false }).setInputFiles(file)
  await expect(attachments).toContainText('处理记录已更新')
  await expect(attachments.getByLabel('添加附件', { exact: false })).toHaveCount(0)
  await attachments.getByRole('button', { name: '刷新附件', exact: true }).click()
  await expect(attachments.getByRole('button', { name: '另一个窗口.txt', exact: true })).toBeVisible()
  const sample = await (await page.request.get(`${api}/samples/${id}`, { headers })).json()
  expect((await page.request.post(`${api}/samples/${id}/task-return`, { headers, data: { version: sample.version, returned: { type: 'commission', reason: '校正委托', details: '', date: result.items[0].date } } })).ok()).toBe(true)
  await attachments.getByLabel('添加附件', { exact: false }).setInputFiles(file)
  await expect(attachments).toContainText('样品状态已变化')
  await attachments.getByRole('button', { name: '刷新附件', exact: true }).click()
  await expect(attachments).toContainText('当前仅支持查看和下载处理记录附件')
  const final = await (await page.request.get(fileApi, { headers })).json()
  expect(final.attachmentCount).toBe(1); expect(final.version).toBe(2)
})
