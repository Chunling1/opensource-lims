import { openReportFiles } from './helpers/reportFiles'
import { expect, test } from '@playwright/test'

const word = (name: string) => ({ name, mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('504b0304', 'hex') })

test('collected demo samples can open report filling and upload attachments', async ({ page }) => {
  for (const number of [21, 24, 27]) {
    await page.goto(`/#/testing/data-entry/demo-yp-${number}/report`)
    await openReportFiles(page)
    await expect(page.getByText('报告配置不完整或组合不可用，请通过委托更改或退回流程修正。')).toHaveCount(0)
    const name = `上传测试-${number}.docx`
    await page.getByLabel('添加附加文件', { exact: false }).setInputFiles(word(name))
    await expect(page.getByRole('button', { name, exact: true })).toBeVisible()
  }
})

test('first upload requires confirmation of the adopted layout; cancellation and layout changes never upload', async ({ page }) => {
  let uploads = 0
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/data-entry/upload')) uploads++ })
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  await openReportFiles(page)
  const layout = page.getByLabel('首页版式', { exact: true })
  const confirmation = page.getByRole('dialog', { name: '完整报告上传确认' })
  const input = page.getByLabel('上传完整报告', { exact: false })
  await expect(input).toHaveAccessibleDescription('请使用当前模板填写完整报告，上传前核对首页版式及报告内容。')
  await input.setInputFiles(word('待上传报告.docx'))
  await expect(confirmation).toContainText('请确认“待上传报告.docx”与当前模板（标准版）首页版式一致，否则无法生成正确的报告。')
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  await expect(confirmation).toHaveCount(0)
  expect(uploads).toBe(0)
  await input.setInputFiles(word('旧版式报告.docx'))
  await page.keyboard.press('Escape')
  await expect(confirmation).toHaveCount(0)
  await page.getByRole('tab', { name: '报告模板', exact: true }).click()
  await layout.selectOption('extended')
  await openReportFiles(page)
  await expect(confirmation).toHaveCount(0)
  expect(uploads).toBe(0)
  await input.setInputFiles(word('扩展版报告.docx'))
  await expect(confirmation).toContainText('请确认“扩展版报告.docx”与当前模板（扩展版）首页版式一致，否则无法生成正确的报告。')
  expect(uploads).toBe(0)
  await expect(page.locator('#entry-report-layout')).toHaveValue('extended')
  await expect(confirmation).toContainText('扩展版报告.docx')
  await confirmation.getByRole('button', { name: '确认上传', exact: true }).click()
  await expect(page.getByRole('button', { name: '扩展版报告.docx', exact: true })).toBeVisible()
  await expect(confirmation).toHaveCount(0)
  expect(uploads).toBe(1)
  await page.reload()
  await expect(page.locator('#entry-report-layout')).toHaveValue('extended')
  await openReportFiles(page)
  await expect(page.getByRole('button', { name: '扩展版报告.docx', exact: true })).toBeVisible()
})

test('replacement keeps the old file until success and disables duplicate uploads', async ({ page }) => {
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  await openReportFiles(page)
  const confirmation = page.getByRole('dialog', { name: '完整报告上传确认' })
  await page.getByLabel('上传完整报告', { exact: false }).setInputFiles(word('原完整报告.docx'))
  await confirmation.getByRole('button', { name: '确认上传', exact: true }).click()
  const original = page.getByRole('button', { name: '原完整报告.docx', exact: true })
  await expect(original).toBeVisible()
  const replacement = page.getByLabel('替换完整报告', { exact: false })
  await replacement.setInputFiles(word('替换完整报告.docx'))
  await expect(confirmation).toContainText('上传成功后替换原完整报告。')
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  await expect(original).toBeVisible()
  await replacement.setInputFiles(word('替换完整报告.docx'))
  await page.route('**/data-entry/upload', route => route.fulfill({ status: 422, json: { error: { code: 'VALIDATION', message: '上传失败，请重试。' } } }))
  await confirmation.getByRole('button', { name: '确认替换', exact: true }).click()
  const retry = page.locator('[data-upload-retry]')
  await expect(retry).toHaveAccessibleName(/上传失败.*点击重试/)
  await expect(original).toBeVisible()
  await expect(confirmation).toHaveCount(0)
  await retry.click()
  await page.unroute('**/data-entry/upload')
  let uploads = 0
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/data-entry/upload', async route => { uploads++; await pending; await route.continue() })
  await replacement.setInputFiles(word('替换完整报告.docx'))
  await confirmation.getByRole('button', { name: '确认替换', exact: true }).click()
  try {
    await expect(confirmation).toHaveCount(0)
    await expect(page.locator('.filepond--root[data-disabled]')).toHaveCount(2)
    await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toBeDisabled()
    await expect(original).toBeVisible()
    await expect.poll(() => uploads).toBe(1)
  } finally { release() }
  await expect(original).toHaveCount(0)
  await expect(page.getByRole('button', { name: '替换完整报告.docx', exact: true })).toBeVisible()
  await expect(confirmation).toHaveCount(0)
  const readonlyLoaded = page.waitForResponse(response => response.url().endsWith('/samples/demo-yp-76/data-entry') && response.request().method() === 'GET')
  await page.goto('/#/testing/data-entry/demo-yp-76/report?mode=view')
  await readonlyLoaded
  await expect(page.locator('input[type=file]')).toHaveCount(0)
  await openReportFiles(page)
  await expect(page.locator('input[type=file]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '替换完整报告.docx', exact: true })).toBeEnabled()
  await expect(confirmation).toHaveCount(0)
})

for (const width of [1440, 390]) {
  test(`upload confirmation wraps long names and supports keyboard at ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/#/testing/data-entry/demo-yp-76/report')
    await openReportFiles(page)
    const confirmation = page.getByRole('dialog', { name: '完整报告上传确认' })
    const filename = `完整报告-${'abcdefghij'.repeat(12)}.docx`
    await page.getByLabel('上传完整报告', { exact: false }).setInputFiles(word(filename))
    await expect(confirmation).toBeFocused()
    for (const theme of ['light', 'dark']) {
      await page.evaluate(theme => document.documentElement.setAttribute('data-bs-theme', theme), theme)
      await confirmation.scrollIntoViewIfNeeded()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
      await page.screenshot({ path: info.outputPath(`upload-confirmation-${width}-${theme}.png`), fullPage: true })
    }
    await confirmation.focus()
    await page.keyboard.press('Tab')
    await expect(confirmation.getByRole('button', { name: '关闭弹窗', exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(confirmation.getByRole('button', { name: '取消', exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(confirmation.getByRole('button', { name: '确认上传', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: filename, exact: true })).toBeVisible()
    await expect(confirmation).toHaveCount(0)
  })
}

for (const width of [1440, 390]) test(`unified report attachments support multi-select, ordering, removal and progress at ${width}`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/#/testing/data-entry/demo-yp-76/report')
  await openReportFiles(page)
  const panel = page.getByRole('region', { name: '报告文件管理', exact: true })
  await expect(panel.locator('.filepond--root')).toHaveCount(2)
  await expect(panel.locator('[data-attachment-placeholders]')).toBeVisible()
  await page.screenshot({ path: info.outputPath(`report-upload-empty-${width}.png`), fullPage: true })
  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  let count = 0
  await page.route('**/data-entry/upload', async route => {
    expect(route.request().resourceType()).toBe('xhr')
    count++
    if (count === 1) await held
    await route.continue()
  })
  const input = page.getByLabel('添加附加文件', { exact: true })
  await input.setInputFiles([word('附件一.docx'), word('附件二.docx')])
  try {
    await expect.poll(() => count).toBe(1)
    await expect(panel.locator('[data-upload-state-icon]').first()).toBeVisible()
    await expect(page.getByRole('tab', { name: '报告预览', exact: true })).toBeDisabled()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`report-upload-progress-${width}.png`), fullPage: true })
  } finally { release() }
  const rows = panel.locator('[data-attachment-file]')
  await expect(rows).toHaveCount(2)
  await expect(rows.first()).toContainText('附件一.docx')
  await expect(rows.last()).toContainText('附件二.docx')
  await page.getByRole('button', { name: '上移 附件二.docx', exact: true }).click()
  await expect(rows.first()).toContainText('附件二.docx')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载附件 附件二.docx', exact: true }).click()
  expect((await downloadPromise).suggestedFilename()).toBe('附件二.docx')
  await page.getByRole('button', { name: '删除附件 附件一.docx', exact: true }).click()
  const deletion = page.getByRole('dialog', { name: '删除报告文件', exact: true })
  let finishDelete!: () => void
  const deleting = new Promise<void>(resolve => { finishDelete = resolve })
  await page.route('**/data-entry/delete', async route => { await deleting; await route.fulfill({ status: 422, json: { error: { code: 'VALIDATION', message: '删除失败，请重试。' } } }) })
  await deletion.getByRole('button', { name: '确认删除', exact: true }).click()
  try {
    await expect(deletion.getByRole('button', { name: '取消', exact: true })).toBeDisabled()
    await expect(deletion.getByRole('button', { name: '关闭弹窗', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(deletion).toBeVisible()
  } finally { finishDelete() }
  await expect(deletion).toContainText('删除失败，请重试。')
  await expect(deletion.getByRole('button', { name: '确认删除', exact: true })).toBeEnabled()
  await page.unroute('**/data-entry/delete')
  await deletion.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(deletion).toHaveCount(0)
  await expect(rows).toHaveCount(1)
  await expect(panel.locator('.filepond--item')).toHaveCount(0, { timeout: 10000 })
  await input.setInputFiles({ name: '不支持.txt', mimeType: 'text/plain', buffer: Buffer.from('test') })
  const retry = panel.locator('[data-upload-retry]')
  await expect(retry).toHaveAccessibleName(/仅支持 DOCX \/ PDF 文件.*点击重试/)
  await retry.click()
  await expect(retry).toHaveCount(0)
  expect(count).toBe(2)
  await page.screenshot({ path: info.outputPath(`report-upload-list-${width}.png`), fullPage: true })
  await page.reload(); await openReportFiles(page)
  await expect(panel.locator('[data-attachment-file]')).toHaveCount(1)
  await expect(panel.locator('[data-attachment-file]')).toContainText('附件二.docx')
})
