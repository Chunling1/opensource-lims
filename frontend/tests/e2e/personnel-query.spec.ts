import { toolbarButton, openToolbarExport } from './helpers/toolbar'
import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { personnelFields } from '../../src/types/quality/personnel'

for (const width of [1440, 390]) test(`personnel query shares registration columns and data, with view-only row actions at ${width}px`, async ({ page }, info) => {
  test.setTimeout(90000)
  await page.setViewportSize({ width, height: 1000 })
  await page.goto('/#/quality/personnel/registration')
  const registration = page.getByRole('table', { name: '人员登记列表', exact: true })
  await expect(registration.locator('tbody tr')).toHaveCount(10)
  for (const [id, qualification] of [['demo-person-1', '工程师'], ['demo-person-2', '高级工程师']]) {
    const url = `/api/registration/quality/personnel/${id}`
    const record = await (await page.request.get(url, { headers: { 'X-Demo-Actor': 'admin' } })).json()
    const response = await page.request.post(`${url}/save`, { headers: { 'X-Demo-Actor': 'admin' }, data: { ...record, qualification, education: '本科', major: '材料检测', department: '实验室' } })
    expect(response.ok()).toBe(true)
  }
  const headings = await registration.getByRole('columnheader').allTextContents()
  // Navigate without reloading: both routes reuse the same component instance.
  await page.evaluate(() => { location.hash = '#/quality/personnel/query' })
  const table = page.getByRole('table', { name: '人员查询列表', exact: true })
  const query = page.getByRole('form', { name: '人员查询条件', exact: true })
  await expect(table.locator('tbody tr')).toHaveCount(10)
  for (const name of ['新增', '下载模板', '导入']) await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0)
  await expect(table.getByRole('columnheader')).toHaveText(headings)
  for (const name of ['姓名', '职称', '文化程度']) await expect(query.getByLabel(name, { exact: true })).toBeVisible()
  const more = query.getByRole('button', { name: /更多筛选/ })
  await expect(more).toHaveAttribute('aria-expanded', 'false')
  for (const name of ['所学专业', '所在部门']) await expect(query.getByLabel(name, { exact: true })).toBeHidden()
  await query.screenshot({ path: info.outputPath(`personnel-query-collapsed-${width}.png`) })
  await more.click()
  await expect(more).toHaveAttribute('aria-expanded', 'true')
  for (const name of ['所学专业', '所在部门']) await expect(query.getByLabel(name, { exact: true })).toBeVisible()
  for (const name of ['编号', '毕业院校']) await expect(query.getByLabel(name, { exact: true })).toHaveCount(0)
  await expect(query.getByRole('combobox', { name: '职称', exact: true }).locator('option')).toHaveText(['全部', '教授级高级工程师', '高级工程师', '工程师', '助理工程师', '技术员'])
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await page.getByLabel('人员查询每页条数', { exact: true }).selectOption('20')
  await expect(table.locator('tbody tr')).toHaveCount(12)
  await query.getByLabel('姓名', { exact: true }).fill('演示人员')
  await query.getByLabel('职称', { exact: true }).selectOption('工程师')
  await query.getByLabel('文化程度', { exact: true }).fill('本科')
  await query.getByLabel('所学专业', { exact: true }).fill('材料')
  await query.getByLabel('所在部门', { exact: true }).fill('实验室')
  await expect(more).toContainText('（2）')
  await more.click()
  await expect(query.getByLabel('所学专业', { exact: true })).toBeHidden()
  await query.getByRole('button', { name: '查询', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await more.click()
  await expect(query.getByLabel('所学专业', { exact: true })).toHaveValue('材料')
  await query.screenshot({ path: info.outputPath(`personnel-query-form-${width}.png`) })
  await table.getByRole('cell', { name: '演示人员01', exact: true }).click()
  await expect(table.getByRole('checkbox', { checked: true })).toHaveCount(0)
  await table.getByRole('button', { name: '演示人员01 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['查看'])
  await page.getByRole('menuitem', { name: '查看', exact: true }).click()
  const view = page.getByRole('dialog', { name: '查看人员', exact: true })
  await expect(view.getByLabel('姓名', { exact: true })).toHaveValue('演示人员01')
  await expect(view.getByLabel('姓名', { exact: true })).toBeDisabled()
  await expect(view.getByRole('button', { name: '保存', exact: true })).toHaveCount(0)
  await page.screenshot({ path: info.outputPath(`personnel-query-view-${width}.png`) })
  await view.getByRole('button', { name: '关闭', exact: true }).click()
  await (await toolbarButton(page, '人员查询', '显示')).click()
  const columns = page.getByRole('dialog', { name: '人员查询显示列', exact: true })
  await expect(columns.getByRole('checkbox')).toHaveCount(20)
  for (const field of personnelFields) await columns.getByRole('checkbox', { name: field.label, exact: true }).check()
  await columns.getByRole('button', { name: '完成', exact: true }).click()
  await expect(table.getByRole('columnheader')).toHaveCount(22)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await table.getByRole('checkbox', { name: '选择人员查询 演示人员01', exact: true }).check()
  await openToolbarExport(page, '人员查询')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出已选记录（1）', exact: true }).click()
  const file = await download
  expect(file.suggestedFilename()).toBe('人员查询.csv')
  const csv = await readFile((await file.path())!, 'utf8')
  expect(csv).toContain('DEMO-001'); expect(csv).not.toContain('DEMO-002')
  await page.reload()
  await expect(more).toHaveAttribute('aria-expanded', 'false')
  await expect(more).toContainText('（2）')
  for (const [label, value] of [['姓名', '演示人员'], ['职称', '工程师'], ['文化程度', '本科'], ['所学专业', '材料'], ['所在部门', '实验室']]) await expect(query.getByLabel(label!, { exact: true })).toHaveValue(value!)
  await expect(table.getByRole('columnheader')).toHaveCount(22)
  await page.evaluate(() => { location.hash = '#/quality/personnel/registration' })
  for (const name of ['新增', '下载模板', '导入']) await toolbarButton(page, '人员登记', name)
  await expect(page.getByRole('button', { name: /更多筛选/ })).toHaveCount(0)
  await registration.getByRole('button', { name: '演示人员01 更多操作', exact: true }).click()
  await expect(page.getByRole('menuitem')).toHaveText(['编辑', '查看', '删除'])
})
